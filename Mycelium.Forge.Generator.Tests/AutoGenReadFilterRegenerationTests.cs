namespace Mycelium.Forge.Generator.Tests
{
    using System.IO;

    using Mycelium.Forge.Generator.Generators;

    /// <summary>
    /// Writes freshly generated read filters to <c>_Forge.Orm.AutoGeneratedFilters/</c> under this test project's own
    /// build output, for visual inspection.
    /// </summary>
    [TestFixture]
    public class AutoGenReadFilterRegenerationTests
    {
        /// <summary>
        /// Regenerates the read filter classes.
        /// </summary>
        [Test]
        public void Regenerate_AutoGenReadFilters()
        {
            var outputDirectory = new DirectoryInfo(Path.Combine(TestContext.CurrentContext.WorkDirectory, "_Forge.Orm.AutoGeneratedFilters"));
            outputDirectory.Create();

            var generator = new UmlCoreReadFilterGenerator();

            Assert.That(async () => await generator.GenerateAsync(GeneratorSetupFixture.XmiReaderResult, outputDirectory), Throws.Nothing);
        }
    }
}
