namespace Mycelium.Forge.Generator.Tests
{
    using System.IO;

    using Mycelium.Forge.Generator.Generators;

    /// <summary>
    /// Writes freshly generated domain services to <c>_Forge.Dal.AutoGeneratedServices/</c> under this test project's own
    /// build output, for visual inspection.
    /// </summary>
    [TestFixture]
    public class AutoGenServiceRegenerationTests
    {
        /// <summary>
        /// Regenerates the domain service interfaces, classes, and service collection extensions.
        /// </summary>
        [Test]
        public void Regenerate_AutoGenServices()
        {
            var outputDirectory = new DirectoryInfo(Path.Combine(TestContext.CurrentContext.WorkDirectory, "_Forge.Dal.AutoGeneratedServices"));
            outputDirectory.Create();

            var generator = new UmlCoreServiceGenerator();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(async () => await generator.GenerateServiceInterfacesAsync(GeneratorSetupFixture.XmiReaderResult, outputDirectory), Throws.Nothing);
                Assert.That(async () => await generator.GenerateServiceClassesAsync(GeneratorSetupFixture.XmiReaderResult, outputDirectory), Throws.Nothing);
                Assert.That(async () => await generator.GenerateServiceRegistryAsync(GeneratorSetupFixture.XmiReaderResult, outputDirectory), Throws.Nothing);
            }
        }
    }
}
