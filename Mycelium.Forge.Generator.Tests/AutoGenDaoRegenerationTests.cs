namespace Mycelium.Forge.Generator.Tests
{
    using System.IO;
    using System.Threading.Tasks;

    using Mycelium.Forge.Generator.Generators;

    /// <summary>
    /// Writes freshly generated DAOs to <c>_Forge.Orm.AutoGeneratedDao/</c> under this test project's own
    /// build output, for visual inspection - matching how the uml4net/SysML2.NET code generation
    /// pipeline works.
    /// </summary>
    [TestFixture]
    public class AutoGenDaoRegenerationTests
    {
        /// <summary>
        /// Verifies that the auto generated DAO is regenerated correctly.
        /// </summary>
        [Test]
        public void VerifyRegenerate_AutoGenDao()
        {
            var outputDirectory = new DirectoryInfo(Path.Combine(TestContext.CurrentContext.WorkDirectory, "_Forge.Orm.AutoGeneratedDao"));
            outputDirectory.Create();

            var generator = new UmlCoreDaoGenerator();

            Assert.That(async () => await generator.GenerateAsync(GeneratorSetupFixture.XmiReaderResult, outputDirectory), Throws.Nothing);
        }

        /// <summary>
        /// Verifies that the auto generated SQL schema is regenerated correctly.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyRegenerate_SqlSchema()
        {
            var generator = new UmlCoreSqlSchemaGenerator();
            var sql = await generator.GenerateSqlSchemaAsync(GeneratorSetupFixture.XmiReaderResult);

            var expectedPath = Path.GetFullPath(Path.Combine(TestContext.CurrentContext.TestDirectory, "../../../Expected/AutoGeneratedSqlSchema/schema.sql"));
            await File.WriteAllTextAsync(expectedPath, sql);

            var migrationPath = Path.GetFullPath(Path.Combine(TestContext.CurrentContext.TestDirectory, "../../../../Mycelium.Forge.Orm/Migrations/Script0001_InitialSchema.sql"));

            if (File.Exists(migrationPath))
            {
                await File.WriteAllTextAsync(migrationPath, sql);
            }
        }
    }
}
