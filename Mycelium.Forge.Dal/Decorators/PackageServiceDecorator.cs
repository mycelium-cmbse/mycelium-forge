namespace Mycelium.Forge.Dal.Decorators
{
    using System.Collections.Immutable;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;

    using Npgsql;

    using ZiggyCreatures.Caching.Fusion;

    /// <summary>
    /// Decorator for <see cref="IPackageService" /> providing pointer key caching and cache invalidation.
    /// </summary>
    public class PackageServiceDecorator : IPackageService
    {
        /// <summary>
        /// The (injected) <see cref="IFusionCache" /> used as a caching layer.
        /// </summary>
        private readonly IFusionCache fusionCache;

        /// <summary>
        /// The decorated <see cref="IPackageService" /> inner service.
        /// </summary>
        private readonly IPackageService innerService;

        /// <summary>
        /// The (injected) <see cref="ILogger{T}" /> logger.
        /// </summary>
        private readonly ILogger<PackageServiceDecorator> logger;

        /// <summary>
        /// Initializes a new instance of the <see cref="PackageServiceDecorator" /> class.
        /// </summary>
        /// <param name="innerService">The decorated <see cref="IPackageService" /> inner service.</param>
        /// <param name="fusionCache">The (injected) <see cref="IFusionCache" /> used as a caching layer.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{T}" /> logger.</param>
        public PackageServiceDecorator(IPackageService innerService, IFusionCache fusionCache, ILogger<PackageServiceDecorator> logger)
        {
            this.innerService = innerService;
            this.fusionCache = fusionCache;
            this.logger = logger;
        }

        /// <summary>
        /// Asynchronously creates (persists) instances of <see cref="IPackage" /> within an existing transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="dtos">The collection of <see cref="IPackage" /> instances to create.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Created}" /> indicating success or failure.</returns>
        public Task<ErrorOr<Created>> CreateAsync(IUserContext userContext, NpgsqlTransaction transaction, IEnumerable<IPackage> dtos, CancellationToken token)
        {
            return this.innerService.CreateAsync(userContext, transaction, dtos, token);
        }

        /// <summary>
        /// Asynchronously creates (persists) instances of <see cref="IPackage" /> managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="dtos">The collection of <see cref="IPackage" /> instances to create.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Created}" /> indicating success or failure.</returns>
        public Task<ErrorOr<Created>> CreateAsync(IUserContext userContext, IEnumerable<IPackage> dtos, CancellationToken token)
        {
            return this.innerService.CreateAsync(userContext, dtos, token);
        }

        /// <summary>
        /// Asynchronously reads instances of <see cref="IPackage" /> within an existing transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <param name="iids">An optional array of unique identifiers to read.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{T}" /> of permitted instances.</returns>
        public Task<ErrorOr<ImmutableList<IPackage>>> ReadAsync(IUserContext userContext, NpgsqlTransaction transaction, CancellationToken token, Guid[] iids = null)
        {
            return this.innerService.ReadAsync(userContext, transaction, token, iids);
        }

        /// <summary>
        /// Asynchronously reads instances of <see cref="IPackage" /> managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <param name="iids">An optional array of unique identifiers to read.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{T}" /> of permitted instances.</returns>
        public Task<ErrorOr<ImmutableList<IPackage>>> ReadAsync(IUserContext userContext, CancellationToken token, Guid[] iids = null)
        {
            return this.innerService.ReadAsync(userContext, token, iids);
        }

        /// <summary>
        /// Asynchronously updates instances of <see cref="IPackage" /> within an existing transaction and invalidates cached
        /// entries.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="dtos">The collection of <see cref="IPackage" /> instances to update.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Updated}" /> indicating success or failure.</returns>
        public async Task<ErrorOr<Updated>> UpdateAsync(IUserContext userContext, NpgsqlTransaction transaction, IEnumerable<IPackage> dtos, CancellationToken token)
        {
            var dtoList = dtos?.ToList() ?? [];

            var result = await this.innerService.UpdateAsync(userContext, transaction, dtoList, token);

            if (!result.IsError)
            {
                foreach (var dto in dtoList)
                {
                    await this.fusionCache.RemoveByTagAsync($"Package:{dto.Id}", token: token);
                }
            }

            return result;
        }

        /// <summary>
        /// Asynchronously updates instances of <see cref="IPackage" /> managing its own connection and transaction and invalidates
        /// cached entries.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="dtos">The collection of <see cref="IPackage" /> instances to update.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Updated}" /> indicating success or failure.</returns>
        public async Task<ErrorOr<Updated>> UpdateAsync(IUserContext userContext, IEnumerable<IPackage> dtos, CancellationToken token)
        {
            var dtoList = dtos?.ToList() ?? [];

            var result = await this.innerService.UpdateAsync(userContext, dtoList, token);

            if (!result.IsError)
            {
                foreach (var dto in dtoList)
                {
                    await this.fusionCache.RemoveByTagAsync($"Package:{dto.Id}", token: token);
                }
            }

            return result;
        }

        /// <summary>
        /// Asynchronously deletes instances of <see cref="IPackage" /> within an existing transaction and invalidates cached
        /// entries.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="iids">The collection of unique identifiers of instances to delete.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Deleted}" /> indicating success or failure.</returns>
        public async Task<ErrorOr<Deleted>> DeleteAsync(IUserContext userContext, NpgsqlTransaction transaction, IEnumerable<Guid> iids, CancellationToken token)
        {
            var idList = iids?.ToList() ?? [];

            var result = await this.innerService.DeleteAsync(userContext, transaction, idList, token);

            if (!result.IsError)
            {
                foreach (var id in idList)
                {
                    await this.fusionCache.RemoveByTagAsync($"Package:{id}", token: token);
                }
            }

            return result;
        }

        /// <summary>
        /// Asynchronously deletes instances of <see cref="IPackage" /> managing its own connection and transaction and invalidates
        /// cached entries.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="iids">The collection of unique identifiers of instances to delete.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Deleted}" /> indicating success or failure.</returns>
        public async Task<ErrorOr<Deleted>> DeleteAsync(IUserContext userContext, IEnumerable<Guid> iids, CancellationToken token)
        {
            var idList = iids?.ToList() ?? [];

            var result = await this.innerService.DeleteAsync(userContext, idList, token);

            if (!result.IsError)
            {
                foreach (var id in idList)
                {
                    await this.fusionCache.RemoveByTagAsync($"Package:{id}", token: token);
                }
            }

            return result;
        }

        /// <summary>
        /// Asynchronously reads a single <see cref="IPackage" /> instance matching the specified scope and package short name
        /// managing its own connection and transaction, utilizing secondary index pointer caching.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="scopeShortName">The short name of the owning scope (organization or account).</param>
        /// <param name="packageShortName">The short name of the package.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the permitted <see cref="IPackage" /> or an error.</returns>
        public async Task<ErrorOr<IPackage>> ReadByCoordinateAsync(IUserContext userContext, string scopeShortName, string packageShortName, CancellationToken token = default)
        {
            if (this.logger.IsEnabled(LogLevel.Debug))
            {
                this.logger.LogDebug("Starting ReadByCoordinateAsync for Package: scope {Scope}, package {Package}", scopeShortName.SanitizeForLog(), packageShortName.SanitizeForLog());
            }

            var cacheKey = $"Package:Coordinate:{scopeShortName.ToLowerInvariant()}/{packageShortName.ToLowerInvariant()}";
            var cached = await this.fusionCache.TryGetByPointerAsync(cacheKey, this.innerService, userContext, packageShortName, token);

            if (cached != null)
            {
                return (Package)cached;
            }

            var result = await this.innerService.ReadByCoordinateAsync(userContext, scopeShortName, packageShortName, token);

            if (result is { IsError: false, Value: not null })
            {
                await this.fusionCache.SetPointerAsync(cacheKey, result.Value.Id, [$"Package:{result.Value.Id}", $"Scope:{result.Value.Owner}"], token);
            }

            return result;
        }

        /// <summary>
        /// Asynchronously reads all <see cref="IPackage" /> instances owned or maintained by the specified account identifier
        /// managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="accountId">The unique identifier of the user account.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>
        /// A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{IPackage}" /> of permitted packages or
        /// an error.
        /// </returns>
        public Task<ErrorOr<ImmutableList<IPackage>>> ReadByMaintainerOrOwnerAsync(IUserContext userContext, Guid accountId, CancellationToken token = default)
        {
            return this.innerService.ReadByMaintainerOrOwnerAsync(userContext, accountId, token);
        }
    }
}
