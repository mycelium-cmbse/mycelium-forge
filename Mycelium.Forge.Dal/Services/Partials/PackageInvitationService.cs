        /// <summary>
        /// Asynchronously accepts a package invitation, transitioning its status to accepted and adding the invited
        /// target account to the package's owners or maintainers within a transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="invitation">The invitation to accept.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the updated <see cref="IPackage" /> or an error.</returns>
        public async Task<ErrorOr<IPackage>> AcceptInvitationAsync(IUserContext userContext, IPackageInvitation invitation, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (invitation is not PackageInvitation packageInvitation)
            {
                return Error.Unexpected(description: "Invalid invitation type.");
            }

            if (this.Logger.IsEnabled(LogLevel.Debug))
            {
                this.Logger.LogDebug("Starting AcceptInvitationAsync for PackageInvitation {InvitationId}", packageInvitation.Id.SanitizeForLog());
            }

            var invitationClone = packageInvitation.Clone();
            invitationClone.Status = InvitationStatusKind.ACCEPTED;

            IPackage acceptedPackage = null;

            var transactionResult = await this.DatabaseSource.ExecuteInTransactionAsync<Success>(async transaction =>
            {
                var updateResult = await this.UpdateAsync(userContext, transaction, [invitationClone], token);

                if (updateResult.IsError)
                {
                    return updateResult.Errors;
                }

                var packageResult = await this.packageDao.ReadAsync(transaction, token, [invitation.Package]);

                if (packageResult.IsError || packageResult.Value.Count == 0)
                {
                    return Error.NotFound(description: "Package not found.");
                }

                var package = packageResult.Value[0];

                if (package is not Package packageEntity)
                {
                    return Error.Unexpected(description: "Invalid package type.");
                }

                var packageClone = packageEntity.Clone();

                if (invitation.PackageInvitationKind == PackageInvitationKind.OWNER)
                {
                    packageClone.PackageOwner.AddIfNotExisting(invitation.Target);
                    packageClone.PackageMaintainer.Remove(invitation.Target);
                }
                else if (!packageClone.PackageOwner.Contains(invitation.Target))
                {
                    packageClone.PackageMaintainer.AddIfNotExisting(invitation.Target);
                }

                var updatePackageResult = await this.packageDao.UpdateAsync(transaction, packageClone, token);

                if (updatePackageResult.IsError)
                {
                    return updatePackageResult.Errors;
                }

                acceptedPackage = packageClone;
                return Result.Success;
            }, token);

            if (transactionResult.IsError)
            {
                return transactionResult.Errors;
            }

            return await ErrorOrFactory.FromAsync(acceptedPackage);
        }
