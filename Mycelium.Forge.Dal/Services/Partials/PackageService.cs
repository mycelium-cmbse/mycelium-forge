        /// <summary>
        /// Asynchronously reads a single <see cref="IPackage" /> instance matching the specified scope and package short name
        /// managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="scopeShortName">The short name of the owning scope (organization or account).</param>
        /// <param name="packageShortName">The short name of the package.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the permitted <see cref="IPackage" /> or an error.</returns>
        public async Task<ErrorOr<IPackage>> ReadByCoordinateAsync(IUserContext userContext, string scopeShortName, string packageShortName, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.logger.IsEnabled(LogLevel.Debug))
            {
                this.logger.LogDebug(
                    "Starting ReadByCoordinateAsync for Package: scope {Scope}, package {Package}",
                    scopeShortName.SanitizeForLog(),
                    packageShortName.SanitizeForLog());
            }

            var filter = (SqlFilter)PackageReadFilter.FromUserContext(userContext);

            filter.Where(
                """
                LOWER("Thing"."data"->>'shortName') = LOWER(@packageShortName)
                AND EXISTS (
                    SELECT 1 FROM "Forge"."Thing" AS "OwnerThing"
                    WHERE "OwnerThing"."id" = "Package"."owner"
                      AND LOWER("OwnerThing"."data"->>'shortName') = LOWER(@scopeShortName)
                )
                """);

            filter.AddParameter("@packageShortName", NpgsqlDbType.Text, packageShortName);
            filter.AddParameter("@scopeShortName", NpgsqlDbType.Text, scopeShortName);

            var readResult = await this.ReadWithFilterAsync(userContext, filter, token);

            if (readResult.IsError)
            {
                return readResult.Errors;
            }

            var item = readResult.Value.FirstOrDefault();

            if (item == null)
            {
                return Error.NotFound(description: $"Package with scope '{scopeShortName}' and name '{packageShortName}' was not found.");
            }

            return (Package)item;
        }

        /// <summary>
        /// Asynchronously reads all <see cref="IPackage" /> instances owned or maintained by the specified account identifier
