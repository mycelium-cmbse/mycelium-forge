    /// <summary>
    /// Service implementation for managing <see cref="IPackage" /> instances, bringing validation, permissions, and data
    /// persistence together.
    /// </summary>
    public partial class PackageService
    {
        /// <summary>
        /// The advisory lock category serializing concurrent operations on the same package coordinate.
        /// </summary>
        public const string CoordinateLockCategory = "coordinate";

        /// <summary>
        /// The error code returned when a package coordinate is already occupied.
        /// </summary>
        public const string CoordinateConflictCode = "Package.CoordinateConflict";

        /// <summary>
        /// The (injected) <see cref="IAccountDao" /> data access object.
        /// </summary>
        private readonly IAccountDao accountDao;

        /// <summary>
        /// The (injected) <see cref="IOrganizationDao" /> data access object.
        /// </summary>
        private readonly IOrganizationDao organizationDao;

        /// <summary>
        /// Initializes a new instance of the <see cref="PackageService" /> class with account and organization DAOs.
        /// </summary>
        /// <param name="dao">The (injected) <see cref="IPackageDao" /> data access object.</param>
        /// <param name="dtoValidator">The (injected) <see cref="PackageValidator" /> DTO validator.</param>
        /// <param name="permissionService">The (injected) <see cref="IPackagePermissionService" /> permission service.</param>
        /// <param name="dtoComparer">The (injected) <see cref="PackageComparer" /> DTO comparer.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{T}" /> logger.</param>
        /// <param name="databaseSource">The (injected) <see cref="IDatabaseSource" /> database connection provider.</param>
        /// <param name="readFilter">The (injected) <see cref="PackageReadFilter" /> read filter provider.</param>
        /// <param name="accountDao">The (injected) <see cref="IAccountDao" /> data access object.</param>
        /// <param name="organizationDao">The (injected) <see cref="IOrganizationDao" /> data access object.</param>
        public PackageService(IPackageDao dao, PackageValidator dtoValidator, IPackagePermissionService permissionService, PackageComparer dtoComparer, ILogger<PackageService> logger, IDatabaseSource databaseSource, PackageReadFilter readFilter, IAccountDao accountDao, IOrganizationDao organizationDao) : base(dao, dtoValidator, permissionService, dtoComparer, logger, databaseSource, readFilter)
        {
            this.accountDao = accountDao;
            this.organizationDao = organizationDao;
        }

        /// <summary>
        /// Asynchronously reads a single <see cref="IPackage" /> instance matching the specified scope and package short name
        /// managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="scopeShortName">The short name of the owning scope (organization or account).</param>
        /// <param name="packageShortName">The short name of the package.</param>
        /// <param name="bypassPermissions">
        /// Whether to bypass user visibility filters to evaluate coordinate occupancy across
        /// private packages.
        /// </param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the permitted <see cref="IPackage" /> or an error.</returns>
        /// <remarks>
        /// Setting <paramref name="bypassPermissions" /> to <c>true</c> bypasses all user visibility filters and checks coordinate
        /// occupancy across private packages. Exercise caution when enabling this option to avoid disclosing confidential entities
        /// across scopes where the user is not a member.
        /// </remarks>
        public Task<ErrorOr<IPackage>> ReadByCoordinateAsync(IUserContext userContext, string scopeShortName, string packageShortName, bool bypassPermissions = false, CancellationToken token = default)
        {
            return this.DatabaseSource.ExecuteInTransactionAsync(transaction => this.ReadByCoordinateAsync(userContext, transaction, scopeShortName, packageShortName, bypassPermissions, token), token);
        }

        /// <summary>
        /// Asynchronously reads all <see cref="IPackage" /> instances owned or maintained by the specified account identifier
        /// managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="accountId">The unique identifier of the user account.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>
        /// A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{IPackage}" /> of permitted packages or
        /// an error.
        /// </returns>
        public async Task<ErrorOr<ImmutableList<IPackage>>> ReadByMaintainerOrOwnerAsync(IUserContext userContext, Guid accountId, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.Logger.IsEnabled(LogLevel.Debug))
            {
                this.Logger.LogDebug("Starting ReadByMaintainerOrOwnerAsync for Package: account {AccountId}", accountId.SanitizeForLog());
            }

            var filter = (SqlFilter)this.ReadFilter.FromUserContext(userContext);

            filter.Where(
                """
                (
                    package.owner = @accountId
                    OR EXISTS (
                        SELECT 1 FROM forge.package_package_owner__account
                        WHERE source_package = package.id AND target_account = @accountId
                    )
                    OR EXISTS (
                        SELECT 1 FROM forge.package_package_maintainer__account
                        WHERE source_package = package.id AND target_account = @accountId
                    )
                )
                """);

            filter.AddParameter("@accountId", NpgsqlDbType.Uuid, accountId);

            return await this.ReadWithFilterAsync(userContext, filter, token);
        }

        /// <summary>
        /// Verifies that the package coordinate is not already occupied in the owning scope before creating the package.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="dto">The <see cref="IPackage" /> about to be created.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating whether the creation may proceed.</returns>
        protected override async Task<ErrorOr<Success>> BeforeCreate(IUserContext userContext, NpgsqlTransaction transaction, IPackage dto, CancellationToken token)
        {
            var scopeResult = await this.ResolveScopeAsync(transaction, dto.Owner, token);

            if (scopeResult.IsError)
            {
                return scopeResult.Errors;
            }

            var scope = scopeResult.Value;
            var coordinate = $"{scope.ShortName}:{dto.ShortName}";
            await this.DatabaseSource.AcquireAdvisoryLockAsync(transaction, CoordinateLockCategory, coordinate, token);

            var existingPackageResult = await this.ReadByCoordinateAsync(userContext, transaction, scope.ShortName, dto.ShortName, true, token);

            if (!existingPackageResult.IsError)
            {
                return Error.Conflict(CoordinateConflictCode, $"Package '{dto.ShortName}' already exists in this scope.");
            }

            if (existingPackageResult.FirstError.Type != ErrorType.NotFound)
            {
                return existingPackageResult.Errors;
            }

            return Result.Success;
        }

        /// <summary>
        /// When the owning scope changes, verifies that the caller may transfer the package to the target scope and that the
        /// package coordinate is not already occupied there.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="existing">The currently persisted <see cref="IPackage" />.</param>
        /// <param name="dto">The updated <see cref="IPackage" />.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating whether the update may proceed.</returns>
        /// <remarks>
        /// Only a package owner or an installation administrator may transfer a package.
        /// </remarks>
        protected override async Task<ErrorOr<Success>> BeforeUpdate(IUserContext userContext, NpgsqlTransaction transaction, IPackage existing, IPackage dto, CancellationToken token)
        {
            if (existing.Owner == dto.Owner)
            {
                return Result.Success;
            }

            var accountId = userContext.AccountId;
            var isInstallationAdministrator = PermissionGuard.HasRole(userContext, RoleKind.InstallationAdministrator);

            if (!isInstallationAdministrator && !(accountId.HasValue && existing.PackageOwner.Contains(accountId.Value)))
            {
                return Error.Forbidden(description: "Access denied: only a package owner or an installation administrator can transfer package ownership.");
            }

            var scopeResult = await this.ResolveScopeAsync(transaction, dto.Owner, token);

            if (scopeResult.IsError)
            {
                return scopeResult.Errors;
            }

            var scope = scopeResult.Value;

            switch (scope)
            {
                case IOrganization organization when !isInstallationAdministrator && !organization.Administrator.Contains(accountId.Value):
                    return Error.Forbidden(description: "You do not have administrative rights on the target organization.");
                case IAccount when !isInstallationAdministrator && scope.Id != accountId.Value:
                    return Error.Forbidden(description: "Ownership can only be transferred to your own account or to an organization you administer.");
            }

            var coordinate = $"{scope.ShortName}:{dto.ShortName}";
            await this.DatabaseSource.AcquireAdvisoryLockAsync(transaction, CoordinateLockCategory, coordinate, token);

            var existingPackageResult = await this.ReadByCoordinateAsync(userContext, transaction, scope.ShortName, dto.ShortName, true, token);

            if (!existingPackageResult.IsError)
            {
                if (existingPackageResult.Value.Id != dto.Id)
                {
                    return Error.Conflict(CoordinateConflictCode, $"Package '{dto.ShortName}' already exists in the target scope.");
                }
            }
            else if (existingPackageResult.FirstError.Type != ErrorType.NotFound)
            {
                return existingPackageResult.Errors;
            }

            return Result.Success;
        }

        /// <summary>
        /// Asynchronously reads a single <see cref="IPackage" /> instance matching the specified scope and package short name
        /// within an existing transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="scopeShortName">The short name of the owning scope (organization or account).</param>
        /// <param name="packageShortName">The short name of the package.</param>
        /// <param name="bypassPermissions">
        /// Whether to bypass user visibility filters to evaluate coordinate occupancy across
        /// private packages.
        /// </param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the permitted <see cref="IPackage" /> or an error.</returns>
        /// <remarks>
        /// Setting <paramref name="bypassPermissions" /> to <c>true</c> bypasses all user visibility filters and checks coordinate
        /// occupancy across private packages. Exercise caution when enabling this option to avoid disclosing confidential entities
        /// across scopes where the user is not a member.
        /// </remarks>
        private async Task<ErrorOr<IPackage>> ReadByCoordinateAsync(IUserContext userContext, NpgsqlTransaction transaction, string scopeShortName, string packageShortName, bool bypassPermissions = false, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.Logger.IsEnabled(LogLevel.Debug))
            {
                this.Logger.LogDebug("Starting ReadByCoordinateAsync for Package within transaction: scope {Scope}, package {Package}", scopeShortName.SanitizeForLog(), packageShortName.SanitizeForLog());
            }

            var filter = bypassPermissions
                ? new SqlFilter()
                : (SqlFilter)this.ReadFilter.FromUserContext(userContext);

            filter.Where(
                """
                thing.class_kind = 'Package'
                AND thing.data->>'shortName' = @packageShortName
                AND EXISTS (
                    SELECT 1 FROM forge.thing AS owner_thing
                    WHERE owner_thing.id = package.owner
                      AND owner_thing.data->>'shortName' = @scopeShortName
                )
                """);

            filter.AddParameter("@packageShortName", NpgsqlDbType.Text, packageShortName);
            filter.AddParameter("@scopeShortName", NpgsqlDbType.Text, scopeShortName);

            var readResult = await this.Dao.ReadAsync(transaction, token, filter: filter);

            if (readResult.IsError)
            {
                return readResult.Errors;
            }

            var item = readResult.Value.FirstOrDefault();

            if (item == null)
            {
                return Error.NotFound(description: $"Package with scope '{scopeShortName}' and name '{packageShortName}' was not found.");
            }

            if (bypassPermissions)
            {
                return (Package)item;
            }

            var isPermitted = await this.PermissionService.IsAllowedToRead(userContext, item, transaction);

            if (isPermitted.IsError)
            {
                return isPermitted.Errors;
            }

            return (Package)item;
        }

        /// <summary>
        /// Resolves the scope entity by querying the account and organization DAOs within the given transaction.
        /// </summary>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="ownerId">The identifier of the scope (account or organization).</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the resolved <see cref="IScope" /> or an error.</returns>
        private async Task<ErrorOr<IScope>> ResolveScopeAsync(NpgsqlTransaction transaction, Guid ownerId, CancellationToken token)
        {
            var accountResult = await this.accountDao.ReadAsync(transaction, token, [ownerId]);

            if (accountResult.IsError)
            {
                return accountResult.Errors;
            }

            if (accountResult.Value.Count > 0)
            {
                return ErrorOrFactory.From<IScope>(accountResult.Value[0]);
            }

            var organizationResult = await this.organizationDao.ReadAsync(transaction, token, [ownerId]);

            if (organizationResult.IsError)
            {
                return organizationResult.Errors;
            }

            if (organizationResult.Value.Count > 0)
            {
                return ErrorOrFactory.From<IScope>(organizationResult.Value[0]);
            }

            return Error.NotFound(description: $"Scope with ID '{ownerId}' was not found.");
        }

        /// <summary>
        /// Asynchronously reads and filters <see cref="IPackage" /> instances matching the specified filter, managing its own
        /// connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="filter">The SQL filter to apply.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>
        /// A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{IPackage}" /> of permitted packages or
        /// an error.
        /// </returns>
        private Task<ErrorOr<ImmutableList<IPackage>>> ReadWithFilterAsync(IUserContext userContext, ISqlFilter filter, CancellationToken token = default)
        {
            return this.DatabaseSource.ReadWithFilterAsync((transaction, cancellationToken) => this.Dao.ReadAsync(transaction, cancellationToken, filter: filter), this.PermissionService, userContext, this.Logger, token);
        }
    }
