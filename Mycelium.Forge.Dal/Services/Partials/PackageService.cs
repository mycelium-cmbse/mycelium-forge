        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="accountId">The unique identifier of the user account.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>
        /// A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{IPackage}" /> of permitted packages or
        /// an error.
        /// </returns>
        public async Task<ErrorOr<ImmutableList<IPackage>>> ReadByMaintainerOrOwnerAsync(IUserContext userContext, Guid accountId, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.logger.IsEnabled(LogLevel.Debug))
            {
                this.logger.LogDebug(
                    "Starting ReadByMaintainerOrOwnerAsync for Package: account {AccountId}",
                    accountId);
            }

            var filter = (SqlFilter)PackageReadFilter.FromUserContext(userContext);

            filter.Where(
                """
                (
                    "Package"."owner" = @accountId
                    OR EXISTS (
                        SELECT 1 FROM "Forge"."Package_packageOwner__Account"
                        WHERE "sourcePackage" = "Package"."id" AND "targetAccount" = @accountId
                    )
                    OR EXISTS (
                        SELECT 1 FROM "Forge"."Package_packageMaintainer__Account"
                        WHERE "sourcePackage" = "Package"."id" AND "targetAccount" = @accountId
                    )
                )
                """);

            filter.AddParameter("@accountId", NpgsqlDbType.Uuid, accountId);

            return await this.ReadWithFilterAsync(userContext, filter, token);
        }

        /// <summary>
        /// Asynchronously reads and filters <see cref="IPackage" /> instances matching the specified filter, managing its own
        /// connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="filter">The SQL filter to apply.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>
        /// A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{IPackage}" /> of permitted packages or
        /// an error.
        /// </returns>
        private async Task<ErrorOr<ImmutableList<IPackage>>> ReadWithFilterAsync(IUserContext userContext, ISqlFilter filter, CancellationToken token = default)
        {
            try
            {
                await using var connection = await this.databaseSource.OpenNewConnectionAsync(token);
                await using var transaction = await connection.BeginTransactionAsync(token);

                var readResult = await this.dao.ReadAsync(transaction, token, filter: filter);

                if (readResult.IsError)
                {
                    await transaction.RollbackAsync(token);
                    return readResult.Errors;
                }

                List<IPackage> permittedItems = [];

                foreach (var item in readResult.Value)
                {
                    var permissionResult = await this.permissionService.IsAllowedToRead(userContext, item, transaction);

                    if (!permissionResult.IsError)
                    {
                        permittedItems.Add((Package)item);
                    }
                }

                await transaction.CommitAsync(token);
                return permittedItems.ToImmutableList();
            }
            catch (Exception exception)
            {
                this.logger.LogError(exception, "ReadWithFilterAsync for Package failed with an error");
                return Error.Failure(description: exception.Message);
            }
        }
