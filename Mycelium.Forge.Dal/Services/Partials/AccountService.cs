        /// Asynchronously reads a single <see cref="IAccount" /> instance matching the specified account short name
        /// managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="shortName">The short name of the account.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the permitted <see cref="IAccount" /> or an error.</returns>
        public async Task<ErrorOr<IAccount>> ReadByShortNameAsync(IUserContext userContext, string shortName, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.logger.IsEnabled(LogLevel.Debug))
            {
                this.logger.LogDebug("Starting ReadByShortNameAsync for Account: shortName {ShortName}", shortName.SanitizeForLog());
            }

            var filter = (SqlFilter)AccountReadFilter.FromUserContext(userContext);

            filter.Where(
                """
                "Thing"."classKind" = 'Account' AND "Thing"."data"->>'shortName' = @shortName
                """);

            filter.AddParameter("@shortName", NpgsqlDbType.Text, shortName.ToLowerInvariant());

            var readResult = await this.databaseSource.ReadWithFilterAsync((transaction, cancellationToken) => this.dao.ReadAsync(transaction, cancellationToken, filter: filter), this.permissionService, userContext, this.logger, token);

            if (readResult.IsError)
            {
                return readResult.Errors;
            }

            var item = readResult.Value.FirstOrDefault();

            if (item == null)
            {
                return Error.NotFound(description: $"Account with short name '{shortName}' was not found.");
            }

            return (Account)item;
        }
