namespace Mycelium.Forge.Dal.AutoGeneratedServices
{
    using System.Text.Json;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.AutoGenDtoComparer;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGenDtoValidator;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Orm.AutoGeneratedDao;
    using Mycelium.Forge.Orm.AutoGeneratedFilters;
    using Mycelium.Forge.Orm.Outbox;

    using Npgsql;

    /// <summary>
    /// Service implementation for managing <see cref="IAccount" /> instances, bringing validation, permissions, and data
    /// persistence together.
    /// </summary>
    public partial class AccountService
    {
        /// <summary>
        /// The injected <see cref="IOutboxDao" /> used to enqueue transactional outbox messages.
        /// </summary>
        private readonly IOutboxDao outboxDao;

        /// <summary>
        /// Initializes a new instance of the <see cref="AccountService" /> class with transactional outbox support.
        /// </summary>
        /// <param name="dao">The (injected) <see cref="IAccountDao" /> data access object.</param>
        /// <param name="dtoValidator">The (injected) <see cref="AccountValidator" /> DTO validator.</param>
        /// <param name="permissionService">The (injected) <see cref="IAccountPermissionService" /> permission service.</param>
        /// <param name="dtoComparer">The (injected) <see cref="AccountComparer" /> DTO comparer.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{T}" /> logger.</param>
        /// <param name="databaseSource">The (injected) <see cref="IDatabaseSource" /> database connection provider.</param>
        /// <param name="readFilter">The (injected) <see cref="AccountReadFilter" /> read filter provider.</param>
        /// <param name="outboxDao">The (injected) <see cref="IOutboxDao" /> outbox data access object.</param>
        public AccountService(IAccountDao dao, AccountValidator dtoValidator, IAccountPermissionService permissionService, AccountComparer dtoComparer, ILogger<AccountService> logger, IDatabaseSource databaseSource, AccountReadFilter readFilter, IOutboxDao outboxDao) : base(dao, dtoValidator, permissionService, dtoComparer, logger, databaseSource, readFilter)
        {
            this.outboxDao = outboxDao;
        }

        /// <summary>
        /// Asynchronously updates instances of <see cref="IAccount" /> and enqueues outbox synchronization messages for identity
        /// changes within the same database transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="dtos">The collection of <see cref="IAccount" /> instances to update.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>An <see cref="ErrorOr{Updated}" /> indicating success or failure.</returns>
        public Task<ErrorOr<Updated>> UpdateAndSyncAsync(IUserContext userContext, IEnumerable<IAccount> dtos, CancellationToken token)
        {
            ArgumentNullException.ThrowIfNull(userContext);
            ArgumentNullException.ThrowIfNull(dtos);

            var dtoList = dtos.ToList();

            if (dtoList.Count == 0)
            {
                return Task.FromResult<ErrorOr<Updated>>(Result.Updated);
            }

            return this.DatabaseSource.ExecuteInTransactionAsync(transaction => this.UpdateAndEnqueueSyncInTransactionAsync(userContext, transaction, dtoList, token), token);
        }

        /// <summary>
        /// Asynchronously updates the supplied <see cref="IAccount" /> instances and enqueues Keycloak synchronization
        /// outbox messages for changed account names or emails within the active database transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The active <see cref="NpgsqlTransaction" />.</param>
        /// <param name="dtoList">The list of <see cref="IAccount" /> instances to update.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>An <see cref="ErrorOr{Updated}" /> indicating success or failure.</returns>
        private async Task<ErrorOr<Updated>> UpdateAndEnqueueSyncInTransactionAsync(IUserContext userContext, NpgsqlTransaction transaction, List<IAccount> dtoList, CancellationToken token)
        {
            var filter = this.ReadFilter.FromUserContext(userContext);
            var existingDtosResult = await this.Dao.ReadAsync(transaction, token, [.. dtoList.Select(x => x.Id)], filter: filter);

            if (existingDtosResult.IsError)
            {
                return existingDtosResult.Errors;
            }

            var updateResult = await this.UpdateAsync(userContext, transaction, dtoList, token);

            if (updateResult.IsError)
            {
                return updateResult.Errors;
            }

            foreach (var dto in dtoList)
            {
                var existing = existingDtosResult.Value.Find(x => x.Id == dto.Id);

                if (existing == null || (string.Equals(existing.Name, dto.Name, StringComparison.Ordinal) && string.Equals(existing.Email, dto.Email, StringComparison.Ordinal)))
                {
                    continue;
                }

                var (firstName, lastName) = dto.Name.SplitFullName();
                var payload = new KeycloakAccountSyncPayload(dto.Id, dto.Email, firstName, lastName);

                var outboxMessage = new OutboxMessage
                {
                    AggregateId = dto.Id,
                    EventType = OutboxEventTypes.AccountKeycloakSync,
                    Payload = JsonSerializer.Serialize(payload)
                };

                var enqueueResult = await this.outboxDao.EnqueueAsync(transaction, outboxMessage, token);

                if (enqueueResult.IsError)
                {
                    this.Logger.LogError("Failed to enqueue outbox sync message for account {AccountId}: {Errors}", dto.Id.SanitizeForLog(), enqueueResult.Errors.ToJoinedDescriptions());
                    return enqueueResult.Errors;
                }
            }

            return Result.Updated;
        }
    }
}
