    public partial class OrganizationService
    {
        /// <summary>
        /// Asynchronously reads all <see cref="IOrganization" /> instances where the specified account is owner, member, or
        /// administrator, managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="accountId">The unique identifier of the user account.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>
        /// A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{IOrganization}" /> of permitted
        /// organizations or an error.
        /// </returns>
        public async Task<ErrorOr<ImmutableList<IOrganization>>> ReadByAccountMembershipAsync(IUserContext userContext, Guid accountId, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.Logger.IsEnabled(LogLevel.Debug))
            {
                this.Logger.LogDebug("Starting ReadByAccountMembershipAsync for Organization: account {AccountId}", accountId.SanitizeForLog());
            }

            var filter = (SqlFilter)this.ReadFilter.FromUserContext(userContext);

            filter.Where(
                """
                (
                    organization.owner = @accountId
                    OR EXISTS (
                        SELECT 1 FROM forge.organization_administrator__account
                        WHERE source_organization = organization.id AND target_account = @accountId
                    )
                    OR EXISTS (
                        SELECT 1 FROM forge.organization_member__account
                        WHERE source_organization = organization.id AND target_account = @accountId
                    )
                )
                """);

            filter.AddParameter("@accountId", NpgsqlDbType.Uuid, accountId);

            return await this.DatabaseSource.ReadWithFilterAsync((transaction, cancellationToken) => this.Dao.ReadAsync(transaction, cancellationToken, filter: filter), this.PermissionService, userContext, this.Logger, token);
        }
    }
