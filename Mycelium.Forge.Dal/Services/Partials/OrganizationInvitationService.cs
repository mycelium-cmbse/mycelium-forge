        /// <summary>
        /// Asynchronously accepts an organization invitation, transitioning its status to accepted and adding the invited
        /// target account to the organization's members (and administrators if applicable) within a transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="invitation">The invitation to accept.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the updated <see cref="IOrganization" /> or an error.</returns>
        public async Task<ErrorOr<IOrganization>> AcceptInvitationAsync(IUserContext userContext, IOrganizationInvitation invitation, CancellationToken token = default)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.Logger.IsEnabled(LogLevel.Debug))
            {
                this.Logger.LogDebug("Starting AcceptInvitationAsync for OrganizationInvitation {InvitationId}", invitation.Id.SanitizeForLog());
            }

            if (invitation is not OrganizationInvitation orgInvitation)
            {
                return Error.Unexpected(description: "Invalid invitation type.");
            }

            var invitationClone = orgInvitation.Clone();
            invitationClone.Status = InvitationStatusKind.ACCEPTED;

            IOrganization acceptedOrganization = null!;

            var transactionResult = await this.DatabaseSource.ExecuteInTransactionAsync<Success>(async transaction =>
            {
                var updateResult = await this.UpdateAsync(userContext, transaction, [invitationClone], token);

                if (updateResult.IsError)
                {
                    return updateResult.Errors;
                }

                var organizationResult = await this.organizationDao.ReadAsync(transaction, token, [invitation.Organization]);

                if (organizationResult.IsError || organizationResult.Value.Count == 0)
                {
                    return Error.NotFound(description: "Organization not found.");
                }

                var organization = organizationResult.Value[0];

                if (organization is not Organization orgEntity)
                {
                    return Error.Unexpected(description: "Invalid organization type.");
                }

                var organizationClone = orgEntity.Clone();

                organizationClone.Member.AddIfNotExisting(invitation.Target);

                if (invitation.OrganizationInvitationKind == OrganizationInvitationKind.ADMINISTRATOR)
                {
                    organizationClone.Administrator.AddIfNotExisting(invitation.Target);
                }

                var updateOrganizationResult = await this.organizationDao.UpdateAsync(transaction, organizationClone, token);

                if (updateOrganizationResult.IsError)
                {
                    return updateOrganizationResult.Errors;
                }

                acceptedOrganization = organizationClone;
                return Result.Success;
            }, token);

            if (transactionResult.IsError)
            {
                return transactionResult.Errors;
            }

            return ErrorOrFactory.From(acceptedOrganization);
        }
