namespace Mycelium.Forge.Dal.Services
{
    using System.Collections.Immutable;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.DatabaseSource;

    using Npgsql;

    /// <summary>
    /// Service implementation for managing and querying <see cref="IScope" /> instances across organizations and accounts.
    /// </summary>
    /// <remarks>
    /// This service does not perform any custom logic directly in the database for retrieving the accounts and organizations.
    /// Instead, it relies on the <see cref="IAccountService" /> and <see cref="IOrganizationService" /> to fetch the
    /// respective data.
    /// This allows this service to query both organizations and accounts in a single operation, returning a combined list of
    /// <see cref="IScope" /> instances
    /// and respecting the permissions of the user context.
    /// </remarks>
    public class ScopeService : IScopeService
    {
        /// <summary>
        /// The (injected) <see cref="IAccountService" /> domain service.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="IDatabaseSource" /> database connection provider.
        /// </summary>
        private readonly IDatabaseSource databaseSource;

        /// <summary>
        /// The (injected) <see cref="ILogger{T}" /> logger.
        /// </summary>
        private readonly ILogger<ScopeService> logger;

        /// <summary>
        /// The (injected) <see cref="IOrganizationService" /> domain service.
        /// </summary>
        private readonly IOrganizationService organizationService;

        /// <summary>
        /// Initializes a new instance of the <see cref="ScopeService" /> class.
        /// </summary>
        /// <param name="organizationService">The (injected) <see cref="IOrganizationService" /> domain service.</param>
        /// <param name="accountService">The (injected) <see cref="IAccountService" /> domain service.</param>
        /// <param name="databaseSource">The (injected) <see cref="IDatabaseSource" /> database connection provider.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{T}" /> logger.</param>
        public ScopeService(IOrganizationService organizationService, IAccountService accountService, IDatabaseSource databaseSource, ILogger<ScopeService> logger)
        {
            this.organizationService = organizationService;
            this.accountService = accountService;
            this.databaseSource = databaseSource;
            this.logger = logger;
        }

        /// <summary>
        /// Asynchronously reads instances of <see cref="IScope" /> within an existing transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <param name="iids">An optional array of unique identifiers to read.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{T}" /> of permitted instances.</returns>
        /// <remarks>
        /// Because an <see cref="IScope" /> can be either an <see cref="IOrganization" /> or an <see cref="IAccount" />,
        /// this method delegates reading sequentially to <see cref="IOrganizationService" /> and <see cref="IAccountService" />
        /// using the shared transaction. NotFound errors from individual underlying services are ignored to allow the remaining
        /// services to resolve any unmatched identifiers.
        /// </remarks>
        public async Task<ErrorOr<ImmutableList<IScope>>> ReadAsync(IUserContext userContext, NpgsqlTransaction transaction, CancellationToken token, Guid[] iids = null)
        {
            ArgumentNullException.ThrowIfNull(userContext);
            ArgumentNullException.ThrowIfNull(transaction);

            if (this.logger.IsEnabled(LogLevel.Debug))
            {
                this.logger.LogDebug("Starting ReadAsync for Scope within transaction");
            }

            var remainingIds = iids is { Length: > 0 } ? new HashSet<Guid>(iids) : null;
            List<IScope> scopes = [];

            var organizationResult = await ReadFromServiceAsync(this.organizationService, userContext, transaction, remainingIds, scopes, token);

            if (organizationResult.IsError)
            {
                return organizationResult.Errors;
            }

            if (remainingIds == null || remainingIds.Count > 0)
            {
                var accountResult = await ReadFromServiceAsync(this.accountService, userContext, transaction, remainingIds, scopes, token);

                if (accountResult.IsError)
                {
                    return accountResult.Errors;
                }
            }

            if (iids is { Length: > 0 } && scopes.Count == 0)
            {
                return Error.NotFound(description: "Scope data not found in the database.");
            }

            return scopes.ToImmutableList();
        }

        /// <summary>
        /// Asynchronously reads instances of <see cref="IScope" /> managing its own connection and transaction.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <param name="iids">An optional array of unique identifiers to read.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing an <see cref="ImmutableList{T}" /> of permitted instances.</returns>
        public Task<ErrorOr<ImmutableList<IScope>>> ReadAsync(IUserContext userContext, CancellationToken token, Guid[] iids = null)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            return this.databaseSource.ExecuteInTransactionAsync(transaction => this.ReadAsync(userContext, transaction, token, iids), token);
        }

        /// <summary>
        /// Asynchronously reads instances of <see cref="IScope" /> matching the specified scope short names managing its own
        /// connection and transaction. Organizations are matched and returned first, followed by accounts for any unresolved
        /// short names. The returned order reflects this sequence rather than the input order.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <param name="shortNames">An optional array of short name values to read.</param>
        /// <returns>A <see cref="ErrorOr{TValue}" /> containing the permitted <see cref="IScope" /> instances.</returns>
        public async Task<ErrorOr<ImmutableList<IScope>>> ReadByShortNameAsync(IUserContext userContext, CancellationToken token, string[] shortNames = null)
        {
            ArgumentNullException.ThrowIfNull(userContext);

            if (this.logger.IsEnabled(LogLevel.Debug))
            {
                this.logger.LogDebug("Starting ReadByShortNameAsync for Scope with {Count} short names", shortNames?.Length ?? 0);
            }

            if (shortNames is not { Length: > 0 })
            {
                return await this.ReadAsync(userContext, token);
            }

            var normalizedShortNames = shortNames.Select(s => s.ToLowerInvariant()).ToArray();
            var organizationResult = await this.organizationService.ReadByShortNameAsync(userContext, token, normalizedShortNames);

            if (organizationResult.IsError)
            {
                return organizationResult.Errors;
            }

            List<IScope> foundScopes = [.. organizationResult.Value];

            var foundShortNames = new HashSet<string>(foundScopes.Select(x => x.ShortName), StringComparer.OrdinalIgnoreCase);
            var remainingShortNames = normalizedShortNames.Where(s => !foundShortNames.Contains(s)).ToArray();

            if (remainingShortNames.Length > 0)
            {
                var accountResult = await this.accountService.ReadByShortNameAsync(userContext, token, remainingShortNames);

                if (accountResult.IsError)
                {
                    return accountResult.Errors;
                }

                foundScopes.AddRange(accountResult.Value);
            }

            return foundScopes.ToImmutableList();
        }

        /// <summary>
        /// Reads scopes from the specified entity read service for the given target identifiers and appends permitted items.
        /// </summary>
        /// <typeparam name="T">The entity type implementing <see cref="IScope" />.</typeparam>
        /// <param name="service">The domain entity read service.</param>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="transaction">The current <see cref="NpgsqlTransaction" /> to the database.</param>
        /// <param name="remainingIds">The set of remaining unique identifiers to read, updated as items are found.</param>
        /// <param name="scopes">The destination list of <see cref="IScope" /> instances.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Success}" /> indicating success or errors encountered.</returns>
        private static async Task<ErrorOr<Success>> ReadFromServiceAsync<T>(IReadService<T> service, IUserContext userContext, NpgsqlTransaction transaction, HashSet<Guid> remainingIds, List<IScope> scopes, CancellationToken token) where T : IThing, IScope
        {
            var targetIds = remainingIds?.ToArray();
            var result = await service.ReadAsync(userContext, transaction, token, targetIds);

            if (result.IsError)
            {
                if (result.Errors.Exists(e => e.Type != ErrorType.NotFound))
                {
                    return result.Errors;
                }

                return Result.Success;
            }

            foreach (var scope in result.Value)
            {
                scopes.Add(scope);
                remainingIds?.Remove(scope.Id);
            }

            return Result.Success;
        }
    }
}
