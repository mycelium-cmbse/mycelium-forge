        /// <summary>
        /// Verifies that <see cref="PackageDao.ReadAsync" /> reads packages by identifiers, handles missing entries,
        /// and enforces organization visibility filters on internal packages.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyReadAsync()
        {
            var packageId = Guid.NewGuid();

            var package = new Package
            {
                Id = packageId,
                Name = "TestPackageRead",
                ShortName = "test-pkg-read",
                Owner = this.accountId,
                PackageType = this.packageTypeId,
                Listed = true,
                Visibility = VisibilityKind.PUBLIC
            };

            await this.Insert(transaction => this.packageDao.CreateAsync(transaction, CancellationToken.None, package));

            var org1PackageId = Guid.NewGuid();

            var org1InternalPackage = new Package
            {
                Id = org1PackageId,
                Name = "Org1InternalPackage",
                ShortName = "org1-internal-pkg",
                Owner = this.org1Id,
                PackageType = this.packageTypeId,
                Listed = true,
                Visibility = VisibilityKind.INTERNAL
            };

            await this.Insert(transaction => this.packageDao.CreateAsync(transaction, CancellationToken.None, org1InternalPackage));

            var orgBUserContext = new UserContext
            {
                AccountId = this.otherAccountId,
                Username = "otherOrgUser",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationMember]
            };

            var orgAUserContext = new UserContext
            {
                AccountId = this.accountId,
                Username = "owningOrgUser",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationMember]
            };

            var orgBFilter = PackageReadFilter.FromUserContext(orgBUserContext);
            var orgAFilter = PackageReadFilter.FromUserContext(orgAUserContext);

            await using (var transaction = await this.Connection.BeginTransactionAsync())
            {
                var readResult = await this.packageDao.ReadAsync(transaction, CancellationToken.None, [packageId]);
                var emptyResult = await this.packageDao.ReadAsync(transaction, CancellationToken.None, [Guid.NewGuid()]);
                var otherOrgReadResult = await this.packageDao.ReadAsync(transaction, CancellationToken.None, [org1PackageId], filter: orgBFilter);
                var owningOrgReadResult = await this.packageDao.ReadAsync(transaction, CancellationToken.None, [org1PackageId], filter: orgAFilter);
                await transaction.CommitAsync();

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(readResult.IsSuccess, Is.True);
                    Assert.That(readResult.Value, Has.Count.EqualTo(1));
                    Assert.That(readResult.Value[0].Name, Is.EqualTo("TestPackageRead"));
                    Assert.That(emptyResult.IsFailed, Is.True);
                    Assert.That(otherOrgReadResult.IsFailed, Is.True);
                    Assert.That(owningOrgReadResult.IsSuccess, Is.True);
                    Assert.That(owningOrgReadResult.Value, Has.Count.EqualTo(1));
                    Assert.That(owningOrgReadResult.Value[0].Id, Is.EqualTo(org1PackageId));
                }
            }
        }

