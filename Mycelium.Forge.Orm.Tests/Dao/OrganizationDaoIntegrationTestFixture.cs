            var addressId2 = Guid.NewGuid();

            var address1 = new Address
            {
                Id = addressId1,
                Owner = this.adminAccountId,
                Country = countryId,
                AddressLine1 = "100 Admin Way",
                Locality = "Metropolis",
                PostalCode = "10001",
                Region = "NY"
            };

            var address2 = new Address
            {
                Id = addressId2,
                Owner = this.otherAccountId,
                Country = countryId,
                AddressLine1 = "200 Other St",
                Locality = "Metropolis",
                PostalCode = "10002",
                Region = "NY"
            };

            var adminAccount = new Account
            {
                Id = this.adminAccountId,
                Owner = this.forgeId,
                PrimaryAddress = addressId1,
                Name = "AdminUser",
                ShortName = "admin-user",
                Email = "admin@example.com",
                BillingEmail = "admin-billing@example.com",
                DefaultPackageVisibility = VisibilityKind.PUBLIC,
                Status = ScopeStatusKind.ACTIVE,
