            {
                Id = this.org2Id,
                Owner = this.forgeId,
                PrimaryAddress = addressId2,
                Name = "OtherOrg",
                ShortName = "other-org",
                Email = "otherorg@example.com",
                BillingEmail = "otherorg-billing@example.com",
                DefaultPackageVisibility = VisibilityKind.PRIVATE,
                Status = ScopeStatusKind.ACTIVE,
                Origin = "https://example.com",
                Administrator = [this.otherAccountId],
                Member = [this.otherAccountId]
