                this.TestLoggerFactory.CreateLogger<AddressDao>(),
                this.Serializer);

            var accountDao = new AccountDao(
                this.TestLoggerFactory.CreateLogger<AccountDao>(),
                this.Serializer);

            this.forgeId = Guid.NewGuid();

            var forge = new Forge
            {
                Id = this.forgeId,
                Name = "TestForge",
                ShortName = "test-forge",
                Description = "Test Forge"
            };

            await this.Insert(transaction => forgeDao.CreateAsync(transaction, CancellationToken.None, forge));

            var countryId = Guid.NewGuid();

            var country = new Country
            {
                Id = countryId,
                Owner = this.forgeId,
                Alpha2Code = "US",
                Alpha3Code = "USA",
                Name = "United States",
                NumericCode = "840"
            };

            await this.Insert(transaction => countryDao.CreateAsync(transaction, CancellationToken.None, country));

