namespace Mycelium.Forge.Orm.Tests.Dao
{
    using Microsoft.Extensions.Logging;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Orm.AutoGeneratedDao;
    using Mycelium.Forge.Orm.Tests.Helper;

    using NUnit.Framework;

    [TestFixture]
    [Category("Database")]
    public class CountryDaoIntegrationTestFixture : BaseIntegrationTestClassFixture
    {
        private CountryDao countryDao;
        private Guid forgeId;

        [Test]
        public async Task VerifyCreateAsync()
        {
            // Case 1: Single entity creation sets timestamps, overrides pre-set values, and persists entity data.
            var countryId = Guid.NewGuid();
            var presetTimestamp = DateTime.UtcNow.AddYears(-1);

            var country = new Country
            {
                Id = countryId,
                Owner = this.forgeId,
                Alpha2Code = "PT",
                Alpha3Code = "PRT",
                Name = "Portugal",
                NumericCode = "620",
                CreatedAt = presetTimestamp,
                ModifiedAt = presetTimestamp
            };

            await this.Insert(transaction => this.countryDao.CreateAsync(transaction, country, CancellationToken.None));

            await using (var readTransaction = await this.Connection.BeginTransactionAsync())
            {
                var readResult = await this.countryDao.ReadAsync(readTransaction, CancellationToken.None, [countryId]);
                await readTransaction.CommitAsync();

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(readResult.IsSuccess, Is.True);
                    Assert.That(readResult.Value, Has.Count.EqualTo(1));
                    Assert.That(readResult.Value[0].Name, Is.EqualTo("Portugal"));
                    Assert.That(readResult.Value[0].CreatedAt, Is.Not.Default);
                    Assert.That(readResult.Value[0].CreatedAt, Is.Not.EqualTo(presetTimestamp));
                    Assert.That(readResult.Value[0].ModifiedAt, Is.EqualTo(readResult.Value[0].CreatedAt));
                }
            }

            // Case 2: Multiple entities created within the same transaction receive identical timestamps.
            var batchCountryId1 = Guid.NewGuid();
            var batchCountryId2 = Guid.NewGuid();

            var batchCountry1 = new Country
            {
                Id = batchCountryId1,
                Owner = this.forgeId,
                Alpha2Code = "ES",
                Alpha3Code = "ESP",
                Name = "Spain",
                NumericCode = "724"
            };

            var batchCountry2 = new Country
            {
                Id = batchCountryId2,
                Owner = this.forgeId,
                Alpha2Code = "IT",
                Alpha3Code = "ITA",
                Name = "Italy",
                NumericCode = "380"
            };

            await using (var batchTransaction = await this.Connection.BeginTransactionAsync())
            {
                var createResult1 = await this.countryDao.CreateAsync(batchTransaction, batchCountry1, CancellationToken.None);
                var createResult2 = await this.countryDao.CreateAsync(batchTransaction, batchCountry2, CancellationToken.None);
                await batchTransaction.CommitAsync();

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(createResult1.IsSuccess, Is.True);
                    Assert.That(createResult2.IsSuccess, Is.True);
                }
            }

            await using (var batchReadTransaction = await this.Connection.BeginTransactionAsync())
            {
                var batchReadResult = await this.countryDao.ReadAsync(batchReadTransaction, CancellationToken.None, [batchCountryId1, batchCountryId2]);
                await batchReadTransaction.CommitAsync();

                var read1 = batchReadResult.Value.Single(c => c.Id == batchCountryId1);
                var read2 = batchReadResult.Value.Single(c => c.Id == batchCountryId2);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(read1.CreatedAt, Is.EqualTo(read2.CreatedAt));
                    Assert.That(read1.ModifiedAt, Is.EqualTo(read2.ModifiedAt));
                }
            }
        }

        [Test]
        public async Task VerifyUpdateAsync()
        {
            // Case 1: Updating an entity bumps ModifiedAt while CreatedAt remains immutable.
            var countryId = Guid.NewGuid();

            var country = new Country
            {
                Id = countryId,
                Owner = this.forgeId,
                Alpha2Code = "DE",
                Alpha3Code = "DEU",
                Name = "Germany",
                NumericCode = "276"
            };

            await this.Insert(transaction => this.countryDao.CreateAsync(transaction, country, CancellationToken.None));

            await Task.Delay(50);

            country.Name = "Federal Republic of Germany";
            country.CreatedAt = DateTime.UtcNow.AddYears(-5);

            await using (var updateTransaction = await this.Connection.BeginTransactionAsync())
            {
                var updateResult = await this.countryDao.UpdateAsync(updateTransaction, country, CancellationToken.None);
                await updateTransaction.CommitAsync();

                Assert.That(updateResult.IsSuccess, Is.True);
            }

            await using (var readTransaction = await this.Connection.BeginTransactionAsync())
            {
                var readResult = await this.countryDao.ReadAsync(readTransaction, CancellationToken.None, [countryId]);
                await readTransaction.CommitAsync();

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(readResult.Value[0].Name, Is.EqualTo("Federal Republic of Germany"));
                    Assert.That(readResult.Value[0].CreatedAt, Is.Not.EqualTo(country.CreatedAt));
                    Assert.That(readResult.Value[0].ModifiedAt, Is.GreaterThan(readResult.Value[0].CreatedAt));
                }
            }

            await Task.Delay(50);

            // Case 2: No-op update with unchanged data does not bump ModifiedAt.
            var noOpCountryId = Guid.NewGuid();

            var noOpCountry = new Country
            {
                Id = noOpCountryId,
                Owner = this.forgeId,
                Alpha2Code = "NL",
                Alpha3Code = "NLD",
                Name = "Netherlands",
                NumericCode = "528"
            };

            await this.Insert(transaction => this.countryDao.CreateAsync(transaction, noOpCountry, CancellationToken.None));

            ICountry createdNoOpCountry;

            await using (var readTransaction = await this.Connection.BeginTransactionAsync())
            {
                var readResult = await this.countryDao.ReadAsync(readTransaction, CancellationToken.None, [noOpCountryId]);
                await readTransaction.CommitAsync();

                createdNoOpCountry = readResult.Value[0];
            }

            await Task.Delay(50);

            await using (var noOpTransaction = await this.Connection.BeginTransactionAsync())
            {
                var noOpResult = await this.countryDao.UpdateAsync(noOpTransaction, createdNoOpCountry, CancellationToken.None);
                await noOpTransaction.CommitAsync();

                Assert.That(noOpResult.IsSuccess, Is.True);
            }

            await using (var noOpReadTransaction = await this.Connection.BeginTransactionAsync())
            {
                var noOpReadResult = await this.countryDao.ReadAsync(noOpReadTransaction, CancellationToken.None, [noOpCountryId]);
                await noOpReadTransaction.CommitAsync();

                Assert.That(noOpReadResult.Value[0].ModifiedAt, Is.EqualTo(createdNoOpCountry.ModifiedAt));
            }

            // Case 3: Multiple entities updated within the same transaction receive identical ModifiedAt timestamps.
            var batchCountryId1 = Guid.NewGuid();
            var batchCountryId2 = Guid.NewGuid();

            var batchCountry1 = new Country
            {
                Id = batchCountryId1,
                Owner = this.forgeId,
                Alpha2Code = "FR",
                Alpha3Code = "FRA",
                Name = "France Initial",
                NumericCode = "250"
            };

            var batchCountry2 = new Country
            {
                Id = batchCountryId2,
                Owner = this.forgeId,
                Alpha2Code = "BE",
                Alpha3Code = "BEL",
                Name = "Belgium Initial",
                NumericCode = "056"
            };

            await this.Insert(transaction => this.countryDao.CreateAsync(transaction, batchCountry1, CancellationToken.None));
            await this.Insert(transaction => this.countryDao.CreateAsync(transaction, batchCountry2, CancellationToken.None));

            await Task.Delay(50);

            batchCountry1.Name = "France Updated";
            batchCountry2.Name = "Belgium Updated";

            await using (var batchUpdateTransaction = await this.Connection.BeginTransactionAsync())
            {
                var updateResult1 = await this.countryDao.UpdateAsync(batchUpdateTransaction, batchCountry1, CancellationToken.None);
                var updateResult2 = await this.countryDao.UpdateAsync(batchUpdateTransaction, batchCountry2, CancellationToken.None);
                await batchUpdateTransaction.CommitAsync();

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(updateResult1.IsSuccess, Is.True);
                    Assert.That(updateResult2.IsSuccess, Is.True);
                }
            }

            await using (var batchReadTransaction = await this.Connection.BeginTransactionAsync())
            {
                var batchReadResult = await this.countryDao.ReadAsync(batchReadTransaction, CancellationToken.None, [batchCountryId1, batchCountryId2]);
                await batchReadTransaction.CommitAsync();

                var read1 = batchReadResult.Value.Single(c => c.Id == batchCountryId1);
                var read2 = batchReadResult.Value.Single(c => c.Id == batchCountryId2);

                Assert.That(read1.ModifiedAt, Is.EqualTo(read2.ModifiedAt));
            }
        }

        protected override async Task PostSetup()
        {
            this.countryDao = new CountryDao(this.TestLoggerFactory.CreateLogger<CountryDao>(), this.Serializer);
            var forgeDao = new ForgeDao(this.TestLoggerFactory.CreateLogger<ForgeDao>(), this.Serializer);
            this.forgeId = Guid.NewGuid();

            var forge = new Forge
            {
                Id = this.forgeId,
                Name = "TestForge",
                ShortName = "test-forge",
                Description = "Test Forge"
            };

            await this.Insert(transaction => forgeDao.CreateAsync(transaction, forge, CancellationToken.None));
        }
    }
