namespace Mycelium.Forge.Orm.Tests.Filters
{
    using Mycelium.Forge.Common;
    using Mycelium.Forge.Orm.AutoGeneratedFilters;

    using Npgsql;

    using NUnit.Framework;

    [TestFixture]
    public class PackageInvitationReadFilterTestFixture
    {
        private Guid userId;
        private UserContext anonymousUserContext;
        private UserContext accountUserContext;
        private UserContext adminUserContext;

        [SetUp]
        public void SetUp()
        {
            this.userId = Guid.NewGuid();

            this.anonymousUserContext = new UserContext
            {
                AccountId = null,
                Username = string.Empty,
                CurrentRoles = [RoleKind.Anonymous]
            };

            this.accountUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "testUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.adminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "adminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator]
            };
        }

        [Test]
        public void VerifyFromUserContext()
        {
            var readFilter = new PackageInvitationReadFilter();
            var anonymousFilter = readFilter.FromUserContext(this.anonymousUserContext);
            var accountFilter = readFilter.FromUserContext(this.accountUserContext);
            var adminFilter = readFilter.FromUserContext(this.adminUserContext);

            using var anonymousCommand = new NpgsqlCommand();
            anonymousFilter.ApplyParameters(anonymousCommand);

            using var accountCommand = new NpgsqlCommand();
            accountFilter.ApplyParameters(accountCommand);

            using var adminCommand = new NpgsqlCommand();
            adminFilter.ApplyParameters(adminCommand);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(anonymousFilter.ToSqlPredicate(), Does.Contain("package_invitation.owner = @callerAccountId"));
                Assert.That(anonymousFilter.ToSqlPredicate(), Does.Contain("package_invitation.target = @callerAccountId"));
                Assert.That(anonymousFilter.ToSqlPredicate(), Does.Contain("forge.package_package_owner__account"));
                Assert.That(anonymousFilter.ToSqlPredicate(), Does.Not.Contain("forge.package_package_maintainer__account"));
                Assert.That(anonymousCommand.Parameters["@callerAccountId"].Value, Is.EqualTo(DBNull.Value));
                Assert.That(anonymousCommand.Parameters["@canManagePackageTeam"].Value, Is.EqualTo(false));

                Assert.That(accountCommand.Parameters["@callerAccountId"].Value, Is.EqualTo(this.userId));
                Assert.That(accountCommand.Parameters["@canManagePackageTeam"].Value, Is.EqualTo(false));

                Assert.That(adminCommand.Parameters["@callerAccountId"].Value, Is.EqualTo(this.userId));
                Assert.That(adminCommand.Parameters["@canManagePackageTeam"].Value, Is.EqualTo(true));
            }
        }
    }
}
