    /// <summary>
    /// Integration test suite for <see cref="PackageMetaDataService" /> verifying end-to-end read behavior
    /// against a real PostgreSQL instance provided by Testcontainers.
    /// </summary>
    [TestFixture]
    [Category("Database")]
    public class PackageMetaDataServiceIntegrationTestFixture : BaseIntegrationTestClassFixture
    {
        private PackageMetaDataService service;
        private PackageVersionService packageVersionService;
        private IUserContext anonymousUserContext;
        private IUserContext sameOrgMemberUserContext;
        private IUserContext otherOrgMemberUserContext;
        private IUserContext packageOwnerUserContext;
        private IUserContext appAdminUserContext;
        private Guid publicPackageMetaDataId;
        private Guid internalPackageMetaDataId;
        private Guid privatePackageMetaDataId;
        private Guid privatePackageVersionId;

        /// <summary>
        /// Verifies that <see cref="PackageMetaDataService.ReadAsync(IUserContext, CancellationToken, Guid[])" />
        /// enforces visibility rules across public, internal, and private packages for different caller roles.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyReadAsync()
        {
            var anonPublicResult = await this.service.ReadAsync(this.anonymousUserContext, CancellationToken.None, [this.publicPackageMetaDataId]);
            var memberPublicResult = await this.service.ReadAsync(this.sameOrgMemberUserContext, CancellationToken.None, [this.publicPackageMetaDataId]);

            var anonInternalResult = await this.service.ReadAsync(this.anonymousUserContext, CancellationToken.None, [this.internalPackageMetaDataId]);
            var otherOrgInternalResult = await this.service.ReadAsync(this.otherOrgMemberUserContext, CancellationToken.None, [this.internalPackageMetaDataId]);
            var sameOrgInternalResult = await this.service.ReadAsync(this.sameOrgMemberUserContext, CancellationToken.None, [this.internalPackageMetaDataId]);

            var sameOrgPrivateResult = await this.service.ReadAsync(this.sameOrgMemberUserContext, CancellationToken.None, [this.privatePackageMetaDataId]);
            var sameOrgPrivateVersionResult = await this.packageVersionService.ReadAsync(this.sameOrgMemberUserContext, CancellationToken.None, [this.privatePackageVersionId]);

            var ownerPrivateResult = await this.service.ReadAsync(this.packageOwnerUserContext, CancellationToken.None, [this.privatePackageMetaDataId]);
            var ownerPrivateVersionResult = await this.packageVersionService.ReadAsync(this.packageOwnerUserContext, CancellationToken.None, [this.privatePackageVersionId]);

            var appAdminPrivateResult = await this.service.ReadAsync(this.appAdminUserContext, CancellationToken.None, [this.privatePackageMetaDataId]);
            var appAdminPrivateVersionResult = await this.packageVersionService.ReadAsync(this.appAdminUserContext, CancellationToken.None, [this.privatePackageVersionId]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(anonPublicResult.IsSuccess, Is.True);
                Assert.That(anonPublicResult.Value, Has.Count.EqualTo(1));
                Assert.That(anonPublicResult.Value[0].Id, Is.EqualTo(this.publicPackageMetaDataId));

                Assert.That(memberPublicResult.IsSuccess, Is.True);
                Assert.That(memberPublicResult.Value, Has.Count.EqualTo(1));
                Assert.That(memberPublicResult.Value[0].Id, Is.EqualTo(this.publicPackageMetaDataId));

                Assert.That(anonInternalResult.IsSuccess, Is.True);
                Assert.That(anonInternalResult.Value, Has.Count.EqualTo(0));

                Assert.That(otherOrgInternalResult.IsSuccess, Is.True);
                Assert.That(otherOrgInternalResult.Value, Has.Count.EqualTo(0));

                Assert.That(sameOrgInternalResult.IsSuccess, Is.True);
                Assert.That(sameOrgInternalResult.Value, Has.Count.EqualTo(1));
                Assert.That(sameOrgInternalResult.Value[0].Id, Is.EqualTo(this.internalPackageMetaDataId));

                Assert.That(sameOrgPrivateResult.IsSuccess, Is.True);
                Assert.That(sameOrgPrivateResult.Value, Has.Count.EqualTo(0));

                Assert.That(sameOrgPrivateVersionResult.IsSuccess, Is.True);
                Assert.That(sameOrgPrivateVersionResult.Value, Has.Count.EqualTo(0));

                Assert.That(ownerPrivateResult.IsSuccess, Is.True);
                Assert.That(ownerPrivateResult.Value, Has.Count.EqualTo(1));
                Assert.That(ownerPrivateResult.Value[0].Id, Is.EqualTo(this.privatePackageMetaDataId));

                Assert.That(ownerPrivateVersionResult.IsSuccess, Is.True);
                Assert.That(ownerPrivateVersionResult.Value, Has.Count.EqualTo(1));
                Assert.That(ownerPrivateVersionResult.Value[0].Id, Is.EqualTo(this.privatePackageVersionId));

                Assert.That(appAdminPrivateResult.IsSuccess, Is.True);
                Assert.That(appAdminPrivateResult.Value, Has.Count.EqualTo(1));
                Assert.That(appAdminPrivateResult.Value[0].Id, Is.EqualTo(this.privatePackageMetaDataId));

                Assert.That(appAdminPrivateVersionResult.IsSuccess, Is.True);
                Assert.That(appAdminPrivateVersionResult.Value, Has.Count.EqualTo(1));
                Assert.That(appAdminPrivateVersionResult.Value[0].Id, Is.EqualTo(this.privatePackageVersionId));
            }
        }

        /// <summary>
        /// Wires up DAOs, the services under test, user contexts, and prerequisite database records before each test.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        protected override async Task PostSetup()
        {
            var databaseSourceMock = new Mock<IDatabaseSource>();

            databaseSourceMock
                .Setup(x => x.OpenNewConnectionAsync(It.IsAny<CancellationToken>()))
                .Returns(async () =>
                {
                    var connection = new NpgsqlConnection(this.ConnectionString);
                    await connection.OpenAsync();
                    return connection;
                });

            var organizationDao = new OrganizationDao(
                this.TestLoggerFactory.CreateLogger<OrganizationDao>(),
                this.Serializer);

            var orgPermissionService = new OrganizationPermissionService();

            var organizationService = new OrganizationService(
                organizationDao,
                new OrganizationValidator(),
                orgPermissionService,
                new OrganizationComparer(),
                this.TestLoggerFactory.CreateLogger<OrganizationService>(),
                databaseSourceMock.Object);

            var packageDao = new PackageDao(
                this.TestLoggerFactory.CreateLogger<PackageDao>(),
                this.Serializer);

            var packagePermissionService = new PackagePermissionService(organizationService);

            var packageService = new PackageService(
                packageDao,
                new PackageValidator(),
                packagePermissionService,
                new PackageComparer(),
                this.TestLoggerFactory.CreateLogger<PackageService>(),
                databaseSourceMock.Object);

            var packageVersionDao = new PackageVersionDao(
                this.TestLoggerFactory.CreateLogger<PackageVersionDao>(),
                this.Serializer);

            var packageVersionPermissionService = new PackageVersionPermissionService(packageService, packagePermissionService);

            this.packageVersionService = new PackageVersionService(
                packageVersionDao,
                new PackageVersionValidator(),
                packageVersionPermissionService,
                new PackageVersionComparer(),
                this.TestLoggerFactory.CreateLogger<PackageVersionService>(),
                databaseSourceMock.Object);

            var packageMetaDataDao = new PackageMetaDataDao(
                this.TestLoggerFactory.CreateLogger<PackageMetaDataDao>(),
                this.Serializer);

            var packageMetaDataPermissionService = new PackageMetaDataPermissionService(this.packageVersionService, packageVersionPermissionService);

            this.service = new PackageMetaDataService(
                packageMetaDataDao,
                new PackageMetaDataValidator(),
                packageMetaDataPermissionService,
                new PackageMetaDataComparer(),
                this.TestLoggerFactory.CreateLogger<PackageMetaDataService>(),
                databaseSourceMock.Object);

            var sameOrgMemberId = Guid.NewGuid();
            var otherOrgMemberId = Guid.NewGuid();
            var orgAdminId = Guid.NewGuid();
            var appAdminId = Guid.NewGuid();

            this.anonymousUserContext = UserContext.CreateAnonymous();

            this.sameOrgMemberUserContext = new UserContext
            {
                AccountId = sameOrgMemberId,
                Username = "sameOrgMember",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationMember]
            };

            this.otherOrgMemberUserContext = new UserContext
            {
                AccountId = otherOrgMemberId,
                Username = "otherOrgMember",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationMember]
            };

            this.packageOwnerUserContext = new UserContext
            {
                AccountId = orgAdminId,
                Username = "packageOwner",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationAdministrator, RoleKind.OrganizationMember]
            };

            this.appAdminUserContext = new UserContext
            {
                AccountId = appAdminId,
                Username = "appAdmin",
                CurrentRoles = [RoleKind.InstallationAdministrator, RoleKind.Account]
            };

            await this.SeedDatabaseAsync(organizationDao, packageDao, packageVersionDao, packageMetaDataDao, sameOrgMemberId, otherOrgMemberId, orgAdminId);
        }

