        [Test]
        public async Task VerifyExtractManifestAsync()
        {
            var package = new Package();
            var packageVersion = new PackageVersion();
            var packageMetaData = new PackageMetaData();
            var content = "dummy-archive-payload"u8.ToArray();

            // Case 1: Unconfigured package type for new release returns validation error
            this.packageTypeServiceMock.Setup(x => x.ReadByNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<string[]>())).ReturnsAsync(ImmutableList<IPackageType>.Empty);

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.ExtractManifestAsync(this.userContext, stream, ArtifactKind.Kpar, "UnknownType", package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Does.Contain("Package type 'UnknownType' is not configured"));
                }
            }

            // Case 2: Configured package type but no matching extractor returns validation error
            var packageType = new PackageType { Id = Guid.NewGuid(), Name = "SysML v2" };
            this.packageTypeServiceMock.Setup(x => x.ReadByNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<string[]>())).ReturnsAsync(ImmutableList.Create<IPackageType>(packageType));
            this.manifestExtractorMock.Setup(x => x.CanHandle(ArtifactKind.Kpar)).Returns(false);

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.ExtractManifestAsync(this.userContext, stream, ArtifactKind.Kpar, "SysML v2", package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Does.Contain("No extractor configured for artifact kind"));
                }
            }

            // Case 3: Extractor returns error
            this.manifestExtractorMock.Setup(x => x.CanHandle(ArtifactKind.Kpar)).Returns(true);
            this.manifestExtractorMock.Setup(x => x.Extract(It.IsAny<Stream>())).Returns(Error.Validation(ValidationTypes.SchemaValidation, "Archive corrupted"));

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.ExtractManifestAsync(this.userContext, stream, ArtifactKind.Kpar, "SysML v2", package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Is.EqualTo("Archive corrupted"));
                }
            }

            // Case 4: Happy path for new package sets package type and applies manifest
            var manifest = new KparManifest { Name = "my-kpar", Version = "1.0.0", Description = "A kpar package" };
            this.manifestExtractorMock.Setup(x => x.Extract(It.IsAny<Stream>())).Returns(manifest);

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.ExtractManifestAsync(this.userContext, stream, ArtifactKind.Kpar, "SysML v2", package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.False);
                    Assert.That(result.Value, Is.EqualTo(manifest));
                    Assert.That(package.PackageType, Is.EqualTo(packageType.Id));
                    Assert.That(packageVersion.SizeInBytes, Is.EqualTo(content.Length));
                    Assert.That(package.Name, Is.EqualTo("my-kpar"));
                    Assert.That(packageVersion.Version, Is.EqualTo("1.0.0"));
                }
            }

            // Case 5: Happy path for existing package skips package type lookup
            var existingPackage = new Package { Id = Guid.NewGuid(), Name = "Existing", PackageType = Guid.NewGuid() };
            var existingVersion = new PackageVersion();
            var existingMetaData = new PackageMetaData();

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.ExtractManifestAsync(this.userContext, stream, ArtifactKind.Kpar, "SysML v2", existingPackage, existingVersion, existingMetaData, true);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.False);
                    this.packageTypeServiceMock.Verify(x => x.ReadByNameAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<string[]>()), Times.Exactly(4));
                }
            }
        }

        [Test]
        public async Task VerifyPublishReleaseAsync()
        {
            var scope = new Account { Id = Guid.NewGuid(), ShortName = "starion" };
            var package = new Package { Id = Guid.NewGuid(), Name = "test", ShortName = "test" };
            var packageVersion = new PackageVersion { Id = Guid.NewGuid(), Version = "1.0.0" };
            var packageMetaData = new PackageMetaData { Id = Guid.NewGuid() };
            var content = "package-archive-content"u8.ToArray();

            // Case 1: Happy path for new package stores artifact and creates records inside transaction
            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.False);
                    Assert.That(packageVersion.Checksum, Is.EqualTo("hash-12345"));
                    Assert.That(package.Owner, Is.EqualTo(scope.Id));
                    this.databaseSourceMock.Verify(x => x.DeferConstraintsAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>()), Times.Once);
                    this.packageServiceMock.Verify(x => x.CreateAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IPackage>>(), It.IsAny<CancellationToken>()), Times.Once);
                    this.packageVersionServiceMock.Verify(x => x.CreateAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IPackageVersion>>(), It.IsAny<CancellationToken>()), Times.Once);
                    this.packageMetaDataServiceMock.Verify(x => x.CreateAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IPackageMetaData>>(), It.IsAny<CancellationToken>()), Times.Once);
                }
            }

            // Case 2: Happy path for existing package skips package create and links new version ID
            this.packageServiceMock.Invocations.Clear();
            var existingPackage = new Package { Id = Guid.NewGuid(), Name = "existing", Owner = scope.Id, Version = [] };
            var newVersion = new PackageVersion { Id = Guid.NewGuid(), Version = "1.1.0" };
            var newMetaData = new PackageMetaData { Id = Guid.NewGuid() };

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, existingPackage, newVersion, newMetaData, true);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.False);
                    Assert.That(existingPackage.Version, Does.Contain(newVersion.Id));
                    this.packageServiceMock.Verify(x => x.CreateAsync(It.IsAny<IUserContext>(), It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IPackage>>(), It.IsAny<CancellationToken>()), Times.Never);
                }
            }

            // Case 3: Artifact storage failure aborts without entering DB transaction
            this.databaseSourceMock.Invocations.Clear();
            this.artifactStoreMock.Setup(x => x.StoreArtifactAsync(It.IsAny<Stream>(), It.IsAny<string>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure(description: "Storage unavailable"));

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Is.EqualTo("Storage unavailable"));
                    this.databaseSourceMock.Verify(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Success>>>>(), It.IsAny<CancellationToken>()), Times.Never);
                }
            }

            // Case 4: DB transaction failure rolls back newly stored artifact
            this.artifactStoreMock.Invocations.Clear();
            this.artifactStoreMock.Setup(x => x.StoreArtifactAsync(It.IsAny<Stream>(), It.IsAny<string>(), It.IsAny<CancellationToken>())).ReturnsAsync(("hash-12345", true));
            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Success>>>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure(description: "DB deadlocked"));

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Is.EqualTo("DB deadlocked"));
                    this.artifactStoreMock.Verify(x => x.DeleteArtifactAsync("hash-12345", It.IsAny<CancellationToken>()), Times.Once);
                }
            }

            // Case 5: DB transaction failure with deduplicated (non-new) artifact does NOT delete artifact
            this.artifactStoreMock.Setup(x => x.StoreArtifactAsync(It.IsAny<Stream>(), It.IsAny<string>(), It.IsAny<CancellationToken>())).ReturnsAsync(("hash-deduped", false));

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    this.artifactStoreMock.Verify(x => x.DeleteArtifactAsync("hash-deduped", It.IsAny<CancellationToken>()), Times.Never);
                }
            }

            // Case 6: Exception during publication logs error, deletes newly stored artifact, and returns failure
            this.artifactStoreMock.Setup(x => x.StoreArtifactAsync(It.IsAny<Stream>(), It.IsAny<string>(), It.IsAny<CancellationToken>())).ReturnsAsync(("hash-throw", true));
            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Success>>>>(), It.IsAny<CancellationToken>())).ThrowsAsync(new InvalidOperationException("Connection broken"));

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Is.EqualTo("Connection broken"));
                    this.artifactStoreMock.Verify(x => x.DeleteArtifactAsync("hash-throw", It.IsAny<CancellationToken>()), Times.Once);
                }
            }

            // Case 7: Exception during publication with deduplicated artifact does not delete artifact
            this.artifactStoreMock.Setup(x => x.StoreArtifactAsync(It.IsAny<Stream>(), It.IsAny<string>(), It.IsAny<CancellationToken>())).ReturnsAsync(("hash-throw-deduped", false));
            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Success>>>>(), It.IsAny<CancellationToken>())).ThrowsAsync(new InvalidOperationException("Connection broken"));

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Is.EqualTo("Connection broken"));
                    this.artifactStoreMock.Verify(x => x.DeleteArtifactAsync("hash-throw-deduped", It.IsAny<CancellationToken>()), Times.Never);
                }
            }

            // Case 8: Entity creation failure inside transaction aborts and rolls back newly stored artifact
            this.artifactStoreMock.Setup(x => x.StoreArtifactAsync(It.IsAny<Stream>(), It.IsAny<string>(), It.IsAny<CancellationToken>())).ReturnsAsync(("hash-entity-fail", true));
            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Success>>>>(), It.IsAny<CancellationToken>())).Returns<Func<NpgsqlTransaction, Task<ErrorOr<Success>>>, CancellationToken>((action, _) => action(null!));
            this.packageServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IPackage>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure(description: "Package insert failed"));

            using (var stream = new MemoryStream(content))
            {
                var result = await this.service.PublishReleaseAsync(this.userContext, stream, scope, package, packageVersion, packageMetaData, false);

                using (Assert.EnterMultipleScope())
                {
                    Assert.That(result.IsError, Is.True);
                    Assert.That(result.FirstError.Description, Is.EqualTo("Package insert failed"));
                    this.artifactStoreMock.Verify(x => x.DeleteArtifactAsync("hash-entity-fail", It.IsAny<CancellationToken>()), Times.Once);
                }
            }
        }

        [Test]
        public async Task VerifyValidateReleaseAsync()
        {
            var scope = new Account { Id = Guid.NewGuid(), ShortName = "starion" };
            var package = new Package { Name = "sysml-core", ShortName = "sysml-core", License = "MIT" };
            var packageVersion = new PackageVersion { Version = "1.0.0" };

            // Case 1: Pre-validation errors short-circuit and convert to failed checks
            var preErrors = new List<Error> { Error.Validation("PreCheck", "Format invalid") };
            var preResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, false, [], preErrors);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(preResult, Has.Count.EqualTo(1));
                Assert.That(preResult[0].Status, Is.EqualTo(ValidationStatus.Fail));
                Assert.That(preResult[0].Detail, Is.EqualTo("Format invalid"));
            }

            // Case 2: Existing package with duplicate version returns fail
            packageVersion.Version = "1.0.0";
            var dupResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, true, ["1.0.0"]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(dupResult.Any(x => x.Title == ValidationTypes.PackageVersion && x.Status == ValidationStatus.Fail), Is.True);
                Assert.That(dupResult.First(x => x.Title == ValidationTypes.PackageVersion).Detail, Does.Contain("already exists"));
            }

            // Case 3: Existing package with version strictly lower returns fail
            packageVersion.Version = "0.9.0";
            var lowerResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, true, ["1.0.0"]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(lowerResult.Any(x => x.Title == ValidationTypes.PackageVersion && x.Status == ValidationStatus.Fail), Is.True);
                Assert.That(lowerResult.First(x => x.Title == ValidationTypes.PackageVersion).Detail, Does.Contain("must be strictly greater"));
            }

            // Case 4: Major bump without release notes returns fail
            packageVersion.Version = "2.0.0";
            packageVersion.ReleaseNotes = string.Empty;
            var majorNoNotesResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, true, ["1.0.0"]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(majorNoNotesResult.Any(x => x.Title == ValidationTypes.PackageVersion && x.Status == ValidationStatus.Fail), Is.True);
                Assert.That(majorNoNotesResult.First(x => x.Title == ValidationTypes.PackageVersion).Detail, Does.Contain("major-version update requires release notes"));
            }

            // Case 5: Major bump with release notes passes
            packageVersion.ReleaseNotes = "Breaking changes included.";
            var majorWithNotesResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, true, ["1.0.0"]);
            Assert.That(majorWithNotesResult.All(x => x.Status == ValidationStatus.Pass), Is.True);

            // Case 6: New package with coordinate collision returns namespace fail
            this.packageServiceMock.Setup(x => x.ReadByCoordinateAsync(this.userContext, "starion", "sysml-core", true, It.IsAny<CancellationToken>())).ReturnsAsync(new Package { Id = Guid.NewGuid() });

            var collisionResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, false, []);
            Assert.That(collisionResult.Any(x => x.Title == ValidationTypes.NamespaceUniqueness && x.Status == ValidationStatus.Fail), Is.True);

            // Case 7: New package without license produces warning
            package.License = string.Empty;
            this.packageServiceMock.Setup(x => x.ReadByCoordinateAsync(this.userContext, "starion", "sysml-core", true, It.IsAny<CancellationToken>())).ReturnsAsync(Error.NotFound());

            var noLicenseResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, false, []);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(noLicenseResult.Any(x => x.Title == ValidationTypes.License && x.Status == ValidationStatus.Warning), Is.True);
                Assert.That(noLicenseResult.Any(x => x.Title == ValidationTypes.NamespaceUniqueness && x.Status == ValidationStatus.Pass), Is.True);
            }

            // Case 8: New package with license produces license pass
            package.License = "Apache-2.0";
            var withLicenseResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, false, []);
            Assert.That(withLicenseResult.Any(x => x.Title == ValidationTypes.License && x.Status == ValidationStatus.Pass), Is.True);

            // Case 9: Minor version bump without release notes passes
            packageVersion.Version = "1.1.0";
            packageVersion.ReleaseNotes = string.Empty;
            var minorNoNotesResult = await this.service.ValidateReleaseAsync(this.userContext, scope, package, packageVersion, true, ["1.0.0"]);
            Assert.That(minorNoNotesResult.Any(x => x.Title == ValidationTypes.PackageVersion && x.Status == ValidationStatus.Pass), Is.True);
        }
