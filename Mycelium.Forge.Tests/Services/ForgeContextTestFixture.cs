namespace Mycelium.Forge.Tests.Services
{
    using System;
    using System.Collections.Immutable;
    using System.Linq;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Services;

    [TestFixture]
    public class ForgeContextTestFixture
    {
        private Mock<IForgeService> forgeServiceMock;
        private Mock<ILogger<ForgeContext>> loggerMock;
        private ForgeContext forgeContext;
        private Forge testForge;

        [SetUp]
        public void SetUp()
        {
            this.forgeServiceMock = new Mock<IForgeService>();
            this.loggerMock = new Mock<ILogger<ForgeContext>>();
            this.testForge = new Forge { Id = Guid.NewGuid() };

            this.forgeContext = new ForgeContext(this.forgeServiceMock.Object, this.loggerMock.Object);
        }

        [Test]
        public void VerifyConstructor()
        {
            using (Assert.EnterMultipleScope())
            {
                Assert.That(() => new ForgeContext(null, this.loggerMock.Object), Throws.ArgumentNullException);
                Assert.That(() => new ForgeContext(this.forgeServiceMock.Object, null), Throws.ArgumentNullException);
            }
        }

        [Test]
        public async Task VerifyInitializeAsync()
        {
            // Scenario 1: Forge service returns an error
            this.forgeServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(Error.Failure("Service error"));

            var failureEx = Assert.ThrowsAsync<InvalidOperationException>(() => this.forgeContext.InitializeAsync(CancellationToken.None));

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureEx.Message, Does.Contain("Failed to initialize Forge context: no Forge instance found."));
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 2: Forge service returns empty list
            this.forgeServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList<IForge>.Empty);

            var emptyEx = Assert.ThrowsAsync<InvalidOperationException>(() => this.forgeContext.InitializeAsync(CancellationToken.None));
            Assert.That(emptyEx.Message, Does.Contain("Failed to initialize Forge context: no Forge instance found."));

            // Scenario 3: Happy path - successful initialization with logger enabled
            this.loggerMock.Setup(x => x.IsEnabled(LogLevel.Information)).Returns(true);
            this.forgeServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IForge>(this.testForge));

            await this.forgeContext.InitializeAsync(CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.forgeContext.ForgeId, Is.EqualTo(this.testForge.Id));
                this.loggerMock.Verify(x => x.Log(LogLevel.Information, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 4: Already initialized - returns early without calling ReadAsync again
            await this.forgeContext.InitializeAsync(CancellationToken.None);
            this.forgeServiceMock.Verify(x => x.ReadAsync(It.Is<IUserContext>(u => u.AccountId == Guid.Empty && u.Username == "system" && u.CurrentRoles.Contains(RoleKind.InstallationAdministrator)), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()), Times.Exactly(3));
        }
    }
}
