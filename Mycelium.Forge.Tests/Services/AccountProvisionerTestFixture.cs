namespace Mycelium.Forge.Tests.Services
{
    using System;
    using System.Collections.Generic;
    using System.Collections.Immutable;
    using System.Linq;
    using System.Security.Claims;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Data;
    using Mycelium.Forge.Services;

    [TestFixture]
    public class AccountProvisionerTestFixture
    {
        private Mock<IAccountService> accountServiceMock;
        private Mock<IForgeContext> forgeContextMock;
        private Mock<ILogger<AccountProvisioner>> loggerMock;
        private AccountProvisioner provisioner;

        [SetUp]
        public void SetUp()
        {
            this.accountServiceMock = new Mock<IAccountService>();
            this.forgeContextMock = new Mock<IForgeContext>();
            this.loggerMock = new Mock<ILogger<AccountProvisioner>>();

            this.forgeContextMock.Setup(context => context.ForgeId).Returns(Guid.NewGuid());

            this.provisioner = new AccountProvisioner(this.accountServiceMock.Object, this.forgeContextMock.Object, this.loggerMock.Object);
        }

        [Test]
        public async Task VerifyProvisionAsync()
        {
            // Case 1: Unauthenticated or invalid claims principal (fail)
            var invalidPrincipal = new ClaimsPrincipal(new ClaimsIdentity());
            var invalidResult = await this.provisioner.ProvisionAsync(invalidPrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(invalidResult.IsError, Is.True);
                Assert.That(invalidResult.FirstError.Code, Is.EqualTo("Account.InvalidClaims"));
            }

            // Case 2: Existing account in database (success)
            var userId = Guid.NewGuid();

            var validClaims = new List<Claim>
            {
                new("sub", userId.ToString()),
                new("preferred_username", "johndoe"),
                new("email", "john@example.com"),
                new("given_name", "John"),
                new("family_name", "Doe")
            };

            var validPrincipal = new ClaimsPrincipal(new ClaimsIdentity(validClaims, "OIDC"));

            this.accountServiceMock
                .Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == userId)))
                .ReturnsAsync(ImmutableList.Create<IAccount>(SeedData.RegisAccount));

            var existingResult = await this.provisioner.ProvisionAsync(validPrincipal, CancellationToken.None);
            Assert.That(existingResult.IsError, Is.False);

            // Case 3: New account not in database (success)
            var newUserId = Guid.NewGuid();

            var newClaims = new List<Claim>
            {
                new("sub", newUserId.ToString()),
                new("preferred_username", "newuser"),
                new("email", "newuser@example.com"),
                new("given_name", "New"),
                new("family_name", "User")
            };

            var newPrincipal = new ClaimsPrincipal(new ClaimsIdentity(newClaims, "OIDC"));

            this.accountServiceMock
                .Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == newUserId)))
                .ReturnsAsync(ImmutableList<IAccount>.Empty);

            this.accountServiceMock
                .Setup(service => service.CreateAsync(It.IsAny<IUserContext>(), It.Is<IEnumerable<IAccount>>(accounts => accounts.Any(a => a.ShortName == "newuser" && a.Name == "New User")), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Created);

            var createdResult = await this.provisioner.ProvisionAsync(newPrincipal, CancellationToken.None);
            Assert.That(createdResult.IsError, Is.False);

            // Case 4: Database read failure (fail)
            var failureUserId = Guid.NewGuid();

            var failureClaims = new List<Claim>
            {
                new("sub", failureUserId.ToString()),
                new("preferred_username", "failuser"),
                new("email", "fail@example.com")
            };

            var failurePrincipal = new ClaimsPrincipal(new ClaimsIdentity(failureClaims, "OIDC"));

            this.accountServiceMock
                .Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == failureUserId)))
                .ReturnsAsync(Error.Failure("Database.Error", "Database read failed"));

            var failureResult = await this.provisioner.ProvisionAsync(failurePrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureResult.IsError, Is.True);
                Assert.That(failureResult.FirstError.Code, Is.EqualTo("Database.Error"));
            }

            // Case 5: Database account creation failure (fail)
            var createFailureUserId = Guid.NewGuid();

            var createFailureClaims = new List<Claim>
            {
                new("sub", createFailureUserId.ToString()),
                new("preferred_username", "createfail"),
                new("email", "createfail@example.com")
            };

            var createFailurePrincipal = new ClaimsPrincipal(new ClaimsIdentity(createFailureClaims, "OIDC"));

            this.accountServiceMock
                .Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == createFailureUserId)))
                .ReturnsAsync(ImmutableList<IAccount>.Empty);

            this.accountServiceMock
                .Setup(service => service.CreateAsync(It.IsAny<IUserContext>(), It.Is<IEnumerable<IAccount>>(accounts => accounts.Any(a => a.ShortName == "createfail")), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Conflict("Account.Duplicate", "Account already exists"));

            var createFailureResult = await this.provisioner.ProvisionAsync(createFailurePrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(createFailureResult.IsError, Is.True);
                Assert.That(createFailureResult.FirstError.Code, Is.EqualTo("Account.Duplicate"));
            }
        }
    }
}
