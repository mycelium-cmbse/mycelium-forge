namespace Mycelium.Forge.Tests.Services
{
    using System;
    using System.Collections.Generic;
    using System.Collections.Immutable;
    using System.Linq;
    using System.Security.Claims;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Services;

    [TestFixture]
    public class AccountProvisionerTestFixture
    {
        private Mock<IAccountService> accountServiceMock;
        private Mock<IForgeContext> forgeContextMock;
        private Mock<ILogger<AccountProvisioner>> loggerMock;
        private AccountProvisioner provisioner;

        [SetUp]
        public void SetUp()
        {
            this.accountServiceMock = new Mock<IAccountService>();
            this.forgeContextMock = new Mock<IForgeContext>();
            this.loggerMock = new Mock<ILogger<AccountProvisioner>>();

            this.forgeContextMock.Setup(context => context.ForgeId).Returns(Guid.NewGuid());

            this.provisioner = new AccountProvisioner(this.accountServiceMock.Object, this.forgeContextMock.Object, this.loggerMock.Object);
        }

        [Test]
        public async Task VerifyProvisionAsync()
        {
            // Case 1: Unauthenticated or invalid claims principal (fail)
            var invalidPrincipal = new ClaimsPrincipal(new ClaimsIdentity());
            var invalidResult = await this.provisioner.ProvisionAsync(invalidPrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(invalidResult.IsError, Is.True);
                Assert.That(invalidResult.FirstError.Code, Is.EqualTo("Account.InvalidClaims"));
            }

            // Case 2: Existing account already matches claims (success, no update)
            var userId = Guid.NewGuid();

            var validClaims = new List<Claim>
            {
                new("sub", userId.ToString()),
                new("preferred_username", "johndoe"),
                new("email", "john@example.com"),
                new("given_name", "John"),
                new("family_name", "Doe")
            };

            var validPrincipal = new ClaimsPrincipal(new ClaimsIdentity(validClaims, "OIDC"));
            var matchingAccount = new Account { Id = userId, ShortName = "johndoe", Name = "John Doe", Email = "john@example.com" };

            this.accountServiceMock.Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == userId))).ReturnsAsync(ImmutableList.Create<IAccount>(matchingAccount));

            var existingResult = await this.provisioner.ProvisionAsync(validPrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(existingResult.IsError, Is.False);
                this.accountServiceMock.Verify(service => service.UpdateAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<IAccount>>(), It.IsAny<CancellationToken>()), Times.Never());
            }

            // Case 2b: Existing account differs in Name and Email, ShortName must remain unchanged (success, updates)
            var syncUserId = Guid.NewGuid();
            var existingOutdated = new Account { Id = syncUserId, ShortName = "original-short", Name = "Old Name", Email = "old@example.com" };

            var syncClaims = new List<Claim>
            {
                new("sub", syncUserId.ToString()),
                new("preferred_username", "changed-short"),
                new("email", "new@example.com"),
                new("given_name", "Jane"),
                new("family_name", "Doe")
            };

            var syncPrincipal = new ClaimsPrincipal(new ClaimsIdentity(syncClaims, "OIDC"));
            IEnumerable<IAccount> capturedUpdated = [];

            this.accountServiceMock.Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == syncUserId))).ReturnsAsync(ImmutableList.Create<IAccount>(existingOutdated));
            this.accountServiceMock.Setup(service => service.UpdateAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<IAccount>>(), It.IsAny<CancellationToken>())).Callback<IUserContext, IEnumerable<IAccount>, CancellationToken>((_, accounts, _) => capturedUpdated = accounts).ReturnsAsync(Result.Updated);

            var syncResult = await this.provisioner.ProvisionAsync(syncPrincipal, CancellationToken.None);
            var syncedAccount = capturedUpdated.Single();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(syncResult.IsError, Is.False);
                Assert.That(syncedAccount.Name, Is.EqualTo("Jane Doe"));
                Assert.That(syncedAccount.Email, Is.EqualTo("new@example.com"));
                Assert.That(syncedAccount.ShortName, Is.EqualTo("original-short"));
                this.accountServiceMock.Verify(service => service.UpdateAsync(It.IsAny<IUserContext>(), It.Is<IEnumerable<IAccount>>(accounts => accounts.Any(a => a.Id == syncUserId)), It.IsAny<CancellationToken>()), Times.Once());
            }

            // Case 2c: Empty given_name/family_name falls back to "name" claim (success, updates)
            var fallbackUserId = Guid.NewGuid();
            var fallbackExisting = new Account { Id = fallbackUserId, ShortName = "fallback", Name = "Old Name", Email = "fallback@example.com" };

            var fallbackClaims = new List<Claim>
            {
                new("sub", fallbackUserId.ToString()),
                new("preferred_username", "fallback"),
                new("email", "fallback@example.com"),
                new("name", "Fallback Display")
            };

            var fallbackPrincipal = new ClaimsPrincipal(new ClaimsIdentity(fallbackClaims, "OIDC"));
            IEnumerable<IAccount> capturedFallback = [];

            this.accountServiceMock.Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == fallbackUserId))).ReturnsAsync(ImmutableList.Create<IAccount>(fallbackExisting));
            this.accountServiceMock.Setup(service => service.UpdateAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<IAccount>>(), It.IsAny<CancellationToken>())).Callback<IUserContext, IEnumerable<IAccount>, CancellationToken>((_, accounts, _) => capturedFallback = accounts).ReturnsAsync(Result.Updated);

            var fallbackResult = await this.provisioner.ProvisionAsync(fallbackPrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(fallbackResult.IsError, Is.False);
                Assert.That(capturedFallback.Single().Name, Is.EqualTo("Fallback Display"));
            }

            // Case 2d: All name claims empty preserves existing Name while updating Email (success, updates)
            var preserveNameUserId = Guid.NewGuid();
            var preserveExisting = new Account { Id = preserveNameUserId, ShortName = "preserve", Name = "Existing Name", Email = "old@example.com" };

            var preserveClaims = new List<Claim>
            {
                new("sub", preserveNameUserId.ToString()),
                new("preferred_username", "preserve"),
                new("email", "updated@example.com")
            };

            var preservePrincipal = new ClaimsPrincipal(new ClaimsIdentity(preserveClaims, "OIDC"));
            IReadOnlyList<IAccount> capturedPreserved = [];

            this.accountServiceMock.Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == preserveNameUserId))).ReturnsAsync(ImmutableList.Create<IAccount>(preserveExisting));
            this.accountServiceMock.Setup(service => service.UpdateAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<IAccount>>(), It.IsAny<CancellationToken>())).Callback<IUserContext, IEnumerable<IAccount>, CancellationToken>((_, accounts, _) => capturedPreserved = accounts?.ToList() ?? []).ReturnsAsync(Result.Updated);

            var preserveResult = await this.provisioner.ProvisionAsync(preservePrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(preserveResult.IsError, Is.False);
                Assert.That(capturedPreserved.Single().Name, Is.EqualTo("Existing Name"));
                Assert.That(capturedPreserved.Single().Email, Is.EqualTo("updated@example.com"));
            }

            // Case 2e: UpdateAsync failure during JIT sync (fail)
            var updateFailUserId = Guid.NewGuid();
            var updateFailExisting = new Account { Id = updateFailUserId, ShortName = "updatefail", Name = "Old", Email = "old@example.com" };

            var updateFailClaims = new List<Claim>
            {
                new("sub", updateFailUserId.ToString()),
                new("preferred_username", "updatefail"),
                new("email", "new@example.com"),
                new("given_name", "New"),
                new("family_name", "Name")
            };

            var updateFailPrincipal = new ClaimsPrincipal(new ClaimsIdentity(updateFailClaims, "OIDC"));

            this.accountServiceMock.Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == updateFailUserId))).ReturnsAsync(ImmutableList.Create<IAccount>(updateFailExisting));
            this.accountServiceMock.Setup(service => service.UpdateAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<IAccount>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Database.UpdateError", "Update failed"));

            var updateFailResult = await this.provisioner.ProvisionAsync(updateFailPrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(updateFailResult.IsError, Is.True);
                Assert.That(updateFailResult.FirstError.Code, Is.EqualTo("Database.UpdateError"));
            }

            // Case 3: New account not in database (success)
            var newUserId = Guid.NewGuid();

            var newClaims = new List<Claim>
            {
                new("sub", newUserId.ToString()),
                new("preferred_username", "newuser"),
                new("email", "newuser@example.com"),
                new("given_name", "New"),
                new("family_name", "User")
            };

            var newPrincipal = new ClaimsPrincipal(new ClaimsIdentity(newClaims, "OIDC"));

            this.accountServiceMock
                .Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == newUserId)))
                .ReturnsAsync(ImmutableList<IAccount>.Empty);

            this.accountServiceMock
                .Setup(service => service.CreateAsync(It.IsAny<IUserContext>(), It.Is<IEnumerable<IAccount>>(accounts => accounts.Any(a => a.ShortName == "newuser" && a.Name == "New User")), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Created);

            var createdResult = await this.provisioner.ProvisionAsync(newPrincipal, CancellationToken.None);
            Assert.That(createdResult.IsError, Is.False);

            // Case 4: Database read failure (fail)
            var failureUserId = Guid.NewGuid();

            var failureClaims = new List<Claim>
            {
                new("sub", failureUserId.ToString()),
                new("preferred_username", "failuser"),
                new("email", "fail@example.com")
            };

            var failurePrincipal = new ClaimsPrincipal(new ClaimsIdentity(failureClaims, "OIDC"));

            this.accountServiceMock
                .Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == failureUserId)))
                .ReturnsAsync(Error.Failure("Database.Error", "Database read failed"));

            var failureResult = await this.provisioner.ProvisionAsync(failurePrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureResult.IsError, Is.True);
                Assert.That(failureResult.FirstError.Code, Is.EqualTo("Database.Error"));
            }

            // Case 5: Database account creation failure (fail)
            var createFailureUserId = Guid.NewGuid();

            var createFailureClaims = new List<Claim>
            {
                new("sub", createFailureUserId.ToString()),
                new("preferred_username", "createfail"),
                new("email", "createfail@example.com")
            };

            var createFailurePrincipal = new ClaimsPrincipal(new ClaimsIdentity(createFailureClaims, "OIDC"));

            this.accountServiceMock
                .Setup(service => service.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == createFailureUserId)))
                .ReturnsAsync(ImmutableList<IAccount>.Empty);

            this.accountServiceMock
                .Setup(service => service.CreateAsync(It.IsAny<IUserContext>(), It.Is<IEnumerable<IAccount>>(accounts => accounts.Any(a => a.ShortName == "createfail")), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Conflict("Account.Duplicate", "Account already exists"));

            var createFailureResult = await this.provisioner.ProvisionAsync(createFailurePrincipal, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(createFailureResult.IsError, Is.True);
                Assert.That(createFailureResult.FirstError.Code, Is.EqualTo("Account.Duplicate"));
            }
        }
    }
}
