namespace Mycelium.Forge.Tests.Components.Pages.PackageSettings.Dialogs
{
    using System;
    using System.Collections.Generic;
    using System.Collections.Immutable;
    using System.Linq;
    using System.Threading;
    using System.Threading.Tasks;

    using BlazorBlueprint.Components;
    using BlazorBlueprint.Primitives.Extensions;

    using Bunit;

    using ErrorOr;

    using Microsoft.AspNetCore.Components;
    using Microsoft.Extensions.DependencyInjection;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Components.Common;
    using Mycelium.Forge.Components.Pages.PackageSettings.Dialogs;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Models.DialogResults;
    using Mycelium.Forge.Services;

    [TestFixture]
    public class AddMaintainerDialogTestFixture
    {
        private BunitContext context;
        private Mock<IDialogReference> dialogReferenceMock;
        private Mock<IAccountService> accountServiceMock;
        private Mock<IUserService> userServiceMock;
        private UserContext userContext;
        private Package testPackage;
        private Guid existingOwnerId;
        private Guid existingMaintainerId;

        [SetUp]
        public void SetUp()
        {
            this.context = new BunitContext();

            this.context.Services.AddBlazorBlueprintPrimitives();
            this.context.Services.AddBlazorBlueprintComponents();
            this.context.JSInterop.Mode = JSRuntimeMode.Loose;

            this.dialogReferenceMock = new Mock<IDialogReference>();
            this.dialogReferenceMock.Setup(x => x.CloseAsync(It.IsAny<DialogResult>())).Returns(Task.CompletedTask);
            this.dialogReferenceMock.Setup(x => x.CancelAsync()).Returns(Task.CompletedTask);

            this.userContext = new UserContext { AccountId = Guid.NewGuid() };

            this.accountServiceMock = new Mock<IAccountService>();
            this.userServiceMock = new Mock<IUserService>();
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.userContext);

            this.context.Services.AddSingleton(this.accountServiceMock.Object);
            this.context.Services.AddSingleton(this.userServiceMock.Object);

            this.existingOwnerId = Guid.NewGuid();
            this.existingMaintainerId = Guid.NewGuid();

            this.testPackage = new Package
            {
                Id = Guid.NewGuid(),
                Name = "ECSS-MM-PWR",
                ShortName = "ecss-mm-pwr",
                PackageOwner = [this.existingOwnerId],
                PackageMaintainer = [this.existingMaintainerId]
            };
        }

        [TearDown]
        public async Task TearDown()
        {
            await this.context.DisposeAsync();
        }

        [Test]
        public async Task VerifyOnCancelClicked()
        {
            var onCancelCalled = false;
            var onCancel = new EventCallbackFactory().Create(this, () => { onCancelCalled = true; });

            var dialog = this.context.Render<AddMaintainerDialog>(parameters =>
            {
                parameters.AddCascadingValue(this.dialogReferenceMock.Object);
                parameters.Add(x => x.Package, this.testPackage);
                parameters.Add(x => x.OnCancel, onCancel);
            });

            var cancelButton = dialog.Find("#add-maintainer-cancel-button");
            await dialog.InvokeAsync(() => cancelButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(onCancelCalled, Is.True);
                this.dialogReferenceMock.Verify(x => x.CancelAsync(), Times.Once);
            }
        }

        [Test]
        public async Task VerifyOnInviteClicked()
        {
            InvitePackageCollaboratorResult receivedResult = null!;
            var onResult = new EventCallbackFactory().Create(this, (InvitePackageCollaboratorResult result) => { receivedResult = result; });

            var pendingTargetId = Guid.NewGuid();
            var revokedTargetId = Guid.NewGuid();
            var rejectedTargetId = Guid.NewGuid();

            var pendingInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = this.testPackage.Id,
                Target = pendingTargetId,
                Status = InvitationStatusKind.PENDING,
                PackageInvitationKind = PackageInvitationKind.MAINTAINER
            };

            var revokedInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = this.testPackage.Id,
                Target = revokedTargetId,
                Status = InvitationStatusKind.REVOKED,
                PackageInvitationKind = PackageInvitationKind.MAINTAINER
            };

            var rejectedInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = this.testPackage.Id,
                Target = rejectedTargetId,
                Status = InvitationStatusKind.REJECTED,
                PackageInvitationKind = PackageInvitationKind.OWNER
            };

            var dialog = this.context.Render<AddMaintainerDialog>(parameters =>
            {
                parameters.AddCascadingValue(this.dialogReferenceMock.Object);
                parameters.Add(x => x.Package, this.testPackage);
                parameters.Add(x => x.PendingInvitations, [pendingInvitation, revokedInvitation, rejectedInvitation]);
                parameters.Add(x => x.OnResult, onResult);
            });

            var targetInput = dialog.FindComponent<BbInput>();
            var roleSelect = dialog.FindComponent<ForgeSelect<PackageInvitationKind>>();
            var submitButton = dialog.Find("#add-maintainer-submit-button");

            // Scenario 1: Empty inputs -> validation fails
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync(string.Empty));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Null);
                Assert.That(dialog.Instance.ValidationManager.HasError(nameof(dialog.Instance.TargetAccount)), Is.True);
                this.dialogReferenceMock.Verify(x => x.CloseAsync(It.IsAny<DialogResult>()), Times.Never);
            }

            // Scenario 2: Invalid regex username
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("@invalid_name!"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Null);
                Assert.That(dialog.Instance.ValidationManager.HasError(nameof(dialog.Instance.TargetAccount)), Is.True);
            }

            // Scenario 3: AccountService returns Error
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(a => ((IEnumerable<string>)a).Contains("erroruser")))).ReturnsAsync(Error.Failure("Lookup failed"));
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("erroruser"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Null);
                Assert.That(dialog.Instance.ValidationManager.HasError(nameof(dialog.Instance.TargetAccount)), Is.True);
            }

            // Scenario 4: Account not found (empty list)
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(a => ((IEnumerable<string>)a).Contains("unknown")))).ReturnsAsync(ImmutableList<IAccount>.Empty);
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("unknown"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Null);
                Assert.That(dialog.Instance.ValidationManager.HasError(nameof(dialog.Instance.TargetAccount)), Is.True);
            }

            // Scenario 5: Already a package owner
            var existingOwnerAccount = new Account { Id = this.existingOwnerId, ShortName = "owneruser" };
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(a => ((IEnumerable<string>)a).Contains("owneruser")))).ReturnsAsync(ImmutableList.Create<IAccount>(existingOwnerAccount));
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("owneruser"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Null);
                Assert.That(dialog.Instance.ValidationManager.HasError(nameof(dialog.Instance.TargetAccount)), Is.True);
            }

            // Scenario 6: Already a package maintainer
            var existingMaintainerAccount = new Account { Id = this.existingMaintainerId, ShortName = "maintaineruser" };
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(a => ((IEnumerable<string>)a).Contains("maintaineruser")))).ReturnsAsync(ImmutableList.Create<IAccount>(existingMaintainerAccount));
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("maintaineruser"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Null);
                Assert.That(dialog.Instance.ValidationManager.HasError(nameof(dialog.Instance.TargetAccount)), Is.True);
            }

            // Scenario 7: Already has a pending invitation
            var pendingTargetAccount = new Account { Id = pendingTargetId, ShortName = "pending" };
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(a => ((IEnumerable<string>)a).Contains("pending")))).ReturnsAsync(ImmutableList.Create<IAccount>(pendingTargetAccount));
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("pending"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Null);
                Assert.That(dialog.Instance.ValidationManager.HasError(nameof(dialog.Instance.TargetAccount)), Is.True);
            }

            // Scenario 8: Past REVOKED invitation allows re-invite
            var revokedTargetAccount = new Account { Id = revokedTargetId, ShortName = "revokeduser" };
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(a => ((IEnumerable<string>)a).Contains("revokeduser")))).ReturnsAsync(ImmutableList.Create<IAccount>(revokedTargetAccount));
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("revokeduser"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Not.Null);
                Assert.That(receivedResult.TargetAccount, Is.EqualTo(revokedTargetAccount));
                Assert.That(receivedResult.Role, Is.EqualTo(PackageInvitationKind.MAINTAINER));
            }

            // Scenario 9: Past REJECTED invitation allows re-invite and OWNER role selection is preserved
            receivedResult = null!;
            var rejectedTargetAccount = new Account { Id = rejectedTargetId, ShortName = "rejecteduser" };
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(a => ((IEnumerable<string>)a).Contains("rejecteduser")))).ReturnsAsync(ImmutableList.Create<IAccount>(rejectedTargetAccount));
            await dialog.InvokeAsync(() => roleSelect.Instance.ValueChanged.InvokeAsync(PackageInvitationKind.OWNER));
            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("rejecteduser"));
            await dialog.InvokeAsync(() => submitButton.ClickAsync());

            using (Assert.EnterMultipleScope())
            {
                Assert.That(receivedResult, Is.Not.Null);
                Assert.That(receivedResult.TargetAccount, Is.EqualTo(rejectedTargetAccount));
                Assert.That(receivedResult.Role, Is.EqualTo(PackageInvitationKind.OWNER));
                this.dialogReferenceMock.Verify(x => x.CloseAsync(It.IsAny<DialogResult>()), Times.Exactly(2));
            }
        }

        [Test]
        public async Task VerifyOnRoleChanged()
        {
            var dialog = this.context.Render<AddMaintainerDialog>(parameters =>
            {
                parameters.AddCascadingValue(this.dialogReferenceMock.Object);
                parameters.Add(x => x.Package, this.testPackage);
            });

            var roleSelect = dialog.FindComponent<ForgeSelect<PackageInvitationKind>>();
            await dialog.InvokeAsync(() => roleSelect.Instance.ValueChanged.InvokeAsync(PackageInvitationKind.OWNER));

            Assert.That(dialog.Instance.SelectedRole, Is.EqualTo(PackageInvitationKind.OWNER));
        }

        [Test]
        public async Task VerifyOnTargetAccountChanged()
        {
            var dialog = this.context.Render<AddMaintainerDialog>(parameters =>
            {
                parameters.AddCascadingValue(this.dialogReferenceMock.Object);
                parameters.Add(x => x.Package, this.testPackage);
            });

            var targetInput = dialog.FindComponent<BbInput>();

            await dialog.InvokeAsync(() => targetInput.Instance.ValueChanged.InvokeAsync("newuser"));
            var targetWithValue = dialog.Instance.TargetAccount;

            dialog.Instance.OnTargetAccountChanged(null!);
            var targetWithNull = dialog.Instance.TargetAccount;

            using (Assert.EnterMultipleScope())
            {
                Assert.That(targetWithValue, Is.EqualTo("newuser"));
                Assert.That(targetWithNull, Is.EqualTo(string.Empty));
            }
        }
    }
}
