        [Test]
        public async Task VerifyOnChangeCollaboratorRole()
        {
            var packageSettingsPage = this.context.Render<PackageSettings>();
            var rows = packageSettingsPage.FindComponents<PackageCollaboratorRow>();

            var ownerRow = rows[0];
            var maintainerRow = rows[1];

            using (Assert.EnterMultipleScope())
            {
                Assert.That(ownerRow.Instance.IsRoleChangeDisabled, Is.True);
                Assert.That(maintainerRow.Instance.IsRoleChangeDisabled, Is.False);
            }

            // Verify disabled change-role item on owner row
            var ownerMenuButton = ownerRow.Find(".package-maintainer-menu-button");
            await ownerRow.InvokeAsync(() => ownerMenuButton.ClickAsync());
            var ownerChangeRoleItem = this.portalHost.FindAll(".package-maintainer-change-role-item").Last();
            Assert.That(ownerChangeRoleItem.HasAttribute("data-disabled"), Is.True);

            // Triggering OnChangeRole on maintainer row opens dialog
            var menuButton = maintainerRow.Find(".package-maintainer-menu-button");
            await maintainerRow.InvokeAsync(() => menuButton.ClickAsync());
            var changeRoleItem = this.portalHost.FindAll(".package-maintainer-change-role-item").Last();
            _ = packageSettingsPage.InvokeAsync(() => changeRoleItem.ClickAsync());

            IRenderedComponent<ChangeCollaboratorRoleDialog> dialog = null!;
            await this.dialogProvider.WaitForAssertionAsync(() => dialog = this.dialogProvider.FindComponent<ChangeCollaboratorRoleDialog>());

            // Same role does not call ViewModel.ChangeCollaboratorRole
            await this.dialogProvider.InvokeAsync(() => dialog.Instance.OnResult.InvokeAsync(PackageInvitationKind.MAINTAINER));
            this.viewModelMock.Verify(x => x.ChangeCollaboratorRole(It.IsAny<IAccount>(), It.IsAny<PackageInvitationKind>(), It.IsAny<CancellationToken>()), Times.Never);

            // Different role calls ViewModel.ChangeCollaboratorRole
            await this.dialogProvider.InvokeAsync(() => dialog.Instance.OnResult.InvokeAsync(PackageInvitationKind.OWNER));
            this.viewModelMock.Verify(x => x.ChangeCollaboratorRole(this.maintainerAccount, PackageInvitationKind.OWNER, It.IsAny<CancellationToken>()), Times.Once);
        }

