namespace Mycelium.Forge.Tests.Components.Pages.OrganizationSettings
{
    using System;
    using System.Linq;
    using System.Threading.Tasks;

    using BlazorBlueprint.Components;
    using BlazorBlueprint.Primitives.Extensions;

    using Bunit;

    using ErrorOr;

    using Microsoft.Extensions.DependencyInjection;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Components.Common;
    using Mycelium.Forge.Components.Pages.OrganizationSettings;
    using Mycelium.Forge.Components.Pages.OrganizationSettings.Dialogs;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.OrganizationSettings;

    [TestFixture]
    public class OrganizationSettingsTestFixture
    {
        private BunitContext context;
        private Mock<IOrganizationSettingsViewModel> viewModelMock;
        private Organization testOrganization;
        private Account testMember;
        private OrganizationInvitation testInvitation;
        private IRenderedComponent<BbDialogProvider> dialogProvider;
        private UserContext testUserContext;

        [SetUp]
        public void SetUp()
        {
            this.context = new BunitContext();

            this.context.Services.AddBlazorBlueprintPrimitives();
            this.context.Services.AddBlazorBlueprintComponents();
            this.context.JSInterop.Mode = JSRuntimeMode.Loose;

            this.viewModelMock = new Mock<IOrganizationSettingsViewModel>();

            var orgId = Guid.NewGuid();
            var memberId = Guid.NewGuid();

            this.testOrganization = new Organization
            {
                Id = orgId,
                Name = "Starion Group",
                ShortName = "starion",
                Origin = "Systems engineering",
                Administrator = [memberId],
                Member = [memberId],
                OwnedPackage = [Guid.NewGuid()]
            };

            this.testMember = new Account
            {
                Id = memberId,
                Name = "Alex Rivera",
                ShortName = "alex.rivera"
            };

            this.testInvitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = orgId,
                Target = Guid.NewGuid(),
                OrganizationInvitationKind = OrganizationInvitationKind.ADMINISTRATOR,
                Status = InvitationStatusKind.PENDING,
                ExperiesAt = DateTime.UtcNow.AddDays(2)
            };

            var adminId = Guid.NewGuid();
            this.testUserContext = new UserContext { AccountId = adminId, CurrentRoles = [RoleKind.OrganizationAdministrator, RoleKind.Account] };

            this.viewModelMock.Setup(x => x.Organization).Returns(this.testOrganization);
            this.viewModelMock.Setup(x => x.CurrentUserRole).Returns(OrganizationRole.Administrator);
            this.viewModelMock.Setup(x => x.CanManageOrganization).Returns(true);
            this.viewModelMock.Setup(x => x.CurrentUserId).Returns(adminId);
            this.viewModelMock.Setup(x => x.UserContext).Returns(this.testUserContext);
            this.viewModelMock.Setup(x => x.Members).Returns([this.testMember]);
            this.viewModelMock.Setup(x => x.PendingInvitations).Returns([this.testInvitation]);
            this.viewModelMock.Setup(x => x.InvitedAccounts).Returns([]);
            this.viewModelMock.Setup(x => x.RoleOptions).Returns([OrganizationRole.Administrator, OrganizationRole.Member]);

            var userServiceMock = new Mock<IUserService>();
            userServiceMock.Setup(x => x.GetUserContext(It.IsAny<bool>())).ReturnsAsync(this.testUserContext);

            this.context.Services.AddSingleton(this.viewModelMock.Object);
            this.context.Services.AddSingleton(new Mock<IAccountService>().Object);
            this.context.Services.AddSingleton(userServiceMock.Object);
            this.dialogProvider = this.context.Render<BbDialogProvider>();
        }

        [TearDown]
        public async Task TearDown()
        {
            this.dialogProvider.Dispose();
            await this.context.DisposeAsync();
        }

        [Test]
        public async Task VerifyChangeMemberRole()
        {
            var orgSettingsPage = this.context.Render<OrganizationSettings>();
            var select = orgSettingsPage.FindComponent<ForgeSelect<OrganizationRole>>();

            Assert.That(select.Instance.Disabled, Is.True);

            this.testOrganization.Administrator = [this.testMember.Id, Guid.NewGuid()];
            orgSettingsPage.Render();

            select = orgSettingsPage.FindComponent<ForgeSelect<OrganizationRole>>();

            Assert.That(select.Instance.Disabled, Is.False);

            await orgSettingsPage.InvokeAsync(() => select.Instance.ValueChanged.InvokeAsync(OrganizationRole.Member));

            this.viewModelMock.Verify(x => x.ChangeMemberRole(this.testMember, OrganizationRole.Member), Times.Once);
        }

        [Test]
        public void VerifyGetBreadcrumbItems()
        {
            var orgSettingsPage = this.context.Render<OrganizationSettings>();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(orgSettingsPage.Markup, Does.Contain("@starion"));
                Assert.That(orgSettingsPage.Markup, Does.Contain("Settings"));
            }
        }

        [Test]
        public void VerifyOnParametersSet()
        {
            var orgSettingsPage = this.context.Render<OrganizationSettings>(parameters => parameters.Add(p => p.ShortName, "starion"));

            using (Assert.EnterMultipleScope())
            {
                Assert.That(orgSettingsPage.Instance, Is.Not.Null);
                this.viewModelMock.Verify(x => x.InitializeViewModel("starion"), Times.Once);
            }
        }

        [Test]
        public async Task VerifyRemoveMember()
        {
            var orgSettingsPage = this.context.Render<OrganizationSettings>();
            var removeButton = orgSettingsPage.FindComponents<BbButton>().First(b => b.Instance.Class != null && b.Instance.Class.Contains("org-remove-member-button"));

            Assert.That(removeButton.Instance.Disabled, Is.True);

            this.testOrganization.Administrator = [this.testMember.Id, Guid.NewGuid()];
            orgSettingsPage.Render();

            removeButton = orgSettingsPage.FindComponents<BbButton>().First(b => b.Instance.Class != null && b.Instance.Class.Contains("org-remove-member-button"));

            Assert.That(removeButton.Instance.Disabled, Is.False);

            var buttonElement = orgSettingsPage.Find(".org-remove-member-button");
            _ = orgSettingsPage.InvokeAsync(() => buttonElement.ClickAsync());

            var continueButton = this.dialogProvider.FindAll("button").First(b => b.TextContent.Trim() == "Continue");
            await this.dialogProvider.InvokeAsync(() => continueButton.ClickAsync());

            this.viewModelMock.Verify(x => x.RemoveMember(this.testMember), Times.Once);
        }

        [Test]
        public void VerifyRenderingWhenUnauthorizedOrNull()
        {
            this.viewModelMock.Setup(x => x.Organization).Returns((Organization)null!);
            var nullPage = this.context.Render<OrganizationSettings>();

            this.viewModelMock.Setup(x => x.Organization).Returns(this.testOrganization);
            this.viewModelMock.Setup(x => x.CanManageOrganization).Returns(false);
            var unauthorizedPage = this.context.Render<OrganizationSettings>();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullPage.Markup.Trim(), Has.Length.LessThan(5));
                Assert.That(unauthorizedPage.Markup.Trim(), Has.Length.LessThan(5));
            }
        }

        [Test]
        public async Task VerifyResendInvitation()
        {
            var orgSettingsPage = this.context.Render<OrganizationSettings>();
            var resendButton = orgSettingsPage.Find(".org-resend-invitation-button");

            await orgSettingsPage.InvokeAsync(() => resendButton.ClickAsync());

            this.viewModelMock.Verify(x => x.ResendInvitation(this.testInvitation), Times.Once);
        }

        [Test]
        public async Task VerifyRevokeInvitation()
        {
            var orgSettingsPage = this.context.Render<OrganizationSettings>();
            var revokeButton = orgSettingsPage.Find(".org-revoke-invitation-button");

            await orgSettingsPage.InvokeAsync(() => revokeButton.ClickAsync());

            this.viewModelMock.Verify(x => x.RevokeInvitation(this.testInvitation), Times.Once);
        }

        [Test]
        public async Task VerifyTransferOrganization()
        {
            var recipient = new Account { Id = Guid.NewGuid(), Name = "Recipient User" };
            this.viewModelMock.Setup(x => x.TransferOrganization(recipient)).ReturnsAsync(Result.Success);

            // Case 1: Button is not rendered when user is not admin and lacks TransferOrganizationAdministration permission
            var nonAdminContext = new UserContext { AccountId = Guid.NewGuid(), CurrentRoles = [RoleKind.Account] };
            this.viewModelMock.Setup(x => x.CurrentUserId).Returns(nonAdminContext.AccountId!.Value);
            this.viewModelMock.Setup(x => x.UserContext).Returns(nonAdminContext);
            var orgSettingsPage = this.context.Render<OrganizationSettings>();
            Assert.That(orgSettingsPage.FindAll("#org-settings-transfer-button"), Has.Count.EqualTo(0));

            // Case 2: Button is rendered when user is an administrator
            this.viewModelMock.Setup(x => x.CurrentUserId).Returns(this.testMember.Id);
            this.viewModelMock.Setup(x => x.UserContext).Returns(this.testUserContext);
            orgSettingsPage.Render();

            var transferButton = orgSettingsPage.Find("#org-settings-transfer-button");
            Assert.That(transferButton, Is.Not.Null);

            // Case 3: Clicking on the button opens dialog and invokes callback
            _ = orgSettingsPage.InvokeAsync(() => transferButton.ClickAsync());

            var dialog = this.dialogProvider.FindComponent<TransferOrganizationOwnershipDialog>();
            await this.dialogProvider.InvokeAsync(() => dialog.Instance.OnResult.InvokeAsync(recipient));

            this.viewModelMock.Verify(x => x.TransferOrganization(recipient), Times.Once);
        }
    }
}
