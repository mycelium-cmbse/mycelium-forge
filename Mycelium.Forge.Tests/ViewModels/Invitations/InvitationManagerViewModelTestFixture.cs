    [TestFixture]
    public class InvitationManagerViewModelTestFixture
    {
        private Mock<IOrganizationInvitationService> organizationInvitationServiceMock;
        private Mock<IPackageInvitationService> packageInvitationServiceMock;
        private Mock<IService<IOrganizationInvitation>> genericServiceMock;
        private Mock<IAccountService> accountServiceMock;
        private Mock<INotificationService> notificationServiceMock;
        private Mock<ILogger<InvitationManagerViewModel<IOrganizationInvitation>>> orgLoggerMock;
        private Mock<ILogger<InvitationManagerViewModel<IPackageInvitation>>> packageLoggerMock;
        private InvitationManagerViewModel<IOrganizationInvitation> orgViewModel;
        private InvitationManagerViewModel<IPackageInvitation> packageViewModel;
        private UserContext userContext;

        [SetUp]
        public void SetUp()
        {
            this.organizationInvitationServiceMock = new Mock<IOrganizationInvitationService>();
            this.packageInvitationServiceMock = new Mock<IPackageInvitationService>();
            this.genericServiceMock = new Mock<IService<IOrganizationInvitation>>();
            this.accountServiceMock = new Mock<IAccountService>();
            this.notificationServiceMock = new Mock<INotificationService>();
            this.orgLoggerMock = new Mock<ILogger<InvitationManagerViewModel<IOrganizationInvitation>>>();
            this.packageLoggerMock = new Mock<ILogger<InvitationManagerViewModel<IPackageInvitation>>>();

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                CurrentRoles = [RoleKind.Account]
            };

            this.orgViewModel = new InvitationManagerViewModel<IOrganizationInvitation>(this.organizationInvitationServiceMock.Object, this.accountServiceMock.Object, this.notificationServiceMock.Object, this.orgLoggerMock.Object);
