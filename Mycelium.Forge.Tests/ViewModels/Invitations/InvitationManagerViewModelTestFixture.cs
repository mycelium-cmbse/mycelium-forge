        [Test]
        public async Task VerifyInitializeViewModel()
        {
            var organizationId = Guid.NewGuid();
            var packageId = Guid.NewGuid();
            var orgTarget = new Account { Id = Guid.NewGuid(), ShortName = "org-target" };
            var pkgTarget = new Account { Id = Guid.NewGuid(), ShortName = "pkg-target" };

            var matchingOrgInvite = new OrganizationInvitation { Id = Guid.NewGuid(), Organization = organizationId, Target = orgTarget.Id, Status = InvitationStatusKind.PENDING };
            var acceptedOrgInvite = new OrganizationInvitation { Id = Guid.NewGuid(), Organization = organizationId, Target = Guid.NewGuid(), Status = InvitationStatusKind.ACCEPTED };
            var otherOrgInvite = new OrganizationInvitation { Id = Guid.NewGuid(), Organization = Guid.NewGuid(), Target = Guid.NewGuid(), Status = InvitationStatusKind.PENDING };

            var matchingPkgInvite = new PackageInvitation { Id = Guid.NewGuid(), Package = packageId, Target = pkgTarget.Id, Status = InvitationStatusKind.PENDING };
            var revokedPkgInvite = new PackageInvitation { Id = Guid.NewGuid(), Package = packageId, Target = Guid.NewGuid(), Status = InvitationStatusKind.REVOKED };

            // Scenario 1: Organization invitations load scoped by ReadByOrganizationAsync and resolve target accounts
            this.organizationInvitationServiceMock.Setup(x => x.ReadByOrganizationAsync(this.userContext, organizationId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>(matchingOrgInvite, acceptedOrgInvite, otherOrgInvite));
            this.accountServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == orgTarget.Id))).ReturnsAsync(ImmutableList.Create<IAccount>(orgTarget));

            await this.orgViewModel.InitializeViewModel(this.userContext, organizationId, true, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.orgViewModel.PendingInvitations.Items, Has.Count.EqualTo(1));
                Assert.That(this.orgViewModel.PendingInvitations.Items[0].Id, Is.EqualTo(matchingOrgInvite.Id));
                Assert.That(this.orgViewModel.GetTargetName(matchingOrgInvite), Is.EqualTo("org-target"));
                this.organizationInvitationServiceMock.Verify(x => x.ReadByOrganizationAsync(this.userContext, organizationId, It.IsAny<CancellationToken>()), Times.Once);
            }

            // Scenario 2: Query error clears previously loaded state
            this.organizationInvitationServiceMock.Setup(x => x.ReadByOrganizationAsync(this.userContext, organizationId, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Read failed"));

            await this.orgViewModel.InitializeViewModel(this.userContext, organizationId, true, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.orgViewModel.PendingInvitations.Items, Is.Empty);
                Assert.That(this.orgViewModel.GetTargetName(matchingOrgInvite), Is.EqualTo("Unknown"));
            }

            // Scenario 3: Package invitations load scoped by ReadByPackageAsync, and canManage=false clears state without querying
            this.packageInvitationServiceMock.Setup(x => x.ReadByPackageAsync(this.userContext, packageId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IPackageInvitation>(matchingPkgInvite, revokedPkgInvite));
            this.accountServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == pkgTarget.Id))).ReturnsAsync(ImmutableList.Create<IAccount>(pkgTarget));

            await this.packageViewModel.InitializeViewModel(this.userContext, packageId, true, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.packageViewModel.PendingInvitations.Items, Has.Count.EqualTo(1));
                Assert.That(this.packageViewModel.GetTargetName(matchingPkgInvite), Is.EqualTo("pkg-target"));
                this.packageInvitationServiceMock.Verify(x => x.ReadByPackageAsync(this.userContext, packageId, It.IsAny<CancellationToken>()), Times.Once);
            }

            await this.packageViewModel.InitializeViewModel(this.userContext, packageId, false, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.packageViewModel.PendingInvitations.Items, Is.Empty);
                this.packageInvitationServiceMock.Verify(x => x.ReadByPackageAsync(this.userContext, packageId, It.IsAny<CancellationToken>()), Times.Once);
            }

            // Scenario 4: Generic IService<TInvitation> fallback uses ReadAsync
            using var fallbackViewModel = new InvitationManagerViewModel<IOrganizationInvitation>(this.genericServiceMock.Object, this.accountServiceMock.Object, this.notificationServiceMock.Object, this.orgLoggerMock.Object);
            this.genericServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>(matchingOrgInvite));

            await fallbackViewModel.InitializeViewModel(this.userContext, organizationId, true, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(fallbackViewModel.PendingInvitations.Items, Has.Count.EqualTo(1));
                this.genericServiceMock.Verify(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>()), Times.Once);
            }
        }

        [Test]
        public async Task VerifyResendInvitation()
        {
            var organizationId = Guid.NewGuid();
            var initialExpiry = DateTime.UtcNow.AddDays(1);
            var invitation = new OrganizationInvitation { Id = Guid.NewGuid(), Organization = organizationId, Target = Guid.NewGuid(), Status = InvitationStatusKind.PENDING, ExperiesAt = initialExpiry };

            this.organizationInvitationServiceMock.Setup(x => x.ReadByOrganizationAsync(this.userContext, organizationId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>(invitation));
            this.accountServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList<IAccount>.Empty);
            await this.orgViewModel.InitializeViewModel(this.userContext, organizationId, true, CancellationToken.None);

            // Scenario 1: Update fails keeps original invitation
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.userContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Resend failed"));

            await this.orgViewModel.ResendInvitation(invitation, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.orgViewModel.PendingInvitations.Items[0], Is.SameAs(invitation));
                Assert.That(invitation.ExperiesAt, Is.EqualTo(initialExpiry));
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to resend invitation.", "Invitation Error", NotificationType.Error), Times.Once);
            }

            // Scenario 2: Update succeeds replaces invitation with cloned updated expiration
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.userContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);

            await this.orgViewModel.ResendInvitation(invitation, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.orgViewModel.PendingInvitations.Items[0], Is.Not.SameAs(invitation));
                Assert.That(this.orgViewModel.PendingInvitations.Items[0].ExperiesAt, Is.GreaterThan(initialExpiry));
                this.notificationServiceMock.Verify(x => x.AddNotification("Invitation resent successfully.", "Invitation Resent", NotificationType.Success), Times.Once);
            }
        }

        [Test]
        public async Task VerifyRevokeInvitation()
        {
            var organizationId = Guid.NewGuid();
            var invitation = new OrganizationInvitation { Id = Guid.NewGuid(), Organization = organizationId, Target = Guid.NewGuid(), Status = InvitationStatusKind.PENDING, ExperiesAt = DateTime.UtcNow.AddDays(3) };

            this.organizationInvitationServiceMock.Setup(x => x.ReadByOrganizationAsync(this.userContext, organizationId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>(invitation));
            this.accountServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList<IAccount>.Empty);
            await this.orgViewModel.InitializeViewModel(this.userContext, organizationId, true, CancellationToken.None);

            // Scenario 1: Update fails retains invitation
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.userContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Revoke failed"));

            await this.orgViewModel.RevokeInvitation(invitation, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.orgViewModel.PendingInvitations.Items, Has.Count.EqualTo(1));
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to revoke invitation.", "Invitation Error", NotificationType.Error), Times.Once);
            }

            // Scenario 2: Update succeeds removes invitation and sets status REVOKED
            IOrganizationInvitation capturedInvitation = null!;
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.userContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).Callback<IUserContext, IEnumerable<IOrganizationInvitation>, CancellationToken>((_, items, _) => capturedInvitation = items.First()).ReturnsAsync(Result.Updated);

            await this.orgViewModel.RevokeInvitation(invitation, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(capturedInvitation.Status, Is.EqualTo(InvitationStatusKind.REVOKED));
                Assert.That(this.orgViewModel.PendingInvitations.Items, Is.Empty);
                this.notificationServiceMock.Verify(x => x.AddNotification("Invitation revoked successfully.", "Invitation Revoked", NotificationType.Success), Times.Once);
            }
        }

        [Test]
        public async Task VerifySendInvitation()
        {
            var organizationId = Guid.NewGuid();
            var packageId = Guid.NewGuid();
            var target = new Account { Id = Guid.NewGuid(), Name = "Invited User", ShortName = "invited-user" };

            this.organizationInvitationServiceMock.Setup(x => x.ReadByOrganizationAsync(this.userContext, organizationId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList<IOrganizationInvitation>.Empty);
            this.packageInvitationServiceMock.Setup(x => x.ReadByPackageAsync(this.userContext, packageId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList<IPackageInvitation>.Empty);
            await this.orgViewModel.InitializeViewModel(this.userContext, organizationId, true, CancellationToken.None);
            await this.packageViewModel.InitializeViewModel(this.userContext, packageId, true, CancellationToken.None);

            // Scenario 1: Organization invitation create fails
            var failingInvitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = organizationId,
                Target = target.Id,
                Owner = this.userContext.AccountId!.Value,
                OrganizationInvitationKind = OrganizationInvitationKind.MEMBER
            };

            this.organizationInvitationServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Create failed"));

            var orgFailResult = await this.orgViewModel.SendInvitation(failingInvitation, target, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(orgFailResult.IsError, Is.True);
                Assert.That(this.orgViewModel.PendingInvitations.Items, Is.Empty);
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to send invitation.", "Invitation Error", NotificationType.Error), Times.Once);
            }

            // Scenario 2: Organization invitation create succeeds and sets Status and ExperiesAt
            var orgInvitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = organizationId,
                Target = target.Id,
                Owner = this.userContext.AccountId!.Value,
                OrganizationInvitationKind = OrganizationInvitationKind.ADMINISTRATOR
            };

            IOrganizationInvitation capturedOrgInvitation = null!;
            this.organizationInvitationServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).Callback<IUserContext, IEnumerable<IOrganizationInvitation>, CancellationToken>((_, items, _) => capturedOrgInvitation = items.First()).ReturnsAsync(Result.Created);

            var orgSuccessResult = await this.orgViewModel.SendInvitation(orgInvitation, target, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(orgSuccessResult.IsError, Is.False);
                Assert.That(capturedOrgInvitation.Organization, Is.EqualTo(organizationId));
                Assert.That(capturedOrgInvitation.Target, Is.EqualTo(target.Id));
                Assert.That(capturedOrgInvitation.Owner, Is.EqualTo(this.userContext.AccountId));
                Assert.That(capturedOrgInvitation.OrganizationInvitationKind, Is.EqualTo(OrganizationInvitationKind.ADMINISTRATOR));
                Assert.That(capturedOrgInvitation.Status, Is.EqualTo(InvitationStatusKind.PENDING));
                Assert.That(capturedOrgInvitation.ExperiesAt, Is.GreaterThan(DateTime.UtcNow));
                Assert.That(this.orgViewModel.PendingInvitations.Items, Has.Count.EqualTo(1));
                Assert.That(this.orgViewModel.GetTargetName(capturedOrgInvitation), Is.EqualTo("invited-user"));
                this.notificationServiceMock.Verify(x => x.AddNotification($"Invitation sent to {target.Name}.", "Invitation Sent", NotificationType.Success), Times.Once);
            }

            // Scenario 3: Package invitation create succeeds and sets Status and ExperiesAt
            var pkgInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = packageId,
                Target = target.Id,
                Owner = this.userContext.AccountId!.Value,
                PackageInvitationKind = PackageInvitationKind.OWNER
            };

            IPackageInvitation capturedPkgInvitation = null!;
            this.packageInvitationServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IPackageInvitation>>(), It.IsAny<CancellationToken>())).Callback<IUserContext, IEnumerable<IPackageInvitation>, CancellationToken>((_, items, _) => capturedPkgInvitation = items.First()).ReturnsAsync(Result.Created);

            var pkgSuccessResult = await this.packageViewModel.SendInvitation(pkgInvitation, target, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(pkgSuccessResult.IsError, Is.False);
                Assert.That(capturedPkgInvitation.Package, Is.EqualTo(packageId));
                Assert.That(capturedPkgInvitation.Target, Is.EqualTo(target.Id));
                Assert.That(capturedPkgInvitation.PackageInvitationKind, Is.EqualTo(PackageInvitationKind.OWNER));
                Assert.That(capturedPkgInvitation.Status, Is.EqualTo(InvitationStatusKind.PENDING));
                Assert.That(capturedPkgInvitation.ExperiesAt, Is.GreaterThan(DateTime.UtcNow));
                Assert.That(this.packageViewModel.PendingInvitations.Items, Has.Count.EqualTo(1));
            }
        }
