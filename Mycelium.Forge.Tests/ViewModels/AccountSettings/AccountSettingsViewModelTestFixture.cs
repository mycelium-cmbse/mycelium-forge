        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Scenario 1: Not authenticated
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.unauthenticatedContext);

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.Null);
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
                this.addressesManagerViewModelMock.Verify(x => x.InitializeViewModel(It.IsAny<Account>()), Times.Never);
            }

            // Scenario 2: Profile is null
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);
            this.accountServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList<IAccount>.Empty);

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.Null);
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Exactly(2));
                this.addressesManagerViewModelMock.Verify(x => x.InitializeViewModel(It.IsAny<Account>()), Times.Never);
            }

            // Scenario 3: Organization read error and no primary address
            var userId = this.authenticatedContext.AccountId!.Value;
            this.accountServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAccount>(this.profileNoAddress));
            this.organizationServiceMock.Setup(x => x.ReadByAccountMembershipAsync(this.authenticatedContext, userId, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Failed to read"));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.EqualTo(this.profileNoAddress));
                Assert.That(this.viewModel.Organizations, Has.Count.EqualTo(0));
                this.addressesManagerViewModelMock.Verify(x => x.InitializeViewModel(this.profileNoAddress), Times.Once);
            }

            // Scenario 4: Happy path with address and organizations
            this.accountServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAccount>(this.profileWithAddress));
            this.organizationServiceMock.Setup(x => x.ReadByAccountMembershipAsync(this.authenticatedContext, userId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganization>(this.adminOrg, this.memberOrg));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.EqualTo(this.profileWithAddress));
                Assert.That(this.viewModel.Organizations, Has.Count.EqualTo(2));
                this.addressesManagerViewModelMock.Verify(x => x.InitializeViewModel(this.profileWithAddress), Times.Once);
                this.pendingRequestsManagerViewModelMock.Verify(x => x.InitializeViewModel(), Times.Exactly(2));
            }

            // Verify OnOrganizationAccepted subscription
            var newOrg = new Organization { Id = Guid.NewGuid(), Name = "Accepted Org" };
            this.pendingRequestsManagerViewModelMock.Object.OnOrganizationAccepted?.Invoke(newOrg);
            Assert.That(this.viewModel.Organizations, Has.Count.EqualTo(3));

            // Verify OnPrimaryAddressChanging callback (failure then success without success notification)
            var newPrimaryAddressId = Guid.NewGuid();
            this.accountServiceMock.Setup(x => x.UpdateAndSyncAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAccount>>(), CancellationToken.None)).ReturnsAsync(Error.Failure("Primary update failed"));

            var primaryErrorResult = await this.addressesManagerViewModelMock.Object.OnPrimaryAddressChanging!(newPrimaryAddressId);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(primaryErrorResult.IsError, Is.True);
                Assert.That(this.viewModel.Profile.PrimaryAddress, Is.EqualTo(this.profileWithAddress.PrimaryAddress));
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to update profile.", "Error", NotificationType.Error), Times.Once);
                this.userServiceMock.Verify(x => x.GetCurrentUser(true), Times.Never);
            }

            this.accountServiceMock.Setup(x => x.UpdateAndSyncAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAccount>>(), CancellationToken.None)).ReturnsAsync(Result.Updated);

            var primarySuccessResult = await this.addressesManagerViewModelMock.Object.OnPrimaryAddressChanging!(newPrimaryAddressId);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(primarySuccessResult.IsError, Is.False);
                Assert.That(this.viewModel.Profile.PrimaryAddress, Is.EqualTo(newPrimaryAddressId));
                this.userServiceMock.Verify(x => x.GetCurrentUser(true), Times.Once);
                this.notificationServiceMock.Verify(x => x.AddNotification(It.IsAny<string>(), It.IsAny<string?>(), NotificationType.Success), Times.Never);
            }
        }

        [Test]
        public async Task VerifyUpdateProfile()
        {
            await this.viewModel.InitializeViewModel();

            var updatedProfile = this.profileWithAddress.Clone();
            updatedProfile.Name = "Alex Updated";

            // Scenario 1: Failure path
            this.accountServiceMock.Setup(x => x.UpdateAndSyncAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAccount>>(), CancellationToken.None)).ReturnsAsync(Error.Failure("Keycloak.SyncFailed", "Sync failed"));

            var errorResult = await this.viewModel.UpdateProfile(updatedProfile);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(errorResult.IsError, Is.True);
                Assert.That(this.viewModel.Profile.Name, Is.EqualTo("Alex Rivera"));
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
                this.notificationServiceMock.Verify(x => x.AddNotification(It.IsAny<string>(), It.IsAny<string?>(), NotificationType.Error), Times.Once);
                this.userServiceMock.Verify(x => x.GetCurrentUser(true), Times.Never);
            }

            // Scenario 1b: Conflict path surfaces email conflict message
            this.accountServiceMock.Setup(x => x.UpdateAndSyncAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAccount>>(), CancellationToken.None)).ReturnsAsync(Error.Conflict("Keycloak.Conflict", "Keycloak request PUT conflicted (409)."));

            var conflictResult = await this.viewModel.UpdateProfile(updatedProfile);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(conflictResult.IsError, Is.True);
                this.notificationServiceMock.Verify(x => x.AddNotification("Unable to use this email address. Please enter a different email address.", "Error", NotificationType.Error), Times.Once);
            }

            // Scenario 2: Success path
            IEnumerable<IAccount> capturedAccounts = [];
            this.accountServiceMock.Setup(x => x.UpdateAndSyncAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAccount>>(), CancellationToken.None)).Callback<IUserContext, IEnumerable<IAccount>, CancellationToken>((_, accounts, _) => capturedAccounts = accounts).ReturnsAsync(Result.Updated);

            var successResult = await this.viewModel.UpdateProfile(updatedProfile);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(this.viewModel.Profile, Is.EqualTo(updatedProfile));
                Assert.That(this.viewModel.Profile.Name, Is.EqualTo("Alex Updated"));
                Assert.That(capturedAccounts.Single().Name, Is.EqualTo("Alex Updated"));
                this.notificationServiceMock.Verify(x => x.AddNotification(It.IsAny<string>(), It.IsAny<string?>(), NotificationType.Success), Times.Once);
                this.userServiceMock.Verify(x => x.GetCurrentUser(true), Times.Once);
            }

            // Scenario 3: Email change sets IsVerified to false and subsequent non-email update preserves it
            var emailChangedProfile = this.viewModel.Profile.Clone();
            emailChangedProfile.Email = "new@example.com";
            emailChangedProfile.IsVerified = false;

            await this.viewModel.UpdateProfile(emailChangedProfile);

            var nonEmailUpdate = this.viewModel.Profile.Clone();
            nonEmailUpdate.Website = "https://example.com";

            await this.viewModel.UpdateProfile(nonEmailUpdate);

            Assert.That(this.viewModel.Profile.IsVerified, Is.False);
        }
