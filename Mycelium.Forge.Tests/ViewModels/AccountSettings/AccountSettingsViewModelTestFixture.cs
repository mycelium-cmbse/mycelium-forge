namespace Mycelium.Forge.Tests.ViewModels.AccountSettings
{
    using System;
    using System.Collections.Generic;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Models.DialogResults;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.AccountSettings;

    [TestFixture]
    public class AccountSettingsViewModelTestFixture
    {
        private Mock<IAccountService> accountServiceMock;
        private Mock<IAddressService> addressServiceMock;
        private Mock<IForgeContext> forgeContextMock;
        private Mock<INotificationService> notificationServiceMock;
        private Mock<IOrganizationService> organizationServiceMock;
        private Mock<IUserService> userServiceMock;
        private Mock<ILogger<AccountSettingsViewModel>> loggerMock;
        private AccountSettingsViewModel viewModel;
        private UserContext unauthenticatedContext;
        private UserContext authenticatedContext;
        private Account profileWithAddress;
        private Account profileNoAddress;
        private Address address;
        private Organization adminOrg;
        private Organization memberOrg;
        private Organization unrelatedOrg;

        [SetUp]
        public void SetUp()
        {
            this.accountServiceMock = new Mock<IAccountService>();
            this.addressServiceMock = new Mock<IAddressService>();
            this.forgeContextMock = new Mock<IForgeContext>();
            this.notificationServiceMock = new Mock<INotificationService>();
            this.organizationServiceMock = new Mock<IOrganizationService>();
            this.userServiceMock = new Mock<IUserService>();
            this.loggerMock = new Mock<ILogger<AccountSettingsViewModel>>();

            var userId = Guid.NewGuid();
            var addressId = Guid.NewGuid();

            this.unauthenticatedContext = new UserContext
            {
                AccountId = null
            };

            this.authenticatedContext = new UserContext
            {
                AccountId = userId
            };

            this.profileWithAddress = new Account
            {
                Id = userId,
                Name = "Alex Rivera",
                PrimaryAddress = addressId
            };

            this.profileNoAddress = new Account
            {
                Id = userId,
                Name = "Alex Rivera",
                PrimaryAddress = null
            };

            this.address = new Address
            {
                Id = addressId,
                Locality = "Darmstadt"
            };

            this.adminOrg = new Organization
            {
                Id = Guid.NewGuid(),
                Name = "Admin Org",
                Administrator = [userId]
            };

            this.memberOrg = new Organization
            {
                Id = Guid.NewGuid(),
                Name = "Member Org",
                Member = [userId]
            };

            this.unrelatedOrg = new Organization
            {
                Id = Guid.NewGuid(),
                Name = "Unrelated Org"
            };

            this.forgeContextMock.Setup(x => x.ForgeId).Returns(Guid.NewGuid());
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);
            this.accountServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAccount>(this.profileWithAddress));
            this.addressServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAddress>(this.address));
            this.organizationServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganization>());

            this.viewModel = new AccountSettingsViewModel(this.loggerMock.Object, this.userServiceMock.Object, this.accountServiceMock.Object, this.addressServiceMock.Object, this.organizationServiceMock.Object, this.forgeContextMock.Object, this.notificationServiceMock.Object);
        }

        [Test]
        public async Task VerifyCreateOrganization()
        {
            await this.viewModel.InitializeViewModel();

            var result = new CreateOrganizationResult
            {
                OrganizationName = "New Org",
                Scope = "@neworg",
                BillingEmail = "billing@neworg.com"
            };

            // Scenario 1: Failure path
            this.organizationServiceMock.Setup(x => x.CreateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IOrganization>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Creation failed"));

            var failureOperationResult = await this.viewModel.CreateOrganization(result);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureOperationResult.IsError, Is.True);
                Assert.That(this.viewModel.Organizations, Has.Count.EqualTo(0));
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 2: Happy path
            this.organizationServiceMock.Setup(x => x.CreateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IOrganization>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Result.Created);

            var successOperationResult = await this.viewModel.CreateOrganization(result);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successOperationResult.IsError, Is.False);
                Assert.That(this.viewModel.Organizations, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.Organizations[0].Name, Is.EqualTo("New Org"));
                Assert.That(this.viewModel.Organizations[0].ShortName, Is.EqualTo("neworg"));
            }
        }

        [Test]
        public void VerifyDeactivateAccount()
        {
            Assert.That(async () => await this.viewModel.DeactivateAccount(), Throws.Nothing);
        }

        [Test]
        public void VerifyDeleteAccount()
        {
            Assert.That(async () => await this.viewModel.DeleteAccount(), Throws.Nothing);
        }

        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Scenario 1: Not authenticated
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.unauthenticatedContext);

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.Null);
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 2: Profile is null
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);
            this.accountServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList<IAccount>.Empty);

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.Null);
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Exactly(2));
            }

            // Scenario 3: Organization read error and no primary address
            this.accountServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAccount>(this.profileNoAddress));
            this.organizationServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Failed to read"));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.EqualTo(this.profileNoAddress));
                Assert.That(this.viewModel.Location, Is.Empty);
                Assert.That(this.viewModel.Organizations, Has.Count.EqualTo(0));
            }

            // Scenario 4: Happy path with address and organizations
            this.accountServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAccount>(this.profileWithAddress));
            this.addressServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAddress>(this.address));
            this.organizationServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganization>(this.adminOrg, this.memberOrg, this.unrelatedOrg));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Profile, Is.EqualTo(this.profileWithAddress));
                Assert.That(this.viewModel.Location, Is.EqualTo("Darmstadt"));
                Assert.That(this.viewModel.Organizations, Has.Count.EqualTo(2));
            }
        }
    }
}
