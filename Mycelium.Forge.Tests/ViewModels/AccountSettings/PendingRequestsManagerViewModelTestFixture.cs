        [Test]
        public async Task VerifyAcceptInvitation()
        {
            await this.viewModel.InitializeViewModel();

            var organizationInvitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = this.organization.Id,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                OrganizationInvitationKind = OrganizationInvitationKind.ADMINISTRATOR,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var packageInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = this.package.Id,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                PackageInvitationKind = PackageInvitationKind.MAINTAINER,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var organizationRow = OrganizationInvitationRowViewModel.GenerateRows([organizationInvitation], [this.organization]).First();
            var packageRow = PackageInvitationRowViewModel.GenerateRows([packageInvitation], [this.package, this.organization]).First();
            this.viewModel.PendingInvitations.Add(organizationRow);
            this.viewModel.PendingInvitations.Add(packageRow);

            IOrganization acceptedOrgFromSubject = null!;
            this.viewModel.OnOrganizationAccepted = org => acceptedOrgFromSubject = org;

            // Scenario 1: Organization invitation failure path
            this.organizationInvitationServiceMock.Setup(x => x.AcceptInvitationAsync(this.authenticatedContext, organizationInvitation, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Update failed"));

            var failureResult = await this.viewModel.AcceptInvitation(organizationInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureResult.IsError, Is.True);
                Assert.That(acceptedOrgFromSubject, Is.Null);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(2));
            }

            // Scenario 2: Organization invitation happy path
            this.organizationInvitationServiceMock.Setup(x => x.AcceptInvitationAsync(this.authenticatedContext, organizationInvitation, It.IsAny<CancellationToken>())).ReturnsAsync(this.organization);

            var successResult = await this.viewModel.AcceptInvitation(organizationInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(1));
                Assert.That(acceptedOrgFromSubject, Is.Not.Null);
                Assert.That(acceptedOrgFromSubject.Id, Is.EqualTo(this.organization.Id));
            }

            // Scenario 3: Package invitation failure path
            this.packageInvitationServiceMock.Setup(x => x.AcceptInvitationAsync(this.authenticatedContext, packageInvitation, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Accept failed"));

            var packageFailureResult = await this.viewModel.AcceptInvitation(packageInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(packageFailureResult.IsError, Is.True);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(1));
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to accept invitation.", "Error", NotificationType.Error), Times.Exactly(2));
            }

            // Scenario 4: Package invitation happy path
            this.packageInvitationServiceMock.Setup(x => x.AcceptInvitationAsync(this.authenticatedContext, packageInvitation, It.IsAny<CancellationToken>())).ReturnsAsync(this.package);

            var packageSuccessResult = await this.viewModel.AcceptInvitation(packageInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(packageSuccessResult.IsError, Is.False);
                Assert.That(this.viewModel.PendingInvitations, Is.Empty);
                this.notificationServiceMock.Verify(x => x.AddNotification("Invitation accepted.", It.IsAny<string>(), NotificationType.Success), Times.Exactly(2));
            }

            // Scenario 5: Unsupported invitation type
            var unsupportedResult = await this.viewModel.AcceptInvitation(null!);

            Assert.That(unsupportedResult.IsError, Is.True);
        }

        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Scenario 1: Unauthenticated
            var unauthenticatedContext = new UserContext { AccountId = null };
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(unauthenticatedContext);

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PendingInvitations, Is.Empty);
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 2: Invitation read error
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);
            this.organizationInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Read failed"));
            this.packageInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Package read failed"));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PendingInvitations, Is.Empty);
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Exactly(2));
            }

            // Scenario 3: No pending invitations
            this.organizationInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>());
            this.packageInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IPackageInvitation>());

            await this.viewModel.InitializeViewModel();

            Assert.That(this.viewModel.PendingInvitations, Is.Empty);

            // Scenario 4: Happy path with pending organization and package invitations
            var organizationId = Guid.NewGuid();
            var packageId = Guid.NewGuid();

            var invitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = organizationId,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var packageInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = packageId,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                PackageInvitationKind = PackageInvitationKind.OWNER,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var expiredPackageInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = packageId,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                PackageInvitationKind = PackageInvitationKind.MAINTAINER,
                ExperiesAt = DateTime.UtcNow.AddDays(-1)
            };

            var targetOrganization = new Organization { Id = organizationId, Name = "Target Org", ShortName = "target" };
            var targetPackage = new Package { Id = packageId, Name = "Target Package", ShortName = "target-package", Owner = organizationId };

            this.organizationInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>(invitation));
            this.organizationServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length > 0))).ReturnsAsync(ImmutableList.Create<IOrganization>(targetOrganization));
            this.packageInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IPackageInvitation>(packageInvitation, expiredPackageInvitation));
            this.packageServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length > 0))).ReturnsAsync(ImmutableList.Create<IPackage>(targetPackage));
            this.scopeServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length > 0))).ReturnsAsync(ImmutableList.Create<IScope>(targetOrganization));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(2));
                Assert.That(this.viewModel.PendingInvitations[0], Is.InstanceOf<OrganizationInvitationRowViewModel>());
                Assert.That(((OrganizationInvitationRowViewModel)this.viewModel.PendingInvitations[0]).Organization, Is.EqualTo(targetOrganization));
                Assert.That(this.viewModel.PendingInvitations[1], Is.InstanceOf<PackageInvitationRowViewModel>());
                Assert.That(((PackageInvitationRowViewModel)this.viewModel.PendingInvitations[1]).Package, Is.EqualTo(targetPackage));
                Assert.That(((PackageInvitationRowViewModel)this.viewModel.PendingInvitations[1]).Scope, Is.EqualTo(targetOrganization));
            }

            // Scenario 5: ReadByTargetAsync returning error clears previously loaded list
            this.organizationInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Organization read failed"));
            this.packageInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Package read failed"));

            await this.viewModel.InitializeViewModel();

            Assert.That(this.viewModel.PendingInvitations, Is.Empty);
        }

        [Test]
        public async Task VerifyRejectInvitation()
        {
            await this.viewModel.InitializeViewModel();

            var organizationInvitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = this.organization.Id,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var packageInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Package = this.package.Id,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                PackageInvitationKind = PackageInvitationKind.MAINTAINER,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var organizationRow = OrganizationInvitationRowViewModel.GenerateRows([organizationInvitation], [this.organization]).First();
            var packageRow = PackageInvitationRowViewModel.GenerateRows([packageInvitation], [this.package, this.organization]).First();
            this.viewModel.PendingInvitations.Add(organizationRow);
            this.viewModel.PendingInvitations.Add(packageRow);

            // Scenario 1: Organization invitation failure path
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Reject failed"));

            var failureResult = await this.viewModel.RejectInvitation(organizationInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureResult.IsError, Is.True);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(2));
            }

            // Scenario 2: Organization invitation happy path
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);

            var successResult = await this.viewModel.RejectInvitation(organizationInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(1));
            }

            // Scenario 3: Package invitation failure path
            this.packageInvitationServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IPackageInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Reject failed"));

            var packageFailureResult = await this.viewModel.RejectInvitation(packageInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(packageFailureResult.IsError, Is.True);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(1));
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to reject invitation.", "Error", NotificationType.Error), Times.Exactly(2));
            }

            // Scenario 4: Package invitation happy path
            IPackageInvitation capturedInvitation = null!;

            this.packageInvitationServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IPackageInvitation>>(), It.IsAny<CancellationToken>())).Callback<IUserContext, IEnumerable<IPackageInvitation>, CancellationToken>((_, invitations, _) => capturedInvitation = invitations.First()).ReturnsAsync(Result.Updated);

            var packageSuccessResult = await this.viewModel.RejectInvitation(packageInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(packageSuccessResult.IsError, Is.False);
                Assert.That(capturedInvitation.Status, Is.EqualTo(InvitationStatusKind.REJECTED));
                Assert.That(this.viewModel.PendingInvitations, Is.Empty);
                this.notificationServiceMock.Verify(x => x.AddNotification("Invitation rejected.", It.IsAny<string>(), NotificationType.Success), Times.Exactly(2));
            }

            // Scenario 5: Unsupported invitation type
            var unsupportedResult = await this.viewModel.RejectInvitation(null!);

            Assert.That(unsupportedResult.IsError, Is.True);
        }
