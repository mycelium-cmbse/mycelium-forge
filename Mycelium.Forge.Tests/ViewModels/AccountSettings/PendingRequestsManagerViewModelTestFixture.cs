namespace Mycelium.Forge.Tests.ViewModels.AccountSettings
{
    using System;
    using System.Collections.Generic;
    using System.Collections.Immutable;
    using System.Linq;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.AccountSettings;
    using Mycelium.Forge.ViewModels.Rows;

    [TestFixture]
    public class PendingRequestsManagerViewModelTestFixture
    {
        private Mock<ILogger<PendingRequestsManagerViewModel>> loggerMock;
        private Mock<IOrganizationService> organizationServiceMock;
        private Mock<IOrganizationInvitationService> organizationInvitationServiceMock;
        private Mock<INotificationService> notificationServiceMock;
        private Mock<IUserService> userServiceMock;
        private PendingRequestsManagerViewModel viewModel;
        private UserContext authenticatedContext;
        private Guid userId;
        private Organization organization;

        [SetUp]
        public void SetUp()
        {
            this.loggerMock = new Mock<ILogger<PendingRequestsManagerViewModel>>();
            this.organizationServiceMock = new Mock<IOrganizationService>();
            this.organizationInvitationServiceMock = new Mock<IOrganizationInvitationService>();
            this.notificationServiceMock = new Mock<INotificationService>();
            this.userServiceMock = new Mock<IUserService>();

            this.userId = Guid.NewGuid();

            this.organization = new Organization
            {
                Id = Guid.NewGuid(),
                Name = "Target Org",
                Member = []
            };

            this.authenticatedContext = new UserContext
            {
                AccountId = this.userId
            };

            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);

            this.organizationInvitationServiceMock
                .Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>()))
                .ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>());

            this.viewModel = new PendingRequestsManagerViewModel(this.loggerMock.Object, this.userServiceMock.Object, this.organizationServiceMock.Object, this.organizationInvitationServiceMock.Object, this.notificationServiceMock.Object);
        }

        [Test]
        public async Task VerifyAcceptInvitation()
        {
            await this.viewModel.InitializeViewModel();

            var invitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = this.organization.Id,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                OrganizationInvitationKind = OrganizationInvitationKind.ADMINISTRATOR,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var row = OrganizationInvitationRowViewModel.GenerateRows([invitation], [this.organization]).First();
            this.viewModel.PendingInvitations.Add(row);

            IOrganization acceptedOrgFromSubject = null!;
            this.viewModel.OnOrganizationAccepted.Subscribe(org => acceptedOrgFromSubject = org);

            // Scenario 1: Failure path
            this.organizationInvitationServiceMock
                .Setup(x => x.AcceptInvitationAsync(this.authenticatedContext, invitation, It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure("Update failed"));

            var failureResult = await this.viewModel.AcceptInvitation(row);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureResult.IsError, Is.True);
                Assert.That(acceptedOrgFromSubject, Is.Null);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(1));
            }

            // Scenario 2: Happy path
            this.organizationInvitationServiceMock
                .Setup(x => x.AcceptInvitationAsync(this.authenticatedContext, invitation, It.IsAny<CancellationToken>()))
                .ReturnsAsync(this.organization);

            var successResult = await this.viewModel.AcceptInvitation(row);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(0));
                Assert.That(acceptedOrgFromSubject, Is.Not.Null);
                Assert.That(acceptedOrgFromSubject.Id, Is.EqualTo(this.organization.Id));
            }
        }

        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Scenario 1: Unauthenticated
            var unauthenticatedContext = new UserContext { AccountId = null };
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(unauthenticatedContext);

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(0));
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 2: Invitation read error
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);
            this.organizationInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Read failed"));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(0));
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 3: No pending invitations
            this.organizationInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>());

            await this.viewModel.InitializeViewModel();

            Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(0));

            // Scenario 4: Happy path with pending invitations
            var orgId = Guid.NewGuid();

            var invitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = orgId,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var targetOrg = new Organization { Id = orgId, Name = "Target Org", ShortName = "target" };

            this.organizationInvitationServiceMock.Setup(x => x.ReadByTargetAsync(this.authenticatedContext, this.userId, It.IsAny<CancellationToken>())).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>(invitation));
            this.organizationServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length > 0))).ReturnsAsync(ImmutableList.Create<IOrganization>(targetOrg));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.PendingInvitations[0].Organization.Name, Is.EqualTo("Target Org"));
            }
        }

        [Test]
        public async Task VerifyRejectInvitation()
        {
            await this.viewModel.InitializeViewModel();

            var invitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Organization = this.organization.Id,
                Target = this.userId,
                Status = InvitationStatusKind.PENDING,
                ExperiesAt = DateTime.UtcNow.AddDays(5)
            };

            var row = OrganizationInvitationRowViewModel.GenerateRows([invitation], [this.organization]).First();
            this.viewModel.PendingInvitations.Add(row);

            // Scenario 1: Failure path
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Reject failed"));
            var failureResult = await this.viewModel.RejectInvitation(row);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureResult.IsError, Is.True);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(1));
            }

            // Scenario 2: Happy path
            this.organizationInvitationServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IOrganizationInvitation>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);
            var successResult = await this.viewModel.RejectInvitation(row);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(this.viewModel.PendingInvitations, Has.Count.EqualTo(0));
            }
        }
    }
}
