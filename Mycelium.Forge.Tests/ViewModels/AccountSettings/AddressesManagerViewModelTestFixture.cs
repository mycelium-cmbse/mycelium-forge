    [TestFixture]
    public class AddressesManagerViewModelTestFixture
    {
        private Mock<ILogger<AddressesManagerViewModel>> loggerMock;
        private Mock<IUserService> userServiceMock;
        private Mock<IAddressService> addressServiceMock;
        private Mock<ICountryService> countryServiceMock;
        private Mock<INotificationService> notificationServiceMock;
        private AddressesManagerViewModel viewModel;
        private UserContext unauthenticatedContext;
        private UserContext authenticatedContext;
        private Guid userId;
        private Country france;
        private Country germany;
        private Address primaryAddress;
        private Address secondaryAddress;
        private Account profileWithAddresses;
        private Account profileNoAddresses;

        [SetUp]
        public void SetUp()
        {
            this.loggerMock = new Mock<ILogger<AddressesManagerViewModel>>();
            this.userServiceMock = new Mock<IUserService>();
            this.addressServiceMock = new Mock<IAddressService>();
            this.countryServiceMock = new Mock<ICountryService>();
            this.notificationServiceMock = new Mock<INotificationService>();

            this.userId = Guid.NewGuid();

            this.unauthenticatedContext = new UserContext
            {
                AccountId = null
            };

            this.authenticatedContext = new UserContext
            {
                AccountId = this.userId
            };

            this.germany = new Country
            {
                Id = Guid.NewGuid(),
                Name = "Germany"
            };

            this.france = new Country
            {
                Id = Guid.NewGuid(),
                Name = "France"
            };

            this.primaryAddress = new Address
            {
                Id = Guid.NewGuid(),
                AddressLine1 = "1 Main Street",
                Locality = "Darmstadt",
                Country = this.germany.Id,
                Owner = this.userId
            };

            this.secondaryAddress = new Address
            {
                Id = Guid.NewGuid(),
                AddressLine1 = "2 Rue de la Paix",
                Locality = "Toulouse",
                Country = this.france.Id,
                Owner = this.userId
            };

            this.profileWithAddresses = new Account
            {
                Id = this.userId,
                PrimaryAddress = this.primaryAddress.Id,
                Address = [this.primaryAddress.Id, this.secondaryAddress.Id]
            };

            this.profileNoAddresses = new Account
            {
                Id = this.userId,
                PrimaryAddress = null,
                Address = []
            };

            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);
            this.countryServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<ICountry>(this.germany, this.france));
            this.addressServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IAddress>(this.primaryAddress, this.secondaryAddress));

            this.viewModel = new AddressesManagerViewModel(this.loggerMock.Object, this.userServiceMock.Object, this.addressServiceMock.Object, this.countryServiceMock.Object, this.notificationServiceMock.Object);
        }

        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Scenario 1: Unauthenticated user logs warning and skips loading
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.unauthenticatedContext);

            await this.viewModel.InitializeViewModel(this.profileWithAddresses);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Countries, Is.Empty);
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(0));
                Assert.That(this.viewModel.PrimaryAddressId, Is.Null);
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
                this.countryServiceMock.Verify(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()), Times.Never);
                this.addressServiceMock.Verify(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()), Times.Never);
            }

            // Scenario 2: Authenticated with no addresses and country read error
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.authenticatedContext);
            this.countryServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(Error.Failure("Countries failed"));

            await this.viewModel.InitializeViewModel(this.profileNoAddresses);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Countries, Is.Empty);
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(0));
                Assert.That(this.viewModel.PrimaryAddressId, Is.Null);
                this.addressServiceMock.Verify(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()), Times.Never);
            }

            // Scenario 3: Happy path sorts countries by Name and populates addresses
            this.countryServiceMock.Setup(x => x.ReadAsync(this.authenticatedContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<ICountry>(this.germany, this.france));

            await this.viewModel.InitializeViewModel(this.profileWithAddresses);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(this.primaryAddress.Id));
                Assert.That(this.viewModel.Countries, Has.Count.EqualTo(2));
                Assert.That(this.viewModel.Countries[0].Name, Is.EqualTo("France"));
                Assert.That(this.viewModel.Countries[1].Name, Is.EqualTo("Germany"));
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(2));
            }
        }

        [Test]
        public async Task VerifyCreateAddress()
        {
            await this.viewModel.InitializeViewModel(this.profileNoAddresses);

            List<Guid?> primaryCallbackIds = [];

            this.viewModel.OnPrimaryAddressChanging = id =>
            {
                primaryCallbackIds.Add(id);
                return Task.FromResult<ErrorOr<Success>>(Result.Success);
            };

            var firstAddress = new Address
            {
                Id = Guid.NewGuid(),
                AddressLine1 = "10 Space Way",
                Locality = "Noordwijk",
                Country = this.germany.Id
            };

            // Scenario 1: CreateAsync failure
            this.addressServiceMock.Setup(x => x.CreateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAddress>>(), CancellationToken.None)).ReturnsAsync(Error.Failure("Create failed"));

            var createErrorResult = await this.viewModel.CreateAddress(firstAddress);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(createErrorResult.IsError, Is.True);
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(0));
                Assert.That(primaryCallbackIds, Is.Empty);
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to create address.", "Error", NotificationType.Error), Times.Once);
            }

            // Scenario 2: CreateAsync succeeds, no primary address yet, OnPrimaryAddressChanging fails
            this.addressServiceMock.Setup(x => x.CreateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAddress>>(), CancellationToken.None)).ReturnsAsync(Result.Created);

            this.viewModel.OnPrimaryAddressChanging = id =>
            {
                primaryCallbackIds.Add(id);
                return Task.FromResult<ErrorOr<Success>>(Error.Failure("Primary update failed"));
            };

            var primaryFailResult = await this.viewModel.CreateAddress(firstAddress);

            Guid?[] expectedFirstId = [firstAddress.Id];

            using (Assert.EnterMultipleScope())
            {
                Assert.That(primaryFailResult.IsError, Is.True);
                Assert.That(firstAddress.Owner, Is.EqualTo(this.userId));
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.PrimaryAddressId, Is.Null);
                Assert.That(primaryCallbackIds, Is.EqualTo(expectedFirstId));
                this.notificationServiceMock.Verify(x => x.AddNotification(It.IsAny<string>(), It.IsAny<string?>(), NotificationType.Success), Times.Never);
            }

            // Scenario 3: CreateAsync succeeds, no primary address yet, OnPrimaryAddressChanging succeeds
            var secondCandidate = new Address
            {
                Id = Guid.NewGuid(),
                AddressLine1 = "20 Orbit Blvd",
                Locality = "Toulouse",
                Country = this.france.Id
            };

            Guid?[] expectedSecondCandidateId = [secondCandidate.Id];

            this.viewModel.Addresses.Clear();
            primaryCallbackIds.Clear();

            this.viewModel.OnPrimaryAddressChanging = id =>
            {
                primaryCallbackIds.Add(id);
                return Task.FromResult<ErrorOr<Success>>(Result.Success);
            };

            var firstSuccessResult = await this.viewModel.CreateAddress(secondCandidate);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(firstSuccessResult.IsError, Is.False);
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(secondCandidate.Id));
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(1));
                Assert.That(primaryCallbackIds, Is.EqualTo(expectedSecondCandidateId));
                this.notificationServiceMock.Verify(x => x.AddNotification("Address created successfully.", "Address Created", NotificationType.Success), Times.Once);
            }

            // Scenario 4: CreateAsync succeeds when primary address is already set -> does not invoke OnPrimaryAddressChanging
            primaryCallbackIds.Clear();

            var thirdAddress = new Address
            {
                Id = Guid.NewGuid(),
                AddressLine1 = "30 Launch Rd",
                Locality = "Paris",
                Country = this.france.Id
            };

            var secondSuccessResult = await this.viewModel.CreateAddress(thirdAddress);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(secondSuccessResult.IsError, Is.False);
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(secondCandidate.Id));
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(2));
                Assert.That(primaryCallbackIds, Is.Empty);
                this.notificationServiceMock.Verify(x => x.AddNotification("Address created successfully.", "Address Created", NotificationType.Success), Times.Exactly(2));
            }
        }

        [Test]
        public async Task VerifyUpdateAddress()
        {
            await this.viewModel.InitializeViewModel(this.profileWithAddresses);

            // Scenario 1: UpdateAsync failure
            var failedUpdate = this.secondaryAddress.Clone();
            failedUpdate.Locality = "Lyon";
            this.addressServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAddress>>(), CancellationToken.None)).ReturnsAsync(Error.Failure("Update failed"));

            var failureResult = await this.viewModel.UpdateAddress(failedUpdate);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failureResult.IsError, Is.True);
                Assert.That(this.viewModel.Addresses.Items.Single(x => x.Id == this.secondaryAddress.Id).Locality, Is.EqualTo("Toulouse"));
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to update address.", "Error", NotificationType.Error), Times.Once);
            }

            // Scenario 2: UpdateAsync succeeds and replaces address in SourceList without changing PrimaryAddressId
            this.addressServiceMock.Setup(x => x.UpdateAsync(this.authenticatedContext, It.IsAny<IEnumerable<IAddress>>(), CancellationToken.None)).ReturnsAsync(Result.Updated);

            var succeededUpdate = this.secondaryAddress.Clone();
            succeededUpdate.Locality = "Marseille";

            var successResult = await this.viewModel.UpdateAddress(succeededUpdate);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(this.viewModel.Addresses.Items.Single(x => x.Id == this.secondaryAddress.Id).Locality, Is.EqualTo("Marseille"));
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(this.primaryAddress.Id));
                this.notificationServiceMock.Verify(x => x.AddNotification("Address updated successfully.", "Address Updated", NotificationType.Success), Times.Once);
            }
        }

        [Test]
        public async Task VerifySetPrimaryAddress()
        {
            await this.viewModel.InitializeViewModel(this.profileWithAddresses);

            List<Guid?> primaryCallbackIds = [];
            Guid?[] expectedSecondaryId = [this.secondaryAddress.Id];

            // Scenario 1: OnPrimaryAddressChanging failure preserves existing PrimaryAddressId
            this.viewModel.OnPrimaryAddressChanging = id =>
            {
                primaryCallbackIds.Add(id);
                return Task.FromResult<ErrorOr<Success>>(Error.Failure("Primary change failed"));
            };

            var failResult = await this.viewModel.SetPrimaryAddress(this.secondaryAddress.Id);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failResult.IsError, Is.True);
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(this.primaryAddress.Id));
                Assert.That(primaryCallbackIds, Is.EqualTo(expectedSecondaryId));
                this.notificationServiceMock.Verify(x => x.AddNotification(It.IsAny<string>(), It.IsAny<string?>(), NotificationType.Success), Times.Never);
            }

            // Scenario 2: Already primary is a no-op without callback or notification
            primaryCallbackIds.Clear();

            var alreadyPrimaryResult = await this.viewModel.SetPrimaryAddress(this.primaryAddress.Id);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(alreadyPrimaryResult.IsError, Is.False);
                Assert.That(primaryCallbackIds, Is.Empty);
                this.notificationServiceMock.Verify(x => x.AddNotification("Primary address updated.", "Primary Address Updated", NotificationType.Success), Times.Once);
            }

            // Scenario 3: Promoting non-primary updates PrimaryAddressId and notifies without calling AddressService.UpdateAsync
            this.viewModel.OnPrimaryAddressChanging = id =>
            {
                primaryCallbackIds.Add(id);
                return Task.FromResult<ErrorOr<Success>>(Result.Success);
            };

            var successResult = await this.viewModel.SetPrimaryAddress(this.secondaryAddress.Id);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(this.secondaryAddress.Id));
                Assert.That(primaryCallbackIds, Is.EqualTo(expectedSecondaryId));
                this.addressServiceMock.Verify(x => x.UpdateAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<IAddress>>(), It.IsAny<CancellationToken>()), Times.Never);
                this.notificationServiceMock.Verify(x => x.AddNotification("Primary address updated.", "Primary Address Updated", NotificationType.Success), Times.Exactly(2));
            }
        }

        [Test]
        public async Task VerifyDeleteAddress()
        {
            await this.viewModel.InitializeViewModel(this.profileWithAddresses);

            List<Guid?> primaryCallbackIds = [];
            Guid?[] expectedNullId = [null];

            // Scenario 1: Deleting primary address fails if OnPrimaryAddressChanging(null) fails
            this.viewModel.OnPrimaryAddressChanging = id =>
            {
                primaryCallbackIds.Add(id);
                return Task.FromResult<ErrorOr<Success>>(Error.Failure("Clear primary failed"));
            };

            var clearErrorResult = await this.viewModel.DeleteAddress(this.primaryAddress.Id);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(clearErrorResult.IsError, Is.True);
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(this.primaryAddress.Id));
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(2));
                Assert.That(primaryCallbackIds, Is.EqualTo(expectedNullId));
                this.addressServiceMock.Verify(x => x.DeleteAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()), Times.Never);
            }

            // Scenario 2: Deleting non-primary address fails in DeleteAsync
            primaryCallbackIds.Clear();

            this.viewModel.OnPrimaryAddressChanging = id =>
            {
                primaryCallbackIds.Add(id);
                return Task.FromResult<ErrorOr<Success>>(Result.Success);
            };

            this.addressServiceMock.Setup(x => x.DeleteAsync(this.authenticatedContext, It.IsAny<IEnumerable<Guid>>(), CancellationToken.None)).ReturnsAsync(Error.Failure("Delete failed"));

            var deleteErrorResult = await this.viewModel.DeleteAddress(this.secondaryAddress.Id);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(deleteErrorResult.IsError, Is.True);
                Assert.That(primaryCallbackIds, Is.Empty);
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(2));
                this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to delete address.", "Error", NotificationType.Error), Times.Once);
            }

            // Scenario 4: Deleting primary address fails in DeleteAsync -> restores PrimaryAddressId
            primaryCallbackIds.Clear();

            var deletePrimaryErrorResult = await this.viewModel.DeleteAddress(this.primaryAddress.Id);

            Guid?[] expectedRestoredIds = [null, this.primaryAddress.Id];

            using (Assert.EnterMultipleScope())
            {
                Assert.That(deletePrimaryErrorResult.IsError, Is.True);
                Assert.That(primaryCallbackIds, Is.EqualTo(expectedRestoredIds));
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(this.primaryAddress.Id));
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(2));
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to delete address.", "Error", NotificationType.Error), Times.Exactly(2));
            }

            // Scenario 5: Deleting non-primary address succeeds without clearing primary
            primaryCallbackIds.Clear();
            this.addressServiceMock.Setup(x => x.DeleteAsync(this.authenticatedContext, It.IsAny<IEnumerable<Guid>>(), CancellationToken.None)).ReturnsAsync(Result.Deleted);

            var deleteNonPrimaryResult = await this.viewModel.DeleteAddress(this.secondaryAddress.Id);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(deleteNonPrimaryResult.IsError, Is.False);
                Assert.That(primaryCallbackIds, Is.Empty);
                Assert.That(this.viewModel.PrimaryAddressId, Is.EqualTo(this.primaryAddress.Id));
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(1));
                this.notificationServiceMock.Verify(x => x.AddNotification("Address deleted successfully.", "Address Deleted", NotificationType.Success), Times.Once);
            }

            // Scenario 6: Deleting primary address clears PrimaryAddressId and removes address
            var deletePrimaryResult = await this.viewModel.DeleteAddress(this.primaryAddress.Id);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(deletePrimaryResult.IsError, Is.False);
                Assert.That(primaryCallbackIds, Is.EqualTo(expectedNullId));
                Assert.That(this.viewModel.PrimaryAddressId, Is.Null);
                Assert.That(this.viewModel.Addresses, Has.Count.EqualTo(0));
                this.notificationServiceMock.Verify(x => x.AddNotification("Address deleted successfully.", "Address Deleted", NotificationType.Success), Times.Exactly(2));
            }
        }
