namespace Mycelium.Forge.Tests.ViewModels.PackageSettings
{
    using System;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.PackageSettings;

    [TestFixture]
    public class TransferPackageOwnershipDialogViewModelTestFixture
    {
        private Mock<IPackageService> packageServiceMock;
        private Mock<IScopeService> scopeServiceMock;
        private Mock<IUserService> userServiceMock;
        private TransferPackageOwnershipDialogViewModel viewModel;
        private UserContext userContext;
        private Package package;
        private Guid userId;

        [SetUp]
        public void SetUp()
        {
            this.packageServiceMock = new Mock<IPackageService>();
            this.scopeServiceMock = new Mock<IScopeService>();
            this.userServiceMock = new Mock<IUserService>();

            this.userId = Guid.NewGuid();
            this.userContext = new UserContext { AccountId = this.userId, CurrentRoles = [RoleKind.Account] };
            this.package = new Package { Id = Guid.NewGuid(), ShortName = "ecss-mm-pwr" };

            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.userContext);
            this.packageServiceMock.Setup(x => x.ReadByCoordinateAsync(It.IsAny<IUserContext>(), It.IsAny<string>(), this.package.ShortName, true, It.IsAny<CancellationToken>())).ReturnsAsync(Error.NotFound(description: "Package not found."));

            this.viewModel = new TransferPackageOwnershipDialogViewModel(this.packageServiceMock.Object, this.scopeServiceMock.Object, this.userServiceMock.Object);
        }

        [Test]
        public async Task VerifyValidateTargetAsync()
        {
            // Case 1: Target scope not found
            this.SetupScope("unknown");
            var notFoundResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "unknown", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(notFoundResult.IsError, Is.True);
                Assert.That(notFoundResult.FirstError.Type, Is.EqualTo(ErrorType.NotFound));
            }

            // Case 2: Target scope lookup fails
            this.scopeServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(names => names.Length == 1 && names[0] == "broken"))).ReturnsAsync(Error.Failure(description: "Lookup failed."));
            var lookupFailResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "broken", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(lookupFailResult.IsError, Is.True);
                Assert.That(lookupFailResult.FirstError.Type, Is.EqualTo(ErrorType.NotFound));
            }

            // Case 3: Current owner scope is rejected even when the user administers it
            var currentOrganization = new Organization { Id = Guid.NewGuid(), ShortName = "starion", Administrator = [this.userId] };
            this.SetupScope("starion", currentOrganization);
            var currentOwnerResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "starion", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(currentOwnerResult.IsError, Is.True);
                Assert.That(currentOwnerResult.FirstError.Type, Is.EqualTo(ErrorType.Validation));
                Assert.That(currentOwnerResult.FirstError.Description, Is.EqualTo("You cannot transfer ownership to the current owner scope."));
            }

            // Case 4: Organization the user does not administer is rejected
            var foreignOrganization = new Organization { Id = Guid.NewGuid(), ShortName = "foreign-org", Administrator = [Guid.NewGuid()] };
            this.SetupScope("foreign-org", foreignOrganization);
            var foreignOrganizationResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "foreign-org", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(foreignOrganizationResult.IsError, Is.True);
                Assert.That(foreignOrganizationResult.FirstError.Type, Is.EqualTo(ErrorType.Validation));
                Assert.That(foreignOrganizationResult.FirstError.Description, Is.EqualTo("You do not have administrative rights on the target organization."));
            }

            // Case 5: Organization administrator of a different organization is rejected
            this.userContext.CurrentRoles = [RoleKind.Account, RoleKind.OrganizationAdministrator];
            var otherOrganizationResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "foreign-org", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(otherOrganizationResult.IsError, Is.True);
                Assert.That(otherOrganizationResult.FirstError.Description, Is.EqualTo("You do not have administrative rights on the target organization."));
            }

            // Case 6: Installation administrator may target an organization they do not administer
            this.userContext.CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator];
            var installationAdministratorResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "foreign-org", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(installationAdministratorResult.IsError, Is.False);
                Assert.That(installationAdministratorResult.Value, Is.SameAs(foreignOrganization));
            }

            // Case 7: Account that is not the user's own account is rejected
            this.userContext.CurrentRoles = [RoleKind.Account];
            var foreignAccount = new Account { Id = Guid.NewGuid(), ShortName = "foreign-user" };
            this.SetupScope("foreign-user", foreignAccount);
            var foreignAccountResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "foreign-user", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(foreignAccountResult.IsError, Is.True);
                Assert.That(foreignAccountResult.FirstError.Type, Is.EqualTo(ErrorType.Validation));
                Assert.That(foreignAccountResult.FirstError.Description, Is.EqualTo("Ownership can only be transferred to your own account or to an organization you administer."));
            }

            // Case 8: Installation administrator may target an account that is not their own
            this.userContext.CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator];
            var installationAdministratorAccountResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "foreign-user", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(installationAdministratorAccountResult.IsError, Is.False);
                Assert.That(installationAdministratorAccountResult.Value, Is.SameAs(foreignAccount));
            }

            // Case 9: Own account is accepted
            this.userContext.CurrentRoles = [RoleKind.Account];
            var ownAccount = new Account { Id = this.userId, ShortName = "own-user" };
            this.SetupScope("own-user", ownAccount);
            var ownAccountResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "own-user", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(ownAccountResult.IsError, Is.False);
                Assert.That(ownAccountResult.Value, Is.SameAs(ownAccount));
            }

            // Case 10: Administered organization is accepted
            var administeredOrganization = new Organization { Id = Guid.NewGuid(), ShortName = "administered-org", Administrator = [this.userId] };
            this.SetupScope("administered-org", administeredOrganization);
            var administeredOrganizationResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "administered-org", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(administeredOrganizationResult.IsError, Is.False);
                Assert.That(administeredOrganizationResult.Value, Is.SameAs(administeredOrganization));
            }

            // Case 11: Coordinate already occupied in the target scope is a conflict (permissions bypassed)
            this.packageServiceMock.Setup(x => x.ReadByCoordinateAsync(It.IsAny<IUserContext>(), "administered-org", this.package.ShortName, true, It.IsAny<CancellationToken>())).ReturnsAsync(new Package { Id = Guid.NewGuid(), ShortName = this.package.ShortName });
            var conflictResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "administered-org", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(conflictResult.IsError, Is.True);
                Assert.That(conflictResult.FirstError.Type, Is.EqualTo(ErrorType.Conflict));
                this.packageServiceMock.Verify(x => x.ReadByCoordinateAsync(this.userContext, "administered-org", this.package.ShortName, true, It.IsAny<CancellationToken>()), Times.Exactly(2));
            }

            // Case 12: Coordinate lookup failure other than NotFound is a failure
            this.packageServiceMock.Setup(x => x.ReadByCoordinateAsync(It.IsAny<IUserContext>(), "administered-org", this.package.ShortName, true, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure(description: "Database unavailable."));
            var coordinateFailureResult = await this.viewModel.ValidateTargetAsync(this.package, "starion", "administered-org", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(coordinateFailureResult.IsError, Is.True);
                Assert.That(coordinateFailureResult.FirstError.Type, Is.EqualTo(ErrorType.Failure));
            }
        }

        private void SetupScope(string shortName, IScope? scope = null)
        {
            var scopes = scope == null ? ImmutableList<IScope>.Empty : ImmutableList.Create(scope);
            this.scopeServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<string[]>(names => names.Length == 1 && names[0] == shortName))).ReturnsAsync(scopes);
        }
    }
}
