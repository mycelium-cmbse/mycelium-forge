        [Test]
        public async Task VerifyDeletePackage()
        {
            this.viewModel.Package = this.package;

            // Scenario 1: Failure
            this.packageServiceMock.Setup(x => x.DeleteAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure("Delete failed"));

            var failResult = await this.viewModel.DeletePackage(CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(failResult.IsError, Is.True);
                this.notificationServiceMock.Verify(x => x.AddNotification("Failed to delete package.", "Delete Failed", NotificationType.Error), Times.Once);
            }

            // Scenario 2: Success
            this.packageServiceMock.Setup(x => x.DeleteAsync(It.IsAny<IUserContext>(), It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Result.Deleted);

            var successResult = await this.viewModel.DeletePackage(CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                this.notificationServiceMock.Verify(x => x.AddNotification("Package deleted successfully.", "Package Deleted", NotificationType.Success), Times.Once);
            }
        }

