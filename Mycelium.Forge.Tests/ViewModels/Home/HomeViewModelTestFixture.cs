namespace Mycelium.Forge.Tests.ViewModels.Home
{
    using System;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.Home;

    /// <summary>
    /// Test fixture for <see cref="HomeViewModel" />.
    /// </summary>
    [TestFixture]
    public class HomeViewModelTestFixture
    {
        private Mock<IPackageService> packageServiceMock;
        private Mock<IScopeService> scopeServiceMock;
        private Mock<IPackageVersionService> packageVersionServiceMock;
        private Mock<IPackageTypeService> packageTypeServiceMock;
        private Mock<IUserService> userServiceMock;
        private IUserContext userContext;
        private HomeViewModel viewModel;

        /// <summary>
        /// Sets up mock dependencies and creates the view model before each test.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.packageServiceMock = new Mock<IPackageService>();
            this.scopeServiceMock = new Mock<IScopeService>();
            this.packageVersionServiceMock = new Mock<IPackageVersionService>();
            this.packageTypeServiceMock = new Mock<IPackageTypeService>();
            this.userServiceMock = new Mock<IUserService>();

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "testuser"
            };

            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.userContext);

            this.viewModel = new HomeViewModel(
                this.packageServiceMock.Object,
                this.scopeServiceMock.Object,
                this.packageVersionServiceMock.Object,
                this.packageTypeServiceMock.Object,
                this.userServiceMock.Object);
        }

        /// <summary>
        /// Verifies that <see cref="HomeViewModel.InitializeViewModel" /> loads packages, scopes, and types.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        [Test]
        public async Task VerifyInitializeViewModel()
        {
            var orgId = Guid.NewGuid();
            var typeSysmlId = Guid.NewGuid();
            var typeCdp4Id = Guid.NewGuid();

            var version1 = new PackageVersion { Id = Guid.NewGuid(), Owner = orgId, Version = "v2025.2", DownloadCount = 500, Listed = true, PublicationDate = DateTime.UtcNow.AddDays(-5) };
            var version2 = new PackageVersion { Id = Guid.NewGuid(), Owner = orgId, Version = "v1.0.0", DownloadCount = 200, Listed = true, PublicationDate = DateTime.UtcNow.AddDays(-15) };

            var sysmlPackage = new Package
            {
                Id = Guid.NewGuid(),
                Owner = orgId,
                PackageType = typeSysmlId,
                Version = [version1.Id],
                Name = "SysMLv2-ISQ-Quantities",
                ShortName = "sysmlv2-isq-quantities",
                CreatedAt = DateTime.UtcNow.AddDays(-10)
            };

            version1.Owner = sysmlPackage.Id;

            var otherPackage = new Package
            {
                Id = Guid.NewGuid(),
                Owner = orgId,
                PackageType = typeCdp4Id,
                Version = [version2.Id],
                Name = "CDP4-COMET-Core",
                ShortName = "cdp4-comet-core",
                CreatedAt = DateTime.UtcNow.AddDays(-20)
            };

            version2.Owner = otherPackage.Id;

            var packages = ImmutableList.Create<IPackage>(sysmlPackage, otherPackage);

            var scopes = ImmutableList.Create<IScope>(
                new Organization { Id = orgId, ShortName = "omg" }
            );

            var versions = ImmutableList.Create<IPackageVersion>(version1, version2);

            var types = ImmutableList.Create<IPackageType>(
                new PackageType { Id = typeSysmlId, Name = PackageFormatConstants.SysMlV2 },
                new PackageType { Id = typeCdp4Id, Name = "Cdp4Comet" }
            );

            this.packageServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, null))
                .ReturnsAsync(ErrorOrFactory.From(packages));

            this.scopeServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(scopes));

            this.packageVersionServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(versions));

            this.packageTypeServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(types));

            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.PackageCount, Is.EqualTo(2));
                Assert.That(this.viewModel.VersionCount, Is.EqualTo(2));
                Assert.That(this.viewModel.PublisherCount, Is.EqualTo(1));
                Assert.That(this.viewModel.DownloadCount, Is.Zero);
                Assert.That(this.viewModel.StandardLibraries, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.RecentlyUpdated, Has.Count.EqualTo(2));
                Assert.That(this.viewModel.MostUsed, Has.Count.EqualTo(2));
                Assert.That(this.viewModel.ModelsFromOtherMbseTools, Has.Count.EqualTo(1));
            }

            this.packageServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, null))
                .ReturnsAsync(Error.Failure("Failed to read packages"));

            await this.viewModel.InitializeViewModel();

            this.userServiceMock.Verify(x => x.GetUserContext(false), Times.Exactly(2));
        }
    }
}
