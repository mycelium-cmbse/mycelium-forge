namespace Mycelium.Forge.Tests.ViewModels.OrganizationDetails
{
    using System;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.OrganizationDetails;

    using Npgsql;

    [TestFixture]
    public class OrganizationDetailsViewModelTestFixture
    {
        private Mock<IDatabaseSource> databaseSourceMock;
        private Mock<IOrganizationService> organizationServiceMock;
        private Mock<IOrganizationPermissionService> organizationPermissionServiceMock;
        private Mock<IPackageService> packageServiceMock;
        private Mock<IPackageVersionService> packageVersionServiceMock;
        private Mock<IPackageTypeService> packageTypeServiceMock;
        private Mock<IUserService> userServiceMock;
        private Mock<ILogger<OrganizationDetailsViewModel>> loggerMock;
        private OrganizationDetailsViewModel viewModel;
        private Organization organization;
        private Package package;
        private PackageVersion packageVersion;
        private PackageType packageType;
        private UserContext adminUserContext;
        private UserContext installAdminContext;
        private UserContext regularUserContext;

        [SetUp]
        public void SetUp()
        {
            this.databaseSourceMock = new Mock<IDatabaseSource>();
            this.organizationServiceMock = new Mock<IOrganizationService>();
            this.packageServiceMock = new Mock<IPackageService>();
            this.packageVersionServiceMock = new Mock<IPackageVersionService>();
            this.packageTypeServiceMock = new Mock<IPackageTypeService>();
            this.userServiceMock = new Mock<IUserService>();
            this.loggerMock = new Mock<ILogger<OrganizationDetailsViewModel>>();

            var adminAccountId = Guid.NewGuid();
            var nonAdminAccountId = Guid.NewGuid();
            var orgId = Guid.NewGuid();
            var packageId = Guid.NewGuid();
            var versionId = Guid.NewGuid();
            var packageTypeId = Guid.NewGuid();

            this.organization = new Organization
            {
                Id = orgId,
                Name = "Starion Group",
                ShortName = "starion",
                Origin = "https://example.com",
                Administrator = [adminAccountId],
                OwnedPackage = [packageId]
            };

            this.package = new Package
            {
                Id = packageId,
                Name = "sysmlv2-kernel-library",
                ShortName = "sysmlv2-kernel-library",
                Owner = orgId,
                Version = [versionId],
                PackageType = packageTypeId
            };

            this.packageVersion = new PackageVersion
            {
                Id = versionId,
                Owner = packageId,
                Version = "1.0.0",
                Listed = true,
                PublicationDate = DateTime.UtcNow
            };

            this.packageType = new PackageType
            {
                Id = packageTypeId,
                Name = "SysML v2"
            };

            this.adminUserContext = new UserContext
            {
                AccountId = adminAccountId,
                CurrentRoles = [RoleKind.Account]
            };

            this.installAdminContext = new UserContext
            {
                AccountId = nonAdminAccountId,
                CurrentRoles = [RoleKind.InstallationAdministrator]
            };

            this.regularUserContext = new UserContext
            {
                AccountId = nonAdminAccountId,
                CurrentRoles = [RoleKind.Account]
            };

            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.adminUserContext);
            this.organizationServiceMock.Setup(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), "starion", It.IsAny<CancellationToken>())).ReturnsAsync(this.organization);
            this.packageServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IPackage>(this.package));
            this.packageVersionServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IPackageVersion>(this.packageVersion));
            this.packageTypeServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IPackageType>(this.packageType));

            this.organizationPermissionServiceMock = new Mock<IOrganizationPermissionService>();

            this.organizationPermissionServiceMock.Setup(x => x.IsAllowedToUpdate(It.IsAny<IUserContext>(), It.IsAny<IOrganization>(), It.IsAny<IOrganization>(), It.IsAny<NpgsqlTransaction>()))
                .ReturnsAsync(Result.Success);

            this.viewModel = new OrganizationDetailsViewModel(this.databaseSourceMock.Object, this.organizationServiceMock.Object, this.packageServiceMock.Object, this.packageVersionServiceMock.Object, this.packageTypeServiceMock.Object, this.userServiceMock.Object, this.organizationPermissionServiceMock.Object, this.loggerMock.Object);
        }

        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Scenario 1: Organization service returns error (null org early return with warning log)
            this.organizationServiceMock.Setup(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), "unknown", It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.NotFound("Not found"));

            await this.viewModel.InitializeViewModel("unknown");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Organization, Is.Null);
                Assert.That(this.viewModel.Packages, Has.Count.EqualTo(0));
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 2: Exception handling with error log
            this.organizationServiceMock.Setup(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), "fail", It.IsAny<CancellationToken>()))
                .ThrowsAsync(new InvalidOperationException("DB error"));

            await this.viewModel.InitializeViewModel("fail");

            this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);

            // Scenario 3: Happy path with admin by membership
            await this.viewModel.InitializeViewModel("@starion");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Organization, Is.Not.Null);
                Assert.That(this.viewModel.Organization.ShortName, Is.EqualTo("starion"));
                Assert.That(this.viewModel.IsUserAdmin, Is.True);
                Assert.That(this.viewModel.Packages, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.Packages[0].IsVerified, Is.False);
            }

            // Scenario 4: User is admin by permission (InstallationAdministrator)
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.installAdminContext);

            await this.viewModel.InitializeViewModel("starion");
            Assert.That(this.viewModel.IsUserAdmin, Is.True);

            // Scenario 5: User is not admin
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.regularUserContext);

            this.organizationPermissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.regularUserContext, It.IsAny<IOrganization>(), It.IsAny<IOrganization>(), It.IsAny<NpgsqlTransaction>()))
                .ReturnsAsync(Error.Forbidden());

            await this.viewModel.InitializeViewModel("starion");
            Assert.That(this.viewModel.IsUserAdmin, Is.False);
        }
    }
}
