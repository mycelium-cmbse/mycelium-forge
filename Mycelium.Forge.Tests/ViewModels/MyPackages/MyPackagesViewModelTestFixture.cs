namespace Mycelium.Forge.Tests.ViewModels.MyPackages
{
    using System;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Data;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.MyPackages;

    /// <summary>
    /// Suite of tests for the <see cref="MyPackagesViewModel" /> class.
    /// </summary>
    [TestFixture]
    public class MyPackagesViewModelTestFixture
    {
        private Mock<IPackageService> packageServiceMock;
        private Mock<IScopeService> scopeServiceMock;
        private Mock<IPackageVersionService> packageVersionServiceMock;
        private Mock<IUserService> userServiceMock;
        private Mock<ILogger<MyPackagesViewModel>> loggerMock;
        private MyPackagesViewModel viewModel;
        private IAccount testAccount;
        private IUserContext userContext;
        private Package testPackage1;
        private Package testPackage2;
        private Organization testOrg;
        private PackageVersion version1;
        private PackageVersion version2;

        /// <summary>
        /// Sets up mock dependencies and test instances before each test.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.packageServiceMock = new Mock<IPackageService>();
            this.scopeServiceMock = new Mock<IScopeService>();
            this.packageVersionServiceMock = new Mock<IPackageVersionService>();
            this.userServiceMock = new Mock<IUserService>();
            this.loggerMock = new Mock<ILogger<MyPackagesViewModel>>();

            this.testAccount = SeedData.RegisAccount;

            this.userContext = new UserContext
            {
                AccountId = this.testAccount.Id,
                Username = this.testAccount.ShortName,
                CurrentRoles = [RoleKind.Account]
            };

            this.testOrg = new Organization
            {
                Id = Guid.NewGuid(),
                Name = "Starion Group",
                ShortName = "starion"
            };

            this.version1 = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Owner = Guid.NewGuid(),
                Version = "1.0.0",
                Listed = true,
                PublicationDate = DateTime.UtcNow.AddDays(-10)
            };

            this.version2 = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Owner = Guid.NewGuid(),
                Version = "2.0.0",
                Listed = true,
                PublicationDate = DateTime.UtcNow
            };

            this.testPackage1 = new Package
            {
                Id = this.version1.Owner,
                Name = "ECSS-MM-PWR",
                ShortName = "ecss-mm-pwr",
                Owner = this.testOrg.Id,
                PackageOwner = [this.testAccount.Id],
                PackageMaintainer = [],
                Version = [this.version1.Id],
                Visibility = VisibilityKind.PUBLIC
            };

            this.testPackage2 = new Package
            {
                Id = this.version2.Owner,
                Name = "Internal-Core",
                ShortName = "internal-core",
                Owner = this.testAccount.Id,
                PackageOwner = [Guid.NewGuid()],
                PackageMaintainer = [this.testAccount.Id],
                Version = [this.version2.Id],
                Visibility = VisibilityKind.PRIVATE
            };

            this.userServiceMock
                .Setup(s => s.GetCurrentUser(It.IsAny<bool>()))
                .ReturnsAsync(this.testAccount);

            this.userServiceMock
                .Setup(s => s.GetUserContext(It.IsAny<bool>()))
                .ReturnsAsync(this.userContext);

            this.packageServiceMock
                .Setup(s => s.ReadByMaintainerOrOwnerAsync(this.userContext, this.testAccount.Id, It.IsAny<CancellationToken>()))
                .ReturnsAsync(ImmutableList.Create<IPackage>(this.testPackage1, this.testPackage2));

            this.scopeServiceMock
                .Setup(s => s.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()))
                .ReturnsAsync(ImmutableList.Create<IScope>(this.testOrg, this.testAccount));

            this.packageVersionServiceMock
                .Setup(s => s.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()))
                .ReturnsAsync(ImmutableList.Create<IPackageVersion>(this.version1, this.version2));

            this.viewModel = new MyPackagesViewModel(
                this.packageServiceMock.Object,
                this.scopeServiceMock.Object,
                this.packageVersionServiceMock.Object,
                this.userServiceMock.Object,
                this.loggerMock.Object);
        }

        /// <summary>
        /// Tears down the view model after each test execution.
        /// </summary>
        [TearDown]
        public void TearDown()
        {
            this.viewModel.Dispose();
        }

        /// <summary>
        /// Verifies the <see cref="MyPackagesViewModel" /> constructor.
        /// </summary>
        [Test]
        public void VerifyConstructor()
        {
            var instance = new MyPackagesViewModel(
                this.packageServiceMock.Object,
                this.scopeServiceMock.Object,
                this.packageVersionServiceMock.Object,
                this.userServiceMock.Object,
                this.loggerMock.Object);

            Assert.That(instance, Is.Not.Null);
        }

        /// <summary>
        /// Verifies all scenarios of <see cref="MyPackagesViewModel.GetLatestVersion" />.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyGetLatestVersion()
        {
            await this.viewModel.InitializeViewModel();

            var latestVersion1 = this.viewModel.GetLatestVersion(this.testPackage1);
            var latestVersion2 = this.viewModel.GetLatestVersion(this.testPackage2);

            var packageWithNoListed = new Package { Id = Guid.NewGuid(), Owner = this.testOrg.Id, Version = [] };
            var noListedVersion = this.viewModel.GetLatestVersion(packageWithNoListed);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(latestVersion1, Is.Not.Null);
                Assert.That(latestVersion1.Version, Is.EqualTo(this.version1.Version));
                Assert.That(latestVersion2, Is.Not.Null);
                Assert.That(latestVersion2.Version, Is.EqualTo(this.version2.Version));
                Assert.That(noListedVersion, Is.Null);
            }
        }

        /// <summary>
        /// Verifies all scenarios of <see cref="MyPackagesViewModel.GetPublisher" />.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyGetPublisher()
        {
            await this.viewModel.InitializeViewModel();

            var starionPublisher = this.viewModel.GetPublisher(this.testPackage1);
            var accountPublisher = this.viewModel.GetPublisher(this.testPackage2);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(starionPublisher, Is.EqualTo($"@{this.testOrg.ShortName}"));
                Assert.That(accountPublisher, Is.EqualTo($"@{this.testAccount.ShortName}"));
            }
        }

        /// <summary>
        /// Verifies all scenarios of <see cref="MyPackagesViewModel.GetRole" />.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyGetRole()
        {
            await this.viewModel.InitializeViewModel();

            // testPackage1: user is in PackageOwner -> OWNER
            var role1 = this.viewModel.GetRole(this.testPackage1);

            // testPackage2: user is Owner (scope) -> OWNER
            var role2 = this.viewModel.GetRole(this.testPackage2);

            // Maintainer-only package
            var maintainerPackage = new Package
            {
                Id = Guid.NewGuid(),
                Owner = Guid.NewGuid(),
                PackageOwner = [Guid.NewGuid()],
                PackageMaintainer = [this.testAccount.Id]
            };

            var maintainerRole = this.viewModel.GetRole(maintainerPackage);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(role1, Is.EqualTo(PackageInvitationKind.OWNER));
                Assert.That(role2, Is.EqualTo(PackageInvitationKind.OWNER));
                Assert.That(maintainerRole, Is.EqualTo(PackageInvitationKind.MAINTAINER));
            }
        }

        /// <summary>
        /// Verifies all scenarios of <see cref="MyPackagesViewModel.InitializeViewModel" />.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Case 1: Happy path
            await this.viewModel.InitializeViewModel();

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Packages, Has.Count.EqualTo(2));
                Assert.That(this.viewModel.Packages[0].Id, Is.EqualTo(this.testPackage1.Id));
                Assert.That(this.viewModel.Packages[1].Id, Is.EqualTo(this.testPackage2.Id));
            }

            // Case 2: Unauthenticated user context
            var unauthUserContext = new UserContext
            {
                AccountId = null,
                Username = null,
                CurrentRoles = []
            };

            this.userServiceMock
                .Setup(s => s.GetUserContext(It.IsAny<bool>()))
                .ReturnsAsync(unauthUserContext);

            await this.viewModel.InitializeViewModel();
            Assert.That(this.viewModel.Packages, Has.Count.EqualTo(0));

            // Case 3: PackageService returns error
            this.userServiceMock
                .Setup(s => s.GetUserContext(It.IsAny<bool>()))
                .ReturnsAsync(this.userContext);

            this.userServiceMock
                .Setup(s => s.GetCurrentUser(It.IsAny<bool>()))
                .ReturnsAsync(this.testAccount);

            this.packageServiceMock
                .Setup(s => s.ReadByMaintainerOrOwnerAsync(this.userContext, this.testAccount.Id, It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "Database error"));

            await this.viewModel.InitializeViewModel();
            Assert.That(this.viewModel.Packages, Has.Count.EqualTo(0));

            // Case 4: PackageService returns empty list
            this.packageServiceMock
                .Setup(s => s.ReadByMaintainerOrOwnerAsync(this.userContext, this.testAccount.Id, It.IsAny<CancellationToken>()))
                .ReturnsAsync(ImmutableList<IPackage>.Empty);

            await this.viewModel.InitializeViewModel();
            Assert.That(this.viewModel.Packages, Has.Count.EqualTo(0));

            // Case 5: Exception thrown
            this.packageServiceMock
                .Setup(s => s.ReadByMaintainerOrOwnerAsync(this.userContext, this.testAccount.Id, It.IsAny<CancellationToken>()))
                .ThrowsAsync(new InvalidOperationException("Connection failed"));

            await this.viewModel.InitializeViewModel();
            Assert.That(this.viewModel.Packages, Has.Count.EqualTo(0));
        }
    }
}
