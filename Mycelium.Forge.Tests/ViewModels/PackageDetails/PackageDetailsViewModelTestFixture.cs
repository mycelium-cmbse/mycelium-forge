namespace Mycelium.Forge.Tests.ViewModels.PackageDetails
{
    using System;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Caching.Memory;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.PackageDetails;

    /// <summary>
    /// Test fixture for <see cref="PackageDetailsViewModel" />.
    /// </summary>
    [TestFixture]
    public class PackageDetailsViewModelTestFixture
    {
        private Mock<IPackageService> packageServiceMock;
        private Mock<IOrganizationService> organizationServiceMock;
        private Mock<IPackageVersionService> packageVersionServiceMock;
        private Mock<IPackageMetaDataService> packageMetaDataServiceMock;
        private Mock<IPackageTypeService> packageTypeServiceMock;
        private Mock<IAccountService> accountServiceMock;
        private Mock<IUserService> userServiceMock;
        private IMemoryCache memoryCache;
        private IUserContext userContext;
        private PackageDetailsViewModel viewModel;

        /// <summary>
        /// Sets up the test context and mocks before each test execution.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.packageServiceMock = new Mock<IPackageService>();
            this.organizationServiceMock = new Mock<IOrganizationService>();
            this.packageVersionServiceMock = new Mock<IPackageVersionService>();
            this.packageMetaDataServiceMock = new Mock<IPackageMetaDataService>();
            this.packageTypeServiceMock = new Mock<IPackageTypeService>();
            this.accountServiceMock = new Mock<IAccountService>();
            this.userServiceMock = new Mock<IUserService>();
            this.memoryCache = new MemoryCache(new MemoryCacheOptions());

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "testuser"
            };

            this.userServiceMock.Setup(x => x.GetUserContext()).Returns(this.userContext);

            this.viewModel = new PackageDetailsViewModel(
                this.packageServiceMock.Object,
                this.organizationServiceMock.Object,
                this.packageVersionServiceMock.Object,
                this.packageMetaDataServiceMock.Object,
                this.packageTypeServiceMock.Object,
                this.accountServiceMock.Object,
                this.userServiceMock.Object,
                this.memoryCache);
        }

        /// <summary>
        /// Tears down the test context after each test execution.
        /// </summary>
        [TearDown]
        public void TearDown()
        {
            this.memoryCache.Dispose();
        }

        /// <summary>
        /// Verifies that <see cref="PackageDetailsViewModel.InitializeViewModel" /> loads and populates package details from
        /// services and cache.
        /// </summary>
        [Test]
        public async Task VerifyInitializeViewModel()
        {
            var orgId = Guid.NewGuid();
            var typeId = Guid.NewGuid();
            var metaDataId = Guid.NewGuid();
            var maintainerId = Guid.NewGuid();

            var version = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Version = "1.3.0",
                MetaData = metaDataId,
                PublicationDate = DateTime.UtcNow.AddDays(-2)
            };

            var package = new Package
            {
                Id = Guid.NewGuid(),
                Name = "ECSS-MM-PWR",
                ShortName = "ecss-mm-pwr",
                Owner = orgId,
                PackageType = typeId,
                Version = [version.Id],
                PackageMaintainer = [maintainerId]
            };

            var org = new Organization
            {
                Id = orgId,
                Name = "Starion Group",
                ShortName = "starion"
            };

            var packageType = new PackageType
            {
                Id = typeId,
                Name = "SysML v2"
            };

            var maintainer = new Account
            {
                Id = maintainerId,
                Name = "Alex Rivera",
                IsVerified = true
            };

            var metaData = new PackageMetaData
            {
                Id = metaDataId,
                Owner = version.Id,
                MetadataSource = MetadataSource.DeclaredByArtefact,
                Elements = [("PowerSubsystem", "«part def»", "Parts", "3 parts")],
                Dependencies = [("@esa/CoreTypes", "Core types", true)],
                QualityChecks = [("Schema check", "Passed", true)]
            };

            this.packageServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IPackage>(package)));

            this.organizationServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IOrganization>(org)));

            this.packageTypeServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IPackageType>(packageType)));

            this.packageVersionServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IPackageVersion>(version)));

            this.accountServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IAccount>(maintainer)));

            this.packageMetaDataServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IPackageMetaData>(metaData)));

            // First call: loads from services
            await this.viewModel.InitializeViewModel("ecss-mm-pwr", "starion", PackageTabConstants.Versions);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Package, Is.Not.Null);
                Assert.That(this.viewModel.Package.Name, Is.EqualTo("ECSS-MM-PWR"));
                Assert.That(this.viewModel.Organization, Is.EqualTo(org));
                Assert.That(this.viewModel.PackageType, Is.EqualTo(packageType));
                Assert.That(this.viewModel.Versions, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.CurrentVersion, Is.EqualTo(version));
                Assert.That(this.viewModel.Maintainers, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.MetaDatas, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.CurrentMetaData, Is.EqualTo(metaData));
                Assert.That(this.viewModel.Elements, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.Dependencies, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.Dependents, Has.Count.EqualTo(0));
                Assert.That(this.viewModel.QualityChecks, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.IsUserAdmin, Is.True);
            }

            // Second call: loaded from cache
            await this.viewModel.InitializeViewModel("ecss-mm-pwr", "starion", PackageTabConstants.Overview);

            this.packageServiceMock.Verify(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()), Times.Once);

            // Non-existent package
            this.packageServiceMock
                .Setup(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()))
                .ReturnsAsync(ErrorOrFactory.From(ImmutableList<IPackage>.Empty));

            await this.viewModel.InitializeViewModel("nonexistent", "other-org");
            Assert.That(this.viewModel.Package, Is.EqualTo(package));
        }
    }
}
