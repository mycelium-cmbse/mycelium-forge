namespace Mycelium.Forge.Tests.ViewModels.PackageDetails
{
    using System;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Caching.Memory;
    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.PackageDetails;

    using Npgsql;

    [TestFixture]
    public class PackageDetailsViewModelTestFixture
    {
        private Mock<IDatabaseSource> databaseSourceMock;
        private Mock<IPackageService> packageServiceMock;
        private Mock<IScopeService> scopeServiceMock;
        private Mock<IPackageVersionService> packageVersionServiceMock;
        private Mock<IPackageMetaDataService> packageMetaDataServiceMock;
        private Mock<IPackageTypeService> packageTypeServiceMock;
        private Mock<IAccountService> accountServiceMock;
        private Mock<IUserService> userServiceMock;
        private Mock<IPackagePermissionService> packagePermissionServiceMock;
        private Mock<ILogger<PackageDetailsViewModel>> loggerMock;
        private MemoryCache memoryCache;
        private UserContext userContext;
        private PackageDetailsViewModel viewModel;
        private PackageVersion version;
        private Package package;
        private Organization org;
        private PackageType packageType;
        private Account maintainer;
        private PackageMetaData metaData;

        [SetUp]
        public void SetUp()
        {
            this.databaseSourceMock = new Mock<IDatabaseSource>();
            this.packageServiceMock = new Mock<IPackageService>();
            this.scopeServiceMock = new Mock<IScopeService>();
            this.packageVersionServiceMock = new Mock<IPackageVersionService>();
            this.packageMetaDataServiceMock = new Mock<IPackageMetaDataService>();
            this.packageTypeServiceMock = new Mock<IPackageTypeService>();
            this.accountServiceMock = new Mock<IAccountService>();
            this.userServiceMock = new Mock<IUserService>();
            this.packagePermissionServiceMock = new Mock<IPackagePermissionService>();
            this.loggerMock = new Mock<ILogger<PackageDetailsViewModel>>();
            this.memoryCache = new MemoryCache(new MemoryCacheOptions());

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "testuser"
            };

            var orgId = Guid.NewGuid();
            var typeId = Guid.NewGuid();
            var metaDataId = Guid.NewGuid();
            var maintainerId = Guid.NewGuid();

            this.version = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Version = "1.3.0",
                MetaData = metaDataId,
                PublicationDate = DateTime.UtcNow.AddDays(-2)
            };

            this.package = new Package
            {
                Id = Guid.NewGuid(),
                Name = "ECSS-MM-PWR",
                ShortName = "ecss-mm-pwr",
                Owner = orgId,
                PackageType = typeId,
                Version = [this.version.Id],
                PackageMaintainer = [maintainerId]
            };

            this.org = new Organization
            {
                Id = orgId,
                Name = "Starion Group",
                ShortName = "starion"
            };

            this.packageType = new PackageType
            {
                Id = typeId,
                Name = "SysML v2"
            };

            this.maintainer = new Account
            {
                Id = maintainerId,
                Name = "Alex Rivera",
                IsVerified = true
            };

            this.metaData = new PackageMetaData
            {
                Id = metaDataId,
                Owner = this.version.Id,
                MetadataSource = MetadataSource.DeclaredByArtefact,
                Elements = [("PowerSubsystem", "«part def»", "Parts", "3 parts")],
                Dependencies = [("@esa/CoreTypes", "Core types", true)],
                QualityChecks = [("Schema check", "Passed", true)]
            };

            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.userContext);
            this.packageServiceMock.Setup(x => x.ReadByCoordinateAsync(this.userContext, "starion", "ecss-mm-pwr", It.IsAny<CancellationToken>())).ReturnsAsync(ErrorOrFactory.From<IPackage>(this.package));
            this.scopeServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IScope>(this.org)));
            this.packageTypeServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IPackageType>(this.packageType)));
            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IPackageVersion>(this.version)));
            this.accountServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IAccount>(this.maintainer)));
            this.packageMetaDataServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ErrorOrFactory.From(ImmutableList.Create<IPackageMetaData>(this.metaData)));
            this.packagePermissionServiceMock.Setup(x => x.IsAllowedToUpdate(It.IsAny<IUserContext>(), It.IsAny<IPackage>(), It.IsAny<IPackage>(), It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Error.Unauthorized());
            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Success>>>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Unauthorized());

            this.viewModel = new PackageDetailsViewModel(this.databaseSourceMock.Object, this.packageServiceMock.Object, this.scopeServiceMock.Object, this.packageVersionServiceMock.Object, this.packageMetaDataServiceMock.Object, this.packageTypeServiceMock.Object, this.accountServiceMock.Object, this.userServiceMock.Object, this.memoryCache, this.packagePermissionServiceMock.Object, this.loggerMock.Object);
        }

        [TearDown]
        public void TearDown()
        {
            this.memoryCache.Dispose();
        }

        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // First call: loads from services
            await this.viewModel.InitializeViewModel("ecss-mm-pwr", "starion", PackageTabConstants.Versions);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Package, Is.Not.Null);
                Assert.That(this.viewModel.Package.Name, Is.EqualTo("ECSS-MM-PWR"));
                Assert.That(this.viewModel.Owner, Is.EqualTo(this.org));
                Assert.That(this.viewModel.PackageType, Is.EqualTo(this.packageType));
                Assert.That(this.viewModel.Versions, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.CurrentVersion, Is.EqualTo(this.version));
                Assert.That(this.viewModel.Maintainers, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.MetaDatas, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.CurrentMetaData, Is.EqualTo(this.metaData));
                Assert.That(this.viewModel.Elements, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.Dependencies, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.Dependents, Has.Count.EqualTo(0));
                Assert.That(this.viewModel.QualityChecks, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.IsUserAdmin, Is.False);
                Assert.That(this.viewModel.DownloadCount, Is.Zero);
            }

            // Second call: loaded from cache
            await this.viewModel.InitializeViewModel("ecss-mm-pwr", "starion", PackageTabConstants.Overview);

            this.packageServiceMock.Verify(x => x.ReadByCoordinateAsync(this.userContext, "starion", "ecss-mm-pwr", It.IsAny<CancellationToken>()), Times.Once);

            // Non-existent package: returns early and logs warning
            this.packageServiceMock
                .Setup(x => x.ReadByCoordinateAsync(this.userContext, "other-org", "nonexistent", It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.NotFound());

            await this.viewModel.InitializeViewModel("nonexistent", "other-org");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Package, Is.EqualTo(this.package));
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }
        }
    }
}
