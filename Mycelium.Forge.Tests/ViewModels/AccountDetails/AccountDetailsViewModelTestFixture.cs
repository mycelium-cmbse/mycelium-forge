namespace Mycelium.Forge.Tests.ViewModels.AccountDetails
{
    using System;
    using System.Collections.Immutable;
    using System.Threading;
    using System.Threading.Tasks;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.AccountDetails;

    [TestFixture]
    public class AccountDetailsViewModelTestFixture
    {
        private Mock<IAccountService> accountServiceMock;
        private Mock<IPackageService> packageServiceMock;
        private Mock<IPackageVersionService> packageVersionServiceMock;
        private Mock<IPackageTypeService> packageTypeServiceMock;
        private Mock<IUserService> userServiceMock;
        private Mock<ILogger<AccountDetailsViewModel>> loggerMock;
        private AccountDetailsViewModel viewModel;
        private Account account;
        private Package package;
        private PackageVersion packageVersion;
        private PackageType packageType;
        private UserContext currentUserContext;
        private UserContext otherUserContext;

        [SetUp]
        public void SetUp()
        {
            this.accountServiceMock = new Mock<IAccountService>();
            this.packageServiceMock = new Mock<IPackageService>();
            this.packageVersionServiceMock = new Mock<IPackageVersionService>();
            this.packageTypeServiceMock = new Mock<IPackageTypeService>();
            this.userServiceMock = new Mock<IUserService>();
            this.loggerMock = new Mock<ILogger<AccountDetailsViewModel>>();

            var accountId = Guid.NewGuid();
            var otherAccountId = Guid.NewGuid();
            var packageId = Guid.NewGuid();
            var versionId = Guid.NewGuid();
            var packageTypeId = Guid.NewGuid();

            this.account = new Account
            {
                Id = accountId,
                Name = "R. Andre",
                ShortName = "r-andre",
                Origin = "Toulouse, France",
                OwnedPackage = [packageId]
            };

            this.package = new Package
            {
                Id = packageId,
                Name = "personal-library",
                ShortName = "personal-library",
                Owner = accountId,
                Version = [versionId],
                PackageType = packageTypeId
            };

            this.packageVersion = new PackageVersion
            {
                Id = versionId,
                Owner = packageId,
                Version = "1.0.0",
                Listed = true,
                PublicationDate = DateTime.UtcNow
            };

            this.packageType = new PackageType
            {
                Id = packageTypeId,
                Name = "SysML v2"
            };

            this.currentUserContext = new UserContext
            {
                AccountId = accountId,
                CurrentRoles = [RoleKind.Account]
            };

            this.otherUserContext = new UserContext
            {
                AccountId = otherAccountId,
                CurrentRoles = [RoleKind.Account]
            };

            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.currentUserContext);
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<string[]>(a => a.Contains("r-andre")))).ReturnsAsync(ImmutableList.Create<IAccount>(this.account));
            this.packageServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IPackage>(this.package));
            this.packageVersionServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IPackageVersion>(this.packageVersion));
            this.packageTypeServiceMock.Setup(x => x.ReadAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>())).ReturnsAsync(ImmutableList.Create<IPackageType>(this.packageType));

            this.viewModel = new AccountDetailsViewModel(this.accountServiceMock.Object, this.packageServiceMock.Object, this.packageVersionServiceMock.Object, this.packageTypeServiceMock.Object, this.userServiceMock.Object, this.loggerMock.Object);
        }

        [Test]
        public async Task VerifyInitializeViewModel()
        {
            // Scenario 1: Account not found (empty result)
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<string[]>(a => a.Contains("unknown")))).ReturnsAsync(ImmutableList<IAccount>.Empty);

            await this.viewModel.InitializeViewModel("unknown");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Account, Is.Null);
                Assert.That(this.viewModel.Packages, Has.Count.EqualTo(0));
                this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);
            }

            // Scenario 2: Account service returns error
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<string[]>(a => a.Contains("errored")))).ReturnsAsync(Error.NotFound());

            await this.viewModel.InitializeViewModel("errored");

            this.loggerMock.Verify(x => x.Log(LogLevel.Warning, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Exactly(2));

            // Scenario 3: Exception handling with error log
            this.accountServiceMock.Setup(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), It.IsAny<CancellationToken>(), It.Is<string[]>(a => a.Contains("fail")))).ThrowsAsync(new InvalidOperationException("DB error"));

            await this.viewModel.InitializeViewModel("fail");

            this.loggerMock.Verify(x => x.Log(LogLevel.Error, It.IsAny<EventId>(), It.Is<It.IsAnyType>((v, t) => true), It.IsAny<Exception?>(), It.IsAny<Func<It.IsAnyType, Exception?, string>>()), Times.Once);

            // Scenario 4: Happy path as current user (verifies mixed-case short name normalization)
            await this.viewModel.InitializeViewModel("R-Andre");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Account, Is.Not.Null);
                Assert.That(this.viewModel.Account.ShortName, Is.EqualTo("r-andre"));
                Assert.That(this.viewModel.IsCurrentUser, Is.True);
                Assert.That(this.viewModel.Packages, Has.Count.EqualTo(1));
                Assert.That(this.viewModel.Packages[0].IsVerified, Is.False);
            }

            // Scenario 5: Viewing another user's profile
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.otherUserContext);

            await this.viewModel.InitializeViewModel("r-andre");

            Assert.That(this.viewModel.IsCurrentUser, Is.False);

            // Scenario 6: Re-initializing with missing account clears previous state
            this.userServiceMock.Setup(x => x.GetUserContext(false)).ReturnsAsync(this.currentUserContext);
            await this.viewModel.InitializeViewModel("R-Andre");
            await this.viewModel.InitializeViewModel("unknown");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(this.viewModel.Account, Is.Null);
                Assert.That(this.viewModel.IsCurrentUser, Is.False);
                Assert.That(this.viewModel.Packages, Has.Count.EqualTo(0));
            }
        }
    }
}
