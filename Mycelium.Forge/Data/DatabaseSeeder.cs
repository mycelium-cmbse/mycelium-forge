namespace Mycelium.Forge.Data
{
    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Orm;

    /// <summary>
    /// Implements database seeding by resetting the schema, executing migrations, and persisting development entities.
    /// </summary>
    public class DatabaseSeeder : IDatabaseSeeder
    {
        /// <summary>
        /// The domain service for <see cref="IAccount" /> entities.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The domain service for <see cref="IAPIKey" /> entities.
        /// </summary>
        private readonly IAPIKeyService apiKeyService;

        /// <summary>
        /// The domain service for <see cref="ICountry" /> entities.
        /// </summary>
        private readonly ICountryService countryService;

        /// <summary>
        /// The database configuration options.
        /// </summary>
        private readonly DatabaseConfig databaseConfig;

        /// <summary>
        /// The database migration service.
        /// </summary>
        private readonly IDatabaseMigrator databaseMigrator;

        /// <summary>
        /// The domain service for <see cref="IForge" /> entities.
        /// </summary>
        private readonly IForgeService forgeService;

        /// <summary>
        /// The logger for diagnostic messages.
        /// </summary>
        private readonly ILogger<DatabaseSeeder> logger;

        /// <summary>
        /// The domain service for <see cref="IOrganization" /> entities.
        /// </summary>
        private readonly IOrganizationService organizationService;

        /// <summary>
        /// The domain service for <see cref="IPackage" /> entities.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The domain service for <see cref="IPackageType" /> entities.
        /// </summary>
        private readonly IPackageTypeService packageTypeService;

        /// <summary>
        /// The domain service for <see cref="IPackageVersion" /> entities.
        /// </summary>
        private readonly IPackageVersionService packageVersionService;

        /// <summary>
        /// Initializes a new instance of the <see cref="DatabaseSeeder" /> class.
        /// </summary>
        /// <param name="forgeService">The domain service for <see cref="IForge" /> entities.</param>
        /// <param name="countryService">The domain service for <see cref="ICountry" /> entities.</param>
        /// <param name="packageTypeService">The domain service for <see cref="IPackageType" /> entities.</param>
        /// <param name="accountService">The domain service for <see cref="IAccount" /> entities.</param>
        /// <param name="organizationService">The domain service for <see cref="IOrganization" /> entities.</param>
        /// <param name="packageService">The domain service for <see cref="IPackage" /> entities.</param>
        /// <param name="packageVersionService">The domain service for <see cref="IPackageVersion" /> entities.</param>
        /// <param name="apiKeyService">The domain service for <see cref="IAPIKey" /> entities.</param>
        /// <param name="databaseConfig">The database configuration options.</param>
        /// <param name="logger">The logger for diagnostic messages.</param>
        public DatabaseSeeder(
            IForgeService forgeService,
            ICountryService countryService,
            IPackageTypeService packageTypeService,
            IAccountService accountService,
            IOrganizationService organizationService,
            IPackageService packageService,
            IPackageVersionService packageVersionService,
            IAPIKeyService apiKeyService,
            DatabaseConfig databaseConfig,
            ILogger<DatabaseSeeder> logger)
        {
            ArgumentNullException.ThrowIfNull(forgeService);
            ArgumentNullException.ThrowIfNull(countryService);
            ArgumentNullException.ThrowIfNull(packageTypeService);
            ArgumentNullException.ThrowIfNull(accountService);
            ArgumentNullException.ThrowIfNull(organizationService);
            ArgumentNullException.ThrowIfNull(packageService);
            ArgumentNullException.ThrowIfNull(packageVersionService);
            ArgumentNullException.ThrowIfNull(apiKeyService);
            ArgumentNullException.ThrowIfNull(databaseConfig);
            ArgumentNullException.ThrowIfNull(logger);

            this.forgeService = forgeService;
            this.countryService = countryService;
            this.packageTypeService = packageTypeService;
            this.accountService = accountService;
            this.organizationService = organizationService;
            this.packageService = packageService;
            this.packageVersionService = packageVersionService;
            this.apiKeyService = apiKeyService;
            this.databaseConfig = databaseConfig;
            this.logger = logger;

            this.databaseMigrator = new DatabaseMigrator();
        }

        /// <summary>
        /// Asynchronously drops existing schema, applies migrations, and seeds initial development entities.
        /// </summary>
        /// <param name="cancellationToken">The cancellation token to abort the seeding operation.</param>
        /// <returns>
        /// A task representing the asynchronous operation, resolving to <see langword="true" /> if seeding
        /// completed successfully; otherwise <see langword="false" />.
        /// </returns>
        public async Task<bool> SeedAsync(CancellationToken cancellationToken = default)
        {
            try
            {
                if (!await this.ResetDatabaseAsync(cancellationToken))
                {
                    return false;
                }

                var seederUserContext = new UserContext
                {
                    AccountId = SeedData.RegisAccount.Id,
                    Username = SeedData.RegisAccount.ShortName,
                    CurrentRoles = [RoleKind.InstallationAdministrator, RoleKind.Account, RoleKind.OrganizationAdministrator]
                };

                if (!await this.SeedThing(seederUserContext, this.forgeService, [SeedData.Forge], cancellationToken) ||
                    !await this.SeedThing(seederUserContext, this.countryService, SeedData.Countries, cancellationToken) ||
                    !await this.SeedThing(seederUserContext, this.packageTypeService, SeedData.PackageTypes, cancellationToken) ||
                    !await this.SeedThing(seederUserContext, this.accountService, SeedData.Accounts, cancellationToken) ||
                    !await this.SeedThing(seederUserContext, this.organizationService, SeedData.Organizations, cancellationToken) ||
                    !await this.SeedThing(seederUserContext, this.packageService, SeedData.Packages, cancellationToken) ||
                    !await this.SeedThing(seederUserContext, this.packageVersionService, SeedData.PackageVersions, cancellationToken) ||
                    !await this.SeedThing(seederUserContext, this.apiKeyService, SeedData.ApiKeys, cancellationToken))
                {
                    return false;
                }

                this.logger.LogInformation("Database seeding completed successfully.");
                return true;
            }
            catch (Exception exception)
            {
                this.logger.LogError(exception, "Database seeding failed unexpectedly.");
                return false;
            }
        }

        /// <summary>
        /// Drops the existing database schema and applies pending migrations.
        /// </summary>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>A task resolving to <see langword="true" /> if migrations succeeded; otherwise <see langword="false" />.</returns>
        private async Task<bool> ResetDatabaseAsync(CancellationToken cancellationToken)
        {
            this.logger.LogInformation("Dropping database schema and resetting migrations...");
            var connectionString = this.databaseConfig.BuildConnectionString();

            var result = await this.databaseMigrator.ResetDatabaseAsync(connectionString, cancellationToken);

            if (!result)
            {
                this.logger.LogError("Failed to apply database migrations during database seeding.");
            }

            return result;
        }

        /// <summary>
        /// Seeds a collection of domain entities using the specified domain service.
        /// </summary>
        /// <typeparam name="T">The domain entity type implementing <see cref="IThing" />.</typeparam>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="service">The domain service for <typeparamref name="T" /> entities.</param>
        /// <param name="things">The collection of <typeparamref name="T" /> instances to seed.</param>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>A task resolving to <see langword="true" /> if seeded successfully; otherwise <see langword="false" />.</returns>
        private async Task<bool> SeedThing<T>(IUserContext userContext, IService<T> service, IEnumerable<T> things, CancellationToken cancellationToken) where T : IThing
        {
            var thingsList = things.ToList();
            var result = await service.CreateAsync(userContext, thingsList, cancellationToken);

            if (result.IsError)
            {
                this.logger.LogError("Failed to seed {EntityName}: {Errors}", typeof(T).Name, string.Join(", ", result.Errors));
                return false;
            }

            this.logger.LogInformation("Seeded {Count} {EntityName}.", thingsList.Count, typeof(T).Name);
            return true;
        }
    }
}
