namespace Mycelium.Forge.ViewModels.Publish
{
    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Models.Publish;
    using Mycelium.Forge.Models.Validation;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides view model state and operations for the Mycelium Forge package publishing wizard page.
    /// </summary>
    public class PublishViewModel : DisposableViewModel, IPublishViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IDatabaseSource" /> database source.
        /// </summary>
        private readonly IDatabaseSource databaseSource;

        /// <summary>
        /// The (injected) <see cref="IFileUploadStagingService" /> upload staging service.
        /// </summary>
        private readonly IFileUploadStagingService fileUploadStagingService;

        /// <summary>
        /// The (injected) <see cref="IPackagePublishService" /> package publishing coordinator service.
        /// </summary>
        private readonly IPackagePublishService packagePublishService;

        /// <summary>
        /// The (injected) <see cref="IPackageService" /> domain service.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The (injected) <see cref="IPackageTypeService" /> domain service.
        /// </summary>
        private readonly IPackageTypeService packageTypeService;

        /// <summary>
        /// The (injected) <see cref="IPackageVersionPermissionService" /> used to validate package version permissions.
        /// </summary>
        private readonly IPackageVersionPermissionService packageVersionPermissionService;

        /// <summary>
        /// The (injected) <see cref="IPackageVersionService" /> domain service.
        /// </summary>
        private readonly IPackageVersionService packageVersionService;

        /// <summary>
        /// The (injected) <see cref="IScopeService" /> domain service.
        /// </summary>
        private readonly IScopeService scopeService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> user context service.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// The account identifier of the authenticated user resolved on initialization.
        /// </summary>
        private Guid currentUserId;

        /// <summary>
        /// The authenticated user context resolved on initialization.
        /// </summary>
        private IUserContext userContext;

        /// <summary>
        /// Initializes a new instance of the <see cref="PublishViewModel" /> class.
        /// </summary>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="scopeService">The (injected) <see cref="IScopeService" />.</param>
        /// <param name="packageService">The (injected) <see cref="IPackageService" />.</param>
        /// <param name="packageVersionService">The (injected) <see cref="IPackageVersionService" />.</param>
        /// <param name="packageTypeService">The (injected) <see cref="IPackageTypeService" />.</param>
        /// <param name="databaseSource">The (injected) <see cref="IDatabaseSource" />.</param>
        /// <param name="fileUploadStagingService">The (injected) <see cref="IFileUploadStagingService" />.</param>
        /// <param name="packagePublishService">The (injected) <see cref="IPackagePublishService" />.</param>
        /// <param name="packageVersionPermissionService">The (injected) <see cref="IPackageVersionPermissionService" />.</param>
        public PublishViewModel(IUserService userService, IScopeService scopeService, IPackageService packageService, IPackageVersionService packageVersionService,
            IPackageTypeService packageTypeService, IDatabaseSource databaseSource, IFileUploadStagingService fileUploadStagingService, IPackagePublishService packagePublishService,
            IPackageVersionPermissionService packageVersionPermissionService)
        {
            this.userService = userService;
            this.scopeService = scopeService;
            this.packageService = packageService;
            this.packageVersionService = packageVersionService;
            this.packageTypeService = packageTypeService;
            this.databaseSource = databaseSource;
            this.fileUploadStagingService = fileUploadStagingService;
            this.packagePublishService = packagePublishService;
            this.packageVersionPermissionService = packageVersionPermissionService;
        }

        /// <summary>
        /// Gets the package being published.
        /// </summary>
        public IPackage Package { get; private set; }

        /// <summary>
        /// Gets the package version being published.
        /// </summary>
        public IPackageVersion PackageVersion { get; private set; }

        /// <summary>
        /// Gets the metadata of the package version being published.
        /// </summary>
        public IPackageMetaData PackageMetaData { get; private set; }

        /// <summary>
        /// Gets or sets the scope that owns the package.
        /// </summary>
        public IScope SelectedScope { get; set; }

        /// <summary>
        /// Gets the staged upload artefact model, or <see langword="null" /> if no artefact has been staged.
        /// </summary>
        public PublishArtefactModel StagedArtefact { get; private set; }

        /// <summary>
        /// Gets a value indicating whether a new version of an already existing package is being published.
        /// </summary>
        public bool IsExistingPackage { get; private set; }

        /// <summary>
        /// Gets the expected package format when publishing a new version of an existing package.
        /// </summary>
        public SupportedPackageFormat ExpectedFormat { get; private set; }

        /// <summary>
        /// Gets a value indicating whether the current authenticated user has permission to publish a new version of the existing
        /// package.
        /// </summary>
        public bool CanUserReleaseExistingPackageVersion { get; private set; } = true;

        /// <summary>
        /// Gets the list of previously published version strings for the existing package.
        /// </summary>
        public IReadOnlyList<string> ExistingVersions { get; private set; } = [];

        /// <summary>
        /// Gets or sets the list of pre-publishing validation rule evaluation results.
        /// </summary>
        public List<ValidationCheckModel> ValidationChecks { get; set; } = [];

        /// <summary>
        /// Gets the scopes the current account can publish to.
        /// </summary>
        public IReadOnlyList<IScope> ScopeOptions { get; private set; } = [];

        /// <summary>
        /// Gets or sets a value indicating whether a package publish operation is currently in progress.
        /// </summary>
        public bool IsPublishing { get; set; }

        /// <summary>
        /// Initializes the view model state and loads the scopes of the current account for creating a new package.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel()
        {
            await this.InitializeBase();

            this.ScopeOptions = await this.scopeService.ReadActiveByAccountAsync(this.userContext, this.currentUserId);
            this.SelectedScope = this.ScopeOptions.Count > 0 ? this.ScopeOptions[0] : null;

            var packageId = Guid.NewGuid();
            this.PackageVersion.Owner = packageId;

            this.Package = new Package
            {
                Id = packageId,
                Owner = this.SelectedScope?.Id ?? Guid.Empty,
                Visibility = this.SelectedScope?.DefaultPackageVisibility ?? VisibilityKind.PRIVATE,
                Listed = true,
                PackageOwner = [this.currentUserId],
                Version = [this.PackageVersion.Id],
                License = string.Empty,
                RepositoryUrl = string.Empty,
                HomepageUrl = string.Empty,
                DocumentationUrl = string.Empty,
                Tags = [],
                IsVerified = this.SelectedScope?.IsVerified() ?? false
            };
        }

        /// <summary>
        /// Initializes the view model state, loads the scopes of the current account, and loads the existing package a new version
        /// is published for.
        /// </summary>
        /// <param name="scopeShortName">The short name of the scope of the existing package.</param>
        /// <param name="packageShortName">The short name of the existing package.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel(string scopeShortName, string packageShortName)
        {
            await this.InitializeBase();
            this.IsExistingPackage = true;

            var existingResult = await this.packageService.ReadByCoordinateAsync(this.userContext, scopeShortName.CleanScope(), packageShortName.Trim().ToLowerInvariant(), token: CancellationToken.None);

            if (existingResult.IsError)
            {
                this.CanUserReleaseExistingPackageVersion = false;
                return;
            }

            this.Package = existingResult.Value;
            this.PackageVersion.Owner = this.Package.Id;

            var packageType = await this.packageTypeService.ReadOrNull(this.userContext, this.Package.PackageType);
            this.ExpectedFormat = SupportedPackageFormat.All.SingleOrDefault(x => x.Name.Equals(packageType?.Name, StringComparison.OrdinalIgnoreCase));

            if (this.ExpectedFormat == null)
            {
                this.CanUserReleaseExistingPackageVersion = false;
                return;
            }

            var packageVersions = await this.packageVersionService.ReadOrEmpty(this.userContext, this.Package.Version);
            this.ExistingVersions = [.. packageVersions.Select(x => x.Version).OrderDescending(SemanticVersionComparer.Instance)];

            this.SelectedScope = await this.scopeService.ReadOrNull(this.userContext, this.Package.Owner);

            var permissionResult = await this.packageVersionPermissionService.IsAllowedToCreate(this.databaseSource, this.userContext, this.PackageVersion);
            this.CanUserReleaseExistingPackageVersion = !permissionResult.IsError;
        }

        /// <summary>
        /// Reads the manifest of the staged artefact, maps its values onto the package metadata, and tracks the staged artefact
        /// model.
        /// </summary>
        /// <param name="artefact">The staged artefact UI model containing the staging token and archive metadata.</param>
        /// <returns>
        /// A <see cref="Task{Boolean}" /> that is <see langword="true" /> when manifest extraction succeeded without
        /// errors; otherwise, <see langword="false" />.
        /// </returns>
        public async Task<bool> ExtractManifest(PublishArtefactModel artefact)
        {
            this.DiscardStagedFile();

            this.StagedArtefact = artefact;

            await using var stream = this.fileUploadStagingService.OpenStagedFile(artefact.StagingToken);
            var extractResult = await this.packagePublishService.ExtractManifestAsync(this.userContext, stream, artefact.Kind, artefact.Format, this.Package, this.PackageVersion, this.PackageMetaData, this.IsExistingPackage);

            artefact.IsManifestValid = !extractResult.IsError;

            if (extractResult.IsError)
            {
                await this.Validate(extractResult.Errors);
                return false;
            }

            return true;
        }

        /// <summary>
        /// Evaluates the pre-publishing validation checks of the package being published.
        /// </summary>
        /// <param name="beforeValidationErrors">
        /// Optional pre-validation or extraction errors to evaluate before executing domain
        /// checks.
        /// </param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task Validate(IReadOnlyList<Error> beforeValidationErrors = null)
        {
            this.ValidationChecks.Clear();

            var checks = await this.packagePublishService.ValidateReleaseAsync(this.userContext, this.SelectedScope, this.Package, this.PackageVersion, this.IsExistingPackage, this.ExistingVersions, beforeValidationErrors);

            this.ValidationChecks.AddRange(checks);
            this.PackageMetaData.QualityChecks = [.. this.ValidationChecks.Select(check => (check.Title, check.Detail, check.Status == ValidationStatus.Pass))];
        }

        /// <summary>
        /// Publishes the staged artefact and persists the package, its version, and its metadata.
        /// </summary>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Success}" /> indicating success or failure of the publish operation.</returns>
        public async Task<ErrorOr<Success>> Publish(CancellationToken token = default)
        {
            this.IsPublishing = true;

            try
            {
                if (!this.IsExistingPackage && this.SelectedScope != null)
                {
                    this.Package.Owner = this.SelectedScope.Id;
                }

                await using var stagedStream = this.fileUploadStagingService.OpenStagedFile(this.StagedArtefact.StagingToken);
                var result = await this.packagePublishService.PublishReleaseAsync(this.userContext, stagedStream, this.Package, this.PackageVersion, this.PackageMetaData, this.IsExistingPackage, token);

                if (!result.IsError)
                {
                    this.DiscardStagedFile();
                }

                return result;
            }
            finally
            {
                this.IsPublishing = false;
            }
        }

        /// <summary>
        /// Deletes the staged artefact of the current upload, if any.
        /// </summary>
        public void DiscardStagedFile()
        {
            if (!string.IsNullOrWhiteSpace(this.StagedArtefact?.StagingToken))
            {
                this.fileUploadStagingService.Cleanup(this.StagedArtefact.StagingToken);
            }

            this.StagedArtefact = null;
        }

        /// <summary>
        /// Releases unmanaged and - optionally - managed resources, cleaning up any staged upload file.
        /// </summary>
        /// <param name="disposing">
        /// <see langword="true" /> to release both managed and unmanaged resources; <see langword="false" /> to release only
        /// unmanaged resources.
        /// </param>
        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                this.DiscardStagedFile();
            }

            base.Dispose(disposing);
        }

        /// <summary>
        /// Initializes the user context and new version and metadata instances shared by both initialization paths.
        /// </summary>
        /// <remarks>
        /// Explicitly initializes partial DTO properties (e.g. Readme, SizeInBytes, Dependencies, Elements) to clean, empty
        /// values to prevent mock defaults defined in prototype partial classes (such as <see cref="PackageVersion" /> and
        /// <see cref="PackageMetaData" />) from persisting into the database. These settings shall be removed in future model
        /// changes.
        /// </remarks>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        private async Task InitializeBase()
        {
            this.userContext = await this.userService.GetUserContext();
            this.currentUserId = this.userContext.AccountId!.Value;

            var versionId = Guid.NewGuid();
            var metaDataId = Guid.NewGuid();

            this.PackageVersion = new PackageVersion
            {
                Id = versionId,
                MetaData = metaDataId,
                Listed = true,
                Readme = string.Empty,
                ReleaseNotes = string.Empty,
                Checksum = string.Empty,
                SizeInBytes = 0
            };

            this.PackageMetaData = new PackageMetaData
            {
                Id = metaDataId,
                Owner = versionId,
                Dependencies = [],
                Elements = [],
                QualityChecks = []
            };
        }
    }
}
