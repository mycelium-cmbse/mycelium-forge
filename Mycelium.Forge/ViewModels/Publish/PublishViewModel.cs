        /// Gets or sets a value indicating whether a package publish operation is currently in progress.
        /// </summary>
        public bool IsPublishing { get; set; }

        /// <summary>
        /// Initializes the view model state and loads the scopes of the current account for creating a new package.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel()
        {
            await this.InitializeBase();

            var packageId = Guid.NewGuid();
            this.PackageVersion.Owner = packageId;

            this.Package = new Package
            {
                Id = packageId,
                Owner = this.SelectedScope?.Id ?? Guid.Empty,
                Visibility = this.SelectedScope?.DefaultPackageVisibility ?? VisibilityKind.PRIVATE,
                Listed = true,
                PackageOwner = [this.currentUserId],
                Version = [this.PackageVersion.Id]
            };
        }

        /// <summary>
        /// Initializes the view model state, loads the scopes of the current account, and loads the existing package a new version
        /// is published for.
        /// </summary>
        /// <param name="scopeShortName">The short name of the scope of the existing package.</param>
        /// <param name="packageShortName">The short name of the existing package.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel(string scopeShortName, string packageShortName)
        {
            await this.InitializeBase();

            var existingResult = await this.packageService.ReadByCoordinateAsync(this.userContext, scopeShortName.CleanScope(), packageShortName.ToShortName(), CancellationToken.None);

            if (existingResult.IsError)
            {
                this.CanUserReleaseExistingPackageVersion = false;
                return;
            }

            this.Package = existingResult.Value;
            this.PackageVersion.Owner = this.Package.Id;
            this.IsExistingPackage = true;

            var packageType = await this.packageTypeService.ReadOrNull(this.userContext, this.Package.PackageType);
            this.ExpectedFormat = SupportedPackageFormat.All.Single(x => x.Name.Equals(packageType?.Name, StringComparison.OrdinalIgnoreCase));

            var packageVersions = await this.packageVersionService.ReadOrEmpty(this.userContext, this.Package.Version);
            this.ExistingVersions = [.. packageVersions.Select(x => x.Version)];

            this.SelectedScope = this.ScopeOptions.FirstOrDefault(x => x.Id == this.Package.Owner)
                                 ?? await this.scopeService.ReadOrNull(this.userContext, this.Package.Owner);

            var permissionResult = await this.packageVersionPermissionService.IsAllowedToCreate(this.databaseSource, this.userContext, this.PackageVersion);
            this.CanUserReleaseExistingPackageVersion = !permissionResult.IsError;
        }

        /// <summary>
        /// Reads the manifest of the staged artefact and maps its values onto the package metadata.
        /// </summary>
        /// <param name="stagingUploadToken">The token identifying the staged artefact.</param>
        /// <param name="artifactKind">The kind of the artefact.</param>
        /// <returns>
        /// A <see cref="Task{Boolean}" /> that is <see langword="true" /> when manifest extraction succeeded without
        /// errors; otherwise, <see langword="false" />.
        /// </returns>
        public async Task<bool> ExtractManifest(string stagingUploadToken, ArtifactKind artifactKind)
        {
            this.DiscardStagedFile();

            this.stagingToken = stagingUploadToken;
            this.extractorErrors = [];

            if (!this.IsExistingPackage)
            {
                var packageTypeName = SupportedPackageFormat.All.Single(x => x.Kind == artifactKind).Name;
                var packageTypeResult = await this.packageTypeService.ReadByNameAsync(this.userContext, CancellationToken.None, [packageTypeName]);

                if (!packageTypeResult.IsError && packageTypeResult.Value.Count > 0)
                {
                    this.Package.PackageType = packageTypeResult.Value[0].Id;
                }
            }

            var extractor = this.manifestExtractors.Single(x => x.CanHandle(artifactKind));

            await using var stream = this.fileUploadStagingService.OpenStagedFile(this.stagingToken);
            this.PackageVersion.SizeInBytes = stream.Length;

            var extractResult = extractor.Extract(stream);

            if (extractResult.IsError)
            {
                this.extractorErrors = extractResult.Errors;
                await this.Validate();
                return false;
            }

            extractResult.Value.ApplyTo(this.Package, this.PackageVersion, this.PackageMetaData, this.IsExistingPackage);
            return true;
        }

        /// <summary>
        /// Evaluates the pre-publishing validation checks of the package being published.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task Validate()
        {
            this.ValidationChecks.Clear();

            if (this.extractorErrors.Count > 0)
            {
                this.ValidationChecks.AddRange(this.extractorErrors.Select(error => new ValidationCheckModel(error.Code, ValidationStatus.Fail, error.Description)));
                this.PackageMetaData.QualityChecks = [.. this.ValidationChecks.Select(check => (check.Title, check.Detail, check.Status == ValidationStatus.Pass))];
                return;
            }

            this.ValidationChecks.Add(new ValidationCheckModel(ValidationTypes.SchemaValidation, ValidationStatus.Pass, "Archive structure and manifests conform to specification."));

            await this.ValidateNamespaceAndVersion();

            var licenseCheck = string.IsNullOrWhiteSpace(this.Package.License)
                ? new ValidationCheckModel(ValidationTypes.License, ValidationStatus.Warning, "No license specified for this package. Consider selecting one.")
                : new ValidationCheckModel(ValidationTypes.License, ValidationStatus.Pass, $"License '{this.Package.License}' declared.");

            this.ValidationChecks.Add(licenseCheck);
            this.PackageMetaData.QualityChecks = [.. this.ValidationChecks.Select(check => (check.Title, check.Detail, check.Status == ValidationStatus.Pass))];
        }

        /// <summary>
        /// Publishes the staged artefact and persists the package, its version, and its metadata.
        /// </summary>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A <see cref="ErrorOr{Success}" /> indicating success or failure of the publish operation.</returns>
        public async Task<ErrorOr<Success>> Publish(CancellationToken token = default)
        {
            this.IsPublishing = true;
            var storedHash = string.Empty;
            var wasArtifactNew = false;

            try
            {
                var artifactResult = await this.StoreStagedArtifact(token);

                if (artifactResult.IsError)
                {
                    return artifactResult.Errors;
                }

                (storedHash, wasArtifactNew) = artifactResult.Value;
                this.PackageVersion.Checksum = storedHash;

                var persistResult = await this.PersistPackageAndRelease(token);

                if (!persistResult.IsError)
                {
                    return Result.Success;
                }

                if (wasArtifactNew)
                {
                    await this.artifactStore.DeleteArtifactAsync(storedHash, token);
                }

                return persistResult.Errors;
            }
            catch (Exception exception)
            {
                this.logger.LogError(exception, "Failed to publish package {PackageName}", this.Package.Name.SanitizeForLog());

                if (wasArtifactNew && !string.IsNullOrWhiteSpace(storedHash))
                {
                    await this.artifactStore.DeleteArtifactAsync(storedHash, token);
                }

                return Error.Failure(description: exception.Message);
            }
            finally
            {
                this.DiscardStagedFile();
                this.IsPublishing = false;
            }
        }

        /// <summary>
        /// Releases unmanaged and - optionally - managed resources, cleaning up any staged upload file.
        /// </summary>
        /// <param name="disposing">
        /// <see langword="true" /> to release both managed and unmanaged resources; <see langword="false" /> to release only
        /// unmanaged resources.
        /// </param>
        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                this.DiscardStagedFile();
            }

            base.Dispose(disposing);
        }

        /// <summary>
        /// Evaluates namespace and version uniqueness checks and appends the results to <see cref="ValidationChecks" />.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        private async Task ValidateNamespaceAndVersion()
        {
            if (this.IsExistingPackage)
            {
                this.ValidationChecks.Add(new ValidationCheckModel(ValidationTypes.NamespaceUniqueness, ValidationStatus.Pass, "Publishing a new version to an existing package in the selected scope."));

                var isDuplicateVersion = this.ExistingVersions.Any(x => string.Equals(x, this.PackageVersion.Version, StringComparison.OrdinalIgnoreCase));

                if (isDuplicateVersion)
                {
                    this.ValidationChecks.Add(new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Fail, $"Version '{this.PackageVersion.Version}' already exists for this package."));
                    return;
                }

                var notGreaterVersion = this.ExistingVersions.FirstOrDefault(x => SemanticVersionComparer.Compare(this.PackageVersion.Version, x) <= 0);

                if (notGreaterVersion != null)
                {
                    this.ValidationChecks.Add(new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Fail, $"Version '{this.PackageVersion.Version}' must be strictly greater than published version '{notGreaterVersion}'."));
                    return;
                }

                var isMajorBump = this.ExistingVersions.Any(x => SemanticVersionComparer.IsMajorBump(this.PackageVersion.Version, x));

                if (isMajorBump && string.IsNullOrWhiteSpace(this.PackageVersion.ReleaseNotes))
                {
                    this.ValidationChecks.Add(new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Fail, "A major-version update requires release notes."));
                    return;
                }

                this.ValidationChecks.Add(new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Pass, "Version is unique and strictly greater than prior releases."));
                return;
            }

            var existingResult = await this.packageService.ReadByCoordinateAsync(this.userContext, this.SelectedScope.ShortName, this.Package.ShortName, CancellationToken.None);

            var uniquenessCheck = !existingResult.IsError
                ? new ValidationCheckModel(ValidationTypes.NamespaceUniqueness, ValidationStatus.Fail, $"Package '{this.Package.ShortName}' already exists in scope '@{this.SelectedScope.ShortName}'.")
                : new ValidationCheckModel(ValidationTypes.NamespaceUniqueness, ValidationStatus.Pass, "Package identifier is available in the selected scope.");

            this.ValidationChecks.Add(uniquenessCheck);
            this.ValidationChecks.Add(new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Pass, "Initial version is valid for publication."));
        }

        /// <summary>
        /// Initializes the user context, available scopes, and new version and metadata instances shared by both initialization
        /// paths.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        private async Task InitializeBase()
        {
            this.userContext = await this.userService.GetUserContext();
            this.currentUserId = this.userContext.AccountId!.Value;

            var scopes = new List<IScope>();
            var account = await this.accountService.ReadOrNull(this.userContext, this.currentUserId);

            if (account is { Status: ScopeStatusKind.ACTIVE })
            {
                scopes.Add(account);
            }

            var organizationsResult = await this.organizationService.ReadByAccountMembershipAsync(this.userContext, this.currentUserId, CancellationToken.None);

            if (!organizationsResult.IsError)
            {
                scopes.AddRange(organizationsResult.Value.Where(x => x.Status == ScopeStatusKind.ACTIVE));
            }

            this.ScopeOptions = scopes;
            this.SelectedScope = scopes.FirstOrDefault();

            var versionId = Guid.NewGuid();
            var metaDataId = Guid.NewGuid();

            this.PackageVersion = new PackageVersion
            {
                Id = versionId,
                MetaData = metaDataId,
                Listed = true
            };

            this.PackageMetaData = new PackageMetaData
            {
                Id = metaDataId,
                Owner = versionId
            };
        }

        /// <summary>
        /// Deletes the staged artefact of the current upload, if any.
        /// </summary>
        private void DiscardStagedFile()
        {
            if (string.IsNullOrWhiteSpace(this.stagingToken))
            {
                return;
            }

            this.fileUploadStagingService.Cleanup(this.stagingToken);
            this.stagingToken = null;
        }

        /// <summary>
        /// Hashes the staged file, checks whether it already exists in object storage, and stores it.
        /// </summary>
        /// <param name="token">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{TValue}" /> containing the stored content hash and whether the blob was newly uploaded.</returns>
        private async Task<ErrorOr<(string Hash, bool WasNew)>> StoreStagedArtifact(CancellationToken token)
        {
            await using var stagedStream = this.fileUploadStagingService.OpenStagedFile(this.stagingToken);

            var hashBytes = await SHA256.HashDataAsync(stagedStream, token);
            var computedHash = Convert.ToHexStringLower(hashBytes);

            var existsResult = await this.artifactStore.ExistsAsync(computedHash, token);

            if (existsResult.IsError)
            {
                return existsResult.Errors;
            }

            var storeResult = await this.artifactStore.StoreArtifactAsync(stagedStream, token: token);

            if (storeResult.IsError)
            {
                return storeResult.Errors;
            }

            return (storeResult.Value, !existsResult.Value);
        }

        /// <summary>
        /// Persists the package, version, and metadata entities within an atomic database transaction.
        /// </summary>
        /// <param name="token">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> representing the persistence outcome.</returns>
        private async Task<ErrorOr<Success>> PersistPackageAndRelease(CancellationToken token)
        {
            this.PackageVersion.PublicationDate = DateTime.UtcNow;

            return await this.databaseSource.ExecuteInTransactionAsync(async transaction =>
            {
                await this.databaseSource.DeferConstraintsAsync(transaction, token);

                // If publishing a new version of an existing package, only the version and metadata records are created; the package record already exists.
                if (this.IsExistingPackage)
                {
                    var versionResult = await this.CreateVersionAndMetaData(transaction, token);

                    if (!versionResult.IsError)
                    {
                        this.Package.Version.Add(this.PackageVersion.Id);
                    }

                    return versionResult;
                }

                // If publishing a new package, the package record is created first, followed by the version and metadata records.
                this.Package.Owner = this.SelectedScope.Id;
                var packageResult = await this.packageService.CreateAsync(this.userContext, transaction, [this.Package], token);

                if (packageResult.IsError)
                {
                    return packageResult.Errors;
                }

                return await this.CreateVersionAndMetaData(transaction, token);
            }, token);
        }

        /// <summary>
        /// Creates the package version and package metadata records within the supplied transaction.
        /// </summary>
        /// <param name="transaction">The active database transaction.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> representing the creation outcome.</returns>
        private async Task<ErrorOr<Success>> CreateVersionAndMetaData(NpgsqlTransaction transaction, CancellationToken token)
        {
            var versionResult = await this.packageVersionService.CreateAsync(this.userContext, transaction, [this.PackageVersion], token);

            if (versionResult.IsError)
            {
                return versionResult.Errors;
            }

            var metaDataResult = await this.packageMetaDataService.CreateAsync(this.userContext, transaction, [this.PackageMetaData], token);

            if (metaDataResult.IsError)
            {
                return metaDataResult.Errors;
            }

            return Result.Success;
        }
    }
