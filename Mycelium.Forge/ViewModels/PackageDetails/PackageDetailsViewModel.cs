namespace Mycelium.Forge.ViewModels.PackageDetails
{
    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides view model state and initialization logic for the Mycelium Forge package details page.
    /// </summary>
    public class PackageDetailsViewModel : IPackageDetailsViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IAccountService" /> used to retrieve maintainer accounts.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="IPackageMetaDataService" /> used to retrieve package metadata.
        /// </summary>
        private readonly IPackageMetaDataService packageMetaDataService;

        /// <summary>
        /// The (injected) <see cref="IPackageService" /> used to retrieve package data.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The (injected) <see cref="IPackageTypeService" /> used to retrieve package type data.
        /// </summary>
        private readonly IPackageTypeService packageTypeService;

        /// <summary>
        /// The (injected) <see cref="IPackageVersionService" /> used to retrieve package version data.
        /// </summary>
        private readonly IPackageVersionService packageVersionService;

        /// <summary>
        /// The (injected) <see cref="IScopeService" /> used to retrieve scope data.
        /// </summary>
        private readonly IScopeService scopeService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> used to retrieve the current user context.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// Initializes a new instance of the <see cref="PackageDetailsViewModel" /> class.
        /// </summary>
        /// <param name="packageService">The (injected) <see cref="IPackageService" />.</param>
        /// <param name="scopeService">The (injected) <see cref="IScopeService" />.</param>
        /// <param name="packageVersionService">The (injected) <see cref="IPackageVersionService" />.</param>
        /// <param name="packageMetaDataService">The (injected) <see cref="IPackageMetaDataService" />.</param>
        /// <param name="packageTypeService">The (injected) <see cref="IPackageTypeService" />.</param>
        /// <param name="accountService">The (injected) <see cref="IAccountService" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        public PackageDetailsViewModel(IPackageService packageService, IScopeService scopeService, IPackageVersionService packageVersionService,
            IPackageMetaDataService packageMetaDataService, IPackageTypeService packageTypeService, IAccountService accountService, IUserService userService)
        {
            this.packageService = packageService;
            this.scopeService = scopeService;
            this.packageVersionService = packageVersionService;
            this.packageMetaDataService = packageMetaDataService;
            this.packageTypeService = packageTypeService;
            this.accountService = accountService;
            this.userService = userService;
        }

        /// <summary>
        /// Gets or sets the underlying package DTO.
        /// </summary>
        public IPackage Package { get; set; }

        /// <summary>
        /// Gets or sets the owning scope DTO.
        /// </summary>
        public IScope Owner { get; set; }

        /// <summary>
        /// Gets or sets the package type DTO.
        /// </summary>
        public IPackageType PackageType { get; set; }

        /// <summary>
        /// Gets or sets the collection of released package version DTOs.
        /// </summary>
        public IReadOnlyList<IPackageVersion> Versions { get; set; } = [];

        /// <summary>
        /// Gets or sets the collection of maintainer account DTOs.
        /// </summary>
        public IReadOnlyList<IAccount> Maintainers { get; set; } = [];

        /// <summary>
        /// Gets or sets the selected or latest package version DTO.
        /// </summary>
        public IPackageVersion CurrentVersion { get; set; }

        /// <summary>
        /// Gets or sets the collection of package metadata DTOs corresponding to package versions.
        /// </summary>
        public IReadOnlyList<IPackageMetaData> MetaDatas { get; set; } = [];

        /// <summary>
        /// Gets the package metadata DTO for the currently selected package version.
        /// </summary>
        public IPackageMetaData CurrentMetaData => this.MetaDatas.FirstOrDefault(m => m.Id == this.CurrentVersion.MetaData || m.Owner == this.CurrentVersion.Id);

        /// <summary>
        /// Gets the collection of model elements contained within the package release.
        /// </summary>
        public IReadOnlyList<(string Name, string Kind, string Category, string AttributeSummary)> Elements => this.CurrentMetaData?.Elements ?? [];

        /// <summary>
        /// Gets the collection of direct package dependencies resolved from the usage projection.
        /// </summary>
        public IReadOnlyList<(string Name, string Summary, bool IsVerified)> Dependencies => this.CurrentMetaData?.Dependencies ?? [];

        /// <summary>
        /// Gets the collection of packages and projects depending on this package.
        /// </summary>
        public IReadOnlyList<(string Name, string Summary, bool IsProject, bool IsVerified)> Dependents => [];

        /// <summary>
        /// Gets the collection of quality evaluation checks.
        /// </summary>
        public IReadOnlyList<(string Title, string Detail, bool Passed)> QualityChecks => this.CurrentMetaData?.QualityChecks ?? [];

        /// <summary>
        /// Gets or sets a value indicating whether the current user is an administrator of the package.
        /// </summary>
        public bool IsUserAdmin { get; set; } = true;

        /// <summary>
        /// Initializes the package view model state for the specified package name and scope asynchronously.
        /// </summary>
        /// <param name="packageName">The name of the package.</param>
        /// <param name="scope">The owning scope or publisher of the package.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel(string packageName, string scope)
        {
            var userContext = this.userService.GetUserContext();
            var packageResult = await this.packageService.ReadByCoordinateAsync(userContext, scope, packageName);

            if (packageResult.IsError || packageResult.Value == null)
            {
                return;
            }

            this.Package = packageResult.Value;

            var ownerTask = this.scopeService.ReadOrNull(userContext, this.Package.Owner);
            var packageTypeTask = this.packageTypeService.ReadOrNull(userContext, this.Package.PackageType);
            var versionsTask = this.packageVersionService.ReadOrEmpty(userContext, this.Package.Version);

            List<Guid> maintainerIds = [.. this.Package.PackageMaintainer, .. this.Package.PackageOwner];
            var maintainersTask = this.accountService.ReadOrEmpty(userContext, maintainerIds);

            await Task.WhenAll(ownerTask, packageTypeTask, versionsTask, maintainersTask);

            this.Owner = ownerTask.Result;
            this.PackageType = packageTypeTask.Result;
            this.Maintainers = maintainersTask.Result;

            this.Versions = versionsTask.Result.OrderByDescending(v => v.PublicationDate).ToList();
            this.CurrentVersion = this.Versions.FirstOrDefault();

            var metaDataIds = this.Versions.Select(v => v.MetaData).ToList();
            this.MetaDatas = (await this.packageMetaDataService.ReadOrEmpty(userContext, metaDataIds)).ToList();
        }
    }
}
