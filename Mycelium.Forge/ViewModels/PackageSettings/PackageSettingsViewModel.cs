namespace Mycelium.Forge.ViewModels.PackageSettings
{
    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides view model state and management logic for the Mycelium Forge package settings page.
    /// </summary>
    public class PackageSettingsViewModel : IPackageSettingsViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IAccountService" /> used to retrieve account data.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="IDatabaseSource" /> database connection provider.
        /// </summary>
        private readonly IDatabaseSource databaseSource;

        /// <summary>
        /// The (injected) <see cref="ILogger{PackageSettingsViewModel}" /> used for diagnostic logging.
        /// </summary>
        private readonly ILogger<PackageSettingsViewModel> logger;

        /// <summary>
        /// The (injected) <see cref="INotificationService" /> used to emit notifications.
        /// </summary>
        private readonly INotificationService notificationService;

        /// <summary>
        /// The (injected) <see cref="IPackagePermissionService" /> used to validate package permissions.
        /// </summary>
        private readonly IPackagePermissionService packagePermissionService;

        /// <summary>
        /// The (injected) <see cref="IPackageService" /> used to retrieve and update package data.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The (injected) <see cref="IPackageVersionService" /> used to retrieve and update package version data.
        /// </summary>
        private readonly IPackageVersionService packageVersionService;

        /// <summary>
        /// The (injected) <see cref="IScopeService" /> used to retrieve scope data.
        /// </summary>
        private readonly IScopeService scopeService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> used to retrieve the current user context.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// The authenticated user context resolved on initialization.
        /// </summary>
        private IUserContext userContext;

        /// <summary>
        /// Initializes a new instance of the <see cref="PackageSettingsViewModel" /> class.
        /// </summary>
        /// <param name="databaseSource">The (injected) <see cref="IDatabaseSource" /> database connection provider.</param>
        /// <param name="packageService">The (injected) <see cref="IPackageService" />.</param>
        /// <param name="scopeService">The (injected) <see cref="IScopeService" />.</param>
        /// <param name="packageVersionService">The (injected) <see cref="IPackageVersionService" />.</param>
        /// <param name="accountService">The (injected) <see cref="IAccountService" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="packagePermissionService">The (injected) <see cref="IPackagePermissionService" />.</param>
        /// <param name="notificationService">The (injected) <see cref="INotificationService" />.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{PackageSettingsViewModel}" />.</param>
        public PackageSettingsViewModel(IDatabaseSource databaseSource, IPackageService packageService, IScopeService scopeService, IPackageVersionService packageVersionService, IAccountService accountService, IUserService userService, IPackagePermissionService packagePermissionService, INotificationService notificationService, ILogger<PackageSettingsViewModel> logger)
        {
            this.databaseSource = databaseSource;
            this.packageService = packageService;
            this.scopeService = scopeService;
            this.packageVersionService = packageVersionService;
            this.accountService = accountService;
            this.userService = userService;
            this.packagePermissionService = packagePermissionService;
            this.notificationService = notificationService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets or sets the underlying package DTO.
        /// </summary>
        public IPackage Package { get; set; }

        /// <summary>
        /// Gets or sets the owning scope DTO.
        /// </summary>
        public IScope Owner { get; set; }

        /// <summary>
        /// Gets or sets the collection of maintainer accounts for the package.
        /// </summary>
        public IReadOnlyList<IAccount> Maintainers { get; set; } = [];

        /// <summary>
        /// Gets or sets the collection of owner accounts for the package.
        /// </summary>
        public IReadOnlyList<IAccount> Owners { get; set; } = [];

        /// <summary>
        /// Gets or sets the collection of released package versions.
        /// </summary>
        public IReadOnlyList<IPackageVersion> Versions { get; set; } = [];

        /// <summary>
        /// Gets or sets a value indicating whether the current user is allowed to manage the package.
        /// </summary>
        public bool CanManagePackage { get; set; }

        /// <summary>
        /// Gets or sets a value indicating whether the current user is allowed to delete the package.
        /// </summary>
        public bool CanDeletePackage { get; set; }

        /// <summary>
        /// Initializes the package settings view model state for the specified package name and scope asynchronously.
        /// </summary>
        /// <param name="packageName">The name of the package.</param>
        /// <param name="scope">The owning scope or publisher identifier.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel(string packageName, string scope)
        {
            this.userContext = await this.userService.GetUserContext();
            var packageResult = await this.packageService.ReadByCoordinateAsync(this.userContext, scope, packageName);

            if (packageResult.IsError)
            {
                this.logger.LogWarning("Package {Scope}/{Name} not found during settings initialization", scope, packageName);
                return;
            }

            this.Package = packageResult.Value;

            var ownerTask = this.scopeService.ReadOrNull(this.userContext, this.Package.Owner);
            var maintainersTask = this.accountService.ReadOrEmpty(this.userContext, this.Package.PackageMaintainer);
            var ownersTask = this.accountService.ReadOrEmpty(this.userContext, this.Package.PackageOwner);
            var versionsTask = this.packageVersionService.ReadOrEmpty(this.userContext, this.Package.Version);
            var canUpdatePackageTask = this.packagePermissionService.IsAllowedToUpdate(this.databaseSource, this.userContext, this.Package);
            var canDeletePackageTask = this.packagePermissionService.IsAllowedToDelete(this.databaseSource, this.userContext, this.Package);

            await Task.WhenAll(ownerTask, maintainersTask, ownersTask, versionsTask, canUpdatePackageTask, canDeletePackageTask);

            this.Owner = ownerTask.Result;
            this.Maintainers = maintainersTask.Result;
            this.Owners = ownersTask.Result;
            this.Versions = [.. versionsTask.Result.OrderByDescending(v => v.PublicationDate)];
            this.CanManagePackage = canUpdatePackageTask.Result.IsSuccess;
            this.CanDeletePackage = canDeletePackageTask.Result.IsSuccess;
        }

        /// <summary>
        /// Updates the package visibility setting asynchronously.
        /// </summary>
        /// <param name="visibility">The target visibility kind.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task SetVisibility(VisibilityKind visibility, CancellationToken token = default)
        {
            this.Package.Visibility = visibility;
            var result = await this.packageService.UpdateAsync(this.userContext, [this.Package], token);

            if (result.IsError)
            {
                const string errorMessage = "Failed to update package visibility.";

                this.logger.LogError(errorMessage);
                this.notificationService.AddNotification(errorMessage, "Visibility Update Failed", NotificationType.Error);
                return;
            }

            this.notificationService.AddNotification($"Package visibility updated to {visibility.ToUpperCaseFirst()}.", "Visibility Updated", NotificationType.Success);
        }

        /// <summary>
        /// Unlists the specified package version asynchronously.
        /// </summary>
        /// <param name="version">The package version to unlist.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task UnlistVersion(IPackageVersion version, CancellationToken token = default)
        {
            version.Listed = false;
            var result = await this.packageVersionService.UpdateAsync(this.userContext, [version], token);

            if (result.IsError)
            {
                const string errorMessage = "Failed to unlist version.";

                this.logger.LogError(errorMessage);
                this.notificationService.AddNotification(errorMessage, "Error", NotificationType.Error);
                return;
            }

            this.notificationService.AddNotification($"Version {version.Version} has been unlisted.", "Version Unlisted", NotificationType.Success);
        }

        /// <summary>
        /// Relists the specified unlisted package version asynchronously.
        /// </summary>
        /// <param name="version">The package version to relist.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task RelistVersion(IPackageVersion version, CancellationToken token = default)
        {
            version.Listed = true;
            var result = await this.packageVersionService.UpdateAsync(this.userContext, [version], token);

            if (result.IsError)
            {
                const string errorMessage = "Failed to relist version.";

                this.logger.LogError(errorMessage);
                this.notificationService.AddNotification(errorMessage, "Error", NotificationType.Error);
                return;
            }

            this.notificationService.AddNotification($"Version {version.Version} has been relisted.", "Version Relisted", NotificationType.Success);
        }

        /// <summary>
        /// Marks the specified package version as deprecated asynchronously.
        /// </summary>
        /// <param name="version">The package version to deprecate.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task DeprecateVersion(IPackageVersion version, CancellationToken token = default)
        {
            version.IsDeprecated = true;
            var result = await this.packageVersionService.UpdateAsync(this.userContext, [version], token);

            if (result.IsError)
            {
                const string errorMessage = "Failed to deprecate version.";

                this.logger.LogError(errorMessage);
                this.notificationService.AddNotification(errorMessage, "Error", NotificationType.Error);
                return;
            }

            this.notificationService.AddNotification($"Version {version.Version} has been deprecated.", "Version Deprecated", NotificationType.Success);
        }

        /// <summary>
        /// Transfers package ownership to the specified recipient scope asynchronously.
        /// </summary>
        /// <param name="targetScope">The target scope short name.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public Task<ErrorOr<Success>> TransferOwnership(string targetScope, CancellationToken token = default)
        {
            // TODO: Implement the logic to transfer package ownership to the specified target scope.
            return Task.FromResult<ErrorOr<Success>>(Result.Success);
        }

        /// <summary>
        /// Deletes the package asynchronously.
        /// </summary>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> DeletePackage(CancellationToken token = default)
        {
            var deleteResult = await this.packageService.DeleteAsync(this.userContext, [this.Package.Id], token);

            if (deleteResult.IsError)
            {
                const string errorMessage = "Failed to delete package.";

                this.logger.LogError(errorMessage);
                this.notificationService.AddNotification(errorMessage, "Delete Failed", NotificationType.Error);
                return deleteResult.Errors;
            }

            this.notificationService.AddNotification("Package deleted successfully.", "Package Deleted", NotificationType.Success);
            return Result.Success;
        }
    }
}
