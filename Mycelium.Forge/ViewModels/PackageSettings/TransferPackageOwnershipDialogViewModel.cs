namespace Mycelium.Forge.ViewModels.PackageSettings
{
    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Represents the view model of the transfer package ownership dialog, validating the transfer target for inline display.
    /// </summary>
    /// <remarks>
    /// These checks only provide immediate feedback; the authoritative checks are enforced by <see cref="IPackageService" />
    /// when the package is updated.
    /// </remarks>
    public class TransferPackageOwnershipDialogViewModel : ITransferPackageOwnershipDialogViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IPackageService" /> used to look up the target coordinate.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The (injected) <see cref="IScopeService" /> used to lookup the target scope.
        /// </summary>
        private readonly IScopeService scopeService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> used to retrieve the current user context.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// Initializes a new instance of the <see cref="TransferPackageOwnershipDialogViewModel" /> class.
        /// </summary>
        /// <param name="packageService">The (injected) <see cref="IPackageService" />.</param>
        /// <param name="scopeService">The (injected) <see cref="IScopeService" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        public TransferPackageOwnershipDialogViewModel(IPackageService packageService, IScopeService scopeService, IUserService userService)
        {
            this.packageService = packageService;
            this.scopeService = scopeService;
            this.userService = userService;
        }

        /// <summary>
        /// Validates the requested transfer target for inline display and resolves it to a scope.
        /// </summary>
        /// <param name="package">The package being transferred.</param>
        /// <param name="currentOwnerShortName">The short name of the current owning scope.</param>
        /// <param name="targetShortName">The short name of the requested target scope.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>The resolved target <see cref="IScope" />, or validation errors describing why it cannot be used.</returns>
        public async Task<ErrorOr<IScope>> ValidateTargetAsync(IPackage package, string currentOwnerShortName, string targetShortName, CancellationToken token = default)
        {
            var userContext = await this.userService.GetUserContext();
            var scopeResult = await this.scopeService.ReadByShortNameAsync(userContext, token, [targetShortName]);

            if (scopeResult.IsError || scopeResult.Value.Count == 0)
            {
                return Error.NotFound(description: $"Scope '{targetShortName}' not found.");
            }

            var scope = scopeResult.Value[0];

            if (string.Equals(targetShortName, currentOwnerShortName, StringComparison.OrdinalIgnoreCase))
            {
                return Error.Validation(description: "You cannot transfer ownership to the current owner scope.");
            }

            var isInstallationAdministrator = PermissionGuard.HasRole(userContext, RoleKind.InstallationAdministrator);
            var isOwnAccount = userContext.AccountId.HasValue && scope.Id == userContext.AccountId.Value;

            switch (scope)
            {
                case IOrganization organization when !isInstallationAdministrator && (!userContext.AccountId.HasValue || !organization.Administrator.Contains(userContext.AccountId.Value)):
                    return Error.Validation(description: "You do not have administrative rights on the target organization.");
                case IAccount when !isInstallationAdministrator && !isOwnAccount:
                    return Error.Validation(description: "Ownership can only be transferred to your own account or to an organization you administer.");
            }

            var existingResult = await this.packageService.ReadByCoordinateAsync(userContext, targetShortName, package.ShortName, true, token);

            if (!existingResult.IsError)
            {
                return Error.Conflict(description: $"Scope '{targetShortName}' already contains a package named '{package.ShortName}'.");
            }

            if (existingResult.FirstError.Type != ErrorType.NotFound)
            {
                return Error.Failure(description: "Could not verify that the package name is available in the target scope.");
            }

            return await ErrorOrFactory.FromAsync(scope);
        }
    }
}
