namespace Mycelium.Forge.ViewModels.MyPackages
{
    using System.Collections.Immutable;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Services;

    using ReactiveUI;

    /// <summary>
    /// Provides view model state and operations for the My Packages page, listing packages
    /// owned or maintained by the current user across their account and organizations.
    /// </summary>
    public class MyPackagesViewModel : DisposableViewModel, IMyPackagesViewModel
    {
        /// <summary>
        /// The (injected) <see cref="ILogger{MyPackagesViewModel}" /> used to log errors.
        /// </summary>
        private readonly ILogger<MyPackagesViewModel> logger;

        /// <summary>
        /// The (injected) <see cref="IPackageService" /> used to retrieve packages.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The (injected) <see cref="IPackageVersionService" /> used to retrieve package version data.
        /// </summary>
        private readonly IPackageVersionService packageVersionService;

        /// <summary>
        /// The (injected) <see cref="IScopeService" /> used to retrieve scope data.
        /// </summary>
        private readonly IScopeService scopeService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> used to retrieve the current user account and context.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// The cached current user account id.
        /// </summary>
        private Guid currentUserId;

        /// <summary>
        /// The cached list of scopes for resolving publishers.
        /// </summary>
        private ImmutableList<IScope> scopes = [];

        /// <summary>
        /// The cached list of package versions for resolving versions and publish dates.
        /// </summary>
        private ImmutableList<IPackageVersion> versions = [];

        /// <summary>
        /// Initializes a new instance of the <see cref="MyPackagesViewModel" /> class.
        /// </summary>
        /// <param name="packageService">The (injected) <see cref="IPackageService" />.</param>
        /// <param name="scopeService">The (injected) <see cref="IScopeService" />.</param>
        /// <param name="packageVersionService">The (injected) <see cref="IPackageVersionService" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{MyPackagesViewModel}" />.</param>
        public MyPackagesViewModel(IPackageService packageService, IScopeService scopeService, IPackageVersionService packageVersionService, IUserService userService, ILogger<MyPackagesViewModel> logger)
        {
            this.packageService = packageService;
            this.scopeService = scopeService;
            this.packageVersionService = packageVersionService;
            this.userService = userService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets or sets a value indicating whether the view model is currently loading data.
        /// </summary>
        public bool IsLoading
        {
            get;
            set => this.RaiseAndSetIfChanged(ref field, value);
        } = true;

        /// <summary>
        /// Gets or sets the collection of packages owned or maintained by the current user.
        /// </summary>
        public List<IPackage> Packages { get; set; } = [];

        /// <summary>
        /// Initializes the view model state and populates the packages collection.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task InitializeViewModel()
        {
            this.IsLoading = true;

            try
            {
                var userContext = await this.userService.GetUserContext();

                if (!userContext.IsAuthenticated)
                {
                    this.Packages = [];
                    return;
                }

                this.currentUserId = userContext.AccountId.GetValueOrDefault();
                var packagesResult = await this.packageService.ReadByMaintainerOrOwnerAsync(userContext, this.currentUserId);

                if (packagesResult.IsError || packagesResult.Value.IsEmpty)
                {
                    this.Packages = [];
                    return;
                }

                this.Packages = [.. packagesResult.Value];

                var scopesTask = this.scopeService.ReadOrEmpty(userContext, this.Packages.Select(p => p.Owner));
                var versionsTask = this.packageVersionService.ReadOrEmpty(userContext, this.Packages.SelectMany(p => p.Version));

                await Task.WhenAll(scopesTask, versionsTask);

                this.scopes = scopesTask.Result;
                this.versions = versionsTask.Result;
            }
            catch (Exception exception)
            {
                this.logger.LogError(exception, "An error occurred while initializing MyPackagesViewModel.");
            }
            finally
            {
                this.IsLoading = false;
            }
        }

        /// <summary>
        /// Gets the publisher string formatted with leading '@' for the specified package.
        /// </summary>
        /// <param name="package">The package DTO.</param>
        /// <returns>The publisher handle string.</returns>
        public string GetPublisher(IPackage package)
        {
            var scope = this.scopes.Find(s => s.Id == package.Owner);
            return scope != null ? $"@{scope.ShortName}" : "-";
        }

        /// <summary>
        /// Gets the latest listed release version for the specified package.
        /// </summary>
        /// <param name="package">The package DTO.</param>
        /// <returns>The latest release version, or <c>null</c> if none found.</returns>
        public IPackageVersion GetLatestVersion(IPackage package)
        {
            return this.versions
                .Where(v => v.Owner == package.Id && v.Listed)
                .OrderByDescending(v => v.PublicationDate)
                .ThenByDescending(v => v.Version)
                .FirstOrDefault();
        }

        /// <summary>
        /// Gets the role of the current user for the specified package.
        /// </summary>
        /// <param name="package">The package DTO.</param>
        /// <returns>The <see cref="PackageInvitationKind" /> role value.</returns>
        public PackageInvitationKind GetRole(IPackage package)
        {
            if (package.Owner == this.currentUserId || package.PackageOwner.Contains(this.currentUserId))
            {
                return PackageInvitationKind.OWNER;
            }

            return PackageInvitationKind.MAINTAINER;
        }
    }
}
