namespace Mycelium.Forge.ViewModels.OrganizationSettings
{
    using DynamicData;

    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides view model state and operations for managing organization members, invitations, and scope configuration.
    /// </summary>
    public class OrganizationSettingsViewModel : IOrganizationSettingsViewModel
    {
        /// <summary>
        /// The default number of days before a resent invitation expires.
        /// </summary>
        private const int InvitationExpirationDays = 7;

        /// <summary>
        /// The list of available role options for organization members.
        /// </summary>
        private static readonly List<OrganizationRole> AvailableRoles =
        [
            OrganizationRole.Administrator,
            OrganizationRole.Member
        ];

        /// <summary>
        /// The (injected) <see cref="IAccountService" /> domain service.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="IDatabaseSource" /> database connection provider.
        /// </summary>
        private readonly IDatabaseSource databaseSource;

        /// <summary>
        /// The (injected) <see cref="ILogger{OrganizationSettingsViewModel}" /> logger.
        /// </summary>
        private readonly ILogger<OrganizationSettingsViewModel> logger;

        /// <summary>
        /// The (injected) <see cref="INotificationService" /> used to emit notifications.
        /// </summary>
        private readonly INotificationService notificationService;

        /// <summary>
        /// The (injected) <see cref="IOrganizationInvitationService" /> domain service.
        /// </summary>
        private readonly IOrganizationInvitationService organizationInvitationService;

        /// <summary>
        /// The (injected) <see cref="IOrganizationPermissionService" /> used to validate organization permissions.
        /// </summary>
        private readonly IOrganizationPermissionService organizationPermissionService;

        /// <summary>
        /// The (injected) <see cref="IOrganizationService" /> domain service.
        /// </summary>
        private readonly IOrganizationService organizationService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> domain service.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// Initializes a new instance of the <see cref="OrganizationSettingsViewModel" /> class.
        /// </summary>
        /// <param name="databaseSource">The (injected) <see cref="IDatabaseSource" /> database connection provider.</param>
        /// <param name="organizationService">The (injected) <see cref="IOrganizationService" />.</param>
        /// <param name="accountService">The (injected) <see cref="IAccountService" />.</param>
        /// <param name="organizationInvitationService">The (injected) <see cref="IOrganizationInvitationService" />.</param>
        /// <param name="organizationPermissionService">The (injected) <see cref="IOrganizationPermissionService" />.</param>
        /// <param name="notificationService">The (injected) <see cref="INotificationService" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{OrganizationSettingsViewModel}" />.</param>
        public OrganizationSettingsViewModel(IDatabaseSource databaseSource, IOrganizationService organizationService, IAccountService accountService, IOrganizationInvitationService organizationInvitationService, IOrganizationPermissionService organizationPermissionService, INotificationService notificationService, IUserService userService, ILogger<OrganizationSettingsViewModel> logger)
        {
            this.databaseSource = databaseSource;
            this.organizationService = organizationService;
            this.accountService = accountService;
            this.organizationInvitationService = organizationInvitationService;
            this.organizationPermissionService = organizationPermissionService;
            this.notificationService = notificationService;
            this.userService = userService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets the authenticated user context resolved on initialization.
        /// </summary>
        public IUserContext UserContext { get; private set; }

        /// <summary>
        /// Gets or sets the organization profile details.
        /// </summary>
        public Organization Organization { get; set; }

        /// <summary>
        /// Gets or sets the current user's role within the organization.
        /// </summary>
        public OrganizationRole CurrentUserRole { get; set; } = OrganizationRole.Member;

        /// <summary>
        /// Gets or sets a value indicating whether the current user is allowed to manage the organization.
        /// </summary>
        public bool CanManageOrganization { get; set; }

        /// <summary>
        /// Gets or sets the unique identifier of the currently authenticated user.
        /// </summary>
        public Guid CurrentUserId { get; set; }

        /// <summary>
        /// Gets or sets the collection of members belonging to the organization.
        /// </summary>
        public IReadOnlyList<IAccount> Members { get; set; } = [];

        /// <summary>
        /// Gets or sets the collection of accounts that have been invited to join the organization.
        /// </summary>
        public IReadOnlyList<IAccount> InvitedAccounts { get; set; } = [];

        /// <summary>
        /// Gets or sets the collection of pending invitations for the organization.
        /// </summary>
        public List<OrganizationInvitation> PendingInvitations { get; set; } = [];

        /// <summary>
        /// Gets or sets the available role options for organization members.
        /// </summary>
        public IReadOnlyList<OrganizationRole> RoleOptions { get; set; } = AvailableRoles;

        /// <summary>
        /// Initializes the view model state for the specified organization short name asynchronously.
        /// </summary>
        /// <param name="shortName">The short name of the organization.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel(string shortName)
        {
            this.UserContext = await this.userService.GetUserContext();

            var orgResult = await this.organizationService.ReadByShortNameAsync(this.UserContext, CancellationToken.None, [shortName.ToLowerInvariant()]);

            if (orgResult.IsError || orgResult.Value.Count == 0 || !this.UserContext.AccountId.HasValue)
            {
                var errors = orgResult.IsError ? orgResult.Errors.ToJoinedDescriptions() : "Organization not found or Account ID missing in user context";
                this.logger.LogWarning("Organization {ShortName} not found: {Errors}", shortName.SanitizeForLog(), errors);
                return;
            }

            this.Organization = (Organization)orgResult.Value[0];
            this.CurrentUserId = this.UserContext.AccountId.Value;

            await this.ComputeCurrentUserPermissions();

            var invitationsResult = await this.organizationInvitationService.ReadAsync(this.UserContext, CancellationToken.None);

            if (!invitationsResult.IsError)
            {
                this.PendingInvitations = [.. invitationsResult.Value.Cast<OrganizationInvitation>().Where(i => i.Organization == this.Organization.Id && i.Status == InvitationStatusKind.PENDING)];
            }

            List<Guid> memberIds = [.. this.Organization.Member, .. this.Organization.Administrator];
            var pendingInvitationTargets = this.PendingInvitations.Select(i => i.Target).ToList();

            var accountsOfInterest = await this.accountService.ReadOrEmpty(this.UserContext, [.. memberIds, .. pendingInvitationTargets]);

            this.Members = [.. accountsOfInterest.Where(a => memberIds.Contains(a.Id))];
            this.InvitedAccounts = [.. accountsOfInterest.Where(a => pendingInvitationTargets.Contains(a.Id))];
        }

        /// <summary>
        /// Changes the role of the specified organization member asynchronously.
        /// </summary>
        /// <param name="member">The member whose role is being updated.</param>
        /// <param name="newRole">The new role to assign to the member.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task ChangeMemberRole(IAccount member, OrganizationRole newRole)
        {
            var organizationClone = this.Organization.Clone();

            if (newRole == OrganizationRole.Administrator)
            {
                organizationClone.Administrator.AddIfNotExisting(member.Id);
            }
            else
            {
                organizationClone.Administrator.Remove(member.Id);
                organizationClone.Member.AddIfNotExisting(member.Id);
            }

            var updateResult = await this.organizationService.UpdateAsync(this.UserContext, [organizationClone], CancellationToken.None);

            if (updateResult.IsError)
            {
                const string errorMessage = "Failed to update member role.";
                this.logger.LogError(errorMessage + " Account: {AccountId} Errors: {Errors}", member.Id, updateResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Role Update Error", NotificationType.Error);
                return;
            }

            this.Organization = organizationClone;
            this.notificationService.AddNotification($"Role updated to {newRole.ToUpperCaseFirst()} for {member.Name}.", "Role Updated", NotificationType.Success);
        }

        /// <summary>
        /// Removes the specified member from the organization asynchronously.
        /// </summary>
        /// <param name="member">The member to remove.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task RemoveMember(IAccount member)
        {
            var organizationClone = this.Organization.Clone();

            organizationClone.Member.Remove(member.Id);
            organizationClone.Administrator.Remove(member.Id);

            var updateResult = await this.organizationService.UpdateAsync(this.UserContext, [organizationClone], CancellationToken.None);

            if (updateResult.IsError)
            {
                const string errorMessage = "Failed to remove member from organization.";
                this.logger.LogError(errorMessage + " Account: {AccountId} Errors: {Errors}", member.Id, updateResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Removal Error", NotificationType.Error);
                return;
            }

            this.Organization = organizationClone;
            this.Members = [.. this.Members.Where(m => m.Id != member.Id)];
            this.notificationService.AddNotification($"{member.Name} has been removed from the organization.", "Member Removed", NotificationType.Success);
        }

        /// <summary>
        /// Resends the specified pending invitation asynchronously.
        /// </summary>
        /// <param name="invitation">The invitation to resend.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task ResendInvitation(OrganizationInvitation invitation)
        {
            var invitationClone = invitation.Clone();
            invitationClone.ExperiesAt = DateTime.UtcNow.AddDays(InvitationExpirationDays);

            var updateResult = await this.organizationInvitationService.UpdateAsync(this.UserContext, [invitationClone], CancellationToken.None);

            if (updateResult.IsError)
            {
                const string errorMessage = "Failed to resend invitation.";
                this.logger.LogError(errorMessage + " Invitation: {InvitationId} Errors: {Errors}", invitation.Id, updateResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Invitation Error", NotificationType.Error);
                return;
            }

            this.PendingInvitations.Replace(invitation, invitationClone);
            this.notificationService.AddNotification("Invitation resent successfully.", "Invitation Resent", NotificationType.Success);
        }

        /// <summary>
        /// Revokes the specified pending invitation asynchronously.
        /// </summary>
        /// <param name="invitation">The invitation to revoke.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task RevokeInvitation(OrganizationInvitation invitation)
        {
            var deleteResult = await this.organizationInvitationService.DeleteAsync(this.UserContext, [invitation.Id], CancellationToken.None);

            if (deleteResult.IsError)
            {
                const string errorMessage = "Failed to revoke invitation.";
                this.logger.LogError(errorMessage + " Invitation: {InvitationId}", invitation.Id);
                this.notificationService.AddNotification(errorMessage, "Invitation Error", NotificationType.Error);
                return;
            }

            this.PendingInvitations.Remove(invitation);
            this.notificationService.AddNotification("Invitation revoked successfully.", "Invitation Revoked", NotificationType.Success);
        }

        /// <summary>
        /// Transfers ownership of the organization to the specified recipient account asynchronously.
        /// </summary>
        /// <param name="recipient">The recipient account to transfer ownership to.</param>
        /// <returns>A <see cref="Task{ErrorOr}" /> representing the asynchronous operation.</returns>
        public async Task<ErrorOr<Success>> TransferOrganization(IAccount recipient)
        {
            var organizationClone = this.Organization.Clone();

            // Administrator subsets Member in the domain schema and seed data, so CurrentUserId remains in Member. Check Organization DTO summary.
            organizationClone.Administrator.AddIfNotExisting(recipient.Id);
            organizationClone.Member.AddIfNotExisting(recipient.Id);
            organizationClone.Administrator.Remove(this.CurrentUserId);

            var updateResult = await this.organizationService.UpdateAsync(this.UserContext, [organizationClone], CancellationToken.None);

            if (updateResult.IsError)
            {
                const string errorMessage = "Failed to transfer organization ownership.";

                this.logger.LogError(errorMessage + " Recipient: {RecipientId} Errors: {Errors}", recipient.Id, updateResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Transfer Error", NotificationType.Error);
                return updateResult.Errors;
            }

            this.Organization = organizationClone;
            await this.ComputeCurrentUserPermissions();

            if (this.Members.All(m => m.Id != recipient.Id))
            {
                this.Members = [.. this.Members, recipient];
            }

            this.notificationService.AddNotification($"Organization ownership transferred to {recipient.Name}.", "Ownership Transferred", NotificationType.Success);
            return Result.Success;
        }

        /// <summary>
        /// Computes and sets the current user's role and management permissions for the organization.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        private async Task ComputeCurrentUserPermissions()
        {
            this.CurrentUserRole = this.Organization.Administrator.Contains(this.CurrentUserId)
                ? OrganizationRole.Administrator
                : OrganizationRole.Member;

            var permissionResult = await this.organizationPermissionService.IsAllowedToUpdate(this.databaseSource, this.UserContext, this.Organization);
            this.CanManageOrganization = permissionResult.IsSuccess;
        }
    }
}
