namespace Mycelium.Forge.ViewModels.AccountSettings
{
    using DynamicData;

    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides view model state and operations for managing the addresses of the user account.
    /// </summary>
    public class AddressesManagerViewModel : IAddressesManagerViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IAddressService" /> domain service.
        /// </summary>
        private readonly IAddressService addressService;

        /// <summary>
        /// The (injected) <see cref="ICountryService" /> domain service.
        /// </summary>
        private readonly ICountryService countryService;

        /// <summary>
        /// The (injected) <see cref="ILogger{AddressesManagerViewModel}" /> logger.
        /// </summary>
        private readonly ILogger<AddressesManagerViewModel> logger;

        /// <summary>
        /// The (injected) <see cref="INotificationService" /> notification service.
        /// </summary>
        private readonly INotificationService notificationService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> domain service.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// The current authenticated user account identifier.
        /// </summary>
        private Guid currentUserId;

        /// <summary>
        /// The authenticated user context.
        /// </summary>
        private IUserContext userContext;

        /// <summary>
        /// Initializes a new instance of the <see cref="AddressesManagerViewModel" /> class.
        /// </summary>
        /// <param name="logger">The (injected) <see cref="ILogger{AddressesManagerViewModel}" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="addressService">The (injected) <see cref="IAddressService" />.</param>
        /// <param name="countryService">The (injected) <see cref="ICountryService" />.</param>
        /// <param name="notificationService">The (injected) <see cref="INotificationService" />.</param>
        public AddressesManagerViewModel(ILogger<AddressesManagerViewModel> logger, IUserService userService, IAddressService addressService, ICountryService countryService, INotificationService notificationService)
        {
            this.logger = logger;
            this.userService = userService;
            this.addressService = addressService;
            this.countryService = countryService;
            this.notificationService = notificationService;
        }

        /// <summary>
        /// Gets the collection of addresses owned by the user account.
        /// </summary>
        public SourceList<Address> Addresses { get; } = new();

        /// <summary>
        /// Gets the countries that can be selected for an address.
        /// </summary>
        public IReadOnlyList<ICountry> Countries { get; private set; } = [];

        /// <summary>
        /// Gets or sets the identifier of the primary address of the user account.
        /// </summary>
        public Guid? PrimaryAddressId { get; set; }

        /// <summary>
        /// Gets or sets the function invoked to persist a new primary address identifier on the user account.
        /// </summary>
        public Func<Guid?, Task<ErrorOr<Success>>> OnPrimaryAddressChanging { get; set; }

        /// <summary>
        /// Initializes the view model state asynchronously for the specified account profile.
        /// </summary>
        /// <param name="profile">The current user profile account.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task InitializeViewModel(Account profile)
        {
            this.userContext = await this.userService.GetUserContext();

            if (!this.userContext.AccountId.HasValue)
            {
                this.logger.LogWarning("User is not authenticated during addresses manager initialization");
                return;
            }

            this.currentUserId = this.userContext.AccountId.Value;
            this.PrimaryAddressId = profile.PrimaryAddress;

            var countries = await this.countryService.ReadOrEmpty(this.userContext, emptyWhenNoIds: false);
            this.Countries = [.. countries.OrderBy(country => country.Name)];

            var addresses = await this.addressService.ReadOrEmpty(this.userContext, profile.Address);

            this.Addresses.Edit(innerList =>
            {
                innerList.Clear();
                innerList.AddRange(addresses.Cast<Address>());
            });
        }

        /// <summary>
        /// Creates a new address for the user account asynchronously. The address becomes the primary address when there is none.
        /// </summary>
        /// <param name="address">The address to create.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> CreateAddress(Address address)
        {
            address.Owner = this.currentUserId;

            var createResult = await this.addressService.CreateAsync(this.userContext, [address], CancellationToken.None);

            if (createResult.IsError)
            {
                return this.HandleErrors("Failed to create address.", address.Id, createResult.Errors);
            }

            var primaryResult = await this.ApplyPrimaryAddress(address.Id, !this.PrimaryAddressId.HasValue);
            this.Addresses.Add(address);

            if (primaryResult.IsError)
            {
                return primaryResult;
            }

            this.notificationService.AddNotification("Address created successfully.", "Address Created", NotificationType.Success);
            return Result.Success;
        }

        /// <summary>
        /// Updates an existing address of the user account asynchronously.
        /// </summary>
        /// <param name="address">The updated address.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> UpdateAddress(Address address)
        {
            var updateResult = await this.addressService.UpdateAsync(this.userContext, [address], CancellationToken.None);

            if (updateResult.IsError)
            {
                return this.HandleErrors("Failed to update address.", address.Id, updateResult.Errors);
            }

            this.Addresses.Edit(innerList => innerList.Replace(innerList.Single(existing => existing.Id == address.Id), address));
            this.notificationService.AddNotification("Address updated successfully.", "Address Updated", NotificationType.Success);
            return Result.Success;
        }

        /// <summary>
        /// Sets the specified address as the primary address of the user account asynchronously.
        /// </summary>
        /// <param name="addressId">The identifier of the address to mark as primary.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> SetPrimaryAddress(Guid addressId)
        {
            var primaryResult = await this.ApplyPrimaryAddress(addressId, true);

            if (primaryResult.IsError)
            {
                return primaryResult;
            }

            this.notificationService.AddNotification("Primary address updated.", "Primary Address Updated", NotificationType.Success);
            return Result.Success;
        }

        /// <summary>
        /// Deletes an address of the user account asynchronously, clearing the primary address first when needed.
        /// </summary>
        /// <param name="addressId">The identifier of the address to delete.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> DeleteAddress(Guid addressId)
        {
            var wasPrimary = this.PrimaryAddressId == addressId;
            var clearResult = await this.ApplyPrimaryAddress(addressId, false);

            if (clearResult.IsError)
            {
                return clearResult;
            }

            var deleteResult = await this.addressService.DeleteAsync(this.userContext, [addressId], CancellationToken.None);

            if (deleteResult.IsError)
            {
                if (wasPrimary)
                {
                    await this.ApplyPrimaryAddress(addressId, true);
                }

                return this.HandleErrors("Failed to delete address.", addressId, deleteResult.Errors);
            }

            this.Addresses.Edit(innerList => innerList.Remove(innerList.Single(address => address.Id == addressId)));
            this.notificationService.AddNotification("Address deleted successfully.", "Address Deleted", NotificationType.Success);
            return Result.Success;
        }

        /// <summary>
        /// Updates the primary address of the user account asynchronously, only when the primary state of the address changed.
        /// </summary>
        /// <param name="addressId">The identifier of the address.</param>
        /// <param name="isPrimary">A value indicating whether the address should be the primary address of the account.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        private async Task<ErrorOr<Success>> ApplyPrimaryAddress(Guid addressId, bool isPrimary)
        {
            var isCurrentlyPrimary = this.PrimaryAddressId == addressId;

            if (isPrimary == isCurrentlyPrimary)
            {
                return Result.Success;
            }

            Guid? primaryAddressId = isPrimary ? addressId : null;

            if (this.OnPrimaryAddressChanging != null)
            {
                var primaryResult = await this.OnPrimaryAddressChanging(primaryAddressId);

                if (primaryResult.IsError)
                {
                    return primaryResult;
                }
            }

            this.PrimaryAddressId = primaryAddressId;
            return Result.Success;
        }

        /// <summary>
        /// Logs the specified errors and notifies the user that the operation failed.
        /// </summary>
        /// <param name="errorMessage">The message describing the failed operation.</param>
        /// <param name="addressId">The identifier of the address involved in the failed operation.</param>
        /// <param name="errors">The errors returned by the failed operation.</param>
        /// <returns>The specified <paramref name="errors" />.</returns>
        private List<Error> HandleErrors(string errorMessage, Guid addressId, List<Error> errors)
        {
            this.logger.LogError("{ErrorMessage} {AddressId} Errors: {Errors}", errorMessage, addressId.SanitizeForLog(), errors.ToJoinedDescriptions());
            this.notificationService.AddNotification(errorMessage, "Error", NotificationType.Error);
            return errors;
        }
    }
}
