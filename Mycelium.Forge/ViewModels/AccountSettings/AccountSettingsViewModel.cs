namespace Mycelium.Forge.ViewModels.AccountSettings
{
    using DynamicData;

    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Models.DialogResults;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides view model state and operations for the user account settings and profile management page.
    /// </summary>
    public class AccountSettingsViewModel : DisposableViewModel, IAccountSettingsViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IAccountService" /> domain service.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="IForgeContext" /> application context.
        /// </summary>
        private readonly IForgeContext forgeContext;

        /// <summary>
        /// The (injected) <see cref="ILogger{AccountSettingsViewModel}" /> logger.
        /// </summary>
        private readonly ILogger<AccountSettingsViewModel> logger;

        /// <summary>
        /// The (injected) <see cref="INotificationService" /> notification service.
        /// </summary>
        private readonly INotificationService notificationService;

        /// <summary>
        /// The (injected) <see cref="IOrganizationService" /> domain service.
        /// </summary>
        private readonly IOrganizationService organizationService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> domain service.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// The current authenticated user account identifier resolved on initialization.
        /// </summary>
        private Guid currentUserId;

        /// <summary>
        /// The authenticated user context resolved on initialization.
        /// </summary>
        private IUserContext userContext;

        /// <summary>
        /// Initializes a new instance of the <see cref="AccountSettingsViewModel" /> class.
        /// </summary>
        /// <param name="logger">The (injected) <see cref="ILogger{AccountSettingsViewModel}" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="accountService">The (injected) <see cref="IAccountService" />.</param>
        /// <param name="organizationService">The (injected) <see cref="IOrganizationService" />.</param>
        /// <param name="pendingRequestsManagerViewModel">The (injected) <see cref="IPendingRequestsManagerViewModel" />.</param>
        /// <param name="addressesManagerViewModel">The (injected) <see cref="IAddressesManagerViewModel" />.</param>
        /// <param name="forgeContext">The (injected) <see cref="IForgeContext" />.</param>
        /// <param name="notificationService">The (injected) <see cref="INotificationService" />.</param>
        public AccountSettingsViewModel(ILogger<AccountSettingsViewModel> logger, IUserService userService, IAccountService accountService, IOrganizationService organizationService, IPendingRequestsManagerViewModel pendingRequestsManagerViewModel, IAddressesManagerViewModel addressesManagerViewModel, IForgeContext forgeContext, INotificationService notificationService)
        {
            this.accountService = accountService;
            this.organizationService = organizationService;
            this.PendingRequestsManagerViewModel = pendingRequestsManagerViewModel;
            this.AddressesManagerViewModel = addressesManagerViewModel;
            this.forgeContext = forgeContext;
            this.notificationService = notificationService;
            this.userService = userService;
            this.logger = logger;

            this.PendingRequestsManagerViewModel.OnOrganizationAccepted = acceptedOrg => { this.Organizations.Edit(innerList => innerList.AddOrReplace(acceptedOrg)); };
            this.AddressesManagerViewModel.OnPrimaryAddressChanging = this.UpdatePrimaryAddress;
        }

        /// <summary>
        /// Gets or sets the user profile account DTO.
        /// </summary>
        public Account Profile { get; set; }

        /// <summary>
        /// Gets the collection of organizations associated with the user account.
        /// </summary>
        public SourceList<IOrganization> Organizations { get; } = new();

        /// <summary>
        /// Gets the view model for managing pending requests.
        /// </summary>
        public IPendingRequestsManagerViewModel PendingRequestsManagerViewModel { get; }

        /// <summary>
        /// Gets the view model for managing the addresses.
        /// </summary>
        public IAddressesManagerViewModel AddressesManagerViewModel { get; }

        /// <summary>
        /// Initializes the view model state and populates initial user profile and organization data asynchronously.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel()
        {
            this.userContext = await this.userService.GetUserContext();

            if (!this.userContext.AccountId.HasValue)
            {
                this.logger.LogWarning("User is not authenticated during account settings initialization");
                return;
            }

            this.currentUserId = this.userContext.AccountId.Value;
            var profile = await this.accountService.ReadOrNull(this.userContext, this.currentUserId) as Account;

            if (profile == null)
            {
                this.logger.LogWarning("Account profile for user {UserId} not found during settings initialization", this.currentUserId);
                return;
            }

            await this.AddressesManagerViewModel.InitializeViewModel(profile);

            this.Profile = profile;

            var organizationsResult = await this.organizationService.ReadByAccountMembershipAsync(this.userContext, this.currentUserId, CancellationToken.None);

            if (!organizationsResult.IsError)
            {
                this.Organizations.Edit(innerList =>
                {
                    innerList.Clear();
                    innerList.AddRange(organizationsResult.Value);
                });
            }

            await this.PendingRequestsManagerViewModel.InitializeViewModel();
        }

        /// <summary>
        /// Creates a new organization associated with the user account asynchronously.
        /// </summary>
        /// <param name="result">The organization creation data.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> CreateOrganization(CreateOrganizationResult result)
        {
            const string errorMessage = "Failed to create organization.";
            var cleanScope = result.Scope.CleanScope();

            var org = new Organization
            {
                Id = Guid.NewGuid(),
                Name = result.OrganizationName,
                ShortName = cleanScope,
                BillingEmail = result.BillingEmail,
                Administrator = [this.currentUserId],
                Member = [this.currentUserId],
                Owner = this.forgeContext.ForgeId,
                Email = result.BillingEmail
            };

            var createResult = await this.organizationService.CreateAsync(this.userContext, [org], CancellationToken.None);

            if (createResult.IsError)
            {
                this.logger.LogError(errorMessage + " {OrgName} Errors: {Errors}", org.Name.SanitizeForLog(), createResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Error", NotificationType.Error);
                return createResult.Errors;
            }

            this.Organizations.Add(org);
            this.notificationService.AddNotification($"Organization {org.Name} created successfully.", "Organization Created", NotificationType.Success);
            return Result.Success;
        }

        /// <summary>
        /// Updates the user profile account and synchronizes identity changes asynchronously.
        /// </summary>
        /// <param name="updatedAccount">The updated <see cref="Account" /> DTO.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating the success or failure of the operation.</returns>
        public Task<ErrorOr<Success>> UpdateProfile(Account updatedAccount)
        {
            return this.PersistProfile(updatedAccount, true);
        }

        /// <summary>
        /// Handles the deactivation of the current user account asynchronously.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public Task DeactivateAccount()
        {
            return Task.CompletedTask;
        }

        /// <summary>
        /// Handles the deletion of the current user account asynchronously.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public Task DeleteAccount()
        {
            return Task.CompletedTask;
        }

        /// <summary>
        /// Persists a new primary address identifier on the user profile asynchronously.
        /// </summary>
        /// <param name="primaryAddressId">The identifier of the new primary address, or <see langword="null" /> to clear it.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating the success or failure of the operation.</returns>
        private Task<ErrorOr<Success>> UpdatePrimaryAddress(Guid? primaryAddressId)
        {
            var updated = this.Profile.Clone();
            updated.PrimaryAddress = primaryAddressId;
            return this.PersistProfile(updated, false);
        }

        /// <summary>
        /// Persists the updated user profile account and synchronizes identity changes asynchronously.
        /// </summary>
        /// <param name="updatedAccount">The updated <see cref="Account" /> DTO.</param>
        /// <param name="notifyOnSuccess">A value indicating whether to emit a success notification.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating the success or failure of the operation.</returns>
        private async Task<ErrorOr<Success>> PersistProfile(Account updatedAccount, bool notifyOnSuccess)
        {
            const string errorMessage = "Failed to update profile.";

            if (string.Equals(updatedAccount.Email, this.Profile.Email, StringComparison.Ordinal))
            {
                // Remove this line once ticket #221 persists IsVerified in the domain model and Account.Clone() copies it.
                updatedAccount.IsVerified = this.Profile.IsVerified;
            }

            var updateResult = await this.accountService.UpdateAndSyncAsync(this.userContext, [updatedAccount], CancellationToken.None);

            if (updateResult.IsError)
            {
                this.logger.LogError(errorMessage + " {AccountId} Errors: {Errors}", updatedAccount.Id.SanitizeForLog(), updateResult.Errors.ToJoinedDescriptions());

                // Remove this Conflict branch once ticket #221 delegates email change to Keycloak (kc_action=UPDATE_EMAIL).
                var notificationMessage = updateResult.FirstError.Type == ErrorType.Conflict
                    ? "Unable to use this email address. Please enter a different email address."
                    : errorMessage;

                this.notificationService.AddNotification(notificationMessage, "Error", NotificationType.Error);
                return updateResult.Errors;
            }

            this.Profile = updatedAccount;

            // Forces the scoped UserService to reload its cached account so other components in the circuit see the updated profile.
            await this.userService.GetCurrentUser(true);

            if (notifyOnSuccess)
            {
                this.notificationService.AddNotification("Profile updated successfully.", "Profile Updated", NotificationType.Success);
            }

            return Result.Success;
        }
    }
}
