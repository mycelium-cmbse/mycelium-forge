    /// <summary>
    /// Provides view model state and operations for the user account settings and profile management page.
    /// </summary>
    public class AccountSettingsViewModel : IAccountSettingsViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IAccountService" /> domain service.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="IAddressService" /> domain service.
        /// </summary>
        private readonly IAddressService addressService;

        /// <summary>
        /// The (injected) <see cref="IForgeContext" /> application context.
        /// </summary>
        private readonly IForgeContext forgeContext;

        /// <summary>
        /// The (injected) <see cref="ILogger{AccountSettingsViewModel}" /> logger.
        /// </summary>
        private readonly ILogger<AccountSettingsViewModel> logger;

        /// <summary>
        /// The (injected) <see cref="INotificationService" /> notification service.
        /// </summary>
        private readonly INotificationService notificationService;

        /// <summary>
        /// The (injected) <see cref="IOrganizationService" /> domain service.
        /// </summary>
        private readonly IOrganizationService organizationService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> domain service.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// The current authenticated user account identifier resolved on initialization.
        /// </summary>
        private Guid currentUserId;

        /// <summary>
        /// The authenticated user context resolved on initialization.
        /// </summary>
        private IUserContext userContext;

        /// <summary>
        /// Initializes a new instance of the <see cref="AccountSettingsViewModel" /> class.
        /// </summary>
        /// <param name="logger">The (injected) <see cref="ILogger{AccountSettingsViewModel}" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="accountService">The (injected) <see cref="IAccountService" />.</param>
        /// <param name="addressService">The (injected) <see cref="IAddressService" />.</param>
        /// <param name="organizationService">The (injected) <see cref="IOrganizationService" />.</param>
        /// <param name="forgeContext">The (injected) <see cref="IForgeContext" />.</param>
        /// <param name="notificationService">The (injected) <see cref="INotificationService" />.</param>
        public AccountSettingsViewModel(ILogger<AccountSettingsViewModel> logger, IUserService userService, IAccountService accountService, IAddressService addressService,
            IOrganizationService organizationService, IForgeContext forgeContext, INotificationService notificationService)
        {
            this.accountService = accountService;
            this.addressService = addressService;
            this.organizationService = organizationService;
            this.forgeContext = forgeContext;
            this.notificationService = notificationService;
            this.userService = userService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets or sets the user profile account DTO.
        /// </summary>
        public IAccount Profile { get; set; }

        /// <summary>
        /// Gets or sets the collection of organizations associated with the user account.
        /// </summary>
        public IReadOnlyList<IOrganization> Organizations { get; set; } = [];

        /// <summary>
        /// Gets or sets the primary address location string.
        /// </summary>
        public string Location { get; set; } = string.Empty;

        /// <summary>
        /// Initializes the view model state and populates initial user profile and organization data asynchronously.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel()
        {
            this.userContext = await this.userService.GetUserContext();

            if (!this.userContext.AccountId.HasValue)
            {
                this.logger.LogWarning("User is not authenticated during account settings initialization");
                return;
            }

            this.currentUserId = this.userContext.AccountId.Value;
            this.Profile = await this.accountService.ReadOrNull(this.userContext, this.currentUserId);

            if (this.Profile == null)
            {
                this.logger.LogWarning("Account profile for user {UserId} not found during settings initialization", this.currentUserId);
                return;
            }

            if (this.Profile.PrimaryAddress.HasValue)
            {
                var address = await this.addressService.ReadOrNull(this.userContext, this.Profile.PrimaryAddress.Value);
                this.Location = address != null ? address.Locality : "-";
            }

            var organizationsResult = await this.organizationService.ReadAsync(this.userContext, CancellationToken.None);

            if (!organizationsResult.IsError)
            {
                this.Organizations = [.. organizationsResult.Value.Where(org => org.Member.Contains(this.currentUserId) || org.Administrator.Contains(this.currentUserId))];
            }
        }

        /// <summary>
        /// Creates a new organization associated with the user account asynchronously.
        /// </summary>
        /// <param name="result">The organization creation data.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> CreateOrganization(CreateOrganizationResult result)
        {
            const string errorMessage = "Failed to create organization.";
            var cleanScope = result.Scope.CleanScope();

            var org = new Organization
            {
                Name = result.OrganizationName,
                ShortName = cleanScope,
                BillingEmail = result.BillingEmail,
                Administrator = [this.currentUserId],
                Member = [this.currentUserId],
                Owner = this.forgeContext.ForgeId,
                CreatedAt = DateTime.Now,
                ModifiedAt = DateTime.Now,
                Email = result.BillingEmail
            };

            var createResult = await this.organizationService.CreateAsync(this.userContext, [org], CancellationToken.None);

            if (createResult.IsError)
            {
                this.logger.LogError(errorMessage + " {OrgName}", org.Name);
                this.notificationService.AddNotification(errorMessage, "Error", NotificationType.Error);
                return createResult.Errors;
            }

            this.Organizations = [.. this.Organizations, org];
            this.notificationService.AddNotification($"Organization {org.Name} created successfully.", "Organization Created", NotificationType.Success);
            return Result.Success;
        }

