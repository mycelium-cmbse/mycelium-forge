namespace Mycelium.Forge.ViewModels.AccountSettings
{
    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Services;
    using Mycelium.Forge.ViewModels.Rows;

    /// <summary>
    /// Provides view model state and operations for managing pending organization and package invitations for the user
    /// account.
    /// </summary>
    public class PendingRequestsManagerViewModel : IPendingRequestsManagerViewModel
    {
        /// <summary>
        /// The (injected) <see cref="ILogger{PendingRequestsManagerViewModel}" /> logger.
        /// </summary>
        private readonly ILogger<PendingRequestsManagerViewModel> logger;

        /// <summary>
        /// The (injected) <see cref="INotificationService" /> notification service.
        /// </summary>
        private readonly INotificationService notificationService;

        /// <summary>
        /// The (injected) <see cref="IOrganizationInvitationService" /> domain service.
        /// </summary>
        private readonly IOrganizationInvitationService organizationInvitationService;

        /// <summary>
        /// The (injected) <see cref="IOrganizationService" /> domain service.
        /// </summary>
        private readonly IOrganizationService organizationService;

        /// <summary>
        /// The (injected) <see cref="IPackageInvitationService" /> domain service.
        /// </summary>
        private readonly IPackageInvitationService packageInvitationService;

        /// <summary>
        /// The (injected) <see cref="IPackageService" /> domain service.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The (injected) <see cref="IScopeService" /> domain service.
        /// </summary>
        private readonly IScopeService scopeService;

        /// <summary>
        /// The (injected) <see cref="IUserService" /> domain service.
        /// </summary>
        private readonly IUserService userService;

        /// <summary>
        /// The current authenticated user account identifier.
        /// </summary>
        private Guid currentUserId;

        /// <summary>
        /// The authenticated user context.
        /// </summary>
        private IUserContext userContext;

        /// <summary>
        /// Initializes a new instance of the <see cref="PendingRequestsManagerViewModel" /> class.
        /// </summary>
        /// <param name="logger">The (injected) <see cref="ILogger{PendingRequestsManagerViewModel}" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="organizationService">The (injected) <see cref="IOrganizationService" />.</param>
        /// <param name="organizationInvitationService">The (injected) <see cref="IOrganizationInvitationService" />.</param>
        /// <param name="packageService">The (injected) <see cref="IPackageService" />.</param>
        /// <param name="packageInvitationService">The (injected) <see cref="IPackageInvitationService" />.</param>
        /// <param name="scopeService">The (injected) <see cref="IScopeService" />.</param>
        /// <param name="notificationService">The (injected) <see cref="INotificationService" />.</param>
        public PendingRequestsManagerViewModel(ILogger<PendingRequestsManagerViewModel> logger, IUserService userService, IOrganizationService organizationService, IOrganizationInvitationService organizationInvitationService, IPackageService packageService, IPackageInvitationService packageInvitationService, IScopeService scopeService, INotificationService notificationService)
        {
            this.userService = userService;
            this.organizationService = organizationService;
            this.organizationInvitationService = organizationInvitationService;
            this.packageService = packageService;
            this.packageInvitationService = packageInvitationService;
            this.scopeService = scopeService;
            this.notificationService = notificationService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets or sets the unified collection of pending organization and package invitations for the user account.
        /// </summary>
        public List<IInvitationRowViewModel> PendingInvitations { get; set; } = [];

        /// <summary>
        /// Gets or sets the action invoked when an organization invitation has been accepted.
        /// </summary>
        public Action<IOrganization> OnOrganizationAccepted { get; set; }

        /// <summary>
        /// Initializes the view model state asynchronously.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task InitializeViewModel()
        {
            this.userContext = await this.userService.GetUserContext();

            if (!this.userContext.AccountId.HasValue)
            {
                this.logger.LogWarning("User is not authenticated during pending requests manager initialization");
                return;
            }

            this.currentUserId = this.userContext.AccountId.Value;
            await this.LoadInvitations();
        }

        /// <summary>
        /// Accepts the specified pending organization or package invitation asynchronously.
        /// </summary>
        /// <param name="invitation">The pending invitation to accept.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> AcceptInvitation(IInvitation invitation, CancellationToken token = default)
        {
            switch (invitation)
            {
                case IOrganizationInvitation organizationInvitation:
                {
                    var acceptResult = await this.organizationInvitationService.AcceptInvitationAsync(this.userContext, organizationInvitation, token);

                    if (acceptResult.IsError)
                    {
                        this.logger.LogError("Failed to accept invitation for organization {OrganizationId}. Errors: {Errors}", organizationInvitation.Organization, acceptResult.Errors.ToJoinedDescriptions());
                        this.notificationService.AddNotification("Failed to accept invitation.", "Error", NotificationType.Error);
                        return acceptResult.Errors;
                    }

                    this.OnOrganizationAccepted?.Invoke(acceptResult.Value);
                    break;
                }

                case IPackageInvitation packageInvitation:
                {
                    var acceptResult = await this.packageInvitationService.AcceptInvitationAsync(this.userContext, packageInvitation, token);

                    if (acceptResult.IsError)
                    {
                        this.logger.LogError("Failed to accept invitation for package {PackageId}. Errors: {Errors}", packageInvitation.Package, acceptResult.Errors.ToJoinedDescriptions());
                        this.notificationService.AddNotification("Failed to accept invitation.", "Error", NotificationType.Error);
                        return acceptResult.Errors;
                    }

                    break;
                }

                default:
                {
                    return Error.Unexpected(description: "Unsupported invitation type.");
                }
            }

            this.PendingInvitations.RemoveAll(row => row.Invitation.Id == invitation.Id);
            this.notificationService.AddNotification("Invitation accepted.", type: NotificationType.Success);

            return Result.Success;
        }

        /// <summary>
        /// Rejects the specified pending organization or package invitation asynchronously.
        /// </summary>
        /// <param name="invitation">The pending invitation to reject.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> RejectInvitation(IInvitation invitation, CancellationToken token = default)
        {
            ErrorOr<Updated> updateResult;

            switch (invitation)
            {
                case OrganizationInvitation organizationInvitation:
                {
                    var rejectedInvitation = organizationInvitation.Clone();
                    rejectedInvitation.Status = InvitationStatusKind.REJECTED;
                    updateResult = await this.organizationInvitationService.UpdateAsync(this.userContext, [rejectedInvitation], token);
                    break;
                }

                case PackageInvitation packageInvitation:
                {
                    var rejectedInvitation = packageInvitation.Clone();
                    rejectedInvitation.Status = InvitationStatusKind.REJECTED;
                    updateResult = await this.packageInvitationService.UpdateAsync(this.userContext, [rejectedInvitation], token);
                    break;
                }

                default:
                {
                    return Error.Unexpected(description: "Unsupported invitation type.");
                }
            }

            if (updateResult.IsError)
            {
                this.logger.LogError("Failed to reject invitation {InvitationId}. Errors: {Errors}", invitation.Id, updateResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification("Failed to reject invitation.", "Error", NotificationType.Error);
                return updateResult.Errors;
            }

            this.PendingInvitations.RemoveAll(row => row.Invitation.Id == invitation.Id);
            this.notificationService.AddNotification("Invitation rejected.", type: NotificationType.Success);

            return Result.Success;
        }

        /// <summary>
        /// Loads pending organization and package invitations for the user account asynchronously.
        /// </summary>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        private async Task LoadInvitations(CancellationToken token = default)
        {
            var organizationInvitationsTask = this.organizationInvitationService.ReadByTargetAsync(this.userContext, this.currentUserId, token);
            var packageInvitationsTask = this.packageInvitationService.ReadByTargetAsync(this.userContext, this.currentUserId, token);

            await Task.WhenAll(organizationInvitationsTask, packageInvitationsTask);

            List<IInvitationRowViewModel> rows = [];

            var organizationInvitationsResult = organizationInvitationsTask.Result;

            if (organizationInvitationsResult.IsError)
            {
                this.logger.LogError("Failed to read pending organization invitations for user {UserId}. Errors: {Errors}", this.currentUserId, organizationInvitationsResult.Errors.ToJoinedDescriptions());
            }
            else
            {
                var pendingOrganizations = organizationInvitationsResult.Value.Where(invitation => invitation.Status == InvitationStatusKind.PENDING && invitation.ExperiesAt > DateTime.UtcNow).ToList();
                var organizationsIds = pendingOrganizations.Select(invitation => invitation.Organization).ToArray();
                var organizationsResult = await this.organizationService.ReadOrEmpty(this.userContext, organizationsIds, token: token);

                rows.AddRange(OrganizationInvitationRowViewModel.GenerateRows(pendingOrganizations, organizationsResult));
            }

            var packageInvitationsResult = packageInvitationsTask.Result;

            if (packageInvitationsResult.IsError)
            {
                this.logger.LogError("Failed to read pending package invitations for user {UserId}. Errors: {Errors}", this.currentUserId, packageInvitationsResult.Errors.ToJoinedDescriptions());
            }
            else
            {
                var pendingPackages = packageInvitationsResult.Value.Where(invitation => invitation.Status == InvitationStatusKind.PENDING && invitation.ExperiesAt > DateTime.UtcNow).ToList();
                var packageIds = pendingPackages.Select(invitation => invitation.Package).Distinct().ToArray();

                var packagesResult = await this.packageService.ReadOrEmpty(this.userContext, packageIds, token: token);
                var scopeIds = packagesResult.Select(package => package.Owner).Distinct().ToArray();
                var scopesResult = await this.scopeService.ReadOrEmpty(this.userContext, scopeIds, token: token);

                rows.AddRange(PackageInvitationRowViewModel.GenerateRows(pendingPackages, [.. packagesResult, .. scopesResult]));
            }

            this.PendingInvitations = rows;
        }
    }
}
