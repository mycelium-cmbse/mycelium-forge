namespace Mycelium.Forge.ViewModels.AccountDetails
{
    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides view model state and operations for the Mycelium Forge account and publisher profile page.
    /// </summary>
    public class AccountDetailsViewModel : ScopeDetailsViewModelBase, IAccountDetailsViewModel
    {
        /// <summary>
        /// The (injected) <see cref="IAccountService" /> used to retrieve account profile data.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="ILogger{AccountDetailsViewModel}" /> used for logging operations.
        /// </summary>
        private readonly ILogger<AccountDetailsViewModel> logger;

        /// <summary>
        /// Initializes a new instance of the <see cref="AccountDetailsViewModel" /> class.
        /// </summary>
        /// <param name="accountService">The (injected) <see cref="IAccountService" />.</param>
        /// <param name="packageService">The (injected) <see cref="IPackageService" />.</param>
        /// <param name="packageVersionService">The (injected) <see cref="IPackageVersionService" />.</param>
        /// <param name="packageTypeService">The (injected) <see cref="IPackageTypeService" />.</param>
        /// <param name="userService">The (injected) <see cref="IUserService" />.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{AccountDetailsViewModel}" />.</param>
        public AccountDetailsViewModel(IAccountService accountService, IPackageService packageService, IPackageVersionService packageVersionService, IPackageTypeService packageTypeService, IUserService userService, ILogger<AccountDetailsViewModel> logger) : base(packageService, packageVersionService, packageTypeService, userService)
        {
            this.accountService = accountService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets or sets the account profile details.
        /// </summary>
        public IAccount Account { get; set; }

        /// <summary>
        /// Gets or sets a value indicating whether the current authenticated user owns this account profile.
        /// </summary>
        public bool IsCurrentUser { get; set; }

        /// <summary>
        /// Initializes the account view model state for the specified account short name asynchronously.
        /// </summary>
        /// <param name="shortName">The short name of the account.</param>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeViewModel(string shortName, CancellationToken cancellationToken = default)
        {
            this.Account = null;
            this.IsCurrentUser = false;
            this.Packages = [];

            try
            {
                var userContext = await this.UserService.GetUserContext();

                var accountResult = await this.accountService.ReadByShortNameAsync(userContext, cancellationToken, [shortName.ToLowerInvariant()]);

                if (accountResult.IsError || accountResult.Value.Count == 0)
                {
                    var errors = accountResult.IsError ? accountResult.Errors.ToJoinedDescriptions() : "Not found";
                    this.logger.LogWarning("Account with short name {ShortName} not found during details initialization: {Errors}", shortName.SanitizeForLog(), errors);
                    return;
                }

                this.Account = accountResult.Value[0];
                this.IsCurrentUser = userContext.AccountId.HasValue && userContext.AccountId.Value == this.Account.Id;

                await this.LoadOwnedPackagesAsync(userContext, this.Account, cancellationToken);
            }
            catch (Exception ex)
            {
                this.logger.LogError(ex, "An error occurred while initializing the AccountDetailsViewModel");
            }
        }
    }
}
