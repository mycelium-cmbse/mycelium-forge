namespace Mycelium.Forge.ViewModels.Invitations
{
    using System.Collections.Immutable;

    using DynamicData;

    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Services;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Provides shared view model state and operations for managing pending invitations and resolving target accounts.
    /// </summary>
    /// <typeparam name="TInvitation">The invitation domain interface type.</typeparam>
    public class InvitationManagerViewModel<TInvitation> : DisposableViewModel, IInvitationManagerViewModel<TInvitation> where TInvitation : class, IInvitation
    {
        /// <summary>
        /// The default number of days before a sent or resent invitation expires.
        /// </summary>
        private const int InvitationExpirationDays = 7;

        /// <summary>
        /// The (injected) <see cref="IAccountService" /> used to resolve target account profiles.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The (injected) <see cref="IService{TInvitation}" /> used to query and persist invitation state changes.
        /// </summary>
        private readonly IService<TInvitation> invitationService;

        /// <summary>
        /// The (injected) <see cref="ILogger{TCategoryName}" /> used for diagnostic logging.
        /// </summary>
        private readonly ILogger<InvitationManagerViewModel<TInvitation>> logger;

        /// <summary>
        /// The (injected) <see cref="INotificationService" /> used to emit user notifications.
        /// </summary>
        private readonly INotificationService notificationService;

        /// <summary>
        /// The contextual user information resolved on initialization.
        /// </summary>
        private IUserContext currentUserContext;

        /// <summary>
        /// The collection of target accounts referenced by the loaded pending invitations.
        /// </summary>
        private List<IAccount> invitedAccounts = [];

        /// <summary>
        /// Initializes a new instance of the <see cref="InvitationManagerViewModel{TInvitation}" /> class.
        /// </summary>
        /// <param name="invitationService">The (injected) <see cref="IService{TInvitation}" /> domain service.</param>
        /// <param name="accountService">The (injected) <see cref="IAccountService" /> domain service.</param>
        /// <param name="notificationService">The (injected) <see cref="INotificationService" /> notification service.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{TCategoryName}" /> logger.</param>
        public InvitationManagerViewModel(IService<TInvitation> invitationService, IAccountService accountService, INotificationService notificationService, ILogger<InvitationManagerViewModel<TInvitation>> logger)
        {
            this.invitationService = invitationService;
            this.accountService = accountService;
            this.notificationService = notificationService;
            this.logger = logger;

            this.Disposables.Add(this.PendingInvitations);
        }

        /// <summary>
        /// Gets the reactive source list of pending invitations.
        /// </summary>
        public SourceList<TInvitation> PendingInvitations { get; } = new();

        /// <summary>
        /// Initializes the invitation manager state for the specified owning entity asynchronously.
        /// </summary>
        /// <param name="userContext">The contextual user information and assigned roles.</param>
        /// <param name="ownerEntityId">The unique identifier of the owning organization or package.</param>
        /// <param name="canManage">A value indicating whether the current user is allowed to manage invitations.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task InitializeViewModel(IUserContext userContext, Guid ownerEntityId, bool canManage = true, CancellationToken token = default)
        {
            this.currentUserContext = userContext;

            if (!canManage || ownerEntityId == Guid.Empty)
            {
                this.PendingInvitations.Clear();
                this.invitedAccounts = [];
                return;
            }

            var invitationsResult = await this.ReadByOwnerEntityAsync(userContext, ownerEntityId, token);

            if (invitationsResult.IsError)
            {
                this.PendingInvitations.Clear();
                this.invitedAccounts = [];
                return;
            }

            List<TInvitation> pending = [.. invitationsResult.Value.Where(invitation => invitation.Status == InvitationStatusKind.PENDING && MatchesOwner(invitation, ownerEntityId))];

            this.PendingInvitations.Edit(innerList =>
            {
                innerList.Clear();
                innerList.AddRange(pending);
            });

            var pendingTargetIds = pending.Select(GetTargetId).Where(id => id != Guid.Empty).Distinct().ToList();
            
            // Deduplicate until Account.OwnedPackageInvitation is updated to UML multiplicity 0..* (#138) and AccountDao.ReadAsync stops returning duplicate rows.
            this.invitedAccounts = [.. (await this.accountService.ReadOrEmpty(userContext, pendingTargetIds, true, token)).DistinctBy(account => account.Id)];
        }

        /// <summary>
        /// Sets default status and expiration details on the specified invitation and persists it asynchronously.
        /// </summary>
        /// <param name="invitation">The invitation entity to send.</param>
        /// <param name="target">The invited target account.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A task indicating the success or failure of the operation.</returns>
        public async Task<ErrorOr<Success>> SendInvitation(TInvitation invitation, IAccount target, CancellationToken token = default)
        {
            invitation.Status = InvitationStatusKind.PENDING;
            invitation.ExperiesAt = DateTime.UtcNow.AddDays(InvitationExpirationDays);

            var createResult = await this.invitationService.CreateAsync(this.currentUserContext, [invitation], token);

            if (createResult.IsError)
            {
                const string errorMessage = "Failed to send invitation.";

                this.logger.LogError(errorMessage + " Target: {TargetId} Errors: {Errors}", target.Id, createResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Invitation Error", NotificationType.Error);
                return createResult.Errors;
            }

            this.PendingInvitations.Add(invitation);
            this.invitedAccounts.AddOrReplace(target);

            this.notificationService.AddNotification($"Invitation sent to {target.Name}.", "Invitation Sent", NotificationType.Success);
            return Result.Success;
        }

        /// <summary>
        /// Resends the specified pending invitation with a refreshed expiration timestamp asynchronously.
        /// </summary>
        /// <param name="invitation">The pending invitation to resend.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task ResendInvitation(TInvitation invitation, CancellationToken token = default)
        {
            var invitationClone = ((ICloneable<TInvitation>)invitation).Clone();
            invitationClone.ExperiesAt = DateTime.UtcNow.AddDays(InvitationExpirationDays);

            var updateResult = await this.invitationService.UpdateAsync(this.currentUserContext, [invitationClone], token);

            if (updateResult.IsError)
            {
                const string errorMessage = "Failed to resend invitation.";

                this.logger.LogError(errorMessage + " Invitation: {InvitationId} Errors: {Errors}", invitation.Id, updateResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Invitation Error", NotificationType.Error);
                return;
            }

            this.PendingInvitations.Replace(invitation, invitationClone);
            this.notificationService.AddNotification("Invitation resent successfully.", "Invitation Resent", NotificationType.Success);
        }

        /// <summary>
        /// Revokes the specified pending invitation asynchronously.
        /// </summary>
        /// <param name="invitation">The pending invitation to revoke.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task RevokeInvitation(TInvitation invitation, CancellationToken token = default)
        {
            var invitationClone = ((ICloneable<TInvitation>)invitation).Clone();
            invitationClone.Status = InvitationStatusKind.REVOKED;

            var updateResult = await this.invitationService.UpdateAsync(this.currentUserContext, [invitationClone], token);

            if (updateResult.IsError)
            {
                const string errorMessage = "Failed to revoke invitation.";

                this.logger.LogError(errorMessage + " Invitation: {InvitationId} Errors: {Errors}", invitation.Id, updateResult.Errors.ToJoinedDescriptions());
                this.notificationService.AddNotification(errorMessage, "Invitation Error", NotificationType.Error);
                return;
            }

            this.PendingInvitations.Remove(invitation);
            this.notificationService.AddNotification("Invitation revoked successfully.", "Invitation Revoked", NotificationType.Success);
        }

        /// <summary>
        /// Resolves the display short name for the target account of the specified invitation.
        /// </summary>
        /// <param name="invitation">The invitation whose target account short name is resolved.</param>
        /// <returns>The short name of the target account, or <c>Unknown</c> when unavailable.</returns>
        public string GetTargetName(TInvitation invitation)
        {
            var targetId = GetTargetId(invitation);
            var target = this.invitedAccounts.FirstOrDefault(account => account.Id == targetId);
            return target?.ShortName ?? "Unknown";
        }

        /// <summary>
        /// Determines whether the specified invitation belongs to the given owning entity identifier.
        /// </summary>
        /// <param name="invitation">The invitation instance to evaluate.</param>
        /// <param name="ownerEntityId">The owning organization or package identifier.</param>
        /// <returns><c>true</c> if the invitation matches the owning entity; otherwise, <c>false</c>.</returns>
        private static bool MatchesOwner(TInvitation invitation, Guid ownerEntityId)
        {
            return invitation switch
            {
                IOrganizationInvitation organizationInvitation => organizationInvitation.Organization == ownerEntityId,
                IPackageInvitation packageInvitation => packageInvitation.Package == ownerEntityId,
                _ => false
            };
        }

        /// <summary>
        /// Extracts the target account identifier from the specified invitation.
        /// </summary>
        /// <param name="invitation">The invitation instance.</param>
        /// <returns>The target account identifier, or <see cref="Guid.Empty" /> if unsupported.</returns>
        private static Guid GetTargetId(TInvitation invitation)
        {
            return invitation switch
            {
                IOrganizationInvitation organizationInvitation => organizationInvitation.Target,
                IPackageInvitation packageInvitation => packageInvitation.Target,
                _ => Guid.Empty
            };
        }

        /// <summary>
        /// Reads invitations scoped to the specified owning entity when supported by the underlying service.
        /// </summary>
        /// <param name="context">The contextual user information.</param>
        /// <param name="entityId">The owning organization or package identifier.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{TValue}" /> containing the retrieved invitations or an error.</returns>
        private async Task<ErrorOr<ImmutableList<TInvitation>>> ReadByOwnerEntityAsync(IUserContext context, Guid entityId, CancellationToken token)
        {
            switch (this.invitationService)
            {
                case IOrganizationInvitationService organizationInvitationService:
                {
                    var result = await organizationInvitationService.ReadByOrganizationAsync(context, entityId, token);
                    return result.IsError ? result.Errors : result.Value.Cast<TInvitation>().ToImmutableList();
                }

                case IPackageInvitationService packageInvitationService:
                {
                    var result = await packageInvitationService.ReadByPackageAsync(context, entityId, token);
                    return result.IsError ? result.Errors : result.Value.Cast<TInvitation>().ToImmutableList();
                }

                default:
                    return await this.invitationService.ReadAsync(context, token);
            }
        }
    }
}
