namespace Mycelium.Forge.Components.Pages.OrganizationSettings.Dialogs
{
    using BlazorBlueprint.Components;

    using Microsoft.AspNetCore.Components;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGenDtoValidator;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Represents a modal dialog for transferring organization ownership to another account.
    /// </summary>
    public partial class TransferOrganizationOwnershipDialog : ComponentBase
    {
        /// <summary>
        /// Gets or sets the (injected) <see cref="IAccountService" /> used to lookup the recipient account.
        /// </summary>
        [Inject]
        public IAccountService AccountService { get; set; }

        /// <summary>
        /// Gets or sets the (injected) <see cref="IUserService" /> used to retrieve the current user context.
        /// </summary>
        [Inject]
        public IUserService UserService { get; set; }

        /// <summary>
        /// Gets or sets the cascading dialog reference used to control and close the dialog.
        /// </summary>
        [CascadingParameter]
        public IDialogReference DialogReference { get; set; }

        /// <summary>
        /// Gets or sets the organization name being transferred.
        /// </summary>
        [Parameter]
        public string OrganizationName { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the event callback invoked with the recipient account when ownership transfer is confirmed.
        /// </summary>
        [Parameter]
        public EventCallback<IAccount> OnResult { get; set; }

        /// <summary>
        /// Gets or sets the event callback invoked when the dialog is cancelled.
        /// </summary>
        [Parameter]
        public EventCallback OnCancel { get; set; }

        /// <summary>
        /// Gets or sets the target recipient username or account identifier.
        /// </summary>
        public string TargetAccount { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the confirmation organization name input typed by the user.
        /// </summary>
        public string ConfirmationOrganizationName { get; set; } = string.Empty;

        /// <summary>
        /// Gets the validation manager used to validate dialog inputs.
        /// </summary>
        public ValidationManager ValidationManager { get; } = new();

        /// <summary>
        /// Handles changes to the target account input and clears previous validation errors.
        /// </summary>
        /// <param name="value">The updated target account input.</param>
        public void OnTargetAccountChanged(string value)
        {
            this.TargetAccount = value ?? string.Empty;
            this.ValidationManager.ClearError(nameof(this.TargetAccount));
        }

        /// <summary>
        /// Handles changes to the confirmation organization name input and clears previous validation errors.
        /// </summary>
        /// <param name="value">The updated confirmation organization name input.</param>
        public void OnConfirmationNameChanged(string value)
        {
            this.ConfirmationOrganizationName = value ?? string.Empty;
            this.ValidationManager.ClearError(nameof(this.ConfirmationOrganizationName));
        }

        /// <summary>
        /// Handles the cancel action, cancelling the dialog and invoking the cancel callback.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task OnCancelClicked()
        {
            await this.OnCancel.InvokeAsync();

            if (this.DialogReference != null)
            {
                await this.DialogReference.CancelAsync();
            }
        }

        /// <summary>
        /// Handles the transfer confirmation action, verifying recipient and confirmation before closing the dialog and invoking
        /// the result callback.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task OnTransferClicked()
        {
            var isTargetValid = !string.IsNullOrWhiteSpace(this.TargetAccount) && AccountValidator.ShortNameFormatRegex().IsMatch(this.TargetAccount);

            var isValid = this.ValidationManager
                .Check(nameof(this.TargetAccount), isTargetValid, "Target account must start and end with an alphanumeric character and contain only lowercase alphanumeric characters and hyphens.")
                .Check(nameof(this.ConfirmationOrganizationName), string.Equals(this.ConfirmationOrganizationName, this.OrganizationName, StringComparison.Ordinal), "Confirmation name does not match.")
                .IsValid;

            if (!isValid)
            {
                return;
            }

            var userContext = await this.UserService.GetUserContext();
            var accountResult = await this.AccountService.ReadByShortNameAsync(userContext, this.TargetAccount, CancellationToken.None);

            if (accountResult.IsError)
            {
                this.ValidationManager.Check(nameof(this.TargetAccount), false, $"Account '{this.TargetAccount}' not found.");
                return;
            }

            if (userContext.AccountId.HasValue && accountResult.Value.Id == userContext.AccountId.Value)
            {
                this.ValidationManager.Check(nameof(this.TargetAccount), false, "You cannot transfer ownership to yourself.");
                return;
            }

            await this.OnResult.InvokeAsync(accountResult.Value);

            if (this.DialogReference != null)
            {
                await this.DialogReference.CloseAsync(DialogResult.Ok());
            }
        }
    }
}
