namespace Mycelium.Forge.Components.Pages.OrganizationSettings.Dialogs
{
    using BlazorBlueprint.Components;

    using Microsoft.AspNetCore.Components;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGenDtoValidator;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Models.DialogResults;
    using Mycelium.Forge.Services;

    /// <summary>
    /// Represents a modal dialog for inviting a new member or administrator to an organization.
    /// </summary>
    public partial class InviteMemberDialog : ComponentBase
    {
        /// <summary>
        /// Gets or sets the (injected) <see cref="IAccountService" /> used to lookup the invited account.
        /// </summary>
        [Inject]
        public IAccountService AccountService { get; set; }

        /// <summary>
        /// Gets or sets the (injected) <see cref="IUserService" /> used to retrieve the current user context.
        /// </summary>
        [Inject]
        public IUserService UserService { get; set; }

        /// <summary>
        /// Gets or sets the cascading dialog reference used to control and close the dialog.
        /// </summary>
        [CascadingParameter]
        public IDialogReference DialogReference { get; set; }

        /// <summary>
        /// Gets or sets the organization entity to which the member is being invited.
        /// </summary>
        [Parameter]
        public IOrganization Organization { get; set; }

        /// <summary>
        /// Gets or sets the list of existing pending invitations for the organization.
        /// </summary>
        [Parameter]
        public IReadOnlyList<OrganizationInvitation> PendingInvitations { get; set; } = [];

        /// <summary>
        /// Gets or sets the event callback invoked with the invitation result when confirmed.
        /// </summary>
        [Parameter]
        public EventCallback<InviteMemberResult> OnResult { get; set; }

        /// <summary>
        /// Gets or sets the event callback invoked when the dialog is cancelled.
        /// </summary>
        [Parameter]
        public EventCallback OnCancel { get; set; }

        /// <summary>
        /// Gets or sets the target account username being invited.
        /// </summary>
        public string TargetAccount { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the selected organization invitation role.
        /// </summary>
        public OrganizationInvitationKind SelectedRole { get; set; } = OrganizationInvitationKind.MEMBER;

        /// <summary>
        /// Gets the available invitation role options.
        /// </summary>
        public IReadOnlyList<OrganizationInvitationKind> RoleOptions { get; } = Enum.GetValues<OrganizationInvitationKind>();

        /// <summary>
        /// Gets the validation manager used to validate dialog inputs.
        /// </summary>
        public ValidationManager ValidationManager { get; } = new();

        /// <summary>
        /// Handles changes to the target account input and clears previous validation errors.
        /// </summary>
        /// <param name="value">The updated target account input.</param>
        public void OnTargetAccountChanged(string value)
        {
            this.TargetAccount = value ?? string.Empty;
            this.ValidationManager.ClearError(nameof(this.TargetAccount));
        }

        /// <summary>
        /// Handles changes to the selected invitation role.
        /// </summary>
        /// <param name="value">The newly selected invitation role.</param>
        public void OnRoleChanged(OrganizationInvitationKind value)
        {
            this.SelectedRole = value;
        }

        /// <summary>
        /// Handles the cancel action, cancelling the dialog and invoking the cancel callback.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task OnCancelClicked()
        {
            await this.OnCancel.InvokeAsync();

            if (this.DialogReference != null)
            {
                await this.DialogReference.CancelAsync();
            }
        }

        /// <summary>
        /// Handles the invitation confirmation action, validating recipient and pending invitations before closing.
        /// </summary>
        /// <returns>A <see cref="Task" /> representing the asynchronous operation.</returns>
        public async Task OnInviteClicked()
        {
            var isTargetValid = !string.IsNullOrWhiteSpace(this.TargetAccount) && AccountValidator.ShortNameFormatRegex().IsMatch(this.TargetAccount);

            var isValid = this.ValidationManager
                .Check(nameof(this.TargetAccount), isTargetValid, "Username must start and end with an alphanumeric character and contain only lowercase alphanumeric characters and hyphens.")
                .IsValid;

            if (!isValid)
            {
                return;
            }

            var userContext = await this.UserService.GetUserContext();
            var accountResult = await this.AccountService.ReadByShortNameAsync(userContext, CancellationToken.None, [this.TargetAccount]);

            if (accountResult.IsError || accountResult.Value.Count == 0)
            {
                this.ValidationManager.Check(nameof(this.TargetAccount), false, $"Account '{this.TargetAccount}' not found.");
                return;
            }

            var account = accountResult.Value[0];

            if (this.Organization.Member.Contains(account.Id) || this.Organization.Administrator.Contains(account.Id))
            {
                this.ValidationManager.Check(nameof(this.TargetAccount), false, $"Account '{this.TargetAccount}' is already a member of this organization.");
                return;
            }

            if (this.PendingInvitations.Any(i => i.Target == account.Id && i.Status == InvitationStatusKind.PENDING))
            {
                this.ValidationManager.Check(nameof(this.TargetAccount), false, $"Account '{this.TargetAccount}' already has a pending invitation.");
                return;
            }

            var result = new InviteMemberResult
            {
                TargetAccount = account,
                Role = this.SelectedRole
            };

            await this.OnResult.InvokeAsync(result);

            if (this.DialogReference != null)
            {
                await this.DialogReference.CloseAsync(DialogResult.Ok());
            }
        }
    }
}
