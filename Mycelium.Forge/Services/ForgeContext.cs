namespace Mycelium.Forge.Services
{
    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;

    /// <summary>
    /// Implements the application-level context for resolving and caching the single Forge registry instance identifier.
    /// </summary>
    public class ForgeContext : IForgeContext
    {
        /// <summary>
        /// The domain service for <see cref="IForge" /> entities.
        /// </summary>
        private readonly IForgeService forgeService;

        /// <summary>
        /// The logger for diagnostic messages.
        /// </summary>
        private readonly ILogger<ForgeContext> logger;

        /// <summary>
        /// A value indicating whether initialization has completed.
        /// </summary>
        private bool isInitialized;

        /// <summary>
        /// Initializes a new instance of the <see cref="ForgeContext" /> class.
        /// </summary>
        /// <param name="forgeService">The domain service for <see cref="IForge" /> entities.</param>
        /// <param name="logger">The logger for diagnostic messages.</param>
        public ForgeContext(IForgeService forgeService, ILogger<ForgeContext> logger)
        {
            ArgumentNullException.ThrowIfNull(forgeService);
            ArgumentNullException.ThrowIfNull(logger);

            this.forgeService = forgeService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets the unique identifier of the Forge instance.
        /// </summary>
        public Guid ForgeId { get; private set; }

        /// <summary>
        /// Initializes the Forge context by querying the Forge service once using super user permissions.
        /// </summary>
        /// <param name="cancellationToken">The cancellation token used to cancel the initialization.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeAsync(CancellationToken cancellationToken = default)
        {
            if (this.isInitialized)
            {
                return;
            }

            var superUser = new UserContext
            {
                AccountId = Guid.Empty,
                Username = "system",
                CurrentRoles = [RoleKind.InstallationAdministrator]
            };

            var result = await this.forgeService.ReadAsync(superUser, cancellationToken);

            if (result.IsError || result.Value.Count == 0)
            {
                this.logger.LogError("Failed to initialize Forge context: no Forge instance found.");
                throw new InvalidOperationException("Failed to initialize Forge context: no Forge instance found.");
            }

            this.ForgeId = result.Value[0].Id;
            this.isInitialized = true;

            if (this.logger.IsEnabled(LogLevel.Information))
            {
                this.logger.LogInformation("Forge context initialized with Forge ID: {ForgeId}", this.ForgeId);
            }
        }
    }
}
