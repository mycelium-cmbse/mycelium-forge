namespace Mycelium.Forge.Services
{
    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;

    /// <summary>
    /// Implements the application-level context for resolving and caching the single Forge registry instance identifier.
    /// </summary>
    public class ForgeContext : IForgeContext
    {
        /// <summary>
        /// The domain service for <see cref="IForge" /> entities.
        /// </summary>
        private readonly IForgeService forgeService;

        /// <summary>
        /// The logger for diagnostic messages.
        /// </summary>
        private readonly ILogger<ForgeContext> logger;

        /// <summary>
        /// The backing field for the unique identifier of the Forge instance.
        /// </summary>
        private Guid forgeId;

        /// <summary>
        /// Initializes a new instance of the <see cref="ForgeContext" /> class.
        /// </summary>
        /// <param name="forgeService">The domain service for <see cref="IForge" /> entities.</param>
        /// <param name="logger">The logger for diagnostic messages.</param>
        public ForgeContext(IForgeService forgeService, ILogger<ForgeContext> logger)
        {
            ArgumentNullException.ThrowIfNull(forgeService);
            ArgumentNullException.ThrowIfNull(logger);

            this.forgeService = forgeService;
            this.logger = logger;
        }

        /// <summary>
        /// Gets the unique identifier of the Forge instance.
        /// </summary>
        public Guid ForgeId
        {
            get => this.GetForgeId();
            private set => this.forgeId = value;
        }

        /// <summary>
        /// Gets a value indicating whether the Forge context has completed initialization.
        /// </summary>
        public bool IsInitialized => this.forgeId != Guid.Empty;

        /// <summary>
        /// Initializes the Forge context by querying the Forge service once using super user permissions.
        /// </summary>
        /// <param name="cancellationToken">The cancellation token used to cancel the initialization.</param>
        /// <returns>A <see cref="Task" /> representing the asynchronous initialization.</returns>
        public async Task InitializeAsync(CancellationToken cancellationToken = default)
        {
            var success = await this.TryInitializeAsync(cancellationToken);

            if (!success)
            {
                throw new InvalidOperationException("Failed to initialize Forge context.");
            }
        }

        /// <summary>
        /// Attempts to initialize the Forge context by querying the Forge service once.
        /// </summary>
        /// <param name="cancellationToken">The cancellation token used to cancel the initialization.</param>
        /// <returns>A <see cref="Task{Boolean}" /> indicating whether initialization succeeded.</returns>
        public async Task<bool> TryInitializeAsync(CancellationToken cancellationToken = default)
        {
            if (this.IsInitialized)
            {
                return true;
            }

            var superUser = new UserContext
            {
                AccountId = Guid.Empty,
                Username = "system",
                CurrentRoles = [RoleKind.InstallationAdministrator]
            };

            try
            {
                var result = await this.forgeService.ReadAsync(superUser, cancellationToken);

                if (result.IsError)
                {
                    this.logger.LogError("Failed to initialize Forge context: database query failed with errors: {Errors}", result.Errors.ToJoinedDescriptions());
                    return false;
                }

                if (result.Value.Count == 0)
                {
                    this.logger.LogWarning("Failed to initialize Forge context: no Forge instance found in the database. Ensure the database is seeded.");
                    return false;
                }

                this.ForgeId = result.Value[0].Id;

                if (this.logger.IsEnabled(LogLevel.Information))
                {
                    this.logger.LogInformation("Forge context initialized with Forge ID: {ForgeId}", this.ForgeId);
                }

                return true;
            }
            catch (Exception exception)
            {
                this.logger.LogError(exception, "Failed to initialize Forge context: connection to database failed.");
                return false;
            }
        }

        /// <summary>
        /// Retrieves the unique identifier of the Forge instance, throwing if not initialized.
        /// </summary>
        /// <returns>The unique identifier of the Forge instance.</returns>
        private Guid GetForgeId()
        {
            if (this.forgeId == Guid.Empty)
            {
                throw new InvalidOperationException("Forge context has not been initialized.");
            }

            return this.forgeId;
        }
    }
}
