namespace Mycelium.Forge.Services
{
    using System.Security.Claims;

    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;

    /// <summary>
    /// Provisions the Forge account of an identity provider user on first sign-in (SSS-FG-AUTH-A2F).
    /// </summary>
    public class AccountProvisioner : IAccountProvisioner
    {
        /// <summary>
        /// The claim type carrying the subject identifier of the user.
        /// </summary>
        private const string SubjectClaimType = "sub";

        /// <summary>
        /// The claim type carrying the preferred username of the user.
        /// </summary>
        private const string PreferredUsernameClaimType = "preferred_username";

        /// <summary>
        /// The claim type carrying the email address of the user.
        /// </summary>
        private const string EmailClaimType = "email";

        /// <summary>
        /// The claim type carrying the given name of the user.
        /// </summary>
        private const string GivenNameClaimType = "given_name";

        /// <summary>
        /// The claim type carrying the family name of the user.
        /// </summary>
        private const string FamilyNameClaimType = "family_name";

        /// <summary>
        /// The injected <see cref="IAccountService" /> used to read and create accounts.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The injected <see cref="IForgeContext" /> used to resolve the owning Forge instance.
        /// </summary>
        private readonly IForgeContext forgeContext;

        /// <summary>
        /// The injected <see cref="ILogger{AccountProvisioner}" /> used for logging.
        /// </summary>
        private readonly ILogger<AccountProvisioner> logger;

        /// <summary>
        /// Initializes a new instance of the <see cref="AccountProvisioner" /> class.
        /// </summary>
        /// <param name="accountService">The injected <see cref="IAccountService" />.</param>
        /// <param name="forgeContext">The injected <see cref="IForgeContext" />.</param>
        /// <param name="logger">The injected <see cref="ILogger{AccountProvisioner}" />.</param>
        public AccountProvisioner(IAccountService accountService, IForgeContext forgeContext, ILogger<AccountProvisioner> logger)
        {
            this.accountService = accountService;
            this.forgeContext = forgeContext;
            this.logger = logger;
        }

        /// <summary>
        /// Ensures a Forge account exists for the authenticated principal, creating it from the identity provider claims
        /// when it does not exist yet.
        /// </summary>
        /// <remarks>
        /// The account is created under a system context, because the signing-in user cannot yet hold a Forge account
        /// that is permitted to create one.
        /// </remarks>
        /// <param name="principal">The principal authenticated by the identity provider.</param>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{TValue}" /> indicating whether the account exists after the call.</returns>
        public async Task<ErrorOr<Success>> ProvisionAsync(ClaimsPrincipal principal, CancellationToken cancellationToken)
        {
            var username = principal.FindFirstValue(PreferredUsernameClaimType);
            var subject = principal.FindFirstValue(SubjectClaimType) ?? principal.FindFirstValue(ClaimTypes.NameIdentifier);
            var email = principal.FindFirstValue(EmailClaimType) ?? principal.FindFirstValue(ClaimTypes.Email);

            if (!Guid.TryParse(subject, out var accountId) || string.IsNullOrWhiteSpace(username) || string.IsNullOrWhiteSpace(email))
            {
                return Error.Validation("Account.InvalidClaims", "The identity provider did not supply a valid subject, preferred username, or email.");
            }

            var systemContext = new UserContext
            {
                AccountId = accountId,
                Username = username,
                CurrentRoles = [RoleKind.InstallationAdministrator, RoleKind.Account]
            };

            var existing = await this.accountService.ReadAsync(systemContext, cancellationToken, [accountId]);

            if (existing.IsError && existing.Errors.Exists(error => error.Type != ErrorType.NotFound))
            {
                return existing.Errors;
            }

            if (!existing.IsError && !existing.Value.IsEmpty)
            {
                return Result.Success;
            }

            return await this.CreateAccountAsync(principal, accountId, username, systemContext, cancellationToken);
        }

        /// <summary>
        /// Asynchronously creates the Forge account entity for a newly authenticated identity provider user.
        /// </summary>
        /// <param name="principal">The principal authenticated by the identity provider.</param>
        /// <param name="accountId">The unique identifier of the account.</param>
        /// <param name="username">The preferred username of the user.</param>
        /// <param name="systemContext">The system context used to execute account creation.</param>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{TValue}" /> indicating whether account creation succeeded.</returns>
        private async Task<ErrorOr<Success>> CreateAccountAsync(ClaimsPrincipal principal, Guid accountId, string username, IUserContext systemContext, CancellationToken cancellationToken)
        {
            var givenName = principal.FindFirstValue(GivenNameClaimType) ?? principal.FindFirstValue(ClaimTypes.GivenName);
            var familyName = principal.FindFirstValue(FamilyNameClaimType) ?? principal.FindFirstValue(ClaimTypes.Surname);
            var displayName = $"{givenName} {familyName}".Trim();

            var account = new Account
            {
                Id = accountId,
                Owner = this.forgeContext.ForgeId,
                Name = displayName,
                ShortName = username,
                Email = principal.FindFirstValue(EmailClaimType) ?? principal.FindFirstValue(ClaimTypes.Email),
                OwnedPackageInvitation = Guid.NewGuid(), // Remove this line once the domain model is updated and OwnedPackageInvitation is no longer mandatory (#138).
                CreatedAt = DateTime.UtcNow,
                ModifiedAt = DateTime.UtcNow
            };

            var created = await this.accountService.CreateAsync(systemContext, [account], cancellationToken);

            if (created.IsError)
            {
                this.logger.LogError("Failed to provision the account of {Username}: {Errors}", username, string.Join(", ", created.Errors));
                return created.Errors;
            }

            if (this.logger.IsEnabled(LogLevel.Information))
            {
                this.logger.LogInformation("Provisioned the account of {Username} on first sign-in", username);
            }

            return Result.Success;
        }
    }
}
