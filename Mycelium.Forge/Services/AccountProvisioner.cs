namespace Mycelium.Forge.Services
{
    using System.Security.Claims;

    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;

    /// <summary>
    /// Provisions and reconciles the Forge account of an identity provider user on sign-in (SSS-FG-AUTH-A2F).
    /// </summary>
    public class AccountProvisioner : IAccountProvisioner
    {
        /// <summary>
        /// The claim type carrying the subject identifier of the user.
        /// </summary>
        private const string SubjectClaimType = "sub";

        /// <summary>
        /// The claim type carrying the preferred username of the user.
        /// </summary>
        private const string PreferredUsernameClaimType = "preferred_username";

        /// <summary>
        /// The claim type carrying the email address of the user.
        /// </summary>
        private const string EmailClaimType = "email";

        /// <summary>
        /// The claim type carrying the given name of the user.
        /// </summary>
        private const string GivenNameClaimType = "given_name";

        /// <summary>
        /// The claim type carrying the family name of the user.
        /// </summary>
        private const string FamilyNameClaimType = "family_name";

        /// <summary>
        /// The claim type carrying the full display name of the user.
        /// </summary>
        private const string NameClaimType = "name";

        /// <summary>
        /// The injected <see cref="IAccountService" /> used to read, create, and update accounts.
        /// </summary>
        private readonly IAccountService accountService;

        /// <summary>
        /// The injected <see cref="IForgeContext" /> used to resolve the owning Forge instance.
        /// </summary>
        private readonly IForgeContext forgeContext;

        /// <summary>
        /// The injected <see cref="ILogger{AccountProvisioner}" /> used for logging.
        /// </summary>
        private readonly ILogger<AccountProvisioner> logger;

        /// <summary>
        /// Initializes a new instance of the <see cref="AccountProvisioner" /> class.
        /// </summary>
        /// <param name="accountService">The injected <see cref="IAccountService" />.</param>
        /// <param name="forgeContext">The injected <see cref="IForgeContext" />.</param>
        /// <param name="logger">The injected <see cref="ILogger{AccountProvisioner}" />.</param>
        public AccountProvisioner(IAccountService accountService, IForgeContext forgeContext, ILogger<AccountProvisioner> logger)
        {
            this.accountService = accountService;
            this.forgeContext = forgeContext;
            this.logger = logger;
        }

        /// <summary>
        /// Ensures a Forge account exists for the authenticated principal, creating it on first sign-in and reconciling
        /// <see cref="IAccount.Name" /> and <see cref="IAccount.Email" /> from identity provider claims on subsequent sign-ins.
        /// </summary>
        /// <remarks>
        /// The account is created and reconciled under a system context, because the signing-in user cannot yet hold a Forge
        /// account that is permitted to create one. <see cref="IAccount.ShortName" /> (<c>preferred_username</c>) is not
        /// synchronized because usernames are currently non-editable (<c>editUsernameAllowed</c> is <c>false</c> in
        /// <c>forge-realm.json</c> and <c>ScopeAlias</c> scope renames from design section 8.5 are not yet implemented);
        /// mutating <see cref="IAccount.ShortName" /> would break existing <c>@username/package</c> coordinates.
        /// </remarks>
        /// <param name="principal">The principal authenticated by the identity provider.</param>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{TValue}" /> indicating whether the account exists and is synchronized after the call.</returns>
        public async Task<ErrorOr<Success>> ProvisionAsync(ClaimsPrincipal principal, CancellationToken cancellationToken)
        {
            var username = principal.FindFirstValue(PreferredUsernameClaimType);
            var subject = principal.FindFirstValue(SubjectClaimType) ?? principal.FindFirstValue(ClaimTypes.NameIdentifier);
            var email = principal.FindFirstValue(EmailClaimType) ?? principal.FindFirstValue(ClaimTypes.Email);

            if (!Guid.TryParse(subject, out var accountId) || string.IsNullOrWhiteSpace(username) || string.IsNullOrWhiteSpace(email))
            {
                return Error.Validation("Account.InvalidClaims", "The identity provider did not supply a valid subject, preferred username, or email.");
            }

            var systemContext = new UserContext
            {
                AccountId = accountId,
                Username = username,
                CurrentRoles = [RoleKind.InstallationAdministrator, RoleKind.Account]
            };

            var existing = await this.accountService.ReadAsync(systemContext, cancellationToken, [accountId]);

            if (existing.IsError && existing.Errors.Exists(error => error.Type != ErrorType.NotFound))
            {
                return existing.Errors;
            }

            if (!existing.IsError && !existing.Value.IsEmpty)
            {
                return await this.ReconcileAccountAsync(principal, existing.Value[0], email, systemContext, cancellationToken);
            }

            return await this.CreateAccountAsync(principal, accountId, username, email, systemContext, cancellationToken);
        }

        /// <summary>
        /// Resolves the display name from the principal's given/family name claims, falling back to the full name claim.
        /// </summary>
        /// <param name="principal">The authenticated claims principal.</param>
        /// <returns>The trimmed display name, or an empty string if no name claims are available.</returns>
        private static string ResolveDisplayName(ClaimsPrincipal principal)
        {
            var givenName = principal.FindFirstValue(GivenNameClaimType) ?? principal.FindFirstValue(ClaimTypes.GivenName);
            var familyName = principal.FindFirstValue(FamilyNameClaimType) ?? principal.FindFirstValue(ClaimTypes.Surname);
            var displayName = $"{givenName} {familyName}".Trim();

            if (!string.IsNullOrWhiteSpace(displayName))
            {
                return displayName;
            }

            var fallbackName = principal.FindFirstValue(NameClaimType) ?? principal.FindFirstValue(ClaimTypes.Name);
            return fallbackName?.Trim() ?? string.Empty;
        }

        /// <summary>
        /// Reconciles the existing Forge account's display name and email address against the identity provider claims.
        /// </summary>
        /// <param name="principal">The principal authenticated by the identity provider.</param>
        /// <param name="existingAccount">The currently persisted Forge account.</param>
        /// <param name="email">The email claim resolved from the identity provider.</param>
        /// <param name="systemContext">The system context used to execute account updates.</param>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating whether reconciliation succeeded.</returns>
        private async Task<ErrorOr<Success>> ReconcileAccountAsync(ClaimsPrincipal principal, IAccount existingAccount, string email, IUserContext systemContext, CancellationToken cancellationToken)
        {
            var resolvedName = ResolveDisplayName(principal);
            var targetName = !string.IsNullOrWhiteSpace(resolvedName) ? resolvedName : existingAccount.Name;

            if (string.Equals(existingAccount.Name, targetName, StringComparison.Ordinal) && string.Equals(existingAccount.Email, email, StringComparison.Ordinal))
            {
                return Result.Success;
            }

            var updated = ((Account)existingAccount).Clone();
            updated.Name = targetName;
            updated.Email = email;

            var updateResult = await this.accountService.UpdateAsync(systemContext, [updated], cancellationToken);

            if (updateResult.IsError)
            {
                this.logger.LogError("Failed to reconcile the account of {Username}: {Errors}", existingAccount.ShortName.SanitizeForLog(), updateResult.Errors.ToJoinedDescriptions());
                return updateResult.Errors;
            }

            if (this.logger.IsEnabled(LogLevel.Information))
            {
                this.logger.LogInformation("Reconciled the account of {Username} on sign-in", existingAccount.ShortName.SanitizeForLog());
            }

            return Result.Success;
        }

        /// <summary>
        /// Asynchronously creates the Forge account entity for a newly authenticated identity provider user.
        /// </summary>
        /// <param name="principal">The principal authenticated by the identity provider.</param>
        /// <param name="accountId">The unique identifier of the account.</param>
        /// <param name="username">The preferred username of the user.</param>
        /// <param name="email">The email address of the user.</param>
        /// <param name="systemContext">The system context used to execute account creation.</param>
        /// <param name="cancellationToken">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{TValue}" /> indicating whether account creation succeeded.</returns>
        private async Task<ErrorOr<Success>> CreateAccountAsync(ClaimsPrincipal principal, Guid accountId, string username, string email, IUserContext systemContext, CancellationToken cancellationToken)
        {
            var displayName = ResolveDisplayName(principal);

            var account = new Account
            {
                Id = accountId,
                Owner = this.forgeContext.ForgeId,
                Name = displayName,
                ShortName = username,
                Email = email,
                OwnedPackageInvitation = Guid.NewGuid() // Remove once Account.OwnedPackageInvitation is updated to UML multiplicity 0..* (non-mandatory) (#138) so AccountDao.ReadAsync stops returning duplicate rows.
            };

            var created = await this.accountService.CreateAsync(systemContext, [account], cancellationToken);

            if (created.IsError)
            {
                this.logger.LogError("Failed to provision the account of {Username}: {Errors}", username.SanitizeForLog(), created.Errors.ToJoinedDescriptions());
                return created.Errors;
            }

            if (this.logger.IsEnabled(LogLevel.Information))
            {
                this.logger.LogInformation("Provisioned the account of {Username} on first sign-in", username.SanitizeForLog());
            }

            return Result.Success;
        }
    }
}
