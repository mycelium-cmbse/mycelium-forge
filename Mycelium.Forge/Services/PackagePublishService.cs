namespace Mycelium.Forge.Services
{
    using ErrorOr;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Enums;
    using Mycelium.Forge.Extensions;
    using Mycelium.Forge.Extractors.Enums;
    using Mycelium.Forge.Extractors.Extractors;
    using Mycelium.Forge.Extractors.Models;
    using Mycelium.Forge.Models.Validation;
    using Mycelium.Forge.Storage.Stores;

    using Npgsql;

    /// <summary>
    /// Service implementation coordinating package publishing operations.
    /// </summary>
    /// <remarks>Encapsulates logic that can be used later for both UI and CLI projects.</remarks>
    public class PackagePublishService : IPackagePublishService
    {
        /// <summary>
        /// The (injected) <see cref="IArtifactStore" /> object storage service.
        /// </summary>
        private readonly IArtifactStore artifactStore;

        /// <summary>
        /// The (injected) <see cref="IDatabaseSource" /> database connection and transaction provider.
        /// </summary>
        private readonly IDatabaseSource databaseSource;

        /// <summary>
        /// The (injected) <see cref="ILogger{PackagePublishService}" /> logger.
        /// </summary>
        private readonly ILogger<PackagePublishService> logger;

        /// <summary>
        /// The (injected) collection of <see cref="IArtifactManifestExtractor" /> instances.
        /// </summary>
        private readonly IEnumerable<IArtifactManifestExtractor> manifestExtractors;

        /// <summary>
        /// The (injected) <see cref="IPackageMetaDataService" /> domain service.
        /// </summary>
        private readonly IPackageMetaDataService packageMetaDataService;

        /// <summary>
        /// The (injected) <see cref="IPackageService" /> domain service.
        /// </summary>
        private readonly IPackageService packageService;

        /// <summary>
        /// The (injected) <see cref="IPackageTypeService" /> domain service.
        /// </summary>
        private readonly IPackageTypeService packageTypeService;

        /// <summary>
        /// The (injected) <see cref="IPackageVersionService" /> domain service.
        /// </summary>
        private readonly IPackageVersionService packageVersionService;

        /// <summary>
        /// Initializes a new instance of the <see cref="PackagePublishService" /> class.
        /// </summary>
        /// <param name="artifactStore">The (injected) <see cref="IArtifactStore" /> object storage service.</param>
        /// <param name="databaseSource">The (injected) <see cref="IDatabaseSource" /> database provider.</param>
        /// <param name="manifestExtractors">The (injected) collection of <see cref="IArtifactManifestExtractor" /> instances.</param>
        /// <param name="packageService">The (injected) <see cref="IPackageService" /> domain service.</param>
        /// <param name="packageVersionService">The (injected) <see cref="IPackageVersionService" /> domain service.</param>
        /// <param name="packageMetaDataService">The (injected) <see cref="IPackageMetaDataService" /> domain service.</param>
        /// <param name="packageTypeService">The (injected) <see cref="IPackageTypeService" /> domain service.</param>
        /// <param name="logger">The (injected) <see cref="ILogger{PackagePublishService}" /> logger.</param>
        public PackagePublishService(IArtifactStore artifactStore, IDatabaseSource databaseSource, IEnumerable<IArtifactManifestExtractor> manifestExtractors,
            IPackageService packageService, IPackageVersionService packageVersionService, IPackageMetaDataService packageMetaDataService, IPackageTypeService packageTypeService,
            ILogger<PackagePublishService> logger)
        {
            this.artifactStore = artifactStore;
            this.databaseSource = databaseSource;
            this.manifestExtractors = manifestExtractors;
            this.packageService = packageService;
            this.packageVersionService = packageVersionService;
            this.packageMetaDataService = packageMetaDataService;
            this.packageTypeService = packageTypeService;
            this.logger = logger;
        }

        /// <summary>
        /// Reads the manifest of an archive stream, maps its values onto the package entities, and resolves the package type.
        /// </summary>
        /// <param name="userContext">The contextual user information.</param>
        /// <param name="archiveStream">The archive stream containing the package files.</param>
        /// <param name="kind">The kind of artifact being extracted.</param>
        /// <param name="formatName">The format name of the artifact.</param>
        /// <param name="package">The package entity to populate.</param>
        /// <param name="packageVersion">The package version entity to populate.</param>
        /// <param name="packageMetaData">The package metadata entity to populate.</param>
        /// <param name="isExistingPackage">A value indicating whether an existing package is being published.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>An <see cref="ErrorOr{IArtifactManifest}" /> containing the extracted manifest or errors.</returns>
        public async Task<ErrorOr<IArtifactManifest>> ExtractManifestAsync(IUserContext userContext, Stream archiveStream, ArtifactKind kind, string formatName, IPackage package, IPackageVersion packageVersion, IPackageMetaData packageMetaData, bool isExistingPackage, CancellationToken token = default)
        {
            if (!isExistingPackage)
            {
                var packageTypeResult = await this.packageTypeService.ReadByNameAsync(userContext, token, [formatName]);

                if (packageTypeResult.IsError || packageTypeResult.Value.Count == 0)
                {
                    return Error.Validation(ValidationTypes.SchemaValidation, $"Package type '{formatName}' is not configured in the registry.");
                }

                package.PackageType = packageTypeResult.Value[0].Id;
            }

            var extractor = this.manifestExtractors.FirstOrDefault(x => x.CanHandle(kind));

            if (extractor == null)
            {
                return Error.Validation(ValidationTypes.SchemaValidation, $"No extractor configured for artifact kind '{kind}'.");
            }

            packageVersion.SizeInBytes = archiveStream.Length;

            var extractResult = extractor.Extract(archiveStream);

            if (extractResult.IsError)
            {
                return extractResult.Errors;
            }

            extractResult.Value.ApplyTo(package, packageVersion, packageMetaData, isExistingPackage);
            return extractResult;
        }

        /// <summary>
        /// Evaluates the pre-publishing domain validation checks (schema, namespace uniqueness, semver progression, and license).
        /// </summary>
        /// <param name="userContext">The contextual user information.</param>
        /// <param name="selectedScope">The owning scope of the package.</param>
        /// <param name="package">The package entity being published.</param>
        /// <param name="packageVersion">The package version being published.</param>
        /// <param name="isExistingPackage">A value indicating whether publishing a new version of an existing package.</param>
        /// <param name="existingVersions">The collection of previously published version strings for this package.</param>
        /// <param name="beforeValidationErrors">
        /// Optional pre-validation or extraction errors to evaluate before executing domain
        /// checks.
        /// </param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>A list of <see cref="ValidationCheckModel" /> rule evaluation results.</returns>
        public async Task<IReadOnlyList<ValidationCheckModel>> ValidateReleaseAsync(IUserContext userContext, IScope selectedScope, IPackage package, IPackageVersion packageVersion, bool isExistingPackage, IReadOnlyList<string> existingVersions, IReadOnlyList<Error> beforeValidationErrors = null, CancellationToken token = default)
        {
            var checks = new List<ValidationCheckModel>();

            if (beforeValidationErrors is { Count: > 0 })
            {
                checks.AddRange(beforeValidationErrors.Select(error => new ValidationCheckModel(error.Code, ValidationStatus.Fail, error.Description)));
                return checks;
            }

            checks.Add(new ValidationCheckModel(ValidationTypes.SchemaValidation, ValidationStatus.Pass, "Archive structure and manifests conform to specification."));
            checks.Add(await this.ValidateNamespaceAsync(userContext, selectedScope, package, isExistingPackage, token));
            checks.Add(ValidateVersion(packageVersion, isExistingPackage, existingVersions));
            checks.Add(ValidateLicense(package));

            return checks;
        }

        /// <summary>
        /// Stores the artifact stream into object storage and atomically persists the package, version, and metadata
        /// in the database within a transaction with deferred constraints. Rolls back object storage on failure.
        /// </summary>
        /// <param name="userContext">The contextual user information.</param>
        /// <param name="artifactStream">The stream of the artifact package file.</param>
        /// <param name="selectedScope">The owning scope of the package.</param>
        /// <param name="package">The package being created or updated.</param>
        /// <param name="packageVersion">The package version to create.</param>
        /// <param name="packageMetaData">The package metadata to create.</param>
        /// <param name="isExistingPackage">A value indicating whether the package record already exists.</param>
        /// <param name="token">The <see cref="CancellationToken" /> used to cancel the operation.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating success or failure of the publication.</returns>
        public async Task<ErrorOr<Success>> PublishReleaseAsync(IUserContext userContext, Stream artifactStream, IScope selectedScope, IPackage package, IPackageVersion packageVersion, IPackageMetaData packageMetaData, bool isExistingPackage, CancellationToken token = default)
        {
            var storedHash = string.Empty;
            var wasArtifactNew = false;

            try
            {
                var artifactResult = await this.artifactStore.StoreArtifactAsync(artifactStream, token: token);

                if (artifactResult.IsError)
                {
                    return artifactResult.Errors;
                }

                (storedHash, wasArtifactNew) = artifactResult.Value;
                packageVersion.Checksum = storedHash;
                packageVersion.PublicationDate = DateTime.UtcNow;

                if (!isExistingPackage && selectedScope != null)
                {
                    package.Owner = selectedScope.Id;
                }

                var dbResult = await this.databaseSource.ExecuteInTransactionAsync(transaction => this.PersistReleaseEntitiesAsync(userContext, transaction, package, packageVersion, packageMetaData, isExistingPackage, token), token);

                if (!dbResult.IsError)
                {
                    return Result.Success;
                }

                if (wasArtifactNew)
                {
                    await this.TryRollbackArtifactAsync(storedHash, token);
                }

                return dbResult.Errors;
            }
            catch (Exception exception)
            {
                this.logger.LogError(exception, "Failed to publish package {PackageName}", package.Name.SanitizeForLog());

                if (wasArtifactNew)
                {
                    await this.TryRollbackArtifactAsync(storedHash, token);
                }

                return Error.Failure(description: exception.Message);
            }
        }

        /// <summary>
        /// Persists the package, package version, and metadata entities in the database during publication.
        /// </summary>
        /// <param name="userContext">The contextual user information.</param>
        /// <param name="transaction">The database transaction.</param>
        /// <param name="package">The package being created or updated.</param>
        /// <param name="packageVersion">The package version to create.</param>
        /// <param name="packageMetaData">The package metadata to create.</param>
        /// <param name="isExistingPackage">A value indicating whether the package record already exists.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>An <see cref="ErrorOr{Success}" /> indicating success or database errors.</returns>
        private async Task<ErrorOr<Success>> PersistReleaseEntitiesAsync(IUserContext userContext, NpgsqlTransaction transaction, IPackage package, IPackageVersion packageVersion, IPackageMetaData packageMetaData, bool isExistingPackage, CancellationToken token)
        {
            await this.databaseSource.DeferConstraintsAsync(transaction, token);

            if (!isExistingPackage)
            {
                var packageResult = await this.packageService.CreateAsync(userContext, transaction, [package], token);

                if (packageResult.IsError)
                {
                    return packageResult.Errors;
                }
            }

            var versionResult = await this.packageVersionService.CreateAsync(userContext, transaction, [packageVersion], token);

            if (versionResult.IsError)
            {
                return versionResult.Errors;
            }

            var metaDataResult = await this.packageMetaDataService.CreateAsync(userContext, transaction, [packageMetaData], token);

            if (metaDataResult.IsError)
            {
                return metaDataResult.Errors;
            }

            if (isExistingPackage)
            {
                package.Version.Add(packageVersion.Id);
            }

            return Result.Success;
        }

        /// <summary>
        /// Validates that the package namespace is unique within the target scope.
        /// </summary>
        /// <param name="userContext">The contextual user information.</param>
        /// <param name="selectedScope">The owning scope of the package.</param>
        /// <param name="package">The package entity being published.</param>
        /// <param name="isExistingPackage">A value indicating whether publishing a new version of an existing package.</param>
        /// <param name="token">The cancellation token.</param>
        /// <returns>A <see cref="ValidationCheckModel" /> representing the namespace uniqueness check.</returns>
        private async Task<ValidationCheckModel> ValidateNamespaceAsync(IUserContext userContext, IScope selectedScope, IPackage package, bool isExistingPackage, CancellationToken token)
        {
            if (isExistingPackage)
            {
                return new ValidationCheckModel(ValidationTypes.NamespaceUniqueness, ValidationStatus.Pass, "Publishing a new version to an existing package in the selected scope.");
            }

            var existingResult = await this.packageService.ReadByCoordinateAsync(userContext, selectedScope?.ShortName ?? string.Empty, package.ShortName, true, token);

            return !existingResult.IsError
                ? new ValidationCheckModel(ValidationTypes.NamespaceUniqueness, ValidationStatus.Fail, $"Package '{package.ShortName}' already exists in scope '@{selectedScope?.ShortName}'.")
                : new ValidationCheckModel(ValidationTypes.NamespaceUniqueness, ValidationStatus.Pass, "Package identifier is available in the selected scope.");
        }

        /// <summary>
        /// Validates version progression and Semantic Versioning conformance.
        /// </summary>
        /// <param name="packageVersion">The package version being published.</param>
        /// <param name="isExistingPackage">A value indicating whether publishing a new version of an existing package.</param>
        /// <param name="existingVersions">The collection of previously published version strings for this package.</param>
        /// <returns>A <see cref="ValidationCheckModel" /> representing the version validation check.</returns>
        private static ValidationCheckModel ValidateVersion(IPackageVersion packageVersion, bool isExistingPackage, IReadOnlyList<string> existingVersions)
        {
            if (!isExistingPackage)
            {
                return new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Pass, "Initial version is valid for publication.");
            }

            var conflictingVersion = existingVersions?.FirstOrDefault(x => SemanticVersionComparer.Instance.Compare(packageVersion.Version, x) <= 0);

            if (conflictingVersion != null)
            {
                var isDuplicate = SemanticVersionComparer.Instance.Compare(packageVersion.Version, conflictingVersion) == 0;

                var detail = isDuplicate
                    ? $"Version '{packageVersion.Version}' already exists for this package."
                    : $"Version '{packageVersion.Version}' must be strictly greater than published version '{conflictingVersion}'.";

                return new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Fail, detail);
            }

            var latestVersion = existingVersions?.OrderByDescending(x => x, SemanticVersionComparer.Instance).FirstOrDefault();
            var isMajorBump = latestVersion != null && SemanticVersionComparer.IsMajorBump(packageVersion.Version, latestVersion);

            if (isMajorBump && string.IsNullOrWhiteSpace(packageVersion.ReleaseNotes))
            {
                return new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Fail, "A major-version update requires release notes.", "Provide release notes for this major release.");
            }

            return new ValidationCheckModel(ValidationTypes.PackageVersion, ValidationStatus.Pass, "Version is unique and strictly greater than prior releases.");
        }

        /// <summary>
        /// Validates that a license is specified for the package.
        /// </summary>
        /// <param name="package">The package entity being published.</param>
        /// <returns>A <see cref="ValidationCheckModel" /> representing the license validation check.</returns>
        private static ValidationCheckModel ValidateLicense(IPackage package)
        {
            return string.IsNullOrWhiteSpace(package.License)
                ? new ValidationCheckModel(ValidationTypes.License, ValidationStatus.Warning, "No license specified for this package. Consider selecting one.")
                : new ValidationCheckModel(ValidationTypes.License, ValidationStatus.Pass, $"License '{package.License}' declared.");
        }

        /// <summary>
        /// Safely attempts to delete a stored artifact during compensation rollback, logging a warning if deletion fails.
        /// </summary>
        /// <param name="storedHash">The content hash of the stored artifact.</param>
        /// <param name="token">The cancellation token.</param>
        private async Task TryRollbackArtifactAsync(string storedHash, CancellationToken token)
        {
            try
            {
                await this.artifactStore.DeleteArtifactAsync(storedHash, token);
            }
            catch (Exception exception)
            {
                this.logger.LogWarning(exception, "Failed to delete stored artifact {StoredHash} during compensation rollback", storedHash.SanitizeForLog());
            }
        }
    }
}
