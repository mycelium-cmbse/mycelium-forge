            var notFoundResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(notFoundResult.IsError, Is.True);
                Assert.That(notFoundResult.Errors[0].Description, Does.Contain("was not found"));
            }

            // Case: Permission denied
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(updatedPackage1.Id)), null, It.IsAny<ISqlFilter>()))
                .ReturnsAsync(ImmutableList.Create<IPackage>(existingPackage1));

            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingPackage1, updatedPackage1, It.IsAny<NpgsqlTransaction>()))
                .ReturnsAsync(Error.Forbidden(description: "Update forbidden"));

            var permissionFailResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(permissionFailResult.IsError, Is.True);
                Assert.That(permissionFailResult.Errors[0].Description, Is.EqualTo("Update forbidden"));
            }

            // Case: DAO Update fails
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingPackage1, updatedPackage1, It.IsAny<NpgsqlTransaction>()))
                .ReturnsAsync(Result.Success);

            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage1, It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "DAO update error"));

            var daoUpdateFailResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(daoUpdateFailResult.IsError, Is.True);
                Assert.That(daoUpdateFailResult.Errors[0].Description, Is.EqualTo("DAO update error"));
            }

            // Case: Happy path within transaction (multi-item batch update with change logging)
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(updatedPackage1.Id) && ((IEnumerable<Guid>)ids).Contains(updatedPackage2.Id)), null, It.IsAny<ISqlFilter>()))
                .ReturnsAsync(ImmutableList.Create<IPackage>(existingPackage1, existingPackage2));

            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingPackage2, updatedPackage2, It.IsAny<NpgsqlTransaction>()))
                .ReturnsAsync(Result.Success);

            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage1, It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Updated);

            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage2, It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Updated);

            var successResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1, updatedPackage2], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                this.daoMock.Verify(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage1, It.IsAny<CancellationToken>()), Times.AtLeastOnce());
                this.daoMock.Verify(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage2, It.IsAny<CancellationToken>()), Times.Once());
                this.loggerMock.Verify(x => x.Log(LogLevel.Information, It.IsAny<EventId>(), It.IsAny<It.IsAnyType>(), It.IsAny<Exception>(), It.IsAny<Func<It.IsAnyType, Exception, string>>()), Times.AtLeastOnce());
            }

            // Case: Standalone connection exception handled gracefully
            this.databaseSourceMock.Setup(x => x.OpenNewConnectionAsync(It.IsAny<CancellationToken>()))
                .ThrowsAsync(new InvalidOperationException("Connection failed"));

            var connectionFailResult = await this.service.UpdateAsync(this.userContext, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(connectionFailResult.IsError, Is.True);
                Assert.That(connectionFailResult.Errors[0].Description, Does.Contain("Connection failed"));
            }
        }

