                Assert.That(async () => await this.service.UpdateAsync(this.userContext, null, CancellationToken.None), Throws.ArgumentNullException);
            }

            // Case: Empty collection returns OK
            var emptyResult = await this.service.UpdateAsync(this.userContext, null, [], CancellationToken.None);
            Assert.That(emptyResult.IsError, Is.False);

            // Case: Validation fails
            var validationFailResult = await this.service.UpdateAsync(this.userContext, null, [invalidPackage], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(validationFailResult.IsError, Is.True);
                Assert.That(validationFailResult.Errors[0].Description, Does.Contain(nameof(Package.Id)));
            }

            // Case: DAO Read existing fails
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(updatedPackage1.Id)), null, It.IsAny<ISqlFilter>()))
                .ReturnsAsync(Error.Failure(description: "DAO read error"));

            var daoReadFailResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(daoReadFailResult.IsError, Is.True);
                Assert.That(daoReadFailResult.Errors[0].Description, Is.EqualTo("DAO read error"));
            }

            // Case: Existing item not found
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(updatedPackage1.Id)), null, It.IsAny<ISqlFilter>()))
                .ReturnsAsync(ImmutableList<IPackage>.Empty);

            var notFoundResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(notFoundResult.IsError, Is.True);
                Assert.That(notFoundResult.Errors[0].Description, Does.Contain("was not found"));
            }

            // Case: Permission denied
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(updatedPackage1.Id)), null, It.IsAny<ISqlFilter>()))
                .ReturnsAsync(ImmutableList.Create<IPackage>(existingPackage1));

            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingPackage1, updatedPackage1, It.IsAny<NpgsqlTransaction>()))
                .ReturnsAsync(Error.Forbidden(description: "Update forbidden"));

            var permissionFailResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(permissionFailResult.IsError, Is.True);
                Assert.That(permissionFailResult.Errors[0].Description, Is.EqualTo("Update forbidden"));
            }

            // Case: DAO Update fails
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingPackage1, updatedPackage1, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage1, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure(description: "DAO update error"));

            var daoUpdateFailResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(daoUpdateFailResult.IsError, Is.True);
                Assert.That(daoUpdateFailResult.Errors[0].Description, Is.EqualTo("DAO update error"));
            }

            // Case: Owner changed by a user who is neither package owner nor installation administrator is forbidden and nothing is persisted
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(transferredPackage.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create<IPackage>(existingTransferPackage));
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingTransferPackage, transferredPackage, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);

            this.daoMock.Invocations.Clear();

            var transferForbiddenResult = await this.service.UpdateAsync(this.userContext, null, [transferredPackage], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(transferForbiddenResult.IsError, Is.True);
                Assert.That(transferForbiddenResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
                Assert.That(transferForbiddenResult.FirstError.Description, Does.Contain("only a package owner or an installation administrator"));
                this.daoMock.Verify(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), transferredPackage, It.IsAny<CancellationToken>()), Times.Never());
            }

            // Case: Happy path within transaction (multi-item batch update with change logging)
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(updatedPackage1.Id) && ((IEnumerable<Guid>)ids).Contains(updatedPackage2.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create<IPackage>(existingPackage1, existingPackage2));
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingPackage2, updatedPackage2, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage1, It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage2, It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);

            var successResult = await this.service.UpdateAsync(this.userContext, null, [updatedPackage1, updatedPackage2], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                this.daoMock.Verify(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage1, It.IsAny<CancellationToken>()), Times.AtLeastOnce());
                this.daoMock.Verify(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), updatedPackage2, It.IsAny<CancellationToken>()), Times.Once());
                this.loggerMock.Verify(x => x.Log(LogLevel.Information, It.IsAny<EventId>(), It.IsAny<It.IsAnyType>(), It.IsAny<Exception>(), It.IsAny<Func<It.IsAnyType, Exception, string>>()), Times.AtLeastOnce());
            }

            await this.VerifyTransferOwnershipScenariosAsync(existingTransferPackage);

            // Case: Standalone connection exception handled gracefully
            this.databaseSourceMock.Setup(x => x.OpenNewConnectionAsync(It.IsAny<CancellationToken>())).ThrowsAsync(new InvalidOperationException("Connection failed"));

            var connectionFailResult = await this.service.UpdateAsync(this.userContext, [updatedPackage1], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(connectionFailResult.IsError, Is.True);
                Assert.That(connectionFailResult.Errors[0].Description, Does.Contain("Connection failed"));
            }
        }

        private async Task VerifyTransferOwnershipScenariosAsync(IPackage existingTransferPackage)
        {
            // Case: Transfer with coordinate conflict in target scope
            var allowedTransferPackage = CreateValidPackage("existing-transfer");
            allowedTransferPackage.Id = existingTransferPackage.Id;
            allowedTransferPackage.Owner = this.userContext.AccountId!.Value;
            existingTransferPackage.PackageOwner = [this.userContext.AccountId.Value];
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(allowedTransferPackage.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create(existingTransferPackage));

            var conflictingTargetPackage = CreateValidPackage("existing-transfer");
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create<IPackage>(conflictingTargetPackage));

            var transferConflictResult = await this.service.UpdateAsync(this.userContext, null, [allowedTransferPackage], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(transferConflictResult.IsError, Is.True);
                Assert.That(transferConflictResult.FirstError.Code, Is.EqualTo(PackageService.CoordinateConflictCode));
            }

            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList<IPackage>.Empty);

            // Case: Transfer with scope resolved from Organization when Account returns empty
            var orgScopedPackage = CreateValidPackage("org-scoped");
            orgScopedPackage.Id = existingTransferPackage.Id;
            var mockOrg = new Mock<IOrganization>();
            mockOrg.SetupGet(x => x.ShortName).Returns("target-org");
            mockOrg.SetupGet(x => x.Administrator).Returns([this.userContext.AccountId.Value]);

            this.SetupTargetScope(orgScopedPackage.Owner, organization: mockOrg.Object);
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(orgScopedPackage.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create(existingTransferPackage));
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList<IPackage>.Empty);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), orgScopedPackage, It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);

            var orgTransferResult = await this.service.UpdateAsync(this.userContext, null, [orgScopedPackage], CancellationToken.None);
            Assert.That(orgTransferResult.IsError, Is.False);

            // Case: Transfer to unadministered organization without installation administrator is forbidden
            var unadministeredOrg = new Mock<IOrganization>();
            unadministeredOrg.SetupGet(x => x.ShortName).Returns("unadministered-org");
            unadministeredOrg.SetupGet(x => x.Administrator).Returns([Guid.NewGuid()]);

            var unadministeredOrgPackage = CreateValidPackage("unadministered-org-pkg");
            unadministeredOrgPackage.Id = existingTransferPackage.Id;

            this.SetupTargetScope(unadministeredOrgPackage.Owner, organization: unadministeredOrg.Object);
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(unadministeredOrgPackage.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create(existingTransferPackage));

            var unadministeredTransferResult = await this.service.UpdateAsync(this.userContext, null, [unadministeredOrgPackage], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(unadministeredTransferResult.IsError, Is.True);
                Assert.That(unadministeredTransferResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
            }

            // Case: Transfer to foreign account without installation administrator is forbidden
            var foreignAccount = new Mock<IAccount>();
            foreignAccount.SetupGet(x => x.Id).Returns(Guid.NewGuid());
            foreignAccount.SetupGet(x => x.ShortName).Returns("foreign-account");

            var foreignAccountPackage = CreateValidPackage("foreign-account-pkg");
            foreignAccountPackage.Id = existingTransferPackage.Id;

            this.SetupTargetScope(foreignAccountPackage.Owner, foreignAccount.Object);
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(foreignAccountPackage.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create(existingTransferPackage));
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList<IPackage>.Empty);

            var foreignAccountTransferResult = await this.service.UpdateAsync(this.userContext, null, [foreignAccountPackage], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(foreignAccountTransferResult.IsError, Is.True);
                Assert.That(foreignAccountTransferResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
            }

            // Case: Installation administrator can transfer unowned package to foreign account
            var adminUserContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "globalAdmin",
                CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator]
            };

            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(adminUserContext, existingTransferPackage, foreignAccountPackage, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), foreignAccountPackage, It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);

            var adminTransferResult = await this.service.UpdateAsync(adminUserContext, null, [foreignAccountPackage], CancellationToken.None);
            Assert.That(adminTransferResult.IsError, Is.False);

            // Case: Transfer when target scope cannot be resolved returns NotFound
            var missingScopePackage = CreateValidPackage("missing-scope-pkg");
            missingScopePackage.Id = existingTransferPackage.Id;

            this.SetupTargetScope(missingScopePackage.Owner);
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(missingScopePackage.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create(existingTransferPackage));

            var missingScopeResult = await this.service.UpdateAsync(this.userContext, null, [missingScopePackage], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(missingScopeResult.IsError, Is.True);
                Assert.That(missingScopeResult.FirstError.Type, Is.EqualTo(ErrorType.NotFound));
            }

            // Case: Transfer when coordinate check encounters database error returns failure
            var dbErrorPackage = CreateValidPackage("db-error-pkg");
            dbErrorPackage.Id = existingTransferPackage.Id;
            dbErrorPackage.Owner = this.userContext.AccountId.Value;

            var mockScope = new Mock<IAccount>();
            mockScope.SetupGet(x => x.Id).Returns(this.userContext.AccountId.Value);
            mockScope.SetupGet(x => x.ShortName).Returns("test-scope");

            this.SetupTargetScope(dbErrorPackage.Owner, mockScope.Object);
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(dbErrorPackage.Id)), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create(existingTransferPackage));
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.IsAny<ISqlFilter>())).ReturnsAsync(Error.Failure(description: "Coordinate check DB error"));

            var coordinateDbErrorResult = await this.service.UpdateAsync(this.userContext, null, [dbErrorPackage], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(coordinateDbErrorResult.IsError, Is.True);
                Assert.That(coordinateDbErrorResult.FirstError.Description, Is.EqualTo("Coordinate check DB error"));
            }
        }

