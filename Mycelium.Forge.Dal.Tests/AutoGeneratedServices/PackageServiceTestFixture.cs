            this.accountDaoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ((IEnumerable<Guid>)ids).Contains(ownerId)), null, null)).ReturnsAsync(account != null ? ImmutableList.Create(account) : ImmutableList<IAccount>.Empty);
