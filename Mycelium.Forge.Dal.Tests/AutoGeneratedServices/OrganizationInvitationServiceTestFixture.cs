        [Test]
        public async Task VerifyReadByTargetAsync()
        {
            var targetAccountId = Guid.NewGuid();
            var organizationId = Guid.NewGuid();
            var invitation1 = new OrganizationInvitation { Id = Guid.NewGuid(), Organization = organizationId, Target = targetAccountId, Owner = Guid.NewGuid(), Status = InvitationStatusKind.PENDING, OrganizationInvitationKind = OrganizationInvitationKind.MEMBER, CreatedAt = DateTime.UtcNow, ModifiedAt = DateTime.UtcNow, ExperiesAt = DateTime.UtcNow.AddDays(7) };
            var invitation2 = new OrganizationInvitation { Id = Guid.NewGuid(), Organization = organizationId, Target = targetAccountId, Owner = Guid.NewGuid(), Status = InvitationStatusKind.PENDING, OrganizationInvitationKind = OrganizationInvitationKind.MEMBER, CreatedAt = DateTime.UtcNow, ModifiedAt = DateTime.UtcNow, ExperiesAt = DateTime.UtcNow.AddDays(7) };

            // Case 1: Null user context throws ArgumentNullException
            Assert.That(async () => await this.service.ReadByTargetAsync(null, targetAccountId, CancellationToken.None), Throws.ArgumentNullException);

            // Case 2: Database connection failure handled gracefully
            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<ImmutableList<IOrganizationInvitation>>>>>(), It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure(description: "Database connection failed"));

            var connectionFailResult = await this.service.ReadByTargetAsync(this.userContext, targetAccountId, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(connectionFailResult.IsError, Is.True);
                Assert.That(connectionFailResult.FirstError.Description, Does.Contain("Database connection failed"));
            }

            // Case 3: DAO read failure returns error
            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<ImmutableList<IOrganizationInvitation>>>>>(), It.IsAny<CancellationToken>())).Returns<Func<NpgsqlTransaction, Task<ErrorOr<ImmutableList<IOrganizationInvitation>>>>, CancellationToken>((action, _) => action(null!));
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.Is<ISqlFilter>(f => MatchesTargetFilter(f, targetAccountId)))).ReturnsAsync(Error.Failure(description: "DAO read failed"));

            var daoFailResult = await this.service.ReadByTargetAsync(this.userContext, targetAccountId, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(daoFailResult.IsError, Is.True);
                Assert.That(daoFailResult.FirstError.Description, Is.EqualTo("DAO read failed"));
            }

            // Case 4: Permitted invitations filtered by target and permission service
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.Is<ISqlFilter>(f => MatchesTargetFilter(f, targetAccountId)))).ReturnsAsync(ImmutableList.Create<IOrganizationInvitation>(invitation1, invitation2));
            this.permissionServiceMock.Setup(x => x.IsAllowedToRead(this.userContext, invitation1, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.permissionServiceMock.Setup(x => x.IsAllowedToRead(this.userContext, invitation2, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Error.Forbidden(description: "Forbidden"));

            var successResult = await this.service.ReadByTargetAsync(this.userContext, targetAccountId, CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(successResult.IsError, Is.False);
                Assert.That(successResult.Value, Has.Count.EqualTo(1));
                Assert.That(successResult.Value[0].Id, Is.EqualTo(invitation1.Id));
                this.daoMock.Verify(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), null, null, It.Is<ISqlFilter>(f => MatchesTargetFilter(f, targetAccountId))), Times.AtLeastOnce());
                this.permissionServiceMock.Verify(x => x.IsAllowedToRead(this.userContext, invitation1, It.IsAny<NpgsqlTransaction>()), Times.Once());
                this.permissionServiceMock.Verify(x => x.IsAllowedToRead(this.userContext, invitation2, It.IsAny<NpgsqlTransaction>()), Times.Once());
            }
        }

        private static bool MatchesTargetFilter(ISqlFilter filter, Guid targetAccountId)
        {
            if (filter == null || !filter.ToSqlPredicate().Contains("\"OrganizationInvitation\".\"target\" = @targetAccountId"))
            {
                return false;
            }

            using var command = new NpgsqlCommand();
            filter.ApplyParameters(command);

            return command.Parameters.Contains("@targetAccountId") && command.Parameters["@targetAccountId"].Value is Guid value && value == targetAccountId;
        }
