        [Test]
        public async Task VerifyReadByShortNameAsync()
        {
            var shortNameProperty = nameof(IAccount.ShortName).ToLowerCaseFirst();
            var account1 = new Account { Id = Guid.NewGuid(), Name = "Alex", ShortName = "alex" };
            var account2 = new Account { Id = Guid.NewGuid(), Name = "Bob", ShortName = "bob" };
            string[] singleShortName = [account1.ShortName];
            string[] multipleShortNames = [account1.ShortName, account2.ShortName];
            string[] unknownShortNames = ["unknown"];

            using (Assert.EnterMultipleScope())
            {
                Assert.That(async () => await this.service.ReadByShortNameAsync(null, null, CancellationToken.None, singleShortName), Throws.ArgumentNullException);
                Assert.That(async () => await this.service.ReadByShortNameAsync(null, CancellationToken.None, singleShortName), Throws.ArgumentNullException);
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, singleShortName)))).ReturnsAsync(ImmutableList.Create<IAccount>(account1));
            this.permissionServiceMock.Setup(x => x.IsAllowedToRead(this.userContext, account1, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);

            var singleResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, singleShortName);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(singleResult.IsError, Is.False);
                Assert.That(singleResult.Value, Has.Count.EqualTo(1));
                Assert.That(singleResult.Value[0].Id, Is.EqualTo(account1.Id));
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, singleShortName))), Times.Once);
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, multipleShortNames)))).ReturnsAsync(ImmutableList.Create<IAccount>(account1, account2));
            this.permissionServiceMock.Setup(x => x.IsAllowedToRead(this.userContext, account2, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);

            var multiResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, multipleShortNames);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(multiResult.IsError, Is.False);
                Assert.That(multiResult.Value, Has.Count.EqualTo(2));
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, multipleShortNames))), Times.Once);
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => f != null && !f.ToSqlPredicate().Contains("ANY(@values)")))).ReturnsAsync(ImmutableList<IAccount>.Empty);

            var nullResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None);
            var emptyResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, []);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullResult.IsError, Is.False);
                Assert.That(emptyResult.IsError, Is.False);
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => f != null && !f.ToSqlPredicate().Contains("ANY(@values)"))), Times.Exactly(2));
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, unknownShortNames)))).ReturnsAsync(ImmutableList<IAccount>.Empty);

            var notFoundResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, unknownShortNames);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(notFoundResult.IsError, Is.False);
                Assert.That(notFoundResult.Value, Is.Empty);
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, unknownShortNames))), Times.Once);
            }

            this.databaseSourceMock.Setup(x => x.OpenNewConnectionAsync(It.IsAny<CancellationToken>())).ThrowsAsync(new InvalidOperationException("Connection failed"));

            var connectionFailResult = await this.service.ReadByShortNameAsync(this.userContext, CancellationToken.None, singleShortName);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(connectionFailResult.IsError, Is.True);
                Assert.That(connectionFailResult.Errors[0].Description, Does.Contain("Connection failed"));
            }
        }

        [Test]
        public async Task VerifyUpdateAndSyncAsync()
        {
            var existingAccount = CreateValidAccount("Alex Rivera", "alex@example.com");
            var websiteChanged = existingAccount.Clone();
            websiteChanged.Website = "https://updated.example.com";

            // Case 1: Null arguments throw ArgumentNullException
            using (Assert.EnterMultipleScope())
            {
                Assert.That(async () => await this.service.UpdateAndSyncAsync(null, [websiteChanged], CancellationToken.None), Throws.ArgumentNullException);
                Assert.That(async () => await this.service.UpdateAndSyncAsync(this.userContext, null, CancellationToken.None), Throws.ArgumentNullException);
            }

            // Case 2: Empty collection returns Result.Updated without opening transaction
            var emptyResult = await this.service.UpdateAndSyncAsync(this.userContext, [], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(emptyResult.IsError, Is.False);
                this.databaseSourceMock.Verify(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Updated>>>>(), It.IsAny<CancellationToken>()), Times.Never());
            }

            this.databaseSourceMock.Setup(x => x.ExecuteInTransactionAsync(It.IsAny<Func<NpgsqlTransaction, Task<ErrorOr<Updated>>>>(), It.IsAny<CancellationToken>())).Returns<Func<NpgsqlTransaction, Task<ErrorOr<Updated>>>, CancellationToken>((action, _) => action(null!));

            // Case 2b: Dao.ReadAsync error returns error before UpdateAsync
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == existingAccount.Id), null, It.IsAny<ISqlFilter>())).ReturnsAsync(Error.Failure(description: "DAO read error"));

            var readErrorResult = await this.service.UpdateAndSyncAsync(this.userContext, [websiteChanged], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(readErrorResult.IsError, Is.True);
                Assert.That(readErrorResult.FirstError.Description, Is.EqualTo("DAO read error"));
                this.accountSyncHandlerMock.Verify(x => x.SyncAccountAsync(It.IsAny<IAccount>(), It.IsAny<IAccount>(), It.IsAny<CancellationToken>()), Times.Never());
            }

            // Case 2c: UpdateAsync error returns error before SyncAccountAsync
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == existingAccount.Id), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create<IAccount>(existingAccount));
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingAccount, websiteChanged, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), websiteChanged, It.IsAny<CancellationToken>())).ReturnsAsync(Error.Failure(description: "DAO update error"));

            var updateErrorResult = await this.service.UpdateAndSyncAsync(this.userContext, [websiteChanged], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(updateErrorResult.IsError, Is.True);
                Assert.That(updateErrorResult.FirstError.Description, Is.EqualTo("DAO update error"));
                this.accountSyncHandlerMock.Verify(x => x.SyncAccountAsync(It.IsAny<IAccount>(), It.IsAny<IAccount>(), It.IsAny<CancellationToken>()), Times.Never());
            }

            // Case 3: Non-synced property change skips SyncAccountAsync
            this.daoMock.Setup(x => x.ReadAsync(It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == existingAccount.Id), null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create<IAccount>(existingAccount));
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingAccount, websiteChanged, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), websiteChanged, It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);

            var websiteResult = await this.service.UpdateAndSyncAsync(this.userContext, [websiteChanged], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(websiteResult.IsError, Is.False);
                this.accountSyncHandlerMock.Verify(x => x.SyncAccountAsync(It.IsAny<IAccount>(), It.IsAny<IAccount>(), It.IsAny<CancellationToken>()), Times.Never());
            }

            // Case 4: Name change triggers SyncAccountAsync and commits
            var nameChanged = existingAccount.Clone();
            nameChanged.Name = "Alex Updated";
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingAccount, nameChanged, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), nameChanged, It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);
            this.accountSyncHandlerMock.Setup(x => x.SyncAccountAsync(existingAccount, nameChanged, CancellationToken.None)).ReturnsAsync(Result.Success);

            var nameResult = await this.service.UpdateAndSyncAsync(this.userContext, [nameChanged], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nameResult.IsError, Is.False);
                this.accountSyncHandlerMock.Verify(x => x.SyncAccountAsync(existingAccount, nameChanged, CancellationToken.None), Times.Once());
            }

            // Case 5: Email change triggers SyncAccountAsync and commits
            var emailChanged = existingAccount.Clone();
            emailChanged.Email = "new@example.com";
            this.permissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.userContext, existingAccount, emailChanged, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);
            this.daoMock.Setup(x => x.UpdateAsync(It.IsAny<NpgsqlTransaction>(), emailChanged, It.IsAny<CancellationToken>())).ReturnsAsync(Result.Updated);
            this.accountSyncHandlerMock.Setup(x => x.SyncAccountAsync(existingAccount, emailChanged, CancellationToken.None)).ReturnsAsync(Result.Success);

            var emailResult = await this.service.UpdateAndSyncAsync(this.userContext, [emailChanged], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(emailResult.IsError, Is.False);
                this.accountSyncHandlerMock.Verify(x => x.SyncAccountAsync(existingAccount, emailChanged, CancellationToken.None), Times.Once());
            }

            // Case 6: SyncAccountAsync error propagates (causing ExecuteInTransactionAsync to roll back)
            this.accountSyncHandlerMock.Setup(x => x.SyncAccountAsync(existingAccount, nameChanged, CancellationToken.None)).ReturnsAsync(Error.Failure("Keycloak.SyncFailed", "Sync failed"));

            var syncErrorResult = await this.service.UpdateAndSyncAsync(this.userContext, [nameChanged], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(syncErrorResult.IsError, Is.True);
                Assert.That(syncErrorResult.FirstError.Code, Is.EqualTo("Keycloak.SyncFailed"));
            }

            // Case 7: Null accountSyncHandler skips sync cleanly
            var serviceWithoutHandler = new AccountService(this.daoMock.Object, this.dtoValidator, this.permissionServiceMock.Object, this.dtoComparer, this.loggerMock.Object, this.databaseSourceMock.Object, this.readFilter);

            var noHandlerResult = await serviceWithoutHandler.UpdateAndSyncAsync(this.userContext, [nameChanged], CancellationToken.None);

            Assert.That(noHandlerResult.IsError, Is.False);
        }

        private static Account CreateValidAccount(string name, string email)
