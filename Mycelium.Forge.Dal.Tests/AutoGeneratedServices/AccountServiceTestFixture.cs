namespace Mycelium.Forge.Dal.Tests.AutoGeneratedServices
{
    using System.Collections.Immutable;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.AutoGenDtoComparer;
    using Mycelium.Forge.Common.Extensions;
    using Mycelium.Forge.Dal.AutoGenDtoValidator;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Orm.AutoGeneratedDao;
    using Mycelium.Forge.Orm.AutoGeneratedFilters;
    using Mycelium.Forge.Orm.Filters;

    using Npgsql;

    using NUnit.Framework;

    [TestFixture]
    public class AccountServiceTestFixture
    {
        private Mock<IAccountDao> daoMock;
        private AccountValidator dtoValidator;
        private Mock<IAccountPermissionService> permissionServiceMock;
        private AccountComparer dtoComparer;
        private Mock<IDatabaseSource> databaseSourceMock;
        private Mock<ILogger<AccountService>> loggerMock;
        private AccountReadFilter readFilter;
        private AccountService service;
        private IUserContext userContext;

        [SetUp]
        public void SetUp()
        {
            this.daoMock = new Mock<IAccountDao>();
            this.dtoValidator = new AccountValidator();
            this.permissionServiceMock = new Mock<IAccountPermissionService>();
            this.dtoComparer = new AccountComparer();
            this.databaseSourceMock = new Mock<IDatabaseSource>();
            this.loggerMock = new Mock<ILogger<AccountService>>();
            this.loggerMock.Setup(x => x.IsEnabled(It.IsAny<LogLevel>())).Returns(true);
            this.readFilter = new AccountReadFilter();

            this.service = new AccountService(this.daoMock.Object, this.dtoValidator, this.permissionServiceMock.Object, this.dtoComparer, this.loggerMock.Object, this.databaseSourceMock.Object, this.readFilter);

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "testUser",
                CurrentRoles = [RoleKind.Account]
            };
        }

        [Test]
        public void VerifyConstructor()
        {
            var instance = new AccountService(this.daoMock.Object, this.dtoValidator, this.permissionServiceMock.Object, this.dtoComparer, this.loggerMock.Object, this.databaseSourceMock.Object, this.readFilter);

            Assert.That(instance, Is.Not.Null);
        }

        [Test]
        public async Task VerifyReadByShortNameAsync()
        {
            var shortNameProperty = nameof(IAccount.ShortName).ToLowerCaseFirst();
            var account1 = new Account { Id = Guid.NewGuid(), Name = "Alex", ShortName = "alex" };
            var account2 = new Account { Id = Guid.NewGuid(), Name = "Bob", ShortName = "bob" };

            using (Assert.EnterMultipleScope())
            {
                Assert.That(async () => await this.service.ReadByShortNameAsync(null, null, CancellationToken.None, ["alex"]), Throws.ArgumentNullException);
                Assert.That(async () => await this.service.ReadByShortNameAsync(null, CancellationToken.None, ["alex"]), Throws.ArgumentNullException);
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, new[] { "alex" })))).ReturnsAsync(ImmutableList.Create<IAccount>(account1));
            this.permissionServiceMock.Setup(x => x.IsAllowedToRead(this.userContext, account1, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);

            var singleResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, ["alex"]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(singleResult.IsError, Is.False);
                Assert.That(singleResult.Value, Has.Count.EqualTo(1));
                Assert.That(singleResult.Value[0].Id, Is.EqualTo(account1.Id));
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, new[] { "alex" }))), Times.Once);
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, new[] { "alex", "bob" })))).ReturnsAsync(ImmutableList.Create<IAccount>(account1, account2));
            this.permissionServiceMock.Setup(x => x.IsAllowedToRead(this.userContext, account2, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);

            var multiResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, ["alex", "bob"]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(multiResult.IsError, Is.False);
                Assert.That(multiResult.Value, Has.Count.EqualTo(2));
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, new[] { "alex", "bob" }))), Times.Once);
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => f != null && !f.ToSqlPredicate().Contains("ANY(@values)")))).ReturnsAsync(ImmutableList<IAccount>.Empty);

            var nullResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None);
            var emptyResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, []);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullResult.IsError, Is.False);
                Assert.That(emptyResult.IsError, Is.False);
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => f != null && !f.ToSqlPredicate().Contains("ANY(@values)"))), Times.Exactly(2));
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, new[] { "unknown" })))).ReturnsAsync(ImmutableList<IAccount>.Empty);

            var notFoundResult = await this.service.ReadByShortNameAsync(this.userContext, null, CancellationToken.None, ["unknown"]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(notFoundResult.IsError, Is.False);
                Assert.That(notFoundResult.Value, Is.Empty);
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.Is<ISqlFilter>(f => MatchesIndexFilter(f, shortNameProperty, new[] { "unknown" }))), Times.Once);
            }

            this.databaseSourceMock.Setup(x => x.OpenNewConnectionAsync(It.IsAny<CancellationToken>())).ThrowsAsync(new InvalidOperationException("Connection failed"));

            var connectionFailResult = await this.service.ReadByShortNameAsync(this.userContext, CancellationToken.None, ["alex"]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(connectionFailResult.IsError, Is.True);
                Assert.That(connectionFailResult.Errors[0].Description, Does.Contain("Connection failed"));
            }
        }

        private static bool MatchesIndexFilter(ISqlFilter filter, string propertyName, string[] expectedValues)
        {
            if (filter == null || !filter.ToSqlPredicate().Contains($"\"Thing\".\"data\"->>'{propertyName}' = ANY(@values)"))
            {
                return false;
            }

            using var command = new NpgsqlCommand();
            filter.ApplyParameters(command);

            return command.Parameters.Contains("@values") &&
                   command.Parameters["@values"].Value is string[] values &&
                   values.SequenceEqual(expectedValues);
        }
    }
}
