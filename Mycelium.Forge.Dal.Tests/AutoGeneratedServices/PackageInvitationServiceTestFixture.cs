        private static bool MatchesPackageFilter(ISqlFilter filter, Guid packageId)
        {
            if (filter == null || !filter.ToSqlPredicate().Contains("package_invitation.package = @packageId"))
            {
                return false;
            }

            using var command = new NpgsqlCommand();
            filter.ApplyParameters(command);

            return command.Parameters.Contains("@packageId") && command.Parameters["@packageId"].Value is Guid value && value == packageId;
        }

        private static bool MatchesTargetFilter(ISqlFilter filter, Guid targetAccountId)
        {
            if (filter == null || !filter.ToSqlPredicate().Contains("package_invitation.target = @targetAccountId"))
            {
                return false;
            }

            using var command = new NpgsqlCommand();
            filter.ApplyParameters(command);

            return command.Parameters.Contains("@targetAccountId") && command.Parameters["@targetAccountId"].Value is Guid value && value == targetAccountId;
        }
