namespace Mycelium.Forge.Dal.Tests.AutoGeneratedServices
{
    using System.Collections.Immutable;

    using ErrorOr;

    using Microsoft.Extensions.Logging;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Common.AutoGenDtoComparer;
    using Mycelium.Forge.Dal.AutoGenDtoValidator;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;
    using Mycelium.Forge.Dal.DatabaseSource;
    using Mycelium.Forge.Orm.AutoGeneratedDao;
    using Mycelium.Forge.Orm.AutoGeneratedFilters;
    using Mycelium.Forge.Orm.Filters;

    using Npgsql;

    using NUnit.Framework;

    [TestFixture]
    public class APIKeyServiceTestFixture
    {
        private Mock<IAPIKeyDao> daoMock;
        private APIKeyValidator dtoValidator;
        private Mock<IAPIKeyPermissionService> permissionServiceMock;
        private APIKeyComparer dtoComparer;
        private Mock<IDatabaseSource> databaseSourceMock;
        private Mock<ILogger<APIKeyService>> loggerMock;
        private APIKeyReadFilter readFilter;
        private APIKeyService service;
        private UserContext userContext;

        [SetUp]
        public void SetUp()
        {
            this.daoMock = new Mock<IAPIKeyDao>();
            this.dtoValidator = new APIKeyValidator();
            this.permissionServiceMock = new Mock<IAPIKeyPermissionService>();
            this.dtoComparer = new APIKeyComparer();
            this.databaseSourceMock = new Mock<IDatabaseSource>();
            this.loggerMock = new Mock<ILogger<APIKeyService>>();
            this.loggerMock.Setup(x => x.IsEnabled(It.IsAny<LogLevel>())).Returns(true);
            this.readFilter = new APIKeyReadFilter();

            this.service = new APIKeyService(this.daoMock.Object, this.dtoValidator, this.permissionServiceMock.Object, this.dtoComparer, this.loggerMock.Object, this.databaseSourceMock.Object, this.readFilter);

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "testUser",
                CurrentRoles = [RoleKind.Account]
            };
        }

        [Test]
        public void VerifyConstructor()
        {
            var instance = new APIKeyService(this.daoMock.Object, this.dtoValidator, this.permissionServiceMock.Object, this.dtoComparer, this.loggerMock.Object, this.databaseSourceMock.Object, this.readFilter);

            Assert.That(instance, Is.Not.Null);
        }

        [Test]
        public async Task VerifyReadByExpiresAtAsync()
        {
            var expiryDate = new DateTime(2026, 12, 31, 23, 59, 59, DateTimeKind.Utc);

            var apiKey = new APIKey
            {
                Id = Guid.NewGuid(),
                Name = "CI-Token",
                ExpiresAt = expiryDate,
                Owner = this.userContext.AccountId!.Value
            };

            using (Assert.EnterMultipleScope())
            {
                Assert.That(async () => await this.service.ReadByExpiresAtAsync(null, null, CancellationToken.None, [expiryDate]), Throws.ArgumentNullException);
                Assert.That(async () => await this.service.ReadByExpiresAtAsync(null, CancellationToken.None, [expiryDate]), Throws.ArgumentNullException);
            }

            this.daoMock.Setup(x => x.ReadAsync(null, CancellationToken.None, null, null, It.IsAny<ISqlFilter>())).ReturnsAsync(ImmutableList.Create<IAPIKey>(apiKey));
            this.permissionServiceMock.Setup(x => x.IsAllowedToRead(this.userContext, apiKey, It.IsAny<NpgsqlTransaction>())).ReturnsAsync(Result.Success);

            var singleResult = await this.service.ReadByExpiresAtAsync(this.userContext, null, CancellationToken.None, [expiryDate]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(singleResult.IsError, Is.False);
                Assert.That(singleResult.Value, Has.Count.EqualTo(1));
                Assert.That(singleResult.Value[0].Id, Is.EqualTo(apiKey.Id));
                this.daoMock.Verify(x => x.ReadAsync(null, CancellationToken.None, null, null, It.IsAny<ISqlFilter>()), Times.Once);
            }
        }
    }
}
