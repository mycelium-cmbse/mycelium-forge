namespace Mycelium.Forge.Dal.Tests.AutoGenPermissionService
{
    using System.Collections.Immutable;

    using FluentResults;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;

    using NUnit.Framework;

    /// <summary>
    /// Test fixture for <see cref="PackageVersionPermissionService" />.
    /// </summary>
    [TestFixture]
    public class PackageVersionPermissionServiceTestFixture
    {
        /// <summary>
        /// The mock package service.
        /// </summary>
        private Mock<IPackageService> packageServiceMock;

        /// <summary>
        /// The mock package permission service.
        /// </summary>
        private Mock<IPackagePermissionService> packagePermissionServiceMock;

        /// <summary>
        /// The permission service under test.
        /// </summary>
        private PackageVersionPermissionService permissionService;

        /// <summary>
        /// The test account identifier.
        /// </summary>
        private Guid userId;

        /// <summary>
        /// A second test account identifier.
        /// </summary>
        private Guid otherUserId;

        /// <summary>
        /// The test package identifier.
        /// </summary>
        private Guid packageId;

        /// <summary>
        /// The user context for the package owner.
        /// </summary>
        private UserContext ownerUserContext;

        /// <summary>
        /// The user context for another account user.
        /// </summary>
        private UserContext otherUserContext;

        /// <summary>
        /// The user context for an installation administrator.
        /// </summary>
        private UserContext adminUserContext;

        /// <summary>
        /// The user context for an unauthenticated user.
        /// </summary>
        private UserContext anonymousUserContext;

        /// <summary>
        /// Sets up mock dependencies and test context before each test.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.packageServiceMock = new Mock<IPackageService>();
            this.packagePermissionServiceMock = new Mock<IPackagePermissionService>();

            this.permissionService = new PackageVersionPermissionService(
                this.packageServiceMock.Object,
                this.packagePermissionServiceMock.Object);

            this.userId = Guid.NewGuid();
            this.otherUserId = Guid.NewGuid();
            this.packageId = Guid.NewGuid();

            this.ownerUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "ownerUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.otherUserContext = new UserContext
            {
                AccountId = this.otherUserId,
                Username = "otherUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.adminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "adminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator]
            };

            this.anonymousUserContext = new UserContext
            {
                AccountId = null,
                Username = string.Empty,
                CurrentRoles = [RoleKind.Anonymous]
            };
        }

        /// <summary>
        /// Verifies the <see cref="PackageVersionPermissionService.IsAllowedToCreate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToCreate()
        {
            var version = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Owner = this.packageId,
                Version = "1.0.0",
                Listed = true
            };

            var package = new Package
            {
                Id = this.packageId,
                Owner = this.userId,
                PackageOwner = [this.userId],
                PackageMaintainer = []
            };

            this.packageServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(Result.Ok(ImmutableList.Create<IPackage>(package)));

            var unauthResult = await this.permissionService.IsAllowedToCreate(this.anonymousUserContext, version);
            var otherResult = await this.permissionService.IsAllowedToCreate(this.otherUserContext, version);
            var ownerResult = await this.permissionService.IsAllowedToCreate(this.ownerUserContext, version);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(unauthResult.IsFailed, Is.True);
                Assert.That(otherResult.IsFailed, Is.True);
                Assert.That(ownerResult.IsSuccess, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="PackageVersionPermissionService.IsAllowedToDelete" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToDelete()
        {
            var version = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Owner = this.packageId
            };

            this.packageServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(Result.Ok(ImmutableList<IPackage>.Empty));

            var adminResult = await this.permissionService.IsAllowedToDelete(this.adminUserContext, version);
            var ownerResult = await this.permissionService.IsAllowedToDelete(this.ownerUserContext, version);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(adminResult.IsSuccess, Is.True);
                Assert.That(ownerResult.IsFailed, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="PackageVersionPermissionService.IsAllowedToRead" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToRead()
        {
            var version = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Owner = this.packageId,
                Version = "1.0.0"
            };

            var package = new Package
            {
                Id = this.packageId,
                Owner = this.userId,
                Visibility = VisibilityKind.PUBLIC
            };

            this.packageServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(Result.Ok(ImmutableList.Create<IPackage>(package)));

            this.packagePermissionServiceMock.Setup(x => x.IsAllowedToRead(
                    It.IsAny<IUserContext>(),
                    It.IsAny<IPackage>()))
                .ReturnsAsync(Result.Ok());

            var readResult = await this.permissionService.IsAllowedToRead(this.ownerUserContext, version);

            Assert.That(readResult.IsSuccess, Is.True);
        }

        /// <summary>
        /// Verifies the <see cref="PackageVersionPermissionService.IsAllowedToUpdate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToUpdate()
        {
            var existingVersion = new PackageVersion
            {
                Id = Guid.NewGuid(),
                Owner = this.packageId,
                Version = "1.0.0",
                Listed = true
            };

            var unlistedVersion = new PackageVersion
            {
                Id = existingVersion.Id,
                Owner = this.packageId,
                Version = "1.0.0",
                Listed = false
            };

            var immutableBreachVersion = new PackageVersion
            {
                Id = existingVersion.Id,
                Owner = this.packageId,
                Version = "1.0.1",
                Listed = true
            };

            var package = new Package
            {
                Id = this.packageId,
                Owner = this.userId,
                PackageOwner = [this.userId]
            };

            this.packageServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(Result.Ok(ImmutableList.Create<IPackage>(package)));

            var immutableResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingVersion, immutableBreachVersion);
            var unlistResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingVersion, unlistedVersion);
            var otherResult = await this.permissionService.IsAllowedToUpdate(this.otherUserContext, existingVersion, unlistedVersion);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(immutableResult.IsFailed, Is.True);
                Assert.That(unlistResult.IsSuccess, Is.True);
                Assert.That(otherResult.IsFailed, Is.True);
            }
        }
    }
}
