namespace Mycelium.Forge.Dal.Tests.AutoGenPermissionService
{
    using System.Collections.Immutable;

    using ErrorOr;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;

    using Npgsql;

    using NUnit.Framework;

    [TestFixture]
    public class PackageMetaDataPermissionServiceTestFixture
    {
        private Mock<IPackageVersionService> packageVersionServiceMock;
        private Mock<IPackageVersionPermissionService> packageVersionPermissionServiceMock;
        private PackageMetaDataPermissionService permissionService;
        private NpgsqlTransaction transaction;
        private Guid userId;
        private Guid versionId;
        private UserContext accountUserContext;
        private UserContext operatorUserContext;
        private UserContext nonOwnerAdminUserContext;
        private UserContext anonymousUserContext;

        [SetUp]
        public void SetUp()
        {
            this.transaction = null;
            this.packageVersionServiceMock = new Mock<IPackageVersionService>();
            this.packageVersionPermissionServiceMock = new Mock<IPackageVersionPermissionService>();
            this.permissionService = new PackageMetaDataPermissionService(this.packageVersionServiceMock.Object, this.packageVersionPermissionServiceMock.Object);

            this.userId = Guid.NewGuid();
            this.versionId = Guid.NewGuid();

            this.accountUserContext = new UserContext { AccountId = this.userId, Username = "accountUser", CurrentRoles = [RoleKind.Account] };
            this.operatorUserContext = new UserContext { AccountId = this.userId, Username = "operatorUser", CurrentRoles = [RoleKind.PlatformOperator] };
            this.nonOwnerAdminUserContext = new UserContext { AccountId = Guid.NewGuid(), Username = "nonOwnerAdmin", CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator] };
            this.anonymousUserContext = new UserContext { AccountId = null, Username = string.Empty, CurrentRoles = [RoleKind.Anonymous] };
        }

        [Test]
        public async Task VerifyIsAllowedToCreate()
        {
            var metaData = new PackageMetaData { Id = Guid.NewGuid(), Owner = this.versionId };
            var version = new PackageVersion { Id = this.versionId, Owner = Guid.NewGuid() };

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.accountUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList.Create<IPackageVersion>(version));
            this.packageVersionPermissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.accountUserContext, version, version, this.transaction)).ReturnsAsync(Result.Success);

            var unauthResult = await this.permissionService.IsAllowedToCreate(this.anonymousUserContext, metaData, this.transaction);
            var operatorResult = await this.permissionService.IsAllowedToCreate(this.operatorUserContext, metaData, this.transaction);
            var accountResult = await this.permissionService.IsAllowedToCreate(this.accountUserContext, metaData, this.transaction);

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.accountUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList<IPackageVersion>.Empty);
            var missingParentResult = await this.permissionService.IsAllowedToCreate(this.accountUserContext, metaData, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(unauthResult.IsError, Is.True);
                Assert.That(unauthResult.FirstError.Type, Is.EqualTo(ErrorType.Unauthorized));
                Assert.That(operatorResult.IsError, Is.True);
                Assert.That(operatorResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
                Assert.That(accountResult.IsError, Is.False);
                Assert.That(missingParentResult.IsError, Is.True);
                Assert.That(missingParentResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
            }
        }

        [Test]
        public async Task VerifyIsAllowedToDelete()
        {
            var metaData = new PackageMetaData { Id = Guid.NewGuid(), Owner = this.versionId };
            var version = new PackageVersion { Id = this.versionId, Owner = Guid.NewGuid() };

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.nonOwnerAdminUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList.Create<IPackageVersion>(version));
            this.packageVersionPermissionServiceMock.Setup(x => x.IsAllowedToDelete(this.nonOwnerAdminUserContext, version, this.transaction)).ReturnsAsync(Result.Success);

            var unauthResult = await this.permissionService.IsAllowedToDelete(this.anonymousUserContext, metaData, this.transaction);
            var accountResult = await this.permissionService.IsAllowedToDelete(this.accountUserContext, metaData, this.transaction);
            var adminResult = await this.permissionService.IsAllowedToDelete(this.nonOwnerAdminUserContext, metaData, this.transaction);

            this.packageVersionPermissionServiceMock.Setup(x => x.IsAllowedToDelete(this.nonOwnerAdminUserContext, version, this.transaction)).ReturnsAsync(Error.Forbidden(description: "Parent delete denied"));
            var parentDeniedResult = await this.permissionService.IsAllowedToDelete(this.nonOwnerAdminUserContext, metaData, this.transaction);

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.nonOwnerAdminUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList<IPackageVersion>.Empty);
            var missingParentResult = await this.permissionService.IsAllowedToDelete(this.nonOwnerAdminUserContext, metaData, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(unauthResult.IsError, Is.True);
                Assert.That(unauthResult.FirstError.Type, Is.EqualTo(ErrorType.Unauthorized));
                Assert.That(accountResult.IsError, Is.True);
                Assert.That(accountResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
                Assert.That(adminResult.IsError, Is.False);
                Assert.That(parentDeniedResult.IsError, Is.True);
                Assert.That(parentDeniedResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
                Assert.That(missingParentResult.IsError, Is.True);
                Assert.That(missingParentResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
                this.packageVersionPermissionServiceMock.Verify(x => x.IsAllowedToDelete(this.nonOwnerAdminUserContext, version, this.transaction), Times.Exactly(2));
            }
        }

        [Test]
        public async Task VerifyIsAllowedToRead()
        {
            var metaData = new PackageMetaData { Id = Guid.NewGuid(), Owner = this.versionId };
            var version = new PackageVersion { Id = this.versionId, Owner = Guid.NewGuid() };

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.accountUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList.Create<IPackageVersion>(version));
            var permittedResult = await this.permissionService.IsAllowedToRead(this.accountUserContext, metaData, this.transaction);

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.accountUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList<IPackageVersion>.Empty);
            var deniedResult = await this.permissionService.IsAllowedToRead(this.accountUserContext, metaData, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(permittedResult.IsError, Is.False);
                Assert.That(deniedResult.IsError, Is.True);
                Assert.That(deniedResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
            }
        }

        [Test]
        public async Task VerifyIsAllowedToUpdate()
        {
            var existingMetaData = new PackageMetaData { Id = Guid.NewGuid(), Owner = this.versionId };
            var updatedMetaData = new PackageMetaData { Id = existingMetaData.Id, Owner = this.versionId };
            var version = new PackageVersion { Id = this.versionId, Owner = Guid.NewGuid() };

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.accountUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList.Create<IPackageVersion>(version));
            this.packageVersionPermissionServiceMock.Setup(x => x.IsAllowedToUpdate(this.accountUserContext, version, version, this.transaction)).ReturnsAsync(Result.Success);

            var unauthResult = await this.permissionService.IsAllowedToUpdate(this.anonymousUserContext, existingMetaData, updatedMetaData, this.transaction);
            var accountResult = await this.permissionService.IsAllowedToUpdate(this.accountUserContext, existingMetaData, updatedMetaData, this.transaction);

            this.packageVersionServiceMock.Setup(x => x.ReadAsync(this.accountUserContext, this.transaction, CancellationToken.None, It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == this.versionId))).ReturnsAsync(ImmutableList<IPackageVersion>.Empty);
            var missingParentResult = await this.permissionService.IsAllowedToUpdate(this.accountUserContext, existingMetaData, updatedMetaData, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(unauthResult.IsError, Is.True);
                Assert.That(unauthResult.FirstError.Type, Is.EqualTo(ErrorType.Unauthorized));
                Assert.That(accountResult.IsError, Is.False);
                Assert.That(missingParentResult.IsError, Is.True);
                Assert.That(missingParentResult.FirstError.Type, Is.EqualTo(ErrorType.Forbidden));
            }
        }
    }
}
