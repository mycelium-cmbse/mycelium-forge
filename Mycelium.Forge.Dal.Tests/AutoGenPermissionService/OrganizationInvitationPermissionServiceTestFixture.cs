namespace Mycelium.Forge.Dal.Tests.AutoGenPermissionService
{
    using System.Collections.Immutable;

    using FluentResults;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;

    using NUnit.Framework;

    /// <summary>
    /// Test fixture for <see cref="OrganizationInvitationPermissionService" />.
    /// </summary>
    [TestFixture]
    public class OrganizationInvitationPermissionServiceTestFixture
    {
        /// <summary>
        /// The mock organization service.
        /// </summary>
        private Mock<IOrganizationService> organizationServiceMock;

        /// <summary>
        /// The permission service under test.
        /// </summary>
        private OrganizationInvitationPermissionService permissionService;

        /// <summary>
        /// The test account identifier.
        /// </summary>
        private Guid userId;

        /// <summary>
        /// A second test account identifier.
        /// </summary>
        private Guid otherUserId;

        /// <summary>
        /// The test organization identifier.
        /// </summary>
        private Guid organizationId;

        /// <summary>
        /// The user context for the organization administrator.
        /// </summary>
        private UserContext orgAdminUserContext;

        /// <summary>
        /// The user context for an invited account user.
        /// </summary>
        private UserContext targetUserContext;

        /// <summary>
        /// The user context for a third-party account user.
        /// </summary>
        private UserContext thirdPartyUserContext;

        /// <summary>
        /// The user context for an installation administrator.
        /// </summary>
        private UserContext adminUserContext;

        /// <summary>
        /// The user context for an unauthenticated user.
        /// </summary>
        private UserContext anonymousUserContext;

        /// <summary>
        /// Sets up mock dependencies and test context before each test.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.organizationServiceMock = new Mock<IOrganizationService>();
            this.permissionService = new OrganizationInvitationPermissionService(this.organizationServiceMock.Object);

            this.userId = Guid.NewGuid();
            this.otherUserId = Guid.NewGuid();
            this.organizationId = Guid.NewGuid();

            this.orgAdminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "orgAdminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationAdministrator]
            };

            this.targetUserContext = new UserContext
            {
                AccountId = this.otherUserId,
                Username = "targetUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.thirdPartyUserContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "thirdPartyUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.adminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "adminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator]
            };

            this.anonymousUserContext = new UserContext
            {
                AccountId = null,
                Username = string.Empty,
                CurrentRoles = [RoleKind.Anonymous]
            };
        }

        /// <summary>
        /// Verifies the <see cref="OrganizationInvitationPermissionService.IsAllowedToCreate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToCreate()
        {
            var org = new Organization
            {
                Id = this.organizationId,
                Administrator = [this.userId],
                Member = [this.userId]
            };

            var invitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Owner = this.organizationId,
                Target = this.otherUserId
            };

            this.organizationServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(Result.Ok(ImmutableList.Create<IOrganization>(org)));

            var nullResult = await this.permissionService.IsAllowedToCreate(this.orgAdminUserContext, null);
            var unauthResult = await this.permissionService.IsAllowedToCreate(this.anonymousUserContext, invitation);
            var targetResult = await this.permissionService.IsAllowedToCreate(this.targetUserContext, invitation);
            var adminResult = await this.permissionService.IsAllowedToCreate(this.orgAdminUserContext, invitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullResult.IsFailed, Is.True);
                Assert.That(unauthResult.IsFailed, Is.True);
                Assert.That(targetResult.IsFailed, Is.True);
                Assert.That(adminResult.IsSuccess, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="OrganizationInvitationPermissionService.IsAllowedToRead" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToRead()
        {
            var invitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                Target = this.otherUserId
            };

            var nullResult = await this.permissionService.IsAllowedToRead(this.orgAdminUserContext, null);
            var ownerResult = await this.permissionService.IsAllowedToRead(this.orgAdminUserContext, invitation);
            var targetResult = await this.permissionService.IsAllowedToRead(this.targetUserContext, invitation);
            var thirdPartyResult = await this.permissionService.IsAllowedToRead(this.thirdPartyUserContext, invitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullResult.IsFailed, Is.True);
                Assert.That(ownerResult.IsSuccess, Is.True);
                Assert.That(targetResult.IsSuccess, Is.True);
                Assert.That(thirdPartyResult.IsFailed, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="OrganizationInvitationPermissionService.IsAllowedToUpdate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToUpdate()
        {
            var existingInvitation = new OrganizationInvitation
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                Target = this.otherUserId
            };

            var updatedInvitation = new OrganizationInvitation
            {
                Id = existingInvitation.Id,
                Owner = this.userId,
                Target = this.otherUserId
            };

            var nullExistingResult = await this.permissionService.IsAllowedToUpdate(this.targetUserContext, null, updatedInvitation);
            var nullUpdatedResult = await this.permissionService.IsAllowedToUpdate(this.targetUserContext, existingInvitation, null);
            var targetResult = await this.permissionService.IsAllowedToUpdate(this.targetUserContext, existingInvitation, updatedInvitation);
            var creatorResult = await this.permissionService.IsAllowedToUpdate(this.orgAdminUserContext, existingInvitation, updatedInvitation);
            var thirdPartyResult = await this.permissionService.IsAllowedToUpdate(this.thirdPartyUserContext, existingInvitation, updatedInvitation);
            var adminResult = await this.permissionService.IsAllowedToUpdate(this.adminUserContext, existingInvitation, updatedInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullExistingResult.IsFailed, Is.True);
                Assert.That(nullUpdatedResult.IsFailed, Is.True);
                Assert.That(targetResult.IsSuccess, Is.True);
                Assert.That(creatorResult.IsSuccess, Is.True);
                Assert.That(thirdPartyResult.IsFailed, Is.True);
                Assert.That(adminResult.IsSuccess, Is.True);
            }
        }
    }
}
