namespace Mycelium.Forge.Dal.Tests.AutoGenPermissionService
{
    using System.Collections.Immutable;

    using ErrorOr;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;

    using NUnit.Framework;

    /// <summary>
    /// Test fixture for <see cref="PackageInvitationPermissionService" />.
    /// </summary>
    [TestFixture]
    public class PackageInvitationPermissionServiceTestFixture
    {
        private Mock<IPackageService> packageServiceMock;
        private PackageInvitationPermissionService permissionService;
        private Guid userId;
        private Guid otherUserId;
        private Guid packageId;
        private UserContext packageOwnerUserContext;
        private UserContext targetUserContext;
        private UserContext thirdPartyUserContext;
        private UserContext adminUserContext;
        private UserContext anonymousUserContext;

        /// <summary>
        /// Sets up mock dependencies and test context before each test.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.packageServiceMock = new Mock<IPackageService>();
            this.permissionService = new PackageInvitationPermissionService(this.packageServiceMock.Object);

            this.userId = Guid.NewGuid();
            this.otherUserId = Guid.NewGuid();
            this.packageId = Guid.NewGuid();

            this.packageOwnerUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "ownerUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.targetUserContext = new UserContext
            {
                AccountId = this.otherUserId,
                Username = "targetUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.thirdPartyUserContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "thirdPartyUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.adminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "adminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator]
            };

            this.anonymousUserContext = new UserContext
            {
                AccountId = null,
                Username = string.Empty,
                CurrentRoles = [RoleKind.Anonymous]
            };
        }

        /// <summary>
        /// Verifies the <see cref="PackageInvitationPermissionService.IsAllowedToCreate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToCreate()
        {
            var package = new Package
            {
                Id = this.packageId,
                Owner = this.userId,
                PackageOwner = [this.userId]
            };

            var invitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Owner = this.packageId,
                Target = this.otherUserId
            };

            this.packageServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(ImmutableList.Create<IPackage>(package));

            var unauthResult = await this.permissionService.IsAllowedToCreate(this.anonymousUserContext, invitation);
            var targetResult = await this.permissionService.IsAllowedToCreate(this.targetUserContext, invitation);
            var ownerResult = await this.permissionService.IsAllowedToCreate(this.packageOwnerUserContext, invitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(unauthResult.IsError, Is.True);
                Assert.That(targetResult.IsError, Is.True);
                Assert.That(ownerResult.IsError, Is.False);
            }
        }

        /// <summary>
        /// Verifies the <see cref="PackageInvitationPermissionService.IsAllowedToRead" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToRead()
        {
            var invitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                Target = this.otherUserId
            };

            this.packageServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(ImmutableList<IPackage>.Empty);

            var ownerResult = await this.permissionService.IsAllowedToRead(this.packageOwnerUserContext, invitation);
            var targetResult = await this.permissionService.IsAllowedToRead(this.targetUserContext, invitation);
            var thirdPartyResult = await this.permissionService.IsAllowedToRead(this.thirdPartyUserContext, invitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(ownerResult.IsError, Is.False);
                Assert.That(targetResult.IsError, Is.False);
                Assert.That(thirdPartyResult.IsError, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="PackageInvitationPermissionService.IsAllowedToUpdate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToUpdate()
        {
            var existingInvitation = new PackageInvitation
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                Target = this.otherUserId
            };

            var updatedInvitation = new PackageInvitation
            {
                Id = existingInvitation.Id,
                Owner = this.userId,
                Target = this.otherUserId
            };

            var targetResult = await this.permissionService.IsAllowedToUpdate(this.targetUserContext, existingInvitation, updatedInvitation);
            var creatorResult = await this.permissionService.IsAllowedToUpdate(this.packageOwnerUserContext, existingInvitation, updatedInvitation);
            var thirdPartyResult = await this.permissionService.IsAllowedToUpdate(this.thirdPartyUserContext, existingInvitation, updatedInvitation);
            var adminResult = await this.permissionService.IsAllowedToUpdate(this.adminUserContext, existingInvitation, updatedInvitation);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(targetResult.IsError, Is.False);
                Assert.That(creatorResult.IsError, Is.False);
                Assert.That(thirdPartyResult.IsError, Is.True);
                Assert.That(adminResult.IsError, Is.False);
            }
        }
    }
}
