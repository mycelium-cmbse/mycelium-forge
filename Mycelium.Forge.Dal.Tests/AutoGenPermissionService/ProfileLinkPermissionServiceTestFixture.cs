namespace Mycelium.Forge.Dal.Tests.AutoGenPermissionService
{
    using System.Collections.Immutable;

    using FluentResults;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;

    using NUnit.Framework;

    /// <summary>
    /// Test fixture for <see cref="ProfileLinkPermissionService" />.
    /// </summary>
    [TestFixture]
    public class ProfileLinkPermissionServiceTestFixture
    {
        /// <summary>
        /// The mock organization service.
        /// </summary>
        private Mock<IOrganizationService> organizationServiceMock;

        /// <summary>
        /// The permission service under test.
        /// </summary>
        private ProfileLinkPermissionService permissionService;

        /// <summary>
        /// The test account identifier.
        /// </summary>
        private Guid userId;

        /// <summary>
        /// A second test account identifier.
        /// </summary>
        private Guid otherUserId;

        /// <summary>
        /// The test organization identifier.
        /// </summary>
        private Guid organizationId;

        /// <summary>
        /// The user context for the account owner.
        /// </summary>
        private UserContext ownerUserContext;

        /// <summary>
        /// The user context for another account user.
        /// </summary>
        private UserContext otherUserContext;

        /// <summary>
        /// The user context for an organization administrator.
        /// </summary>
        private UserContext orgAdminUserContext;

        /// <summary>
        /// The user context for an unauthenticated user.
        /// </summary>
        private UserContext anonymousUserContext;

        /// <summary>
        /// Sets up mock dependencies and test context before each test.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.organizationServiceMock = new Mock<IOrganizationService>();
            this.permissionService = new ProfileLinkPermissionService(this.organizationServiceMock.Object);

            this.userId = Guid.NewGuid();
            this.otherUserId = Guid.NewGuid();
            this.organizationId = Guid.NewGuid();

            this.ownerUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "ownerUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.otherUserContext = new UserContext
            {
                AccountId = this.otherUserId,
                Username = "otherUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.orgAdminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "orgAdminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationAdministrator]
            };

            this.anonymousUserContext = new UserContext
            {
                AccountId = null,
                Username = string.Empty,
                CurrentRoles = [RoleKind.Anonymous]
            };
        }

        /// <summary>
        /// Verifies the <see cref="ProfileLinkPermissionService.IsAllowedToCreate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToCreate()
        {
            var personalLink = new ProfileLink
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                Uri = "https://github.com/alice"
            };

            var org = new Organization
            {
                Id = this.organizationId,
                Administrator = [this.userId],
                Member = [this.userId, this.otherUserId]
            };

            var orgLink = new ProfileLink
            {
                Id = Guid.NewGuid(),
                Owner = this.organizationId,
                Uri = "https://github.com/my-org"
            };

            this.organizationServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(Result.Ok(ImmutableList.Create<IOrganization>(org)));

            var nullResult = await this.permissionService.IsAllowedToCreate(this.ownerUserContext, null);
            var unauthResult = await this.permissionService.IsAllowedToCreate(this.anonymousUserContext, personalLink);
            var personalOwnerResult = await this.permissionService.IsAllowedToCreate(this.ownerUserContext, personalLink);
            var personalOtherResult = await this.permissionService.IsAllowedToCreate(this.otherUserContext, personalLink);
            var orgAdminResult = await this.permissionService.IsAllowedToCreate(this.orgAdminUserContext, orgLink);
            var orgMemberResult = await this.permissionService.IsAllowedToCreate(this.otherUserContext, orgLink);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullResult.IsFailed, Is.True);
                Assert.That(unauthResult.IsFailed, Is.True);
                Assert.That(personalOwnerResult.IsSuccess, Is.True);
                Assert.That(personalOtherResult.IsFailed, Is.True);
                Assert.That(orgAdminResult.IsSuccess, Is.True);
                Assert.That(orgMemberResult.IsFailed, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="ProfileLinkPermissionService.IsAllowedToDelete" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToDelete()
        {
            var link = new ProfileLink
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                Uri = "https://github.com/alice"
            };

            var nullResult = await this.permissionService.IsAllowedToDelete(this.ownerUserContext, null);
            var ownerResult = await this.permissionService.IsAllowedToDelete(this.ownerUserContext, link);
            var otherResult = await this.permissionService.IsAllowedToDelete(this.otherUserContext, link);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullResult.IsFailed, Is.True);
                Assert.That(ownerResult.IsSuccess, Is.True);
                Assert.That(otherResult.IsFailed, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="ProfileLinkPermissionService.IsAllowedToUpdate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToUpdate()
        {
            var existingLink = new ProfileLink
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                Uri = "https://github.com/alice"
            };

            var updatedLink = new ProfileLink
            {
                Id = existingLink.Id,
                Owner = this.userId,
                Uri = "https://github.com/alice-updated"
            };

            var nullExistingResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, null, updatedLink);
            var nullUpdatedResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingLink, null);
            var ownerResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingLink, updatedLink);
            var otherResult = await this.permissionService.IsAllowedToUpdate(this.otherUserContext, existingLink, updatedLink);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(nullExistingResult.IsFailed, Is.True);
                Assert.That(nullUpdatedResult.IsFailed, Is.True);
                Assert.That(ownerResult.IsSuccess, Is.True);
                Assert.That(otherResult.IsFailed, Is.True);
            }
        }
    }
}
