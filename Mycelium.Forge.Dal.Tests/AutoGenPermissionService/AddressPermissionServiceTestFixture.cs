namespace Mycelium.Forge.Dal.Tests.AutoGenPermissionService
{
    using System.Collections.Immutable;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.AutoGenPermissionService;

    using Npgsql;

    using NUnit.Framework;

    /// <summary>
    /// Test fixture for <see cref="AddressPermissionService" />.
    /// </summary>
    [TestFixture]
    public class AddressPermissionServiceTestFixture
    {
        private Mock<IOrganizationService> organizationServiceMock;
        private AddressPermissionService permissionService;
        private NpgsqlTransaction transaction;
        private Guid userId;
        private Guid otherUserId;
        private Guid organizationId;
        private UserContext ownerUserContext;
        private UserContext otherUserContext;
        private UserContext orgAdminUserContext;
        private UserContext adminUserContext;
        private UserContext anonymousUserContext;

        /// <summary>
        /// Sets up mock dependencies and test context before each test.
        /// </summary>
        [SetUp]
        public void SetUp()
        {
            this.transaction = null;
            this.organizationServiceMock = new Mock<IOrganizationService>();
            this.permissionService = new AddressPermissionService(this.organizationServiceMock.Object);

            this.userId = Guid.NewGuid();
            this.otherUserId = Guid.NewGuid();
            this.organizationId = Guid.NewGuid();

            this.ownerUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "ownerUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.otherUserContext = new UserContext
            {
                AccountId = this.otherUserId,
                Username = "otherUser",
                CurrentRoles = [RoleKind.Account]
            };

            this.orgAdminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "orgAdminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.OrganizationAdministrator]
            };

            this.adminUserContext = new UserContext
            {
                AccountId = this.userId,
                Username = "adminUser",
                CurrentRoles = [RoleKind.Account, RoleKind.InstallationAdministrator]
            };

            this.anonymousUserContext = new UserContext
            {
                AccountId = null,
                Username = string.Empty,
                CurrentRoles = [RoleKind.Anonymous]
            };
        }

        /// <summary>
        /// Verifies the <see cref="AddressPermissionService.IsAllowedToCreate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToCreate()
        {
            var personalAddress = new Address
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                AddressLine1 = "123 Main St",
                PostalCode = "12345"
            };

            var org = new Organization
            {
                Id = this.organizationId,
                Administrator = [this.userId],
                Member = [this.userId, this.otherUserId]
            };

            var orgAddress = new Address
            {
                Id = Guid.NewGuid(),
                Owner = this.organizationId,
                AddressLine1 = "456 Corp Ave",
                PostalCode = "67890"
            };

            this.organizationServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<NpgsqlTransaction>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync(ImmutableList.Create<IOrganization>(org));

            var unauthResult = await this.permissionService.IsAllowedToCreate(this.anonymousUserContext, personalAddress, this.transaction);
            var personalOwnerResult = await this.permissionService.IsAllowedToCreate(this.ownerUserContext, personalAddress, this.transaction);
            var personalOtherResult = await this.permissionService.IsAllowedToCreate(this.otherUserContext, personalAddress, this.transaction);
            var orgAdminResult = await this.permissionService.IsAllowedToCreate(this.orgAdminUserContext, orgAddress, this.transaction);
            var orgMemberResult = await this.permissionService.IsAllowedToCreate(this.otherUserContext, orgAddress, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(unauthResult.IsError, Is.True);
                Assert.That(personalOwnerResult.IsError, Is.False);
                Assert.That(personalOtherResult.IsError, Is.True);
                Assert.That(orgAdminResult.IsError, Is.False);
                Assert.That(orgMemberResult.IsError, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="AddressPermissionService.IsAllowedToDelete" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToDelete()
        {
            var address = new Address
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                AddressLine1 = "123 Main St"
            };

            var ownerResult = await this.permissionService.IsAllowedToDelete(this.ownerUserContext, address, this.transaction);
            var otherResult = await this.permissionService.IsAllowedToDelete(this.otherUserContext, address, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(ownerResult.IsError, Is.False);
                Assert.That(otherResult.IsError, Is.True);
            }
        }

        /// <summary>
        /// Verifies the <see cref="AddressPermissionService.IsAllowedToRead" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToRead()
        {
            var personalAddress = new Address
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                AddressLine1 = "123 Main St"
            };

            var org = new Organization
            {
                Id = this.organizationId,
                Administrator = [this.userId],
                Member = [this.userId, this.otherUserId]
            };

            var orgAddress = new Address
            {
                Id = Guid.NewGuid(),
                Owner = this.organizationId,
                AddressLine1 = "456 Corp Ave"
            };

            this.organizationServiceMock.Setup(x => x.ReadAsync(
                    It.IsAny<IUserContext>(),
                    It.IsAny<NpgsqlTransaction>(),
                    It.IsAny<CancellationToken>(),
                    It.IsAny<Guid[]>()))
                .ReturnsAsync((IUserContext _, NpgsqlTransaction _, CancellationToken _, Guid[] ids) =>
                    ids is { Length: > 0 } && ids[0] == this.organizationId
                        ? ImmutableList.Create<IOrganization>(org)
                        : ImmutableList<IOrganization>.Empty);

            var ownerResult = await this.permissionService.IsAllowedToRead(this.ownerUserContext, personalAddress, this.transaction);
            var nonOwnerResult = await this.permissionService.IsAllowedToRead(this.otherUserContext, personalAddress, this.transaction);
            var adminResult = await this.permissionService.IsAllowedToRead(this.adminUserContext, personalAddress, this.transaction);
            var orgMemberResult = await this.permissionService.IsAllowedToRead(this.otherUserContext, orgAddress, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(ownerResult.IsError, Is.False);
                Assert.That(nonOwnerResult.IsError, Is.True);
                Assert.That(adminResult.IsError, Is.False);
                Assert.That(orgMemberResult.IsError, Is.False);
            }
        }

        /// <summary>
        /// Verifies the <see cref="AddressPermissionService.IsAllowedToUpdate" /> method.
        /// </summary>
        /// <returns>An awaitable <see cref="Task" />.</returns>
        [Test]
        public async Task VerifyIsAllowedToUpdate()
        {
            var existingAddress = new Address
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                AddressLine1 = "123 Main St"
            };

            var updatedAddress = new Address
            {
                Id = existingAddress.Id,
                Owner = this.userId,
                AddressLine1 = "123 Main St Suite 200"
            };

            var ownerResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingAddress, updatedAddress, this.transaction);
            var otherResult = await this.permissionService.IsAllowedToUpdate(this.otherUserContext, existingAddress, updatedAddress, this.transaction);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(ownerResult.IsError, Is.False);
                Assert.That(otherResult.IsError, Is.True);
            }
        }
    }
}
