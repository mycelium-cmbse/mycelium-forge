        [Test]
        public async Task VerifyIsAllowedToUpdate()
        {
            var existingPackage = new Package
            {
                Id = Guid.NewGuid(),
                Owner = this.userId,
                PackageOwner = [this.userId],
                PackageMaintainer = [this.otherUserId],
                Visibility = VisibilityKind.PRIVATE
            };

            var updatedSettingsPackage = new Package
            {
                Id = existingPackage.Id,
                Owner = this.userId,
                PackageOwner = [this.userId],
                PackageMaintainer = [this.otherUserId],
                Visibility = VisibilityKind.PRIVATE,
                Name = "UpdatedName"
            };

            var updatedOwnershipPackage = new Package
            {
                Id = existingPackage.Id,
                Owner = this.otherUserId,
                PackageOwner = [this.userId],
                PackageMaintainer = [this.otherUserId],
                Visibility = VisibilityKind.PRIVATE
            };

            var updatedVisibilityPackage = new Package
            {
                Id = existingPackage.Id,
                Owner = this.userId,
                PackageOwner = [this.userId],
                PackageMaintainer = [this.otherUserId],
                Visibility = VisibilityKind.PUBLIC
            };

            var settingsOwnerResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingPackage, updatedSettingsPackage, this.transaction);
            var settingsMaintainerResult = await this.permissionService.IsAllowedToUpdate(this.maintainerUserContext, existingPackage, updatedSettingsPackage, this.transaction);

            var ownershipOwnerResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingPackage, updatedOwnershipPackage, this.transaction);
            var ownershipMaintainerResult = await this.permissionService.IsAllowedToUpdate(this.maintainerUserContext, existingPackage, updatedOwnershipPackage, this.transaction);

            var visibilityOwnerResult = await this.permissionService.IsAllowedToUpdate(this.ownerUserContext, existingPackage, updatedVisibilityPackage, this.transaction);
            var visibilityMaintainerResult = await this.permissionService.IsAllowedToUpdate(this.maintainerUserContext, existingPackage, updatedVisibilityPackage, this.transaction);

            var orgId = Guid.NewGuid();
            var orgAdminId = Guid.NewGuid();
