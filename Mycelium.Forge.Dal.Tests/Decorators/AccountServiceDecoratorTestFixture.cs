namespace Mycelium.Forge.Dal.Tests.Decorators
{
    using System.Collections.Immutable;

    using ErrorOr;

    using Moq;

    using Mycelium.Forge.Common;
    using Mycelium.Forge.Dal.AutoGeneratedServices;
    using Mycelium.Forge.Dal.Decorators;

    using Npgsql;

    using NUnit.Framework;

    using ZiggyCreatures.Caching.Fusion;

    [TestFixture]
    public class AccountServiceDecoratorTestFixture
    {
        private Mock<IAccountService> innerServiceMock;
        private IFusionCache fusionCache;
        private AccountServiceDecorator decorator;
        private IUserContext userContext;

        [SetUp]
        public void SetUp()
        {
            this.innerServiceMock = new Mock<IAccountService>();
            this.fusionCache = new FusionCache(new FusionCacheOptions());
            this.decorator = new AccountServiceDecorator(this.innerServiceMock.Object, this.fusionCache);

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "testUser",
                CurrentRoles = [RoleKind.Account]
            };
        }

        [TearDown]
        public void TearDown()
        {
            this.fusionCache.Dispose();
        }

        [Test]
        public void VerifyConstructor()
        {
            var instance = new AccountServiceDecorator(this.innerServiceMock.Object, this.fusionCache);
            Assert.That(instance, Is.Not.Null);
        }

        [Test]
        public async Task VerifyCreateAsync()
        {
            var account = new Account { Id = Guid.NewGuid(), Name = "test-account" };

            // Overload with transaction - success
            this.innerServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IAccount>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Created);

            var txResult = await this.decorator.CreateAsync(this.userContext, null, [account], CancellationToken.None);

            // Overload without transaction - error
            this.innerServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IAccount>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "Creation failed"));

            var standaloneResult = await this.decorator.CreateAsync(this.userContext, [account], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(txResult.IsError, Is.False);
                Assert.That(standaloneResult.IsError, Is.True);
                this.innerServiceMock.Verify(x => x.CreateAsync(this.userContext, null, It.IsAny<IEnumerable<IAccount>>(), CancellationToken.None), Times.Once());
                this.innerServiceMock.Verify(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IAccount>>(), CancellationToken.None), Times.Once());
            }
        }

        [Test]
        public async Task VerifyDeleteAsync()
        {
            var accountId1 = Guid.NewGuid();
            var accountId2 = Guid.NewGuid();

            // Prime cache with entries tagged by Scope:{id}
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Scope:{accountId1}"]);
            await this.fusionCache.SetAsync("Key2", "Val2", tags: [$"Scope:{accountId2}"]);

            // Overload with transaction - success -> invalidates tags
            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Deleted);

            var txResult = await this.decorator.DeleteAsync(this.userContext, null, [accountId1], CancellationToken.None);
            var cachedKey1 = await this.fusionCache.TryGetAsync<string>("Key1");
            var cachedKey2 = await this.fusionCache.TryGetAsync<string>("Key2");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(txResult.IsError, Is.False);
                Assert.That(cachedKey1.HasValue, Is.False);
                Assert.That(cachedKey2.HasValue, Is.True);
            }

            // Overload without transaction - error -> does NOT invalidate tags
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Scope:{accountId1}"]);

            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "Delete failed"));

            var errorResult = await this.decorator.DeleteAsync(this.userContext, [accountId1], CancellationToken.None);
            var cachedKey1AfterError = await this.fusionCache.TryGetAsync<string>("Key1");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(errorResult.IsError, Is.True);
                Assert.That(cachedKey1AfterError.HasValue, Is.True);
            }

            // Overload without transaction - success
            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Deleted);

            var standaloneSuccess = await this.decorator.DeleteAsync(this.userContext, [accountId1, accountId2], CancellationToken.None);
            var cachedKey2AfterSuccess = await this.fusionCache.TryGetAsync<string>("Key2");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(standaloneSuccess.IsError, Is.False);
                Assert.That(cachedKey2AfterSuccess.HasValue, Is.False);
            }

            // Null iids handled safely
            var nullIdsResult = await this.decorator.DeleteAsync(this.userContext, null, CancellationToken.None);
            Assert.That(nullIdsResult.IsError, Is.False);
        }

        [Test]
        public async Task VerifyReadAsync()
        {
            var accountId = Guid.NewGuid();
            var account = new Account { Id = accountId, Name = "read-account" };

            // Overload with transaction - success
            this.innerServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()))
                .ReturnsAsync(ImmutableList.Create<IAccount>(account));

            var txResult = await this.decorator.ReadAsync(this.userContext, null, CancellationToken.None, [accountId]);

            // Overload without transaction - error
            this.innerServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.IsAny<Guid[]>()))
                .ReturnsAsync(Error.Failure(description: "Read failed"));

            var standaloneResult = await this.decorator.ReadAsync(this.userContext, CancellationToken.None, [accountId]);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(txResult.IsError, Is.False);
                Assert.That(txResult.Value, Has.Count.EqualTo(1));
                Assert.That(standaloneResult.IsError, Is.True);
                this.innerServiceMock.Verify(x => x.ReadAsync(this.userContext, null, CancellationToken.None, It.IsAny<Guid[]>()), Times.Once());
                this.innerServiceMock.Verify(x => x.ReadAsync(this.userContext, CancellationToken.None, It.IsAny<Guid[]>()), Times.Once());
            }
        }

