            var txResult = await this.decorator.CreateAsync(this.userContext, null, [package], CancellationToken.None);

            // Overload without transaction - error
            this.innerServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IPackage>>(), It.IsAny<CancellationToken>()))
