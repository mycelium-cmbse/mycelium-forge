            }
        }

        [Test]
        public async Task VerifyDeleteAsync()
        {
            var packageId1 = Guid.NewGuid();
            var packageId2 = Guid.NewGuid();

            // Prime cache with tags
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Package:{packageId1}"]);
            await this.fusionCache.SetAsync("Key2", "Val2", tags: [$"Package:{packageId2}"]);

            // Overload with transaction - success -> invalidates tag
            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Deleted);

            var txResult = await this.decorator.DeleteAsync(this.userContext, null, [packageId1], CancellationToken.None);
            var cachedKey1 = await this.fusionCache.TryGetAsync<string>("Key1");
            var cachedKey2 = await this.fusionCache.TryGetAsync<string>("Key2");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(txResult.IsError, Is.False);
                Assert.That(cachedKey1.HasValue, Is.False);
                Assert.That(cachedKey2.HasValue, Is.True);
            }

            // Overload without transaction - error -> does NOT invalidate
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Package:{packageId1}"]);

            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "Delete failed"));

            var errorResult = await this.decorator.DeleteAsync(this.userContext, [packageId1], CancellationToken.None);
            var cachedKey1AfterError = await this.fusionCache.TryGetAsync<string>("Key1");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(errorResult.IsError, Is.True);
                Assert.That(cachedKey1AfterError.HasValue, Is.True);
            }

            // Overload without transaction - success
            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Deleted);

            var standaloneSuccess = await this.decorator.DeleteAsync(this.userContext, [packageId1, packageId2], CancellationToken.None);
            var cachedKey2AfterSuccess = await this.fusionCache.TryGetAsync<string>("Key2");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(standaloneSuccess.IsError, Is.False);
                Assert.That(cachedKey2AfterSuccess.HasValue, Is.False);
            }

            // Null iids handled safely
            var nullIdsResult = await this.decorator.DeleteAsync(this.userContext, null, CancellationToken.None);
            Assert.That(nullIdsResult.IsError, Is.False);
        }

