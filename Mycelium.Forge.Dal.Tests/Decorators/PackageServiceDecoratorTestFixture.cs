        [Test]
        public async Task VerifyReadByCoordinateAsync()
        {
            var packageId = Guid.NewGuid();
            var ownerId = Guid.NewGuid();

            var package = new Package
            {
                Id = packageId,
                Owner = ownerId,
                Name = "Core Package",
                ShortName = "core"
            };

            const string cacheKey = "Package:Coordinate:starion/core";

            // Case 1: Cache hit via pointer
            await this.fusionCache.SetPointerAsync(cacheKey, packageId, [$"Package:{packageId}", $"Scope:{ownerId}"], CancellationToken.None);

            this.innerServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == packageId)))
                .ReturnsAsync(ImmutableList.Create<IPackage>(package));

            var cacheHitResult = await this.decorator.ReadByCoordinateAsync(this.userContext, "starion", "core", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(cacheHitResult.IsError, Is.False);
                Assert.That(cacheHitResult.Value.Id, Is.EqualTo(packageId));
                Assert.That(cacheHitResult.Value.ShortName, Is.EqualTo("core"));
                this.innerServiceMock.Verify(x => x.ReadByCoordinateAsync(It.IsAny<IUserContext>(), It.IsAny<string>(), It.IsAny<string>(), It.IsAny<CancellationToken>()), Times.Never());
            }

            // Case 2: Cache miss -> calls innerService.ReadByCoordinateAsync and caches pointer
            await this.fusionCache.RemoveAsync(cacheKey);

            this.innerServiceMock.Setup(x => x.ReadByCoordinateAsync(this.userContext, "starion", "core", It.IsAny<CancellationToken>()))
                .ReturnsAsync(package);

            var cacheMissResult = await this.decorator.ReadByCoordinateAsync(this.userContext, "starion", "core", CancellationToken.None);
            var cachedPointer = await this.fusionCache.TryGetAsync<Guid>(cacheKey);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(cacheMissResult.IsError, Is.False);
                Assert.That(cacheMissResult.Value.Id, Is.EqualTo(packageId));
                Assert.That(cachedPointer.HasValue, Is.True);
                Assert.That(cachedPointer.Value, Is.EqualTo(packageId));
                this.innerServiceMock.Verify(x => x.ReadByCoordinateAsync(this.userContext, "starion", "core", It.IsAny<CancellationToken>()), Times.Once());
            }

            // Case 3: Invalidation via Scope tag
            await this.fusionCache.RemoveByTagAsync($"Scope:{ownerId}");
            var cachedPointerAfterScopeTag = await this.fusionCache.TryGetAsync<Guid>(cacheKey);
            Assert.That(cachedPointerAfterScopeTag.HasValue, Is.False);

            // Case 4: Inner service error -> does NOT cache pointer
            await this.fusionCache.RemoveAsync(cacheKey);

            this.innerServiceMock.Setup(x => x.ReadByCoordinateAsync(this.userContext, "starion", "notfound", It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.NotFound(description: "Not found"));

            var errorResult = await this.decorator.ReadByCoordinateAsync(this.userContext, "starion", "notfound", CancellationToken.None);
            var cachedPointerAfterError = await this.fusionCache.TryGetAsync<Guid>("Package:Coordinate:starion/notfound");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(errorResult.IsError, Is.True);
                Assert.That(cachedPointerAfterError.HasValue, Is.False);
            }
        }

