    {
        private Mock<IOrganizationService> innerServiceMock;
        private IFusionCache fusionCache;
        private Mock<ILogger<OrganizationServiceDecorator>> loggerMock;
        private OrganizationServiceDecorator decorator;
        private IUserContext userContext;

        [SetUp]
        public void SetUp()
        {
            this.innerServiceMock = new Mock<IOrganizationService>();
            this.fusionCache = new FusionCache(new FusionCacheOptions());
            this.loggerMock = new Mock<ILogger<OrganizationServiceDecorator>>();
            this.loggerMock.Setup(x => x.IsEnabled(It.IsAny<LogLevel>())).Returns(true);

            this.decorator = new OrganizationServiceDecorator(this.innerServiceMock.Object, this.fusionCache, this.loggerMock.Object);

            this.userContext = new UserContext
            {
                AccountId = Guid.NewGuid(),
                Username = "testUser",
                CurrentRoles = [RoleKind.Account]
            };
        }

        [TearDown]
        public void TearDown()
        {
            this.fusionCache.Dispose();
        }

        [Test]
        public void VerifyConstructor()
        {
            var instance = new OrganizationServiceDecorator(this.innerServiceMock.Object, this.fusionCache, this.loggerMock.Object);

            Assert.That(instance, Is.Not.Null);
        }

        [Test]
        public async Task VerifyCreateAsync()
        {
            var org = new Organization
            {
                Id = Guid.NewGuid(),
                Name = "test-org",
                ShortName = "test-org"
            };

            // Overload with transaction - success
            this.innerServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IOrganization>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Created);

            var txResult = await this.decorator.CreateAsync(this.userContext, null, [org], CancellationToken.None);

            // Overload without transaction - error
            this.innerServiceMock.Setup(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IOrganization>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "Creation failed"));

            var standaloneResult = await this.decorator.CreateAsync(this.userContext, [org], CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(txResult.IsError, Is.False);
                Assert.That(standaloneResult.IsError, Is.True);
                this.innerServiceMock.Verify(x => x.CreateAsync(this.userContext, null, It.IsAny<IEnumerable<IOrganization>>(), CancellationToken.None), Times.Once());
                this.innerServiceMock.Verify(x => x.CreateAsync(this.userContext, It.IsAny<IEnumerable<IOrganization>>(), CancellationToken.None), Times.Once());
            }
        }

        [Test]
        public async Task VerifyDeleteAsync()
        {
            var orgId1 = Guid.NewGuid();
            var orgId2 = Guid.NewGuid();

            // Prime cache with tags
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Scope:{orgId1}"]);
            await this.fusionCache.SetAsync("Key2", "Val2", tags: [$"Scope:{orgId2}"]);

            // Overload with transaction - success -> invalidates tag
            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Deleted);

            var txResult = await this.decorator.DeleteAsync(this.userContext, null, [orgId1], CancellationToken.None);
            var cachedKey1 = await this.fusionCache.TryGetAsync<string>("Key1");
            var cachedKey2 = await this.fusionCache.TryGetAsync<string>("Key2");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(txResult.IsError, Is.False);
                Assert.That(cachedKey1.HasValue, Is.False);
                Assert.That(cachedKey2.HasValue, Is.True);
            }

            // Overload without transaction - error -> does NOT invalidate
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Scope:{orgId1}"]);

            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "Delete failed"));

            var errorResult = await this.decorator.DeleteAsync(this.userContext, [orgId1], CancellationToken.None);
            var cachedKey1AfterError = await this.fusionCache.TryGetAsync<string>("Key1");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(errorResult.IsError, Is.True);
                Assert.That(cachedKey1AfterError.HasValue, Is.True);
            }

            // Overload without transaction - success
            this.innerServiceMock.Setup(x => x.DeleteAsync(this.userContext, It.IsAny<IEnumerable<Guid>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Deleted);

            var standaloneSuccess = await this.decorator.DeleteAsync(this.userContext, [orgId1, orgId2], CancellationToken.None);
            var cachedKey2AfterSuccess = await this.fusionCache.TryGetAsync<string>("Key2");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(standaloneSuccess.IsError, Is.False);
                Assert.That(cachedKey2AfterSuccess.HasValue, Is.False);
            }

            // Null iids handled safely
            var nullIdsResult = await this.decorator.DeleteAsync(this.userContext, null, CancellationToken.None);
            Assert.That(nullIdsResult.IsError, Is.False);
        }

