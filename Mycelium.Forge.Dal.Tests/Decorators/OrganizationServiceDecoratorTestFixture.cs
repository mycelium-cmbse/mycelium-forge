        [Test]
        public async Task VerifyReadByShortNameAsync()
        {
            var orgId = Guid.NewGuid();

            var org = new Organization
            {
                Id = orgId,
                Name = "Starion Org",
                ShortName = "starion"
            };

            const string cacheKey = "Scope:ShortName:starion";

            // Case 1: Cache hit via pointer
            await this.fusionCache.SetPointerAsync(cacheKey, orgId, [$"Scope:{orgId}"], CancellationToken.None);

            this.innerServiceMock.Setup(x => x.ReadAsync(this.userContext, It.IsAny<CancellationToken>(), It.Is<Guid[]>(ids => ids.Length == 1 && ids[0] == orgId)))
                .ReturnsAsync(ImmutableList.Create<IOrganization>(org));

            var cacheHitResult = await this.decorator.ReadByShortNameAsync(this.userContext, "starion", CancellationToken.None);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(cacheHitResult.IsError, Is.False);
                Assert.That(cacheHitResult.Value.Id, Is.EqualTo(orgId));
                Assert.That(cacheHitResult.Value.ShortName, Is.EqualTo("starion"));
                this.innerServiceMock.Verify(x => x.ReadByShortNameAsync(It.IsAny<IUserContext>(), It.IsAny<string>(), It.IsAny<CancellationToken>()), Times.Never());
            }

            // Case 2: Cache miss -> calls innerService.ReadByShortNameAsync and caches pointer
            await this.fusionCache.RemoveAsync(cacheKey);

            this.innerServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, "starion", It.IsAny<CancellationToken>()))
                .ReturnsAsync(org);

            var cacheMissResult = await this.decorator.ReadByShortNameAsync(this.userContext, "starion", CancellationToken.None);
            var cachedPointer = await this.fusionCache.TryGetAsync<Guid>(cacheKey);

            using (Assert.EnterMultipleScope())
            {
                Assert.That(cacheMissResult.IsError, Is.False);
                Assert.That(cacheMissResult.Value.Id, Is.EqualTo(orgId));
                Assert.That(cachedPointer.HasValue, Is.True);
                Assert.That(cachedPointer.Value, Is.EqualTo(orgId));
                this.innerServiceMock.Verify(x => x.ReadByShortNameAsync(this.userContext, "starion", It.IsAny<CancellationToken>()), Times.Once());
            }

            // Case 3: Inner service error -> does NOT cache pointer
            await this.fusionCache.RemoveAsync("Scope:ShortName:notfound");

            this.innerServiceMock.Setup(x => x.ReadByShortNameAsync(this.userContext, "notfound", It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.NotFound(description: "Not found"));

            var errorResult = await this.decorator.ReadByShortNameAsync(this.userContext, "notfound", CancellationToken.None);
            var cachedPointerAfterError = await this.fusionCache.TryGetAsync<Guid>("Scope:ShortName:notfound");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(errorResult.IsError, Is.True);
                Assert.That(cachedPointerAfterError.HasValue, Is.False);
            }
        }

        [Test]
        public async Task VerifyUpdateAsync()
        {
            var orgId1 = Guid.NewGuid();
            var org1 = new Organization { Id = orgId1, Name = "Org One", ShortName = "org-one-new" };
            var orgId2 = Guid.NewGuid();
            var org2 = new Organization { Id = orgId2, Name = "Org Two", ShortName = "org-two" };

            // Prime cache with tags and short name keys, including old short name and package coordinate tagged with Scope ID
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Scope:{orgId1}"]);
            await this.fusionCache.SetAsync("Scope:ShortName:org-one-old", orgId1, tags: [$"Scope:{orgId1}"]);
            await this.fusionCache.SetAsync("Package:Coordinate:org-one-old/my-package", Guid.NewGuid(), tags: [$"Scope:{orgId1}"]);
            await this.fusionCache.SetAsync("Scope:ShortName:org-one-new", orgId1);
            await this.fusionCache.SetAsync("Key2", "Val2", tags: [$"Scope:{orgId2}"]);
            await this.fusionCache.SetAsync("Scope:ShortName:org-two", orgId2);

            // Overload with transaction - success -> invalidates tag and short name key
            this.innerServiceMock.Setup(x => x.UpdateAsync(this.userContext, It.IsAny<NpgsqlTransaction>(), It.IsAny<IEnumerable<IOrganization>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Updated);

            var txResult = await this.decorator.UpdateAsync(this.userContext, null, [org1], CancellationToken.None);
            var cachedKey1 = await this.fusionCache.TryGetAsync<string>("Key1");
            var cachedOldShortName1 = await this.fusionCache.TryGetAsync<Guid>("Scope:ShortName:org-one-old");
            var cachedCoordinate1 = await this.fusionCache.TryGetAsync<Guid>("Package:Coordinate:org-one-old/my-package");
            var cachedNewShortName1 = await this.fusionCache.TryGetAsync<Guid>("Scope:ShortName:org-one-new");
            var cachedKey2 = await this.fusionCache.TryGetAsync<string>("Key2");
            var cachedShortName2 = await this.fusionCache.TryGetAsync<Guid>("Scope:ShortName:org-two");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(txResult.IsError, Is.False);
                Assert.That(cachedKey1.HasValue, Is.False);
                Assert.That(cachedOldShortName1.HasValue, Is.False);
                Assert.That(cachedCoordinate1.HasValue, Is.False);
                Assert.That(cachedNewShortName1.HasValue, Is.False);
                Assert.That(cachedKey2.HasValue, Is.True);
                Assert.That(cachedShortName2.HasValue, Is.True);
            }

            // Overload without transaction - error -> does NOT invalidate
            await this.fusionCache.SetAsync("Key1", "Val1", tags: [$"Scope:{orgId1}"]);
            await this.fusionCache.SetAsync("Scope:ShortName:org-one", orgId1);

            this.innerServiceMock.Setup(x => x.UpdateAsync(this.userContext, It.IsAny<IEnumerable<IOrganization>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Error.Failure(description: "Update failed"));

            var errorResult = await this.decorator.UpdateAsync(this.userContext, [org1], CancellationToken.None);
            var cachedKey1AfterError = await this.fusionCache.TryGetAsync<string>("Key1");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(errorResult.IsError, Is.True);
                Assert.That(cachedKey1AfterError.HasValue, Is.True);
            }

            // Overload without transaction - success
            this.innerServiceMock.Setup(x => x.UpdateAsync(this.userContext, It.IsAny<IEnumerable<IOrganization>>(), It.IsAny<CancellationToken>()))
                .ReturnsAsync(Result.Updated);

            var standaloneSuccess = await this.decorator.UpdateAsync(this.userContext, [org1, org2], CancellationToken.None);
            var cachedKey2AfterSuccess = await this.fusionCache.TryGetAsync<string>("Key2");
            var cachedShortName2AfterSuccess = await this.fusionCache.TryGetAsync<Guid>("Scope:ShortName:org-two");

            using (Assert.EnterMultipleScope())
            {
                Assert.That(standaloneSuccess.IsError, Is.False);
                Assert.That(cachedKey2AfterSuccess.HasValue, Is.False);
                Assert.That(cachedShortName2AfterSuccess.HasValue, Is.False);
            }

            // Null dtos handled safely
            var nullDtosResult = await this.decorator.UpdateAsync(this.userContext, null, CancellationToken.None);
            Assert.That(nullDtosResult.IsError, Is.False);
        }
